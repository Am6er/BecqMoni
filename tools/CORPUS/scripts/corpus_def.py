# Модель разрешения строится ОДНА НА ГРУППУ `det`, а поверки 2016 и 2024
# расходятся по ширине линии на 10.4 %: измерено `scripts/g1s_split_check.py`
# попарно «тот же источник, та же геометрия, другой год» — 11 пар из 12 одного
# знака, знаковый критерий p = 0.0063; загрузка как причина отвергнута. Одна
# модель на обе поверки усредняет две разные ширины, и это молча портит и
# поиск пиков, и полноспектральный разбор.
#
# ⚠ Прибор при этом ОДИН И ТОТ ЖЕ. Прежняя запись «два экземпляра, №0086-16 и
# №0247-24» — ошибка чтения заголовков: во всех 218 исходных `.spe` поле
# `DETECTOR` называет один блок (`УДС-ГЦ-63х63-USB №0086-16`), `CONFIGNAME` в
# оба года — один анализатор (`Гамма-1С №0221-16`), а `№0247-24` встречается
# только ВНУТРИ путей к файлам калибровок (`C:\Lsrm\Work\Гамма-1С_№0247-24\…`),
# то есть это имя рабочей папки на машине ЛСРМ. Расходятся не кристаллы, а
# восемь лет между поверками (и, судя по тем же путям, возможно анализатор:
# спектры 2016 ссылаются на папку `Гамма-1С №0207-13`).
#
# Поэтому суффикс группы — ГОД ПОВЕРКИ, а не номер прибора. Геометрия при этом
# НЕ делится: сосуд и расстояние от года не зависят, и одна геометрия законно
# собирает спектры обоих годов (`CorpusGeomProbe.Build`).
