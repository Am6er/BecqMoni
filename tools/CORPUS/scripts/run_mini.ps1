# Прогон МАЛОЙ БАЗЫ корпуса — постоянного набора для частых замеров (`S136`).
#
#   & 'tools\CORPUS\scripts\run_mini.ps1' -Out tools\pie\out_mini
#   & 'tools\CORPUS\scripts\run_mini.ps1' -Out tools\pie\out_mini_arm -Extra '--pairth=1'
#
# ⛔ ЗВАТЬ ОПЕРАТОРОМ ВЫЗОВА `&` ИЗ ТЕКУЩЕЙ СЕССИИ, а не порождать `pwsh` на файл:
#    массив `-Extra` уходит в порождённый процесс через командную строку и
#    схлопывается в один элемент (`T84`). С ОДНИМ ключом разницы не видно —
#    ломается молча начиная со второго.
#
# ## Зачем эта база вообще
#
# Решение Amber 04.09.2026: «прогоны корпуса по много часов на каждой задаче —
# неправильный путь». Полный корпус гоняем, когда список задач устаканится и
# матрицы перестанут переделываться.
#
# ⛔ **Дорог не прогон, а СЦЕНЫ.** Разбор всех 129 спектров идёт 28 секунд;
# часы съедает пересчёт матриц отклика, и матрица считается НА СЦЕНУ. У полного
# корпуса сцен 44, и сорок из них несут ПО ОДНОМУ спектру каждая — они и
# составляют почти всю цену. Малая база сделана по этому признаку: 59 спектров
# на ПЯТИ сценах, то есть при смене физики пересчитывать надо 5 матриц вместо 44.
#
# Состав и обоснование каждой строки — `corpus/mini.csv`.
#
# ## ⛔ Умолчание `-Out` — НЕ УДОБСТВО, а условие приёмки (`T248`)
#
# Малая база объявлена ИМЕНЕМ каталога («малая `out_mini`»), и проверяющий
# естественным движением пересчитывает `score.py` по нему. Значит переобъявление
# обязано прогонять базу В ЭТОТ каталог (умолчание ниже) либо называть в
# объявлении тот каталог, где объявленные числа действительно лежат.
#
# 06.09.2026 не сделано ни того, ни другого: объявление сказало `out_mini`, а
# каталог держал прогон 04.09.2026 — снятую базу (556.0 / 5.91 / 100 % и
# 205.3 / 4.95 / 90 % против объявленных 556.1 / 5.93 / 98 % и 205.9 / 4.95 /
# 93 %). ⛔ Отказа при этом не бывает: числа правдоподобны, разница в десятых,
# подмену поколения видно только по дате файлов.
#
# Приёмка после переобъявления — одной командой, и она же стоит в читателе
# сторожей (`tools/check_all.py`):
#
#     python tools\check_declared_base.py        # код 0 = каталог из
#                                                # объявления даёт объявленные числа
#
# ⚠ Плечо считается в СВОЙ `-Out`, а не в `out_mini`: подменять им базовый
#   каталог — это и есть смесь поколений, ради которой сторож написан.
#
# ## Чего этот скрипт НЕ делает
#
# Он НЕ считает матрицы. Пять сцен малой базы лежат готовыми в своём складе
# (`tools\effmaker\out\mini16`, физика 16), и пока версия физики не менялась,
# прогон берёт их оттуда. Пересчёт — отдельное движение (`CorpusMatrixProbe` +
# `mx_swap.py --into`), и звать его надо явно.
#
# ## Ключ `-List` — добор спектра из ПОЛНОГО корпуса
#
# Уточнение Amber 10.09.2026, дословно: «Если задачи требуют прогона корпуса —
# используй минимальный корпус для прогона и построения матриц. Если каких-то
# специфичных спектров или детекторов или геометрий не хватает в минимальном
# корпусе — возьми нужный спектр из полного и используй. Не гони бездумно весь
# корпус!»
#
#   & 'tools\CORPUS\scripts\run_mini.ps1' -List <свой>.csv -Out tools\pie\out_p40
#
# Список задаётся ТЕМ ЖЕ форматом, что `mini.csv` (ключ — первый столбец, строки
# с `#` и заголовок `spectrum,` пропускаются), и уходит И прогону, И
# `score.py --only=` — двум спискам разойтись нечем, ровно как у самой базы
# (`S137`: без `--only` recall считается против ВСЕГО манифеста и ложен ПО
# ПОСТРОЕНИЮ — спектр, который НЕ ГОНЯЛИ, идёт промахом наравне с упавшим).
#
# ⛔ ЭТО ТРЕТЬЯ ВЫБОРКА, а не «малая база плюс спектр». Её числа нельзя
# сравнивать ни с объявленной малой базой, ни с полным корпусом, и переобъявлять
# ею базу НЕЛЬЗЯ: сравнение возможно только внутри одного захода, где ОБА плеча
# гнались ЭТИМ ЖЕ списком. Поэтому `-List` требует своего `-Out` и отказывается
# писать в `out_mini` — каталог объявления (`T248`).
#
# ⛔ Матрицы он, как и всё здесь, НЕ СЧИТАЕТ: добранная сцена понятной части
# требует своей матрицы в складе, иначе разбор напечатает «БЕЗ МАТРИЦЫ» строкой,
# которую в отчёте легко принять за норму непонятной части. Сцену досчитывать
# явно — в этом и вся цена добора: одна сцена стоит минут счёта, не часов.
param(
    [string]$Out = 'tools\pie\out_mini',
    [string[]]$Extra = @(),
    # Оснастка и сборка — для ПЛЕЧА с другим складом матриц. Плечо считается в
    # СВОЙ каталог матриц, кладётся в СВОЮ копию оснастки (`mx_swap.py --wd`) и
    # гоняется ею; базовый склад корпуса при этом не трогается вовсе.
    [string]$Wd = '',
    [string]$Bin = '',
    [string]$ProbeBuild = '',
    # `S138`: склад матриц ПЛЕЧА. Пустой — штатный склад корпуса. Оснастка
    # берёт матрицы из его `response`, и сторож сверяет клейма с НИМ ЖЕ, а не
    # с корпусом, — иначе плечо объявлялось бы расхождением и требовало
    # `-Force`, который сам же объявляет числа негодными для журнала.
    [string]$Store = '',
    # Уточнение Amber 10.09.2026: свой список вместо малой базы — добор
    # спектров, которых в ней нет. Пустой — штатная `corpus\mini.csv`.
    # ⛔ Третья выборка, требует своего `-Out`; подробности в шапке.
    [string]$List = '',
    [switch]$Force,
    [switch]$SkipScore
)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$lab = Split-Path -Parent $here
$root = Split-Path -Parent (Split-Path -Parent $lab)
$mini = Join-Path $lab 'corpus\mini.csv'

# ⛔ `-Out` ОБЯЗАН быть абсолютным. Проба запускается ИЗ `wd_app` и относительный
# путь трактует от СВОЕГО каталога: `-Out tools\pie\out_mini` кладёт результат в
# `wd_app\tools\pie\out_mini`, а счёт ищет его в корне дерева и падает
# «не удаётся найти путь». Поймано первым же прогоном 04.09.2026 — прогон при
# этом ПРОШЁЛ и вернул 0, то есть молчаливой эта ошибка не была только потому,
# что следом звался `score.py`.
if (-not [System.IO.Path]::IsPathRooted($Out)) {
    $Out = Join-Path $root $Out
}

# ⛔ ОТДЕЛЬНОГО СКЛАДА У МАЛОЙ БАЗЫ БОЛЬШЕ НЕТ (полоса П13, 06.09.2026).
#
# С 04.09.2026 здесь стояла своя тройка «склад + оснастка + сборка»
# (`tools\effmaker\out\mini16`, `wd_mini16`, `bin\Release_A101b`,
# `probes\build_a101b`): корпусный склад был тогда физики 15, малая база —
# физики 16, и мешать их было нельзя. 06.09.2026 склад корпуса пересчитан
# ЦЕЛИКОМ (44 сцены, физика 16, полоса П1, `E34`/`A40`) и переложен в
# `corpus/geometries` — то есть повод для отдельной тройки исчез.
#
# ⛔ И оставлять её было НЕЛЬЗЯ, а не просто незачем. Всякая матрица,
# посчитанная ДО счётного захода 06.09.2026, новым кодом отвергается по
# отпечатку — склад `mini16` в том числе. Измерено полосой П13: с ним понятная
# часть малой базы даёт матрицу у 0 из 42 спектров,
# Σχ² 567.4 вместо 556.1, recall 86 % вместо 98 %. Отказа при этом НЕ БЫВАЕТ:
# прогон проходит с кодом 0 и печатает «БЕЗ МАТРИЦЫ» строкой, которую в отчёте
# легко принять за норму непонятной части. То есть умолчание, оставленное
# как есть, тихо мерило бы не то — ровно `B20`.
#
# ⛔ ЧЕМ ИМЕННО ОТВЕРГАЕТСЯ — назван замером, и НЕ ТЕМ коммитом, что писали
# раньше (`A272`, полоса П18, развёртка по 9 сборкам плюс накладка одним
# файлом). Отвергает склад `ResponseMatrix.cs` из коммита `b2ee8207`
# (счётный заход): новый предикат `ResponseMatrix.SingleScatterErased` заставил
# клеймо писать `scat=0` там, где ветка одиночного рассеяния погашена, и всякая
# матрица со старым `scat=1` перестала сходиться. САМО ПОЛЕ `scat=` в клейме не
# ново — оно стоит там с `43c54ef4`, с появления матриц.
#
# ⚠ Прежняя формулировка «правка `E34` добавила в клеймо поле `scat=`» неверна
# дважды: поле не добавлялось, и коммит `a7aa6684` (заголовок «`E34`: недобор
# пика…») склад НЕ отвергает — на нём 42 матрицы из 42, понятная 555.9 / 100 %.
# Он ввёл `peakw=1` (пишется, только когда ключ включён; умолчание — выключено)
# и хвост `PKWT`, совместимый в обе стороны. Путаница от того, что ветку «а»
# `E34` делала полоса П1, и ЕЁ правка приехала уже внутри `b2ee8207`.
#
# Теперь умолчаний нет вовсе: склад, оснастка и сборка берутся те же, что у
# полного корпуса (`run_appwd.ps1` → `wd_app`, склад `corpus/geometries`).
# Ключи `-Store`/`-Wd`/`-Bin`/`-ProbeBuild` остались и работают — ими задаётся
# ПЛЕЧО, и задаётся ЦЕЛИКОМ: подменить один конец, оставив другой, — это и есть
# смесь поколений, которую сторож ловит по клеймам, а глазом не видно вовсе.

# `-List`: свой список вместо определения малой базы (Amber 10.09.2026).
$extended = $false
if ($List) {
    if (-not [System.IO.Path]::IsPathRooted($List)) { $List = Join-Path $root $List }
    if (-not (Test-Path $List)) { Write-Error "нет списка для -List: $List"; exit 2 }
    # ⛔ Своё имя каталога ОБЯЗАТЕЛЬНО. Прогон по ДРУГОЙ выборке, положенный в
    #    `out_mini`, — это смесь поколений, ради которой написан
    #    `check_declared_base.py`: сторож увидит расхождение с объявлением и
    #    будет прав, а виноватым окажется он.
    $decl = [System.IO.Path]::GetFullPath((Join-Path $root 'tools\pie\out_mini')).TrimEnd('\')
    if ([System.IO.Path]::GetFullPath($Out).TrimEnd('\') -eq $decl) {
        Write-Error '-List требует своего -Out: out_mini держит ОБЪЯВЛЕННУЮ малую базу'
        exit 2
    }
    $mini = $List
    $extended = $true
}

if (-not (Test-Path $mini)) {
    Write-Error "нет определения малой базы: $mini"
    exit 2
}

# Строки-комментарии начинаются с `#`, заголовок — `spectrum,...`.
$rows = Get-Content $mini | Where-Object { $_ -notmatch '^\s*#' -and $_ -notmatch '^spectrum,' -and $_.Trim() }
$keys = $rows | ForEach-Object { ($_ -split ',')[0] }
if ($keys.Count -eq 0) { Write-Error 'в mini.csv нет ни одной строки'; exit 2 }

$known = ($rows | Where-Object { ($_ -split ',')[2] -eq 'known' }).Count
$unknown = ($rows | Where-Object { ($_ -split ',')[2] -eq 'unknown' }).Count
$scenes = ($rows | ForEach-Object { ($_ -split ',')[3] } | Where-Object { $_ } | Sort-Object -Unique)

if ($extended) {
    Write-Output '=== СВОЙ СПИСОК (малая база + добор) ==='
    Write-Output ("  список: {0}" -f $mini)
} else {
    Write-Output '=== МАЛАЯ БАЗА ==='
}
Write-Output ("  спектров {0} (понятных {1}, непонятных {2}), сцен {3}: {4}" -f `
    $keys.Count, $known, $unknown, $scenes.Count, ($scenes -join ', '))
Write-Output '  ⛔ числа частей НЕ складывать; с полным корпусом НЕ сравнивать'
if ($extended) {
    Write-Output '  ⛔ ТРЕТЬЯ ВЫБОРКА: не сравнивать НИ с объявленной малой базой,'
    Write-Output '     НИ с полным корпусом; базу ею НЕ переобъявлять — только'
    Write-Output '     плечо А/Б внутри одного захода, ОБА этим же списком'
}
Write-Output ''

$sw = [Diagnostics.Stopwatch]::StartNew()
$argv = @("--only=$($keys -join ',')") + $Extra
# ⛔ Именованные параметры собираются в хеш-таблицу и уходят СПЛАТТИНГОМ: пустая
# строка, переданная как `-Wd ''`, у `run_appwd.ps1` значит «оснастка по
# умолчанию», а вот `-Force:$false` она понимает иначе, чем отсутствие ключа.
$pass = @{ Out = $Out; Extra = $argv }
if ($Wd) { $pass['Wd'] = $Wd }
if ($Bin) { $pass['Bin'] = $Bin }
if ($ProbeBuild) { $pass['ProbeBuild'] = $ProbeBuild }
if ($Store) { $pass['Store'] = $Store }
if ($Force) { $pass['Force'] = $true }
& (Join-Path $here 'run_appwd.ps1') @pass
$code = $LASTEXITCODE
$spent = $sw.Elapsed.TotalSeconds

if ($code -ne 0) {
    Write-Output ("⛔ прогон отказал, код {0}; счёт не считается" -f $code)
    exit $code
}

Write-Output ''
Write-Output ("ПРОГОН МАЛОЙ БАЗЫ: {0:N1} с" -f $spent)

if (-not $SkipScore) {
    foreach ($part in @('known', 'unknown')) {
        Write-Output ''
        Write-Output ("=== score.py --part=$part ===")
        # ⚠ `--members` ОБЯЗАТЕЛЕН: приложение раскладывает спектр на ДОЧЕРНИЕ
        #    нуклиды, а манифест говорит цепочками; без разворота каждый спектр
        #    разом промах и фантом, и счёт врёт вдвое.
        # ⛔ `--only` ОБЯЗАТЕЛЕН ЗДЕСЬ: без него recall считается против всего
        #    манифеста, и спектр, который НЕ ГОНЯЛИ, идёт промахом наравне с
        #    упавшим. Первый прогон малой базы дал так «итого 79, recall 48 %»
        #    на 42 спектрах (`S136`). Список берётся из ТОГО ЖЕ `mini.csv`, что
        #    задаёт прогон, — двум спискам разойтись было бы нечем помешать.
        & python 'tools\pie\score.py' --mode=spline "--out-dir=$Out" "--part=$part" `
            --members "--only=$mini" | Select-Object -Last 10
    }
}

exit 0
