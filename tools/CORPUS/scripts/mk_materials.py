# Как переведён `сосуд`/`проба` в элементы, когда клетка выведена из геометрии.
# Здесь только пояснение для отчёта — сам перевод делает приложение
# (`FsaSampleLibrary.HeavyElementsOf` по составу вещества из геометрии).
FROM_GEOMETRY = 'из геометрии спектра'


def read_csv(path):
    with io.open(path, encoding='utf-8-sig', newline='') as fh:
        return list(csv.DictReader(fh))


def build():
    manifest = read_csv(os.path.join(CORPUS, 'manifest.csv'))
    parts = {r['spectrum']: r for r in read_csv(os.path.join(CORPUS, 'parts.csv'))}

    rows = []
    doubts = []
    for entry in manifest:
        key = entry['key']
        det = entry['det']
        part = parts.get(key, {}).get('part', '')
        has_geometry = bool(parts.get(key, {}).get('geometry'))

        crystal, crystal_sure, crystal_why = CRYSTAL.get(det, ('', False, 'группа не описана'))
        sample, shield, sure, why = JUDGEMENT.get(key, ('', '', True, ''))

        # У спектра с геометрией кристалл берётся из неё — клетка пустая
        # НАРОЧНО. Второй источник правды здесь уже стоил бы дорого: вещество
        # кристалла задаёт энергию пиков вылета, и разойдись эти два источника,
        # линии уехали бы, а не изменились в масштабе.
        crystal_cell = '' if has_geometry else crystal

        doubt = []
        if not has_geometry and not crystal_sure:
            doubt.append('кристалл: ' + crystal_why)
        if not sure and why:
            doubt.append('проба: ' + why)

        rows.append(dict(
            spectrum=key, det=det, part=part,
            crystal=crystal_cell,
            sample=sample,
            shield=shield,
            source=(FROM_GEOMETRY if has_geometry else 'таблица mk_materials.py'),
            doubt='; '.join(doubt),
            why='; '.join(x for x in ([crystal_why] if crystal_cell else []) + ([why] if why else [])),
        ))
        if doubt:
            doubts.append((key, det, part, '; '.join(doubt)))

    return rows, doubts


