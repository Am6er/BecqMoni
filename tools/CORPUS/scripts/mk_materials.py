def main():
    rows, doubts = build()
    if '--check' in sys.argv:
        if not os.path.exists(OUT):
            sys.exit('нет %s — сначала запустите без --check' % OUT)
        have = read_csv(OUT)
        if len(have) != len(rows):
            sys.exit('в %s строк %d, а спектров %d' % (OUT, len(have), len(rows)))
        print('materials.csv: %d строк, спектров %d — сходится' % (len(have), len(rows)))
        return

    write(rows, doubts)
    print('%s: %d строк' % (OUT, len(rows)))
    print('%s: %d сомнительных клеток' % (DOUBTS, len(doubts)))
    for key, det, part, doubt in doubts:
        print('   %-24s %-10s %-8s %s' % (key, det, part, doubt))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main()
