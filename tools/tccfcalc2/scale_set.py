# -*- coding: utf-8 -*-
u"""
Поддельный набор ENSDF «Scale»: произвольная сетка энергий для TCCFCALC.

`TCCFCALC_Prepare` умеет выбрать только нуклид (A, Z, изомер), поэтому
произвольную сетку энергий EffCalcMC получает подлогом: кладёт в библиотеку
ПОДДЕЛЬНЫЙ набор (`Data\\Scale.enx`, A = 290, Z = 27, «Fake ENSDF2 B- DECAY») —
столько уровней, сколько нужно точек, каждый заселяется своей бета-ветвью и
разряжается одной гаммой прямо в основное состояние. Каскадов при такой схеме
нет, и `Eff` в отчёте — чистая эффективность в пике полного поглощения.
Внутри DLL под A = 290 есть отдельная ветка, то есть подлог предусмотрен
самими ЛСРМ.

ВАЖНО про новую DLL (2.10.1844): в этом режиме она принудительно ставит
`xrays = false`, `annihilation = false`, `angular = false`,
`calc_coincidence = false` и включает `angle_optimize` — что бы ни стояло в
файле. Для моноэнергетической сетки это безразлично (рентгена и аннигиляции в
поддельной схеме нет), но шапка отчёта показывает итог, а не файл. Подробности
— [README.md](README.md) §13.3.

Модуль перенесён сюда 08.08.2026 из `tools/tccfcalc/run_tccf.py` вместе со
сборкой старой DLL: сама старая сборка убрана (решение Amber), а подлог нужен
и новой. Настоящая библиотека новой DLL лежит в `Lib\\ENSDF` в стандартном
формате ENSDF; поддельный набор кладётся в `Lib\\ENSDF2`, которого в поставке
НЕТ, — этот каталог создаём мы.
"""
import io

FAKE_A, FAKE_Z = 290, 27

DEFAULT_ENERGIES = [40, 50, 60, 80, 100, 120, 150, 200, 250, 300, 400, 500,
                    600, 662, 800, 1000, 1250, 1461, 1800, 2200, 2614, 3000]


def write_scale(path, energies):
    u"""Собрать поддельный набор ENSDF по образцу `Data\\Scale.enx`.

    Колонки жёсткие: 1-5 номер уровня, 8 тип записи, 10-19 энергия, 22-29
    интенсивность, 56-62 коэффициент конверсии. Он выставлен в ноль нарочно:
    иначе часть переходов уйдёт в конверсионные электроны и выход перестанет
    быть тем, что мы задали.
    """
    n = len(energies)
    share = 100.0 / n
    lines = []
    lines.append("%03dXX   *Fake ENSDF2 B- DECAY" % FAKE_A)
    lines.append("%03d %2d I    %2d        %2d         0        %2d         1"
                 % (FAKE_A, FAKE_Z, n + 1, n, n))
    lines.append("       N 1.0         1.0       1.0       1.0")
    lines.append("%03dCO  P 0.0" % FAKE_A)
    lines.append("    1  L 0.0")
    for i, energy in enumerate(energies, start=2):
        # 1-5 номер, 8 тип, 10-19 энергия, 20-21 её погрешность (пусто),
        # 22-29 интенсивность, 56-62 коэффициент конверсии
        lines.append("%5d  L %-10.4f" % (i, energy))
        lines.append("       B %-10.4f  %-8.4f" % (0.0, share))
        lines.append("    1  G %-10.4f  %-8.4f%26s%-7s"
                     % (energy, share, "", "0.0"))
    with io.open(path, "w", encoding="latin-1", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
