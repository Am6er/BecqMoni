def enable_members():
    """Развернуть цепочки в дочерние нуклиды (состав приложения)."""
    for chain, members in CHAIN_MEMBERS.items():
        fam = FAMILY.get(chain, chain)
        for member in members:
            # Столкновений быть не должно: радиевая ветвь названа один раз.
            # Если появится — молчать нельзя, иначе дочерний уедет в чужое
            # семейство и станет то промахом, то фантомом.
            if MEMBER_FAMILY.get(member, fam) != fam:
                sys.exit('дочерний %s принадлежит двум семействам: %s и %s'
                         % (member, MEMBER_FAMILY[member], fam))
            MEMBER_FAMILY[member] = fam


def read_only(spec):
    """Множество ключей из `--only`: список через запятую либо файл (`S136`).

    Файл читается как csv/txt, где ключ — ПЕРВЫЙ столбец; строки, начинающиеся
    с `#`, и заголовок `spectrum,...` пропускаются. Так один и тот же
    `corpus/mini.csv` служит и определением базы, и её списком для счёта: два
    списка разошлись бы молча, а одного разойтись не с чем.
    """
    if os.path.exists(spec):
        names = set()
        with io.open(spec, encoding='utf-8-sig') as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith('#'):
                    continue
                key = line.split(',')[0].strip()
                if not key or key == 'spectrum':
                    continue
                names.add(key)
        return names
    return {x.strip() for x in spec.split(',') if x.strip()}


def load_parts():
    """Спектр -> часть корпуса (known / unknown / excluded)."""
    parts = {}
    if not os.path.exists(PARTS):
        return parts
    with open(PARTS, encoding='utf-8-sig', newline='') as fh:
        for row in csv.DictReader(fh):
            if row.get('spectrum'):
                parts[row['spectrum']] = row['part']
    return parts


def load_resolutions():
    """Группа -> ПШПВ на 662 кэВ, % (последняя колонка detectors.csv)."""
    res = {}
    with open(DETECTORS, encoding='utf-8-sig') as fh:
        for row in csv.reader(fh):
            if len(row) < 2 or not row[0] or row[0].startswith('#'):
                continue
            try:
                res[row[0]] = float(row[-1])
            except ValueError:
                continue          # строка заголовка
    return res


def load_truth():
    truth = {}
    with open(MANIFEST, encoding='utf-8-sig') as fh:
        for row in csv.DictReader(fh):
            comps = set()
            for ch in (row['chains'] or '').split(';'):
                ch = ch.strip()
                if not ch:
                    continue
                if ch not in CHAIN_MAP:
                    sys.exit('манифест: неизвестная цепочка %r у %s' % (ch, row['key']))
                comps.update(CHAIN_MAP[ch])
            for nu in (row['nuclides'] or '').split(';'):
                nu = nu.strip()
                if not nu:
                    continue
                if nu not in NUCLIDE_MAP:
                    # Молчать нельзя: пропущенный нуклид не просто выпадает из
                    # recall — он же появляется в разложении и считается там
                    # фантомом, то есть обе мерки едут в разные стороны разом.
                    sys.exit('манифест: неизвестный нуклид %r у %s — допишите его '
                             'в NUCLIDE_MAP (S59)' % (nu, row['key']))
                if NUCLIDE_MAP[nu]:
                    comps.add(NUCLIDE_MAP[nu])
            truth[row['key']] = {
                'components': comps,
                'has_bg': row['background'] not in ('', 'нет', '-'),
                'det': row['det'],
            }
    return truth


def load_results(mode, out_dir):
    """(spectrum -> строки components.csv, группы из имён файлов,
    спектры с ERROR в парном *_runs.csv, chi2/ndf, невязка, ОТКАЗЫ ФОНА)."""
    suffix = '_%s_components.csv' % mode
    results = defaultdict(list)
    source = {}
    groups = set()
    errors = set()
    chi2 = {}
    eps = {}
    bg_rej = {}
    for name in sorted(os.listdir(out_dir)):
        if not name.endswith(suffix):
            continue
        group = name[:-len(suffix)]
        groups.add(group)
        with open(os.path.join(out_dir, name), encoding='utf-8-sig') as fh:
            for row in csv.DictReader(fh):
                spec = row['spectrum']
                if spec in source and source[spec] != name:
                    print('ВНИМАНИЕ: %s есть и в %s, и в %s — строки смешаны'
                          % (spec, source[spec], name), file=sys.stderr)
                source[spec] = name
                results[spec].append(row)
        runs = os.path.join(out_dir, '%s_%s_runs.csv' % (group, mode))
        if os.path.exists(runs):
            with open(runs, encoding='utf-8-sig') as fh:
                for row in csv.DictReader(fh):
                    if row.get('chi2ndf') == 'ERROR':
                        errors.add(row['spectrum'])
                        continue
                    try:
                        chi2[row['spectrum']] = float(row['chi2ndf'])
                    except (TypeError, ValueError):
                        pass
                    # S51: невязка модели. Колонка молодая — у прежних прогонов
                    # её нет, и это не повод падать: сводка тогда печатает
                    # только chi2/ndf, как раньше.
                    try:
                        eps[row['spectrum']] = float(row['model_residual_pct'])
                    except (TypeError, ValueError, KeyError):
                        pass
                    # S44: ФОН ПОДАН И НЕ ВЗЯТ. Колонка `bg_rejected`
                    # заведена 15.08.2026, читателя у неё до сих пор не
                    # было НИ ОДНОГО: `CorpusFsaProbe` печатает строку в
                    # свой лог, а сводка — то, по чему судят о прогоне, —
                    # молчала. Двенадцать спектров G1S разобрались без
                    # вычитания фона именно так: числа вышли ровные, и
                    # никто не спросил. Колонка молодая — у прежних
                    # прогонов её нет, и это не повод падать.
                    note = (row.get('bg_rejected') or '').strip()
                    if note:
                        bg_rej[row['spectrum']] = note
    return results, groups, errors, chi2, eps, bg_rej


def warn_members(results, members_on):
    """Сказать, если состав назван ДОЧЕРНИМИ, а считают по цепочкам.

    Ошибка старая и дорогая: выход `CorpusFsaProbe` называет состав дочерними
    нуклидами (Ac-228, Pb-212, Tl-208 — так их подписывает поиск пиков), а
    манифест — цепочками (Th-232). Без `--members` цепочка не засчитывается ни
    разу, и recall выходит примерно вдвое хуже правды. В завещаниях это
    записано словами трижды, но словами: сам скрипт молчал и выдавал ровные
    неверные числа, по которым делались выводы.

    Признак — прямой: среди названных компонентов есть ЧЛЕНЫ цепочек, которые
    сами цепочками не являются. Пусто — считают выход `tools/pie` (он раскладывает
    на цепочки), и ключ действительно не нужен.
    """
    if members_on:
        return

    daughters = set()
    for chain, members in CHAIN_MEMBERS.items():
        for member in members:
            if member not in CHAIN_MEMBERS:
                daughters.add(member)

    seen = set()
    for rows in results.values():
        for row in rows:
            name = row.get('component')
            if name in daughters:
                seen.add(name)

    if not seen:
        return

    print('⚠ СОСТАВ НАЗВАН ДОЧЕРНИМИ, А СЧИТАЕТСЯ ПО ЦЕПОЧКАМ — добавьте --members',
          file=sys.stderr)
    print('   встречены: %s%s'
          % (', '.join(sorted(seen)[:8]), ' …' if len(seen) > 8 else ''),
          file=sys.stderr)
    print('   без ключа цепочка не засчитывается ни разу: recall выйдет примерно '
          'вдвое хуже правды', file=sys.stderr)


def main():
    ap = argparse.ArgumentParser()
    # Умолчание ВЫВЕДЕНО развёрткой 23.08.2026 под нынешнюю меру доли (`S90`,
    # шапка файла): самый высокий порог, не стоящий recall ни одной части.
    ap.add_argument('--sthr', type=float, default=S_THR, help='порог доли, %%')
    ap.add_argument('--zthr', type=float, default=Z_THR, help='порог z')
    ap.add_argument('--mode', default='snip', choices=['snip', 'spline'])
    ap.add_argument('--out-dir', default=OUT,
                    help='каталог с <группа>_<режим>_{components,runs}.csv')
    ap.add_argument('--verbose', action='store_true')
    # Приборы с разрешением лучше 3 % (HPGe, CZT) — вне предмета: там пик
    # разрешается сам, и полноспектральная декомпозиция решает другую задачу.
    # Порог 0 возвращает весь корпус.
    ap.add_argument('--min-fwhm', type=float, default=0.0,
                    help='нижняя граница ПШПВ на 662 кэВ, %% (3 — только сцинтилляторы)')
    ap.add_argument('--part', default='all', choices=['all', 'known', 'unknown'],
                    help='часть корпуса по corpus/parts.csv; германий (excluded) '
                         'не считается никогда')
    ap.add_argument('--members', action='store_true',
                    help='состав назван ДОЧЕРНИМИ нуклидами (разбор приложения), '
                         'а не цепочками: развернуть цепочки манифеста в их членов')
    # ⛔ `A280`, решение Amber 10.09.2026: «Решение одно на цепочку». Умолчание
    # — поцепочечное; ключ ниже возвращает ПРЕЖНЮЮ поштучную мерку и нужен
    # ровно для плеча А/Б. Обоснование — в шапке файла.
    ap.add_argument('--per-member', action='store_true',
                    help='ПЛЕЧО А: судить порогом КАЖДОГО члена цепочки '
                         'по отдельности (мерка до A280)')
    # ⛔ ПОДМНОЖЕСТВО КОРПУСА (`S136`). Без этого ключа recall прогона по части
    # спектров ЛОЖЕН по построению: знаменатель берётся из манифеста, и спектр,
    # который НЕ ГОНЯЛИ, считается промахом наравне с упавшим. Измерено
    # 04.09.2026 первым же прогоном малой базы: 42 спектра дали «итого 79,
    # recall 48 %», где 79 — это все понятные спектры задетых групп, а 48 % —
    # доля прогнанных, а не найденных.
    #
    # ⚠ Сторож покрытия при этом НЕ отключается и отключать его нельзя: он
    # ловит спектр, который УПАЛ и не оставил строк, — иначе тот молча выпал бы
    # из recall. Ключ лишь переносит меру покрытия с манифеста на ОБЪЯВЛЕННЫЙ
    # список: спектр, названный в списке и не давший результата, по-прежнему
    # находка.
    ap.add_argument('--only', default=None,
                    help='ограничить объявленным списком: имена через запятую '
                         'либо путь к csv/txt, где ключ — первый столбец '
                         '(строки с # и заголовок пропускаются)')
    args = ap.parse_args()

    if args.members:
        enable_members()

    truth = load_truth()

    # Что вообще есть в манифесте — запоминается ДО отбора по части: иначе
    # спектр, выброшенный отбором, попадает в предупреждение «есть в
    # результатах, но не в манифесте», которое означает совсем другое (ключ
    # разошёлся с описью). Полсотни ложных строк подряд гасят настоящую.
    in_manifest = set(truth)

    # Часть корпуса. Отбор идёт ДО скоринга, потому что покрытие считается по
    # тем же строкам: спектр, выброшенный из истины, не должен всплыть в
    # «НЕТ РЕЗУЛЬТАТА».
    parts = load_parts()
    if parts:
        truth = {k: t for k, t in truth.items()
                 if parts.get(k, 'unknown') != 'excluded'
                 and (args.part == 'all' or parts.get(k, 'unknown') == args.part)}
    elif args.part != 'all':
        sys.exit('нет %s — часть корпуса выбрать нечем' % PARTS)

    # Подмножество (`S136`) — ПОСЛЕ отбора по части, чтобы «объявлено» и
    # «судится» считались в одних и тех же границах.
    if args.only:
        declared = read_only(args.only)
        if not declared:
            sys.exit('--only=%s: не нашлось ни одного имени' % args.only)
        unknown_names = sorted(declared - in_manifest)
        if unknown_names:
            print('ВНИМАНИЕ: в списке --only есть имена, которых нет в манифесте '
                  '(%d): %s' % (len(unknown_names), ', '.join(unknown_names[:5])),
                  file=sys.stderr)
        truth = {k: t for k, t in truth.items() if k in declared}
        if not truth:
            sys.exit('--only: в части «%s» не осталось ни одного спектра списка'
                     % args.part)
        print('подмножество: объявлено %d, в части «%s» судится %d'
              % (len(declared), args.part, len(truth)))
    results, groups, errors, chi2, eps, bg_rej = load_results(args.mode, args.out_dir)
    if not results:
        sys.exit('нет результатов режима %s в %s' % (args.mode, args.out_dir))

    warn_members(results, args.members)

    resolution = load_resolutions()
    if args.min_fwhm > 0.0:
        dropped = sorted(d for d, f in resolution.items() if f < args.min_fwhm)
        truth = {k: t for k, t in truth.items()
                 if resolution.get(t['det'], 0.0) >= args.min_fwhm}
        print('исключены по разрешению < %.1f %%: %s'
              % (args.min_fwhm, ', '.join(dropped) or '-'))

    # покрытие: группа, чей файл есть в результатах, обязана содержать все
    # свои спектры из манифеста — упавший спектр не оставляет строк в
    # components.csv и иначе молча выпадал бы из recall
    missing = sorted(k for k, t in truth.items()
                     if t['det'] in groups and k not in results)
    for s in sorted(results):
        if s not in in_manifest:
            print('ВНИМАНИЕ: %s есть в результатах, но не в манифесте — не скорится'
                  % s, file=sys.stderr)

    # пятая клетка (`S95`): спектров, где приборный образ пересилил ВЕСЬ
    # объявленный нуклидный состав
    per_det = defaultdict(lambda: [0, 0, 0, 0, 0])  # hits, truths, phantoms, spectra, suppressed
    total_soft = 0
    # `A279`: промахи разряда «ниже предела обнаружения», поимённо. Счёт
    # разрядов ведётся ЗДЕСЬ, а не в `per_det`: таблица по детекторам не
    # меняется ни одним знаком, и объявленные числа сравнимы побитово.
    lod_rows = []
    # `T118`: спектры, где нуклидного состава НЕТ ВОВСЕ. Разряд `ПОДАВЛЕН`
    # (`S95`) отвечает на вопрос «что больше», и ноль внутри него читается как
    # «один образ больше прочих», а не как «называть нечего». Собирается
    # отдельным списком; на recall, фантомы и счёт подавленных не влияет ничем.
    empty_rows = []
    print('режим=%s, часть корпуса=%s%s, критерий: share>=%.2f%% и z>=%.1f, '
          'решение %s (A280)'
          % (args.mode, args.part, ', состав по дочерним' if args.members else '',
             args.sthr, args.zthr,
             'ПОШТУЧНОЕ (плечо А)' if args.per_member else 'ОДНО НА ЦЕПОЧКУ'))
    print()
    print('%-22s %-28s %-34s %s' % ('спектр', 'истина', 'найдено (доля%/z)', 'вердикт'))
    for spectrum in sorted(set(results) | set(missing)):
        if spectrum not in truth:
            continue
        t = truth[spectrum]
        truth_fams = {family(c) for c in t['components']}
        acc = per_det[t['det']]

        if spectrum not in results:
            why = 'ERROR в runs.csv' if spectrum in errors else 'нет строк в components.csv'
            print('%-22s %-28s %-34s %s' % (
                spectrum, '+'.join(sorted(t['components'])) or '-', '-',
                'НЕТ РЕЗУЛЬТАТА (%s) — весь спектр в промах' % why))
            acc[1] += len(truth_fams)
            acc[3] += 1
            continue

        detected = {}
        # `A279`: компоненты, чья ДОЛЯ проходит, а `z` — нет. Это не «не
        # найден»: нуклид в разборе ЕСТЬ и назван, просто набор не позволяет
        # его различить. Разряды разводятся ниже; на recall это не влияет.
        below = {}
        # `S95`: приборные образы БОЛЬШЕ НЕ ВЫБРАСЫВАЮТСЯ молча. Прежде строка
        # `kind == 'nuisance'` просто пропускалась, и мерка по построению не
        # могла увидеть худший из исходов — когда образ прибора забирает счёт
        # у объявленного нуклида. Так прошли мимо нас `B24` (`Esc-NaI` 61 % и
        # НИ ОДНОЙ нуклидной строки у бария от бариевого источника) и
        # `G1S24_Cd109_P5` (`Xray-I` 82 % против Cd-109 14 %): recall спрашивает
        # «нуклид назван?», а не «нуклид ли объясняет спектр».
        nuisance_top = ('', 0.0)
        nuclide_sum = 0.0
        # `A280`: строки нуклидов раскладываются ПО СЕМЕЙСТВАМ ещё до порога —
        # решение принимается один раз на цепочку, а не на каждого её члена.
        fam_rows = defaultdict(list)      # семейство -> [(компонент, доля, z)]
        for row in results[spectrum]:
            share = float(row['share_pct'])
            if row['kind'] == 'nuisance':
                if (row['component'] not in SUPPRESS_EXEMPT
                        and share > nuisance_top[1]):
                    nuisance_top = (row['component'], share)
                continue
            nuclide_sum += share
            fam_rows[family(row['component'])].append(
                (row['component'], share, float(row['z'])))

        for fam, members in fam_rows.items():
            if args.per_member:
                # ПЛЕЧО А (мерка до `A280`): порог у каждого члена свой.
                for comp, share, z in members:
                    if share >= args.sthr:
                        if z >= args.zthr:
                            detected[comp] = (share, z)
                        else:
                            below[comp] = (share, z)
                continue

            # ⛔ `A280`, РЕШЕНИЕ ОДНО НА ЦЕПОЧКУ (Amber 10.09.2026, дословно:
            # «Решение одно на цепочку»). У цепочки ОДНА свободная амплитуда и
            # ОДИН `z`, проставленный каждому её члену, — значит порог судит
            # величину, которой у члена нет вовсе. Мерка спрашивала
            # `share >= sthr and z >= zthr` у КАЖДОГО, и девять членов ряда
            # отваливались разом независимо от доли: на `AS80_Charoite` одно и
            # то же z = 1.74 стояло и у `Bi-214` (70.455 %, 471.3 отсчёта в
            # пике), и у `Po-210` (0.001 %, 0.0 отсчёта).
            #
            # Доля цепочки — СУММА долей её членов: доля одного члена не
            # величина цепочки, а её кусок, и порог 0.30 % отсекал цепочку,
            # чьи одиннадцать членов дают вместе процент, ни один по
            # отдельности не набирая трети процента.
            #
            # ⚠ `z` берётся НАИБОЛЬШИЙ, и это единственное место, где пришлось
            # выйти за дословную формулировку: при связке равновесием z у всех
            # членов ОДИН И ТОТ ЖЕ, и максимум равен ему; без равновесия у
            # членов свои амплитуды и свои z, и тогда за цепочку говорит
            # лучше всех определённый её член.
            share = sum(m[1] for m in members)
            z = max(m[2] for m in members)
            if share >= args.sthr:
                if z >= args.zthr:
                    detected[fam] = (share, z)
                else:
                    below[fam] = (share, z)

        det_fams = {family(c) for c in detected}

        hits = truth_fams & det_fams
        misses = truth_fams - det_fams

        # `A279`: ПРОМАХ ПРОМАХУ РОЗНЬ — метка, а не исключение из счёта.
        # `hits` и `misses` выше НЕ ТРОГАЮТСЯ: recall остаётся прежним до
        # последней цифры (решение Amber 07.09.2026 «цена нулевая»). Здесь
        # промахи лишь РАЗМЕЧАЮТСЯ на два разряда:
        #   не найден           — компонента в разборе нет вовсе либо его доля
        #                         ниже `--sthr`;
        #   ниже предела обн.   — компонент в разборе есть, доля проходит, а
        #                         `z` ниже `--zthr`, то есть набор не позволяет
        #                         его различить.
        # Из семейства берётся член с НАИБОЛЬШИМ z — тот, что ближе всех к
        # порогу: он и говорит, чего не хватило.
        below_fams = {}
        for c, (s, z) in below.items():
            f = family(c)
            if f not in misses:
                continue                      # семейство и так засчитано
            if f not in below_fams or z > below_fams[f][2]:
                below_fams[f] = (c, s, z)
        lod = sorted(below_fams)
        notfound = sorted(misses - set(below_fams))
        phantom_comps = [c for c in detected if family(c) not in truth_fams]
        hard, soft = [], []
        for c in phantom_comps:
            if family(c) in ROOM_FAMILIES:
                soft.append(c)
            else:
                hard.append(c)

        det_str = ', '.join('%s(%.0f/%.0f)' % (c, s, z)
                            for c, (s, z) in sorted(detected.items(), key=lambda kv: -kv[1][0]))
        verdict = []
        if notfound:
            verdict.append('MISS:' + '+'.join(notfound))
        # `A279`: второй разряд промаха виден ПРЯМО В СТРОКЕ спектра и без
        # ключей — вместе с тем, чего не хватило (доля есть, z мал).
        if lod:
            def _lod_str(f):
                # Имя компонента показывается, только когда оно ОТЛИЧАЕТСЯ от
                # семейства: у цепочки под `--members` это дочерний (Ac-228 у
                # thorium), у одиночного нуклида повтор был бы шумом.
                c, s, z = below_fams[f]
                return '%s(%s%.2f%%/z%.2f)' % (f, '' if c == f else c + ' ', s, z)
            verdict.append('НИЖЕ-ПРЕДЕЛА:' + '+'.join(_lod_str(f) for f in lod))
            for f in lod:
                c, s, z = below_fams[f]
                lod_rows.append((spectrum, f, c, s, z))
        if hard:
            verdict.append('PHANTOM:' + '+'.join(sorted(hard)))
        if soft:
            verdict.append('room:' + '+'.join(sorted(soft)))
        # `S95`: сравнивается со ВСЕМ нуклидным составом, а не с крупнейшей его
        # строкой. Иначе признак кричал бы на каждой цепочке: у Th-232 доля
        # разложена по десятку дочерних, и обратное рассеяние 33 % оказывается
        # больше любой одной из них, не будучи больше их суммы.
        if nuisance_top[1] > nuclide_sum:
            # ⛔ `T118`: НУЛЬ — ЭТО ДРУГОЕ СОБЫТИЕ, И У НЕГО СВОЁ СЛОВО.
            # «Состав слабее образа» и «состава нет вовсе» — не одна беда разной
            # силы: первое говорит про разнос долей, второе про то, что назвать
            # спектр НЕЧЕМ, и это самое важное число случая. В сравнении долей
            # оно пряталось под «(61.0%>0.0%)» и читалось как «один образ больше
            # прочих». Счёт подавленных при этом НЕ меняется ни на единицу:
            # разряд — метка, а не исключение (та же мерка, что у `A279`).
            if nuclide_sum <= 0.0:
                verdict.append('СОСТАВА НЕТ:%s(%.1f%%) — нуклидных долей ноль'
                               % (nuisance_top[0], nuisance_top[1]))
                empty_rows.append((spectrum, nuisance_top[0], nuisance_top[1]))
            else:
                # Десятая доля процента нужна: у `ASN8_Th232_3000` это 45.1 против
                # 44.8, и с целыми процентами признак печатал бы «45%>45%».
                verdict.append('ПОДАВЛЕН:%s(%.1f%%>%.1f%%)'
                               % (nuisance_top[0], nuisance_top[1], nuclide_sum))
            acc[4] += 1
        if not verdict:
            verdict.append('ok')
        print('%-22s %-28s %-34s %s' % (
            spectrum, '+'.join(sorted(t['components'])) or '-', det_str or '-', ' '.join(verdict)))

        acc[0] += len(hits)
        acc[1] += len(truth_fams)
        acc[2] += len(hard)
        acc[3] += 1
        total_soft += len(soft)

    print()
    print('%-10s %8s %10s %10s %10s'
          % ('детектор', 'спектров', 'recall', 'фантомов', 'подавлен'))
    th = tt = tp = ts = tsup = 0
    for det in sorted(per_det):
        h, t_, p, n, sup = per_det[det]
        th += h; tt += t_; tp += p; ts += n; tsup += sup
        print('%-10s %8d %9.0f%% %10d %10d'
              % (det, n, 100.0 * h / t_ if t_ else 0, p, sup))
    # Итог ВСЕГДА называет свою часть: числа понятной и непонятной частей
    # относятся к разным моделям (образ с матрицей против образа из одних
    # пиков), и строка «итого» без имени части читается как корпусная.
    print('%-10s %8d %9.0f%% %10d %10d  (+%d комнатных)  часть: %s' % (
        'итого', ts, 100.0 * th / tt if tt else 0, tp, tsup, total_soft,
        args.part))
    # `A279`: РАЗБОРКА ПРОМАХОВ НА ДВА РАЗРЯДА — решение Amber 07.09.2026
    # «оставить порог 4, но развести „не найден“ и „ниже предела обнаружения“».
    #
    # Почему это метка, а не вычет: измерено 07.09.2026 (`A279`, П28), что σ
    # НЕ сломана и порог мерки не покупает ничего (фантомов 0 при любом пороге
    # от 1 до 8), — значит порог остаётся 4, и recall остаётся прежним. Но
    # промах «нуклида в разборе нет вовсе» и промах «нуклид назван, доля
    # проходит, а набора не хватило на различение» — разные события, и
    # смешивать их в одном слове `MISS` значит терять единственный признак
    # того, что мерка упёрлась в СТАТИСТИКУ, а не в модель.
    #
    # Строка печатается ВСЕГДА, в том числе нулями: разряд, который видно
    # только когда он сработал, неотличим от незаведённого (`T101`, `T76`).
    #
    # ⚠ Окно разряда узкое по построению: отсев самой модели `FsaAnalyzer.RefitZ`
    # = 3 удаляет компонент раньше мерки, поэтому «ниже предела» ловится лишь
    # при z в [3, 4). Всё, что слабее, не доживает до мерки и честно числится
    # ненайденным.
    misses_total = tt - th
    print('       ПРОМАХОВ %d: не найдено %d, ниже предела обнаружения %d'
          ' (доля >= %.2f%%, но z < %.1f) (A279)'
          % (misses_total, misses_total - len(lod_rows), len(lod_rows),
             args.sthr, args.zthr))
    for sp_name, fam, comp, share, z in lod_rows:
        print('         %-24s %-10s доля %.2f %%  z %.2f%s'
              % (sp_name, fam, share, z,
                 '' if comp == fam else '  (компонент %s)' % comp))
    # S44: ОТКАЗ ВЫЧИТАНИЯ ФОНА — отдельной строкой и ПОИМЁННО, сразу
    # под итогом. Спектр, чей фон подан и не взят, разобран по
    # неочищенному счёту: recall его не замечает (нуклид назван), chi2/ndf
    # почти не шевелится, а в состав приходит комната. Измерено впрыском
    # 25.08.2026: обрезанный до 1004 каналов фон `G1S24_K40_Mar` добавил
    # ШЕСТЬ комнатных нуклидов ряда Th-232 (31 -> 37 по части) при
    # chi2/ndf 1.475 -> 1.549 — и невязка модели при этом УЛУЧШИЛАСЬ
    # (9.1 -> 6.0 %), то есть все заглавные числа говорят «стало не хуже».
    # Считать сюда только спектры своей части: числа частей не складывают.
    rejected = sorted(k for k in bg_rej if k in truth)
    if rejected:
        print('       ФОН НЕ ВЗЯТ у %d из %d: разбор идёт по НЕВЫЧТЕННОМУ'
              ' счёту (S44)' % (len(rejected), ts))
        for k in rejected:
            print('         %-24s %s' % (k, bg_rej[k]))

    if tsup:
        # `S95`: не тонуть в подвале. Спектр, чей объявленный состав пересилен
        # приборным образом, разобран НЕВЕРНО, даже если recall его засчитал.
        print('       ПОДАВЛЕННЫХ %d: объявленный состав слабее приборного'
              ' образа — recall этого не видит (S95)' % tsup)
    # ⛔ `T118`: СОСТАВА НЕТ ВОВСЕ — своя строка, и печатается ВСЕГДА, нулём в
    # том числе. Разряд, который видно только когда он сработал, неотличим от
    # незаведённого (`T101`, `T76`); а нулевой нуклидный состав при живом
    # приборном образе — не «слабее», а «спектр назвать нечем», и это самое
    # важное число случая. Из `ПОДАВЛЕННЫХ` он НЕ вычтен: там метка, а не отбор.
    print('       СОСТАВА НЕТ ВОВСЕ у %d из %d: сумма нуклидных долей ноль,'
          ' спектр объяснён приборным образом (T118)' % (len(empty_rows), ts))
    for sp_name, image, share in empty_rows:
        print('         %-24s %-12s %.1f %%' % (sp_name, image, share))

    # χ²/ndf по тем же спектрам, что вошли в скоринг: сумма — чтобы сравнивать
    # прогоны между собой, медиана — чтобы один тяжёлый спектр не решал всё.
    scored = sorted(chi2[s] for s in chi2 if s in truth)
    if scored:
        mid = scored[len(scored) // 2] if len(scored) % 2 else \
            0.5 * (scored[len(scored) // 2 - 1] + scored[len(scored) // 2])
        # без греческих букв: консоль под cp1251 их не печатает
        print('%-10s %8d  sum chi2/ndf %.1f   медиана %.2f'
              % ('', len(scored), sum(scored), mid))

    # S51: НЕВЯЗКА МОДЕЛИ — рядом с chi2/ndf, а не вместо. Сумма для неё
    # бессмысленна (это доля, а не вклад), поэтому медиана и квартили:
    # chi2/ndf растёт со статистикой и между спектрами несравним, невязка
    # сравнима. Измерено по корпусу: r(lg отсчётов, lg chi2/ndf) = +0.72,
    # r(lg отсчётов, невязка) = -0.03.
    se = sorted(eps[s] for s in eps if s in truth)
    if se:
        def quant(p):
            i = max(0, min(len(se) - 1, int(round(p * (len(se) - 1)))))
            return se[i]
        print('%-10s %8d  model residual медиана %.1f %%   кварт. %.1f .. %.1f %%'
              % ('', len(se), quant(0.5), quant(0.25), quant(0.75)))


