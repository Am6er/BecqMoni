# -*- coding: utf-8 -*-
# П92: комментарий у печати порогов — измеренные числа (cut 1 мм, CsI 692 / NaI 620 кэВ), а не «0.7 мм / 592» по П55.
import io, sys
p = sys.argv[1]
s = io.open(p, encoding='utf-8', newline='').read()
old = ('    // Пороги рождения вторичных (production cuts) по веществам сцены — в шапку\r\n'
       '    // каждого прогона (`M12`, П92; факт П55 §5.2): умолчание cut 0.7 мм даёт в\r\n'
       '    // NaI/CsI порог явных δ-электронов ~592 кэВ, и без этой печати он невидим —\r\n'
       '    // все сверки вылета/заноса электронов идут при этом пороге. Печать, не\r\n')
new = ('    // Пороги рождения вторичных (production cuts) по веществам сцены — в шапку\r\n'
       '    // каждого прогона (`M12`, П92; факт П55 §5.2). Измерено этой печатью\r\n'
       '    // 17.09.2026: range cut 1 мм (П55 писала 0.7 по памяти), порог явных\r\n'
       '    // δ-электронов e- в CsI 692 кэВ, NaI 620 (592 — это порог e+), Al 598,\r\n'
       '    // PTFE 541; без печати он невидим — все сверки вылета/заноса электронов\r\n'
       '    // (П20/П27/П44/П55/П92) идут при этом пороге. Печать, не\r\n')
assert s.count(old) == 1, s.count(old)
s = s.replace(old, new)
io.open(p, 'w', encoding='utf-8', newline='').write(s)
print('ok')
