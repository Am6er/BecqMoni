def main():
    apply = '--apply' in sys.argv
    raw = open(README, 'rb').read()
    crlf, lf = raw.count(b'\r\n'), raw.count(b'\n')
    if crlf != lf:
        print(u'ОТКАЗ: README не CRLF-целиком (CRLF %d, LF %d)' % (crlf, lf)); return 1
    bom = raw.startswith(b'\xef\xbb\xbf')
    text = raw.decode('utf-8-sig').replace(u'\r\n', u'\n')
    new = text

    # 1, 2 — вставки перед якорями
    for i, (anchor, bullet) in enumerate(((ANCHOR_15, BULLET_15), (ANCHOR_5, BULLET_5))):
        n = new.count(anchor)
        if n != 1:
            print(u'ОТКАЗ: якорь %d найден %d раз: %s' % (i, n, anchor[:60])); return 1
        if bullet[:60] in new:
            print(u'ОТКАЗ: пункт %d уже вставлен' % i); return 1
        new = new.replace(anchor, bullet + anchor, 1)

    # 3 — объявление
    a = new.find(OLD_HEAD)
    b = new.find(CUT_TO)
    if a < 0 or b < 0 or b < a or new.count(OLD_HEAD) != 1 or new.count(CUT_TO) != 1:
        print(u'ОТКАЗ: раздел rev23 не найден ровно один раз (head %d, cut %d)' % (a, b)); return 1
    old_section = new[a:b]
    new = new[:a] + NEW_SECTION + new[b:]
    if new.count(OLD_JOURNAL) != 1:
        print(u'ОТКАЗ: ссылка на журнал П66 найдена %d раз' % new.count(OLD_JOURNAL)); return 1
    new = new.replace(OLD_JOURNAL, NEW_JOURNAL, 1)
    if u'out_rev23_' in new.replace(NEW_SECTION, u''):
        print(u'ОТКАЗ: снятая база out_rev23_* названа вне объявления'); return 1

    out = new.replace(u'\n', u'\r\n').encode('utf-8')
    if bom:
        out = b'\xef\xbb\xbf' + out
    print(u'README: %d -> %d байт; строк %d -> %d; снятый раздел rev23 — %d строк' % (len(raw), len(out), text.count(u'\n'), new.count(u'\n'), old_section.count(u'\n')))
    here = os.path.dirname(os.path.abspath(__file__))
    with io.open(os.path.join(here, 'readme_section_rev23_removed.md'), 'w', encoding='utf-8', newline='') as fh:
        fh.write(old_section)
    if apply:
        open(README, 'wb').write(out)
        chk = open(README, 'rb').read()
        print(u'записано; CRLF %d = LF %d: %s' % (chk.count(b'\r\n'), chk.count(b'\n'), chk.count(b'\r\n') == chk.count(b'\n')))
    return 0


if __name__ == '__main__':
    for s in (sys.stdout, sys.stderr):
        try:
            s.reconfigure(encoding='utf-8', errors='replace')
        except Exception:
            pass
    sys.exit(main())
