# -*- coding: utf-8 -*-
r"""П99 — второй проход по README корпуса: числа сверки с аттестацией после +7 мм, заглушка изм/ожид точки 50 мм.
  python edit_readme_parts2.py <README.md>
"""
import sys

path = sys.argv[1]
raw = open(path, 'rb').read()
bom = raw.startswith(b'\xef\xbb\xbf')
text = raw.decode('utf-8-sig')
crlf = '\r\n' in text
text = text.replace('\r\n', '\n')

REPS = [
 ("  завышение, растущее с приближением источника: 25 см +9 %, 5 см +33 %, сосуды\n  +21…+50 %. Обвязка не добывается (решение Amber 14.08.2026 «не будет», `E15`):\n  завышение остаётся измеренным свойством понятной части, активности по её кривым\n  читать с этой оговоркой;\n",
  "  завышение, растущее с приближением источника: у сосудов +23…+47 % (медианы по\n  геометриям: Дента 1.47, Петри 1.29, маринелли 1.23); у точечных сцен после поправки\n  +7 мм (`S170`/`B30`, 18.09.2026) — 25 см **+3 %** (медиана 1.027, было 1.083), 5 см\n  **+10 %** (1.104, было 1.341). Обвязка не добывается (решение Amber 14.08.2026 «не\n  будет», `E15`): завышение остаётся измеренным свойством понятной части, активности по\n  её кривым читать с этой оговоркой;\n"),
 ("* **Уровень кривых ближней зоны у G1S завышен** (25 см +9 %, 5 см +33 %, сосуды\n  +21…+50 %; обвязка пресета заимствована, `E15` — «не будет»). На разложение со\n",
  "* **Уровень кривых ближней зоны у G1S завышен** (сосуды +23…+47 %; точечные после\n  +7 мм — 25 см +3 %, 5 см +10 %, до 18.09.2026 было +8 % и +34 %; обвязка пресета\n  заимствована, `E15` — «не будет»). На разложение со\n"),
 ("  RC103_50MM_RATIO с зазором) — на контакте есть ещё положение\n",
  "  **1.19** с зазором 3.5 мм, rev29) — на контакте есть ещё положение\n"),
]
for a, b in REPS:
    n = text.count(a)
    if n != 1:
        sys.stderr.write(u'⛔ якорь встречается %d раз: %r\n' % (n, a[:80]))
        sys.exit(1)
    text = text.replace(a, b)
out = text.replace('\n', '\r\n') if crlf else text
data = out.encode('utf-8')
if bom:
    data = b'\xef\xbb\xbf' + data
open(path, 'wb').write(data)
print(u'README: правок %d' % len(REPS))
