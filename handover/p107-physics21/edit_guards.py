def sub(rel, old, new):
    p = WT + '\\' + rel.replace('/', '\\')
    b = io.open(p, 'rb').read()
    crlf = b.count(b'\r\n')
    t = b.decode('utf-8').replace('\r\n', '\n')
    assert old in t, (rel, old[:70])
    assert t.count(old) == 1, (rel, 'not unique')
    t = t.replace(old, new, 1)
    out = t.replace('\n', '\r\n') if crlf else t
    io.open(p, 'wb').write(out.encode('utf-8'))
    print(rel, 'ok')


