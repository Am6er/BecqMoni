# П16 11.09.2026: кривые относительного света на фотон r(E) (свет пика / E), NaI:Tl.
# Три источника:
#   model — собственная фотонная кривая модели (LightScaleProbe, G1S_point5, 200k историй, П14,
#           handover/p14-anchor-poly/lightscale_g1s_point5.txt); нормировка — свет электрона 662 кэВ = 1.
#   lit   — Ходюк 2010 (JAP 107, 113513; arXiv:1102.3799), ДОСЛОВНЫЕ числа текста, 9…100 кэВ,
#           нормировка 662 кэВ = 1, числа из текста статьи (раздел результатов): 100 кэВ 111.2 %, 50 кэВ 115.8 %
#           (между ними по тексту линейно), минимум K-провала 114.1 % на 34.5 кэВ, 20 кэВ 117.2 %, 9 кэВ 111.5 %;
#           10 кэВ 112 % — Ходюк—Доренбос 2012 (arXiv:1204.4350), табл. I.
#           ВЫШЕ 100 кэВ у Ходюка чисел нет (синхротрон 9…100 кэВ, 662 — нормировка) — две достройки:
#           litA — форма модели, растянутая множителем k так, чтобы r(100) сошёлся с 111.2 %:
#                  r = 1 + k·(r_model(E)/r_model(662) − 1), k = 0.112 / (r_model(100)/r_model(662) − 1);
#           litB — избыток r−1 падает линейно по ln E от +0.112 (100 кэВ) до 0 (662), выше 662 — форма
#                  модели (нормированная на 662).
import math

MODEL_RAW = [  # (E, свет пика/E) — lightscale_g1s_point5.txt, П14
    (22.0, 1.1321), (31.0, 1.1020), (35.0, 1.1062), (40.0, 1.1042), (53.0, 1.0887), (59.5, 1.0747),
    (81.0, 1.0601), (88.0, 1.0550), (122.0, 1.0388), (166.0, 1.0285), (245.0, 1.0206), (344.0, 1.0161),
    (356.0, 1.0157), (511.0, 1.0116), (662.0, 1.0091), (835.0, 1.0073), (964.0, 1.0062),
    (1173.0, 1.0051), (1332.0, 1.0044), (1408.0, 1.0042), (2614.0, 1.0021),
]

KHODYUK = [  # дословные точки Ходюка 2010/2012, r относительно 662
    (9.0, 1.115), (10.0, 1.12), (20.0, 1.172), (34.5, 1.141), (50.0, 1.158), (100.0, 1.112),
]
# Между 20 и 34.5 у Ходюка словами: «drop in the range 30-45 keV» — то есть до 30 кэВ кривая держится
# у значения 20 кэВ; K-край иода 33.169. Достройка (не дословно): 30 кэВ 1.170, 33.0 кэВ 1.160.
KHODYUK_FILL = [(30.0, 1.170), (33.0, 1.160), (45.0, 1.158)]


def interp_loglog(table, e):
    """Кусочно-линейная интерполяция по ln E; вне таблицы — крайние значения."""
    if e <= table[0][0]:
        return table[0][1]
    if e >= table[-1][0]:
        return table[-1][1]
    for i in range(1, len(table)):
        e0, r0 = table[i - 1]
        e1, r1 = table[i]
        if e <= e1:
            t = (math.log(e) - math.log(e0)) / (math.log(e1) - math.log(e0))
            return r0 + (r1 - r0) * t
    return table[-1][1]


def r_model(e):
    return interp_loglog(MODEL_RAW, e)


R_MODEL_662 = r_model(662.0)


def r_model_norm(e):
    return r_model(e) / R_MODEL_662


K_LIT = 0.112 / (r_model_norm(100.0) - 1.0)

_LIT_LOW = sorted(KHODYUK + KHODYUK_FILL)


def r_litA(e):
    if e <= 100.0:
        return interp_loglog(_LIT_LOW, e)
    return 1.0 + K_LIT * (r_model_norm(e) - 1.0)


def r_litB(e):
    if e <= 100.0:
        return interp_loglog(_LIT_LOW, e)
    if e <= 662.0:
        return 1.0 + 0.112 * (math.log(662.0) - math.log(e)) / (math.log(662.0) - math.log(100.0))
    return r_model_norm(e)


CURVES = {'model': r_model, 'litA': r_litA, 'litB': r_litB}


def chord_miss(r, e, e1, e2):
    """Промах линии E над хордой через E1 и E2 (прямая по свету), кэВ."""
    h = e * r(e)
    h1 = e1 * r(e1)
    h2 = e2 * r(e2)
    return (h - h1) * (e2 - e1) / (h2 - h1) + e1 - e


def s_light(r, e, e0=661.657):
    """s(E) = E·r(E)/r(E0) − E — сдвиг положения пика в шкале, откалиброванной по E0, кэВ."""
    return e * r(e) / r(e0) - e


