        Correction Compute(FsaComponent component)
        {
            int count = component.Lines.Count;
            double[] factors = new double[count];
            for (int i = 0; i < count; i++)
            {
                factors[i] = 1.0;
            }

            List<SumPeak> sumPeaks = new List<SumPeak>();
            List<SumPeak> dropped = new List<SumPeak>();
            List<SumContinuum> continua = new List<SumContinuum>();
            List<LineNote> notes = new List<LineNote>();
            bool any = false;

            // Пары совпадений живут ВНУТРИ одного нуклида: у компонента-цепочки
            // линии разных дочерних, и мешать их каскады нельзя.
            foreach (string nuclide in DistinctNuclides(component))
            {
                NuclideData data = Data(nuclide);
                if (data == null)
                {
                    continue;
                }

                // Масштаб нормировки: интенсивности компонента даны на распад
                // РОДИТЕЛЯ цепочки, база — на распад самого нуклида. Отношение
                // берётся по самой сильной сошедшейся линии; в CF оно
                // сокращается, а площади сумм-пиков без него уехали бы.
                double scale = Scale(component, nuclide, data);
                double strongest = 0.0;
                for (int i = 0; i < count; i++)
                {
                    FsaLine line = component.Lines[i];
                    if (!Belongs(line, nuclide))
                    {
                        continue;
                    }

                    double area = line.Intensity / 100.0 * this.PeakEfficiency(line.Energy);
                    if (area > strongest)
                    {
                        strongest = area;
                    }

                    double baseEnergy;
                    if (!Match(data.Intensity, line.Energy, out baseEnergy))
                    {
                        continue;
                    }

                    // В образ идёт ОБРАТНАЯ величина: см. Correction.LineFactors.
                    double loss, inShare, direct;
                    double cf = this.CoincidenceFactor(data, baseEnergy,
                                                       out loss, out inShare, out direct);
                    notes.Add(new LineNote
                    {
                        Nuclide = nuclide,
                        EnergyKev = line.Energy,
                        Cf = cf,
                        Loss = loss,
                        InShare = inShare,
                        DirectArea = direct
                    });

                    if (cf > 0.0 && Math.Abs(cf - 1.0) > 1.0E-6)
                    {
                        factors[i] = 1.0 / cf;
                        any = true;
                    }
                }

                // Суммы нуклида собираются в СВОЙ список: срез по площади
                // (`SumPeakAreaShare`, решение Amber 17.09.2026) меряется от
                // суммарной площади сумм-пиков ЭТОГО нуклида, а не компонента.
                var nuclidePeaks = new List<SumPeak>();
                var nuclideDropped = new List<SumPeak>();
                this.CollectSumPeaks(component, nuclide, data, scale, strongest, nuclidePeaks,
                                     continua, nuclideDropped);
                TrimByArea(nuclidePeaks, nuclideDropped);
                sumPeaks.AddRange(nuclidePeaks);
                dropped.AddRange(nuclideDropped);
            }

            if (sumPeaks.Count > 0)
            {
                any = true;
                // Порядок — по убыванию площади, как и печатает `Describe`;
                // счёту он безразличен.
                sumPeaks.Sort((a, b) => b.Area.CompareTo(a.Area));
            }

            if (continua.Count > 0)
            {
                any = true;
            }

            return new Correction
            {
                LineFactors = factors,
                SumPeaks = sumPeaks,
                DroppedSumPeaks = dropped,
                SumContinua = continua,
                Notes = notes,
                Any = any
            };
        }

        /// <summary>
        /// CF одной линии по формуле EFFTRAN — в принятом смысле: во столько
        /// раз наблюдённая площадь МЕНЬШЕ истинной (A_ист = A_набл · CF).
        /// Больше единицы — суммирование выносит из пика больше, чем вносит.
        /// </summary>
        /// <summary>
        /// Потолок поправки: при нём образ линии множится на 1e-6, что для
        /// фита неотличимо от «линии нет». Величина не физическая, а
        /// численная — см. возврат <see cref="CoincidenceFactor"/>.
        /// </summary>
        const double MaxCoincidenceFactor = 1.0E6;

        double CoincidenceFactor(NuclideData data, double energy)
        {
            double loss, inShare, direct;
            return this.CoincidenceFactor(data, energy, out loss, out inShare, out direct);
        }

        /// <summary>
        /// То же с раскладкой на составляющие — для отчёта
        /// (<see cref="Describe"/>). Один и тот же счёт, две подписи: копия
        /// формулы ради печати однажды разошлась бы с той, по которой считают.
        /// </summary>
        double CoincidenceFactor(NuclideData data, double energy,
                                 out double loss, out double inShare, out double direct)
        {
            loss = 0.0;
            inShare = 0.0;
            direct = 0.0;

            double intensity;
            if (!data.Intensity.TryGetValue(energy, out intensity) || !(intensity > 0.0))
            {
                return 1.0;
            }

            // Вынос: любой партнёр, оставивший в кристалле хоть что-нибудь,
            // уносит событие из пика. Нужна вероятность ОБЪЕДИНЕНИЯ «хоть один
            // зарегистрирован», и считается она через выживание.
            loss = 1.0 - this.SurviveAll(data, Partners(data, energy), SupplyOf(data, energy),
                                         this.LossJointFactor ? energy : 0.0, energy);

            // Влёт: пары, сумма которых попадает в окно этой линии. Сравнивается
            // ВИДИМАЯ сумма (по свету, S20) — окно задано на шкале прибора, а
            // сумма встаёт на неё сдвинутой на единицы кэВ.
            double sumIn = 0.0;
            foreach (double[] pair in data.Pairs)
            {
                if (Math.Abs(this.ApparentSum(pair[0], pair[1]) - energy) >= SumWindowKev)
                {
                    continue;
                }

                sumIn += this.PairArea(data, pair);
            }

            direct = intensity / 100.0 * this.PeakEfficiency(energy);
            inShare = direct > 0.0 ? sumIn / direct : 0.0;

            // Знаменатель — ДОЛЯ ВЫЖИВШИХ в полном пике: именно она уходит
            // в образ (`factors[i] = 1 / cf`, см. Correction.LineFactors).
            double denominator = (1.0 - loss) + inShare;

            // ⛔ ПРЕЖДЕ ЗДЕСЬ СТОЯЛО `: 1.0`, И ЭТО БЫЛО НАОБОРОТ (`S144`).
            // Ноль знаменателя означает «из полного пика не выжило ничего»,
            // то есть линия обязана ИСЧЕЗНУТЬ из образа; возврат единицы
            // оставлял её нетронутой — поправка молча выключалась ровно там,
            // где она сильнейшая. Потолок нужен лишь затем, чтобы вместо
            // бесконечности в образ ушёл множитель 1e-6, то есть та же
            // исчезнувшая линия, но без NaN дальше по счёту.
            return denominator > 0.0
                ? Math.Min(1.0 / denominator, MaxCoincidenceFactor)
                : MaxCoincidenceFactor;
        }

        /// <summary>
        /// Срез сумм-пиков одного нуклида ПО ПЛОЩАДИ (`S176`, решение Amber
        /// 17.09.2026 «Срез по площади: держать 99 % Σ»): <paramref name="peaks"/>
        /// сортируется по убыванию площади, и в образе остаётся начальный
        /// отрезок, набравший <see cref="SumPeakAreaShare"/> от Σ площади
        /// кандидатов (самих <paramref name="peaks"/> — пар и троек, прошедших
        /// свои пороги; подпороговое, уже лежащее в <paramref name="dropped"/>,
        /// в Σ не входит — довод у константы), но не длиннее
        /// <see cref="MaxSumPeaks"/>. Хвост переезжает в
        /// <paramref name="dropped"/> с пометкой <see cref="SumPeak.Trimmed"/>
        /// и печатается `Describe` как «(не в образе: срез)»: срезанное не
        /// пропадает, отчёт обязан назвать, почему суммы нет в образе (П90).
        /// </summary>
        static void TrimByArea(List<SumPeak> peaks, List<SumPeak> dropped)
        {
            if (peaks.Count == 0)
            {
                return;
            }

            double total = 0.0;
            foreach (SumPeak peak in peaks)
            {
                total += peak.Area;
            }

            peaks.Sort((a, b) => b.Area.CompareTo(a.Area));
            double target = total * SumPeakAreaShare;
            double cumulative = 0.0;
            int keep = 0;
            while (keep < peaks.Count && keep < MaxSumPeaks)
            {
                cumulative += peaks[keep].Area;
                keep++;
                if (cumulative >= target)
                {
                    break;
                }
            }

            if (keep < peaks.Count)
            {
                List<SumPeak> tail = peaks.GetRange(keep, peaks.Count - keep);
                foreach (SumPeak peak in tail)
                {
                    peak.Trimmed = true;
                }

                dropped.AddRange(tail);
                peaks.RemoveRange(keep, peaks.Count - keep);
            }
        }

        /// <summary>
        /// Сумм-пики нуклида: пары, чья сумма НЕ попала ни в одну линию этого
        /// компонента. Попавшие уже учтены влётом в CF той линии, и ставить их
        /// вторично значило бы посчитать одно и то же дважды.
        /// </summary>
        void CollectSumPeaks(FsaComponent component, string nuclide, NuclideData data,
                             double scale, double strongest, List<SumPeak> sumPeaks,
                             List<SumContinuum> continua, List<SumPeak> dropped)
        {
            if (!(scale > 0.0))
            {
                return;
            }

            double floor = strongest * SumPeakFloor;

            // ⛔ У ТРОЕК СВОЙ ПОРОГ, И СЧИТАЕТСЯ ОН ОТ СИЛЬНЕЙШЕЙ ПАРЫ
            // (`S113`, решение Amber 10.09.2026 вопросником: «Свой порог
            // тройкам»).
            //
            // Прежде тройная площадь судилась тем же `floor`, что и парная, —
            // долей от сильнейшей ЛИНИИ компонента. Но тройная меньше парной
            // ровно на `третий.Value · ε_p(третьего)`, то есть на порядок-два,
            // и порог срезал их ВСЕ: журнал `LogTriples` на `ASN16_Lu176`
            // показал 13 029 рассмотренных троек и НОЛЬ прошедших, а у самой
            // близкой (603.35 = 201.82+88.35+306.88) площадь 4.009E-6 против
            // порога 4.557E-6 — ниже на 12 %. Механизм жил с 13.08.2026 и всё
            // это время был мёртв целиком.
            //
            // Мерка тройки — сильнейшая ПАРНАЯ сумма того же компонента: она
            // одного рода с тройкой (обе — суммы, обе несут эффективности), и
            // отношение «тройная к сильнейшей парной» отвечает на тот же
            // вопрос, на который у пар отвечает доля от сильнейшей линии.
            //
            // ⚠ Правка трогает ТОЛЬКО тройки: `floor` парных остаётся прежним
            // бит в бит, и цена ограничена вкладом троек — по Geant4 это 0.8 %
            // от суммы пары (четыре события из 200 000 на тройную 596.95).
            double strongestPair = 0.0;
            foreach (double[] pair in data.Pairs)
            {
                double pairArea = scale * this.PairArea(data, pair);
                if (pairArea > strongestPair)
                {
                    strongestPair = pairArea;
                }
            }

            double tripleFloor = strongestPair * SumPeakFloor;
            foreach (double[] pair in data.Pairs)
            {
                // Энергия сумм-пика — ВИДИМАЯ (по свету, S20): именно на это
                // место шкалы событие ложится, и именно с этим местом надо
                // сверять окна линий компонента.
                double energy = this.ApparentSum(pair[0], pair[1]);
                if (this.PeakEfficiency(energy) <= 0.0)
                {
                    continue;
                }

                bool absorbed = false;
                foreach (FsaLine line in component.Lines)
                {
                    if (Belongs(line, nuclide) && Math.Abs(line.Energy - energy) < SumWindowKev)
                    {
                        absorbed = true;
                        break;
                    }
                }

                if (absorbed)
                {
                    continue;
                }

                double area = scale * this.PairArea(data, pair);
                if (area > floor)
                {
                    sumPeaks.Add(new SumPeak(energy, area, nuclide, pair[0], pair[1]));
                }
                else if (area > 0.0)
                {
                    // Ниже порога — в образ не идёт, но в отчёте называется.
                    dropped.Add(new SumPeak(energy, area, nuclide, pair[0], pair[1]));
                }

                this.CollectTripleSums(component, nuclide, data, pair, scale, tripleFloor, sumPeaks,
                                       continua);
            }
        }

        /// <summary>
        /// Тройные суммы пары (S19). Множитель выживания `S_ij` вычитает из пары
        /// те случаи, когда третий квант каскада тоже попал в кристалл, и до
        /// 13.08.2026 вычтенное просто пропадало. Между тем часть его —
        /// ε_p(m) из ε_T(m) — это ПОЛНОЕ поглощение третьего, то есть свой пик
        /// на E_i+E_j+E_m. Мерено на Lu-176: сумма всех трёх (88.34+201.83+306.78)
        /// стоит отдельным пиком на пустом месте, и модель его не ставила вовсе.
        ///
        /// Остаток `ε_T(m) − ε_p(m)` — частичное поглощение третьего — по-прежнему
        /// пропадает: он даёт не пик, а сплошной подъём между E_i+E_j и
        /// E_i+E_j+E_m, и для него нужен отдельный образ (вторая половина S19).
        /// </summary>
        /// <param name="floor">
        /// Порог ТРОЕК (`S113`): доля от сильнейшей ПАРНОЙ суммы компонента, а
        /// не от сильнейшей линии. Порог пар сюда не годится — тройная меньше
        /// парной на `ε_p(третьего)`, и общим порогом их срезало все до одной.
        /// Считает его <see cref="CollectSumPeaks"/>, там же и довод.
        /// </param>
        void CollectTripleSums(FsaComponent component, string nuclide, NuclideData data,
                               double[] pair, double scale, double floor, List<SumPeak> sumPeaks,
                               List<SumContinuum> continua)
        {
            double baseArea = this.PairBase(data, pair);
            if (!(baseArea > 0.0))
            {
                return;
            }

            double pairEnergy = this.ApparentSum(pair[0], pair[1]);
            HashSet<double> thirdSupply;
            foreach (KeyValuePair<double, double> third
                     in this.PairThird(data, pair[0], pair[1], out thirdSupply))
            {
                double peakThird = this.PeakEfficiency(third.Key);
                double totalThird = this.TotalEfficiency(third.Key);

                // Частичное поглощение третьего кванта — сумм-континуум (S19,
                // вторая половина). Именно эту долю `S_ij` вычитал и терял:
                // пика она не даёт, но и в нуль не обращается. Вес идёт БЕЗ
                // эффективности третьего — она придёт из строки матрицы.
                if (totalThird > peakThird && third.Value > 0.0 && baseArea > 0.0)
                {
                    continua.Add(new SumContinuum(pairEnergy, third.Key,
                                                  scale * baseArea * third.Value, nuclide));
                }

                if (!(peakThird > 0.0))
                {
                    continue;
                }

                // κ пары уже внутри `baseArea`; третий квант идёт БЕЗ
                // поправки — для тройки нужна своя, трёхчастичная, а её никто
                // не мерил. Занижение названное: тройные суммы срезает порог
                // все до одной (`S113`), их вклад 0.8 % от суммы пары.
                double area = scale * baseArea * third.Value * peakThird;
                double energy = this.ApparentSum(pair[0], pair[1], third.Key);
                if (LogTriples)
                {
                    TripleLog.Add(string.Format(CultureInfo.InvariantCulture,
                        "  {0,9:F2} = {1:F2}+{2:F2}+{3:F2}  {4,-8}  площадь {5:E3}  порог {6:E3}  {7}",
                        energy, pair[0], pair[1], third.Key, nuclide, area, floor,
                        area > floor ? "проходит" : "НИЖЕ ПОРОГА"));
                }

                if (!(area > floor))
                {
                    continue;
                }

                if (this.PeakEfficiency(energy) <= 0.0)
                {
                    continue;
                }

                // Та же защита от двойного счёта, что у пар: сумма, попавшая в
                // окно линии компонента, уже учтена влётом в CF этой линии.
                bool absorbed = false;
                foreach (FsaLine line in component.Lines)
                {
                    if (Belongs(line, nuclide) && Math.Abs(line.Energy - energy) < SumWindowKev)
                    {
                        absorbed = true;
                        break;
                    }
                }

                if (absorbed)
                {
                    continue;
                }

                // И защита от двойного счёта между самими тройками: пара (i,j) с
                // третьим m и пара (i,m) с третьим j дают ОДНО И ТО ЖЕ событие.
                // Держим первую встреченную — суммы уже стоят на одном месте
                // шкалы, и вторая была бы чистым удвоением.
                bool already = false;
                foreach (SumPeak have in sumPeaks)
                {
                    if (have.IsTriple && Math.Abs(have.Energy - energy) < SamePairLineKev)
                    {
                        already = true;
                        break;
                    }
                }

                if (!already)
                {
                    sumPeaks.Add(new SumPeak(energy, area, nuclide, pair[0], pair[1], third.Key));
                }
            }
        }

        /// <summary>
        /// ⚡ МНОЖИТЕЛЬ СОВМЕСТНОЙ ЭФФЕКТИВНОСТИ ПАРЫ (`S112`).
        ///
        /// Замерный рычаг перекрывает таблицу; иначе κ(E₁,E₂) берётся из матрицы,
        /// а у матрицы без таблицы он равен единице — то есть счёт до правки.
        /// </summary>
        double JointFactor(double firstKev, double secondKev)
        {
            if (JointFactorOverride > 0.0)
            {
                return JointFactorOverride;
            }

            return this.matrix != null ? this.matrix.JointFactor(firstKev, secondKev) : 1.0;
        }

        /// <summary>
        /// Площадь сумм-события пары на распад: оба кванта поглощены целиком и
        /// ТРЕТИЙ квант каскада не помешал.
        /// </summary>
        double PairArea(NuclideData data, double[] pair)
        {
            double survive = this.Survive(data, pair);
            return survive > 0.0 ? this.PairBase(data, pair) * survive : 0.0;
        }

        /// <summary>
        /// Площадь пары БЕЗ множителя выживания: оба кванта поглощены целиком, а
        /// что делает третий — ещё не решено. Отделено от <see cref="PairArea"/>
        /// ради S19: та часть, которую `S_ij` вычитает, не исчезает — при полном
        /// поглощении третьего она даёт тройной сумм-пик.
        /// </summary>
        double PairBase(NuclideData data, double[] pair)
        {
            double intensity;
            if (!data.Intensity.TryGetValue(pair[0], out intensity) || !(intensity > 0.0))
            {
                return 0.0;
            }

            // ⚡ κ СТОИТ ЗДЕСЬ, А НЕ У СУММ-ПИКА (`S112`, решение Amber
            // 09.09.2026 «сумм-пики + влёт Σ_in, одна таблица κ_pp»).
            //
            // Через `PairBase` проходят ВСЕ места, где перемножаются пиковые
            // эффективности двух квантов одного распада: площадь сумм-пика,
            // влёт `Σ_in` в `CoincidenceFactor`, тройные суммы и сумм-континуум.
            // Пока множитель стоял только у сумм-пика, одна и та же сумма была
            // поднята на 34 % как отдельный пик и НЕ поднята, когда попадала в
            // окно чужой линии, — модель спорила сама с собой.
            // ⛔ ВТОРОЙ ПОТРЕБИТЕЛЬ ИСПОРЧЕННОЙ СТРОКИ ПОСТАВКИ (`D49`), и
            // зажима у него в дереве НЕТ вовсе: доля 129 у `Ir192` множит
            // площадь сумм-события на 129, а через `inShare` поднимает и образ
            // линии, в чьё окно эта сумма попала.
            double joint = pair[2];

            // ⛔ СУДИТСЯ ДОЛЯ СОБЫТИЯ, А НЕ ЧИСЛО КВАНТОВ (`D49`, та же беда,
            // что `S147` уже вылечила в выносе). У аннигиляции величина в паре
            // — ОЖИДАЕМОЕ ЧИСЛО квантов на распад (2·доля β⁺), и для Na-22 она
            // законно равна 1.806. Зажим «в единицу», поставленный ей, срезает
            // сумм-пик 511+1274 почти вдвое.
            //
            // ⚠ ИЗМЕРЕНО, а не выведено: с зажимом в 1.0 малая база теряет на
            // четырёх спектрах Na-22 — χ²/ndf 4.5265 → 4.5528, 18.9646 →
            // 19.3547, 18.1857 → 18.3052, 57.8650 → 58.6707, Σχ² понятной
            // части 566.4 → 567.7. Ни один задетый `D49` нуклид при этом не
            // шелохнулся: правило било по здоровому.
            //
            // Делится на кратность — и величина снова становится ВЕРОЯТНОСТЬЮ,
            // для которой «больше единицы» действительно невозможно. Зажим
            // тогда ставит не 1.0, а `quanta`: максимум, физически достижимый
            // для этой пары.
            double quanta = PairQuanta(data, pair);
            double share = quanta > 0.0 ? joint / quanta : joint;
            if (share > 1.0)
            {
                // (`D49`) Тот же раздел, что и в выносе: ядерная пара приходит
                // из поставки дословно, а атомная (рентген, аннигиляция)
                // посчитана нами. ⚠ «Посчитана» не значит «безупречна»: у
                // `Ir-192` вероятность рентгена собирается из тех же
                // испорченных условных и перескакивает единицу вслед за ними.
                bool listed = IsSupply(data, pair[0], pair[1]);
                SuperUnitPairs++;
                if (listed)
                {
                    SuperUnitPairsSupply++;
                }
                else
                {
                    SuperUnitPairsDerived++;
                }

                if (share > WorstSuperUnitPair)
                {
                    WorstSuperUnitPair = share;
                    WorstSuperUnitPairKev = pair[0];
                    WorstSuperUnitPairWithKev = pair[1];
                    WorstSuperUnitPairFromSupply = listed;
                }

                if (SuperUnitPolicy == SuperUnitRule.Drop)
                {
                    return 0.0;
                }

                if (SuperUnitPolicy == SuperUnitRule.Clamp)
                {
                    joint = quanta > 0.0 ? quanta : 1.0;
                }
            }

            // (`N14`) Угловая корреляция — ЗДЕСЬ ЖЕ, где κ: через `PairBase`
            // проходят все места, где перемножаются пиковые эффективности двух
            // квантов одного распада, и множитель, поставленный только у
            // сумм-пика, спорил бы сам с собой во влёте (`S112`).
            return intensity / 100.0 * joint
                   * this.PeakEfficiency(pair[0]) * this.PeakEfficiency(pair[1])
                   * this.JointFactor(pair[0], pair[1])
                   * this.AngularFactor(data, pair);
        }

        /// <summary>
        /// Доля пар, которым третий квант каскада не помешал:
        /// `S_ij = ∏_m (1 − P(m | i∧j) · ε_T(m))` (`S144`); условная третьего
        /// при паре — ходом по схеме уровней (`S177`, <see cref="PairThird"/>).
        /// </summary>
        double Survive(NuclideData data, double[] pair)
        {
            HashSet<double> supply;
            Dictionary<double, double> third = this.PairThird(data, pair[0], pair[1], out supply);
            // (`S166`, П18) Условие «оба кванта пары в пике» — тройная
            // совместность, таблицы под неё нет; третий квант считается
            // по-прежнему, без множителя.
            return this.SurviveAll(data, third, supply, 0.0, 0.0);
        }

        /// <summary>
        /// (`S177`, 18.09.2026) ТРЕТИЙ КВАНТ ПАРЫ — УСЛОВНАЯ ПРИ ОБОИХ, ХОДОМ ПО
        /// СХЕМЕ УРОВНЕЙ, а не max(P(m|i), P(m|j)).
        ///
        /// ЧТО БЫЛО. <see cref="MergedThird"/> брал для каждого третьего m
        /// больший из двух парных условных. Для каскада i → j это точно у m
        /// ниже j и «консервативно» у m выше i, а два случая считались не тем
        /// числом вовсе: (1) m, ИСКЛЮЧАЮЩИЙ пару (альтернативная ветвь того же
        /// уровня, переход в обход j), при паре невозможен — P = 0, а max
        /// давал P(m|i) > 0; (2) K-рентген конверсии ПАРТНЁРА: `Partners[i]`
        /// несёт вакансию от конверсии j с весом P(j|i)·α_K(j), а в паре
        /// (γ_i, γ_j) партнёр вышел квантом, то есть НЕ конвертировал, и этой
        /// вакансии в событии нет. На `G1S_point5` у Eu-152 1408+122 это
        /// 0.315·ω_K·ε_T(40 кэВ) ≈ 1.8 % площади суммы (П90 §1.1), и того же
        /// порядка у 964/1112/244 + 122.
        ///
        /// ЧТО СТАЛО. Ядро снимает возбуждение одним путём вниз, и при паре
        /// (i выше j) третий квант m лежит ровно в одном из трёх мест:
        ///
        ///   * ВЫШЕ i (конечный уровень m достигает начального уровня i) —
        ///     P(m | i∧j) = P(m | i): прошлое каскада от будущего независимо
        ///     (марковость хода), берётся обратная условная, как и прежде;
        ///   * МЕЖДУ i и j (с конечного уровня i достижим начальный уровень m,
        ///     с конечного уровня m — начальный уровень j) —
        ///     P = R(T_i→F_m)·s_m·R(T_m→F_j) / R(T_i→F_j), где R — достижимость
        ///     (<see cref="CascadeAtomicData.LevelScheme.ReachOf"/>), s_m —
        ///     доля кванта m на его уровне (I_m/Σ I(1+α));
        ///   * НИЖЕ j — P = R(T_j→F_m)·s_m, то есть P(m | j) схемы;
        ///   * иначе — НОЛЬ: m и пара в одном событии не бывают.
        ///
        /// Партнёр j ищется по энергии среди уровней, достижимых с конечного
        /// уровня i (те же кандидаты и веса, из которых <see cref="RectifyBySchemes"/>
        /// сложил P(j|i)), и по ним берётся взвешенное среднее; переход i —
        /// тот, что выбран там же (<see cref="NuclideData.CarrierScheme"/>).
        /// Третьи m перебираются по ПРЕЖНЕМУ перечню — партнёрам i и j из
        /// поставки и атомным (перечень пар остаётся у поставки, П90 §3); у
        /// каждого m складываются все переходы схемы с его энергией (ближайший
        /// выход на уровень, как в <c>GammaShare</c>).
        ///
        /// K-РЕНТГЕН при паре γ+γ — <see cref="XrayGivenGammaPair"/>: захват
        /// плюс конверсия соседей T ∉ {i, j} с P(γ_T | i∧j) тем же ходом.
        /// ПАРА γ+K-РЕНТГЕН — <see cref="XrayPairThird"/>: вакансия дана, и
        /// каждый источник вакансии (захват, конверсия T) даёт третьему m
        /// свою условную; у m = T она ноль — T ушёл электроном, кванта нет.
        ///
        /// ЧЕГО НЕТ, названо: пары с аннигиляцией, носители без перехода в
        /// схеме, партнёр выше носителя или вне его хода — прежнее правило max
        /// (<see cref="PairThirdFallback"/> считает такие); второй K-рентген
        /// при паре с первым и 511 при любой паре — по-прежнему max; гейт по
        /// времени у соседей T берётся от носителя i, а не от тройки.
        /// </summary>
        Dictionary<double, double> PairThird(NuclideData data, double i, double j,
                                             out HashSet<double> supply)
        {
            string cacheKey = i.ToString("R", CultureInfo.InvariantCulture) + "|"
                              + j.ToString("R", CultureInfo.InvariantCulture);
            ThirdSet set;
            // ⚠ Под замком: когда атомных данных нет (изомер, ключи выключены),
            // `Augment` отдаёт ОБЩИЙ кэшированный объект поставки, а не копию, и
            // два разбора в разных потоках писали бы в один словарь. Набор от
            // матрицы не зависит, так что общий кэш верен по числам — опасна
            // только одновременная запись.
            lock (data)
            {
                if (data.ThirdCache == null)
                {
                    data.ThirdCache = new Dictionary<string, ThirdSet>(StringComparer.Ordinal);
                }

                if (data.ThirdCache.TryGetValue(cacheKey, out set))
                {
                    supply = set.Supply;
                    return set.Partners;
                }
            }

            string how;
            set = this.ComputeThird(data, i, j, out how);
            lock (data)
            {
                data.ThirdCache[cacheKey] = set;
            }

            supply = set.Supply;
            return set.Partners;
        }

        /// <summary>
        /// (`S177`) Сам выбор хода для пары (i, j) — без кэша: γ+K по источникам
        /// вакансии, γ+γ по схеме, иначе прежнее правило max; <paramref name="how"/>
        /// называет выбранное словами (для читателя <see cref="ThirdTable"/>).
        /// </summary>
        ThirdSet ComputeThird(NuclideData data, double i, double j, out string how)
        {
            ThirdSet set = null;
            how = "прежнее правило max";
            bool annihilation = Math.Abs(i - AnnihilationKev) < SamePairLineKev
                                || Math.Abs(j - AnnihilationKev) < SamePairLineKev;
            if (!annihilation)
            {
                if (data.XrayShare != null && data.XrayShare.ContainsKey(j))
                {
                    set = this.XrayPairThird(data, i, j);
                    if (set != null)
                    {
                        how = "γ+K по источникам вакансии";
                        lock (Gate)
                        {
                            PairThirdXray++;
                        }
                    }
                }
                else if (data.XrayShare == null || !data.XrayShare.ContainsKey(i))
                {
                    set = this.GammaPairThird(data, i, j);
                    if (set != null)
                    {
                        how = "γ+γ по схеме" + (set.Fallbacks > 0
                            ? string.Format(CultureInfo.InvariantCulture, ", у {0} третьих — прежний max", set.Fallbacks)
                            : "");
                        lock (Gate)
                        {
                            PairThirdGamma++;
                        }
                    }
                }
            }

            if (set == null)
            {
                HashSet<double> marks;
                set = new ThirdSet { Partners = MergedThird(data, i, j, out marks), Supply = marks };
                lock (Gate)
                {
                    PairThirdFallback++;
                }
            }

            return set;
        }

        /// <summary>Нижний переход пары как кандидат: уровни и вес R(T_i→F)·s.</summary>
        struct LowerCandidate
        {
            public int FromSeq;
            public int ToSeq;
            public double Weight;
        }

        /// <summary>
        /// (`S177`) Кандидаты нижнего перехода пары по энергии среди уровней,
        /// достижимых с уровня <paramref name="start"/>: вес — R(start→F)·s,
        /// в сумме ровно P(j | i) схемы (<c>GammaShare</c>). Пусто — квант
        /// такой энергии после старта не бывает.
        /// </summary>
        static List<LowerCandidate> LowerCandidates(CascadeAtomicData.LevelScheme scheme, int start,
                                                    double energyKev, out double total)
        {
            var found = new List<LowerCandidate>();
            total = 0.0;
            foreach (KeyValuePair<int, double> entry in scheme.Reach(start))
            {
                if (!(entry.Value > 0.0))
                {
                    continue;
                }

                CascadeAtomicData.LevelScheme.Exit exit =
                    scheme.NearestExit(entry.Key, energyKev, SchemeMatchKev);
                if (exit == null)
                {
                    continue;
                }

                double weight = entry.Value * scheme.GammaShareOf(entry.Key, exit);
                if (!(weight > 0.0))
                {
                    continue;
                }

                found.Add(new LowerCandidate { FromSeq = entry.Key, ToSeq = exit.ToSeq, Weight = weight });
                total += weight;
            }

            return found;
        }

        /// <summary>
        /// (`S177`) Условная одного перехода m = (fm → tm) с долей кванта
        /// <paramref name="shareM"/> при верхнем переходе (fu → tu) и нижних
        /// кандидатах <paramref name="lower"/> (взвешенных, Σ весов
        /// <paramref name="lowerTotal"/>; пусто — нижнего нет, условная при
        /// одном верхнем): «между» и «ниже» — числом, «выше» — признаком,
        /// потому что там нужна обратная условная с выходами на распад, а её
        /// знает вызывающий.
        /// </summary>
        static double Segment(CascadeAtomicData.LevelScheme scheme, int fu, int tu,
                              List<LowerCandidate> lower, double lowerTotal,
                              int fm, int tm, double shareM, ref bool above)
        {
            if (tm >= fu)
            {
                // Выше верхнего: возможен, только если его конец ведёт к началу верхнего.
                if (scheme.ReachOf(tm, fu) > 0.0)
                {
                    above = true;
                }

                return 0.0;
            }

            if (lower == null || lower.Count == 0)
            {
                // Одиночный верхний: всё, что ниже его конца.
                return fm <= tu ? scheme.ReachOf(tu, fm) * shareM : 0.0;
            }

            if (!(lowerTotal > 0.0))
            {
                return 0.0;
            }

            double sum = 0.0;
            foreach (LowerCandidate c in lower)
            {
                if (fm <= tu && tm >= c.FromSeq)
                {
                    // МЕЖДУ: путь T_u → F_m → (m) → T_m → F_j, отнесённый к T_u → F_j.
                    double denominator = scheme.ReachOf(tu, c.FromSeq);
                    if (denominator > 0.0)
                    {
                        sum += c.Weight * scheme.ReachOf(tu, fm) * shareM * scheme.ReachOf(tm, c.FromSeq)
                               / denominator;
                    }
                }
                else if (fm <= c.ToSeq)
                {
                    // НИЖЕ: с конца нижнего перехода.
                    sum += c.Weight * scheme.ReachOf(c.ToSeq, fm) * shareM;
                }
            }

            return sum / lowerTotal;
        }

        /// <summary>
        /// (`S177`) P(квант энергии <paramref name="mKev"/> | верхний (fu→tu) ∧
        /// нижние кандидаты): по всем уровням схемы с выходом этой энергии —
        /// <see cref="Segment"/>; для случая «выше верхнего» — обратная
        /// условная из `Partners` верхнего ключа (<paramref name="upperKey"/>,
        /// посчитана при загрузке как P(i|m)·I(m)/I(i)), а нет её — тем же
        /// правилом по схеме и выходам на распад.
        /// </summary>
        static double SchemeThird(NuclideData data, CascadeAtomicData.LevelScheme scheme,
                                  int fu, int tu, List<LowerCandidate> lower, double lowerTotal,
                                  double upperKey, double mKev)
        {
            double p = 0.0;
            bool above = false;
            foreach (int level in scheme.Levels)
            {
                CascadeAtomicData.LevelScheme.Exit exit = scheme.NearestExit(level, mKev, SchemeMatchKev);
                if (exit == null)
                {
                    continue;
                }

                p += Segment(scheme, fu, tu, lower, lowerTotal, level, exit.ToSeq,
                             scheme.GammaShareOf(level, exit), ref above);
            }

            if (above)
            {
                p += AboveConditional(data, scheme, fu, tu, upperKey, mKev);
            }

            return p;
        }

        /// <summary>
        /// (`S177`) P(m | верхний), когда m стоит ВЫШЕ верхнего перехода: из
        /// `Partners` верхнего ключа (там лежит обратная условная загрузки),
        /// иначе — Σ по переходам m, ведущим к началу верхнего,
        /// R(T_m→F_u)·s_u·I(m)/I(u) по выходам на распад. Нет выходов — ноль.
        /// </summary>
        static double AboveConditional(NuclideData data, CascadeAtomicData.LevelScheme scheme,
                                       int fu, int tu, double upperKey, double mKev)
        {
            Dictionary<double, double> bag;
            if (!double.IsNaN(upperKey) && data.Partners.TryGetValue(upperKey, out bag))
            {
                foreach (KeyValuePair<double, double> entry in bag)
                {
                    if (Math.Abs(entry.Key - mKev) < SamePairLineKev)
                    {
                        return entry.Value;
                    }
                }
            }

            double iu, im;
            if (double.IsNaN(upperKey) || !data.Intensity.TryGetValue(upperKey, out iu) || !(iu > 0.0)
                || !MatchIntensity(data, mKev, out im) || !(im > 0.0))
            {
                return 0.0;
            }

            CascadeAtomicData.LevelScheme.Exit upper = scheme.ExitTo(fu, tu);
            double shareU = scheme.GammaShareOf(fu, upper);
            if (!(shareU > 0.0))
            {
                return 0.0;
            }

            double p = 0.0;
            foreach (int level in scheme.Levels)
            {
                CascadeAtomicData.LevelScheme.Exit exit = scheme.NearestExit(level, mKev, SchemeMatchKev);
                if (exit == null || exit.ToSeq < fu)
                {
                    continue;
                }

                p += scheme.ReachOf(exit.ToSeq, fu) * shareU * im / iu;
            }

            return p;
        }

        /// <summary>Ключ пары для линии распада T: её ключ в таблице выходов (допуск `SameLineKev`) либо NaN.</summary>
        static double PairKeyOf(NuclideData data, double decayKev)
        {
            double key;
            return Match(data.Intensity, decayKev, out key) ? key : double.NaN;
        }

        /// <summary>
        /// (`S177`) P(γ_T | пара) для соседа T с ЯВНЫМ переходом (не по
        /// энергии): T ниже верхнего — <see cref="Segment"/> с его уровнями;
        /// T выше верхнего — обратная условная <paramref name="aboveValue"/>
        /// (при одиночном верхнем это прежнее P(T|i)); ни то ни другое — ноль.
        /// </summary>
        static double SchemeThirdOf(CascadeAtomicData.LevelScheme scheme, int fu, int tu,
                                    List<LowerCandidate> lower, double lowerTotal,
                                    CascadeAtomicData.Transition t, double aboveValue)
        {
            CascadeAtomicData.LevelScheme.Exit exit = scheme.ExitTo(t.FromSeq, t.ToSeq);
            double shareT = scheme.GammaShareOf(t.FromSeq, exit);
            if (!(shareT > 0.0))
            {
                return 0.0;
            }

            bool above = false;
            double p = Segment(scheme, fu, tu, lower, lowerTotal, t.FromSeq, t.ToSeq, shareT, ref above);
            return above ? aboveValue : p;
        }

        /// <summary>
        /// (`S177`) Третьи кванты пары γ+γ ходом по схеме (см. <see cref="PairThird"/>).
        /// Null — хода нет: у носителя нет перехода в схеме либо партнёр не
        /// лежит ниже него по ходу (тогда прежнее правило max).
        /// </summary>
        ThirdSet GammaPairThird(NuclideData data, double i, double j)
        {
            SchemeRef upper;
            if (data.CarrierScheme == null || !data.CarrierScheme.TryGetValue(i, out upper))
            {
                return null;
            }

            CascadeAtomicData.LevelScheme scheme = upper.Scheme;
            double lowerTotal;
            List<LowerCandidate> lower = LowerCandidates(scheme, upper.ToSeq, j, out lowerTotal);
            if (lower.Count == 0 || !(lowerTotal > 0.0))
            {
                return null;
            }

            LineIdentity li = null, lj = null;
            if (data.Lines != null)
            {
                data.Lines.TryGetValue(i, out li);
                data.Lines.TryGetValue(j, out lj);
            }

            var set = new ThirdSet
            {
                Partners = new Dictionary<double, double>(),
                Supply = new HashSet<double>()
            };
            foreach (double m in ThirdKeys(data, i, j))
            {
                double p;
                if (data.XrayShare != null && data.XrayShare.ContainsKey(m))
                {
                    p = this.XrayGivenGammaPair(data, scheme, upper, lower, lowerTotal, li, j, m);
                    if (double.IsNaN(p))
                    {
                        p = MaxOfSides(data, i, j, m, set.Supply);
                        set.Fallbacks++;
                    }
                }
                else if (Math.Abs(m - AnnihilationKev) < SamePairLineKev)
                {
                    p = MaxOfSides(data, i, j, m, set.Supply);
                    set.Fallbacks++;
                }
                else
                {
                    p = SchemeThird(data, scheme, upper.FromSeq, upper.ToSeq, lower, lowerTotal, i, m);
                }

                set.Partners[m] = p;
            }

            return set;
        }

        /// <summary>
        /// (`S177`) P(K-линия <paramref name="xKey"/> | γ_i ∧ γ_j): доля линии
        /// в серии · ω_K · [захват при i + Σ_{T ∉ {i, j}} P(γ_T | i∧j)·α_K(T)·вместе].
        /// Слагаемого партнёра j НЕТ — он вышел квантом; соседи — при паре, а
        /// не при одной гамме. NaN — считать нечем (нет личности носителя, её
        /// ветвь ведёт в другую схему), и вызывающий берёт прежнее правило.
        /// </summary>
        double XrayGivenGammaPair(NuclideData data, CascadeAtomicData.LevelScheme scheme,
                                  SchemeRef upper, List<LowerCandidate> lower, double lowerTotal,
                                  LineIdentity li, double jKey, double xKey)
        {
            if (li == null || li.Terms == null || li.Branch == null
                || !ReferenceEquals(CascadeAtomicData.LevelScheme.Of(li.Branch.Z, li.Branch.A), scheme))
            {
                return double.NaN;
            }

            double share;
            if (!data.XrayShare.TryGetValue(xKey, out share) || !(share > 0.0))
            {
                return double.NaN;
            }

            double vacancy = 0.0;
            vacancy += li.Capture;
            foreach (VacancyTerm term in li.Terms)
            {
                // Партнёр пары конвертировать не мог: он вышел квантом.
                if (Math.Abs(term.Kev - jKey) < SameLineKev)
                {
                    continue;
                }

                double conditional = SchemeThirdOf(scheme, upper.FromSeq, upper.ToSeq, lower, lowerTotal,
                                                   term.Transition, term.Conditional);
                if (!(conditional > 0.0))
                {
                    continue;
                }

                vacancy += conditional * term.AlphaK * term.Together;
            }

            return share * vacancy * li.OmegaK;
        }

        /// <summary>
        /// (`S177`) Третьи кванты пары γ_i + K-рентген: вакансия ДАНА, и каждый
        /// её источник u_s (захват; конверсия соседа T с весом
        /// P(T|i)·α_K(T)·вместе) даёт третьему m свою условную:
        ///
        ///     P(γ_m | i ∧ K) = [u_захв·P(m|i) + Σ_T u_T·P(m | i∧T)] / Σ u_s,
        ///
        /// где у m = T слагаемое НОЛЬ (T ушёл электроном — кванта T в событии
        /// нет; прежний max ставил сюда P(122|1408) = 0.464 при паре 1408+Kα,
        /// хотя вакансия Kα в этой паре по большей части и есть конверсия
        /// 122), а P(m | i∧T) — ход по схеме с T нижним либо верхним. Второй
        /// K-квант и 511 — прежним правилом. Null — считать нечем.
        /// </summary>
        ThirdSet XrayPairThird(NuclideData data, double i, double x)
        {
            LineIdentity li;
            if (data.Lines == null || !data.Lines.TryGetValue(i, out li) || li == null || li.Terms == null)
            {
                return null;
            }

            // Переход носителя: выбранный при замене долей, иначе — переход
            // самой строки распада (у нуклида с одной гаммой пар γ-γ нет, и
            // носителем в схеме он не бывает).
            CascadeAtomicData.LevelScheme scheme = null;
            int fi = 0, ti = 0;
            SchemeRef upper;
            if (data.CarrierScheme != null && data.CarrierScheme.TryGetValue(i, out upper))
            {
                scheme = upper.Scheme;
                fi = upper.FromSeq;
                ti = upper.ToSeq;
            }
            else if (li.Branch != null && li.Gamma != null && li.Gamma.Transition != null)
            {
                scheme = CascadeAtomicData.LevelScheme.Of(li.Branch.Z, li.Branch.A);
                fi = li.Gamma.Transition.FromSeq;
                ti = li.Gamma.Transition.ToSeq;
            }

            if (scheme == null || scheme.Count == 0
                || (li.Branch != null && !ReferenceEquals(CascadeAtomicData.LevelScheme.Of(li.Branch.Z, li.Branch.A), scheme)))
            {
                return null;
            }

            double total = li.Capture;
            foreach (VacancyTerm term in li.Terms)
            {
                total += term.Conditional * term.AlphaK * term.Together;
            }

            if (!(total > 0.0))
            {
                return null;
            }

            var set = new ThirdSet
            {
                Partners = new Dictionary<double, double>(),
                Supply = new HashSet<double>()
            };
            var single = new List<LowerCandidate>();
            foreach (double m in ThirdKeys(data, i, x))
            {
                if ((data.XrayShare != null && data.XrayShare.ContainsKey(m))
                    || Math.Abs(m - AnnihilationKev) < SamePairLineKev)
                {
                    set.Partners[m] = MaxOfSides(data, i, x, m, set.Supply);
                    continue;
                }

                // P(m | i) — из партнёров носителя, иначе по схеме.
                double pI;
                Dictionary<double, double> bag;
                if (!(data.Partners.TryGetValue(i, out bag) && bag.TryGetValue(m, out pI)))
                {
                    pI = SchemeThird(data, scheme, fi, ti, null, 0.0, i, m);
                }

                double acc = li.Capture * pI;
                foreach (VacancyTerm term in li.Terms)
                {
                    double u = term.Conditional * term.AlphaK * term.Together;
                    if (!(u > 0.0))
                    {
                        continue;
                    }

                    if (Math.Abs(term.Kev - m) < SameLineKev)
                    {
                        // Вакансия от конверсии самого m: кванта m нет.
                        continue;
                    }

                    CascadeAtomicData.Transition t = term.Transition;
                    double pMT;
                    if (scheme.ReachOf(ti, t.FromSeq) > 0.0)
                    {
                        // T ниже носителя: пара (i, T), m — третий.
                        single.Clear();
                        single.Add(new LowerCandidate { FromSeq = t.FromSeq, ToSeq = t.ToSeq, Weight = 1.0 });
                        pMT = SchemeThird(data, scheme, fi, ti, single, 1.0, i, m);
                    }
                    else if (scheme.ReachOf(t.ToSeq, fi) > 0.0)
                    {
                        // T выше носителя: пара (T, i), m — третий; «выше T» —
                        // из партнёров ключа T.
                        single.Clear();
                        single.Add(new LowerCandidate { FromSeq = fi, ToSeq = ti, Weight = 1.0 });
                        pMT = SchemeThird(data, scheme, t.FromSeq, t.ToSeq, single, 1.0,
                                          PairKeyOf(data, term.Kev), m);
                    }
                    else
                    {
                        // Схема не связывает T с носителем — судить нечем.
                        pMT = pI;
                    }

                    acc += u * pMT;
                }

                set.Partners[m] = acc / total;
            }

            return set;
        }

        /// <summary>Перечень третьих квантов пары — партнёры обоих её концов, без самих концов; порядок — первого появления.</summary>
        static List<double> ThirdKeys(NuclideData data, double i, double j)
        {
            var keys = new List<double>();
            foreach (double side in new[] { i, j })
            {
                foreach (KeyValuePair<double, double> entry in Partners(data, side))
                {
                    if (Math.Abs(entry.Key - i) < SamePairLineKev || Math.Abs(entry.Key - j) < SamePairLineKev)
                    {
                        continue;
                    }

                    if (!keys.Contains(entry.Key))
                    {
                        keys.Add(entry.Key);
                    }
                }
            }

            return keys;
        }

        /// <summary>Прежнее правило для одного третьего: max(P(m|i), P(m|j)) с меткой происхождения победителя (`D49`).</summary>
        static double MaxOfSides(NuclideData data, double i, double j, double m, HashSet<double> supply)
        {
            double best = 0.0;
            bool any = false;
            foreach (double side in new[] { i, j })
            {
                double have;
                if (!Partners(data, side).TryGetValue(m, out have))
                {
                    continue;
                }

                if (!any || have > best)
                {
                    best = have;
                    any = true;
                    HashSet<double> marks = SupplyOf(data, side);
                    if (marks != null && marks.Contains(m))
                    {
                        supply.Add(m);
                    }
                    else
                    {
                        supply.Remove(m);
                    }
                }
            }

            return best;
        }

        /// <summary>
        /// (`S177`) ЧИТАТЕЛЬ ДЛЯ ПРОБ: третьи кванты пары (i, j) нуклида
        /// прежним правилом max и новым ходом — строки {E_m, P_max, P_схемы,
        /// ε_T(m)} и оба множителя выживания S_ij (на этой матрице, без κ и
        /// корреляций — как в <see cref="Survive"/>). Пусто — нуклид не
        /// разбирается или пары нет. Положительный контроль правки: у пары с
        /// конвертированным партнёром или исключающим третьим два столбца
        /// ОБЯЗАНЫ разойтись, у пары без третьего — совпасть.
        /// </summary>
        public List<double[]> ThirdTable(string nuclide, double iKev, double jKev,
                                         out double surviveMax, out double surviveScheme, out string how)
        {
            surviveMax = 1.0;
            surviveScheme = 1.0;
            how = "";
            var rows = new List<double[]>();
            NuclideData data = this.Data(nuclide);
            if (data == null)
            {
                how = "нуклид не разбирается";
                return rows;
            }

            double i, j;
            if (!Match(data.Intensity, iKev, out i) || !Match(data.Intensity, jKev, out j))
            {
                how = "линии нет в таблице выходов";
                return rows;
            }

            HashSet<double> oldMarks;
            Dictionary<double, double> old = MergedThird(data, i, j, out oldMarks);
            // Мимо кэша: читателю нужен и сам выбор хода, а не только числа.
            // Счётчики при этом сдвигаются на единицу — читатель идёт после
            // счёта, и его строка в сводке пробы не участвует.
            ThirdSet fresh = this.ComputeThird(data, i, j, out how);
            surviveMax = this.SurviveAll(data, old, oldMarks, 0.0, 0.0);
            surviveScheme = this.SurviveAll(data, fresh.Partners, fresh.Supply, 0.0, 0.0);
            foreach (double m in ThirdKeys(data, i, j))
            {
                double a, b;
                old.TryGetValue(m, out a);
                fresh.Partners.TryGetValue(m, out b);
                rows.Add(new[] { m, a, b, this.TotalEfficiency(m) });
            }

            return rows;
        }

        /// <summary>
        /// Доля событий, в которых НЕ зарегистрирован НИ ОДИН из партнёров:
        /// `∏_j (1 − p_j)`, где `p_j = P(j|k) · ε_T(j)` (`S144`).
        ///
        /// ⛔ БЫЛО `1 − Σ p_j`, И ЭТО РАЗНЫЕ ВЕЛИЧИНЫ. Сумма маргинальных
        /// вероятностей равна вероятности объединения только у ВЗАИМНО
        /// ИСКЛЮЧАЮЩИХ событий; здесь же класс сам строит ТРОЙНЫЕ сумм-пики,
        /// то есть прямо допускает регистрацию двух партнёров сразу. Для двух
        /// независимых верно `p₁ + p₂ − p₁p₂`, а сумма учитывала пересечение
        /// дважды — тем сильнее, чем больше партнёров и чем ближе геометрия.
        ///
        /// ⛔ Вторая половина той же беды была ОТКАЗОМ БЕЗ ОТКАЗА: завышенная
        /// сумма перескакивала единицу, знаменатель `(1 − loss) + inShare`
        /// становился неположительным, и метод возвращал `CF = 1` — поправка
        /// МОЛЧА выключалась ровно там, где она сильнейшая. У произведения
        /// такого исхода нет по построению: оно лежит в [0, 1].
        ///
        /// ⚠ ПРИБЛИЖЕНИЕ НАЗВАНО: партнёры считаются независимыми при данном
        /// опорном кванте. У ВЗАИМНО ИСКЛЮЧАЮЩИХ ветвей это чуть занижает
        /// потерю (верна была бы сумма), но разводить их нечем — условные
        /// вероятности поставки не несут признака ветви. Родня: `S145`.
        /// </summary>
        double SurviveAll(NuclideData data, Dictionary<double, double> partners,
                          HashSet<double> supply, double referenceKev, double angularKev)
        {
            double survive = 1.0;
            foreach (KeyValuePair<double, double> partner in partners)
            {
                double efficiency = this.TotalEfficiency(partner.Key);
                if (!(efficiency > 0.0) || !(partner.Value > 0.0))
                {
                    continue;
                }

                // (`N14`) Угловая корреляция В ВЫНОСЕ: партнёр уносит событие,
                // куда бы он ни попал, поэтому условная вероятность его задеть
                // при опорном кванте в пике — ε_T(j)·(1 + Σ A_kk·Q_k^p(k)·Q_k^T(j))
                // с моментами ПОЛНОЙ эффективности партнёра. Именно здесь живёт
                // цена из строки (Cs-134 1365: CF 0.807 против 0.854 у ЛСРМ) —
                // сумм-пик её только показывает. Ноль опорной энергии — не
                // считается (третий квант пары, тройная совместность).
                if (angularKev > 0.0)
                {
                    efficiency = Math.Min(1.0, efficiency * this.AngularLossFactor(data, angularKev, partner.Key));
                }

                // (`S166`, П18 12.09.2026) Полная эффективность партнёра —
                // УСЛОВНАЯ на том, что опорный квант поглощён целиком:
                // ⟨ε_p(k)·ε_T(j)⟩/⟨ε_p(k)⟩ = κ_pT(k,j)·ε_T(j). Своей таблицы у
                // κ_pT нет; замер `KappaPeakTotalProbe` на двух сценах Lu-176
                // дал κ_pT = κ_pp в пределах ±2 % (1.293 против 1.289…1.293 на
                // `ASN16_lu_side`, 1.106 против 1.104…1.106 на `AS80_lu_front`),
                // поэтому берётся таблица κ_pp матрицы (`JointFactor`). Ноль
                // опорной энергии — множителя нет (прежний счёт, побитово).
                if (referenceKev > 0.0)
                {
                    efficiency = Math.Min(1.0, efficiency * this.JointFactor(referenceKev, partner.Key));
                }

                // ⛔ КРАТНОСТЬ ПАРТНЁРА (`S147`). У аннигиляции `Partners` несёт
                // не вероятность, а ОЖИДАЕМОЕ ЧИСЛО квантов (2·доля β⁺). Два
                // фотона рождаются ВМЕСТЕ, а не независимо, поэтому верная
                // потеря равна q·(1−(1−ε)ᵐ), где q — доля события, а m — число
                // квантов в нём. Прежнее `value·ε` при q = 1 и ε = 0.6 давало
                // 1.2, зажималось в единицу — «пик потерян целиком» вместо
                // верных 0.84.
                double quanta = 1.0;
                if (data != null && data.PartnerQuanta != null)
                {
                    double had;
                    if (data.PartnerQuanta.TryGetValue(partner.Key, out had) && had > 0.0)
                    {
                        quanta = had;
                    }
                }

                double share = partner.Value / quanta;
                if (share > 1.0)
                {
                    // Доля события больше единицы физически невозможна: значит
                    // поставка даёт на распад больше одного такого кванта, и
                    // осторожнее считать событие достоверным.
                    //
                    // ⚡ (`D49`) Счётчик и рычаг. Зажим — максимальный
                    // возможный вынос линии из пика, и до 10.09.2026 он стоял
                    // МОЛЧА: отличить «зажали 1820 раз» от «ни разу» было
                    // нечем.
                    //
                    // ⛔ СЧЁТЧИК РАЗДЕЛЁН НА ДВА СЛУЧАЯ, и это не украшение.
                    // Доля, СПИСАННАЯ из поставки и большая единицы, — дефект
                    // `sandia.decay.xml` (1820 пар у 99 родителей). Доля,
                    // ПОСЧИТАННАЯ нами, перескакивает единицу законно:
                    // обратная условная `P(A|B) = P(B|A)·I(A)/I(B)` при разных
                    // выходах двух линий, и дополнение атомными партнёрами.
                    // У `Co-60` поставка безупречна (0.999872), а зажим
                    // срабатывает четыре раза — сложенный счётчик послал бы
                    // чинить поставку там, где чинить нечего.
                    bool listed = supply != null && supply.Contains(partner.Key);
                    SuperUnitShares++;
                    if (listed)
                    {
                        SuperUnitSharesSupply++;
                    }
                    else
                    {
                        SuperUnitSharesDerived++;
                    }

                    if (share > WorstSuperUnitShare)
                    {
                        WorstSuperUnitShare = share;
                        WorstSuperUnitShareKev = partner.Key;
                        WorstSuperUnitShareFromSupply = listed;
                    }

                    if (SuperUnitPolicy == SuperUnitRule.Drop)
                    {
                        continue;
                    }

                    if (SuperUnitPolicy != SuperUnitRule.Raw)
                    {
                        share = 1.0;
                    }
                }

                double miss = Math.Pow(1.0 - efficiency, quanta);
                double p = share * (1.0 - miss);
                survive *= p < 1.0 ? 1.0 - p : 0.0;
            }

            return survive;
        }

        /// <summary>
        /// ЗАПАСНОЕ ПРАВИЛО третьего кванта пары (i, j) — из одних парных
        /// данных: P(m|i∧j) ≈ max(P(m|i), P(m|j)) — для каскада i→j квант ниже
        /// j воспроизводится точно, выше i консервативно, исключающий пару и
        /// рентген конверсии партнёра — завышаются. С 18.09.2026 (`S177`)
        /// рабочий путь — <see cref="PairThird"/> ходом по схеме; сюда
        /// приходят пары без схемы (изомеры, носители без перехода, партнёр
        /// вне хода, аннигиляция) — счётчик <see cref="PairThirdFallback"/>.
        /// </summary>
        static Dictionary<double, double> MergedThird(NuclideData data, double i, double j,
                                                      out HashSet<double> supply)
        {
            Dictionary<double, double> merged = new Dictionary<double, double>();

            // (`D49`) Метка происхождения едет за ПОБЕДИВШИМ значением: у
            // максимума одно происхождение, и приписывать ему чужое нельзя.
            supply = new HashSet<double>();
            foreach (double side in new[] { i, j })
            {
                HashSet<double> marks = SupplyOf(data, side);
                foreach (KeyValuePair<double, double> entry in Partners(data, side))
                {
                    if (Math.Abs(entry.Key - i) < SamePairLineKev || Math.Abs(entry.Key - j) < SamePairLineKev)
                    {
                        continue;
                    }

                    double have;
                    if (!merged.TryGetValue(entry.Key, out have) || entry.Value > have)
                    {
                        merged[entry.Key] = entry.Value;
                        if (marks != null && marks.Contains(entry.Key))
                        {
                            supply.Add(entry.Key);
                        }
                        else
                        {
                            supply.Remove(entry.Key);
                        }
                    }
                }
            }

            return merged;
        }

        static Dictionary<double, double> Partners(NuclideData data, double energy)
        {
            Dictionary<double, double> bag;
            return data.Partners.TryGetValue(energy, out bag)
                ? bag
                : new Dictionary<double, double>();
        }

        /// <summary>
        /// Отношение «выход в компоненте / выход в базе» по самой сильной
        /// сошедшейся линии нуклида.
        /// </summary>
        static double Scale(FsaComponent component, string nuclide, NuclideData data)
        {
            double best = 0.0;
            double scale = 1.0;
            foreach (FsaLine line in component.Lines)
            {
                double baseEnergy;
                if (!Belongs(line, nuclide) || !(line.Intensity > 0.0)
                    || !Match(data.Intensity, line.Energy, out baseEnergy))
                {
                    continue;
                }

                double baseIntensity = data.Intensity[baseEnergy];
                if (baseIntensity > best && baseIntensity > 0.0)
                {
                    best = baseIntensity;
                    scale = line.Intensity / baseIntensity;
                }
            }

            return scale;
        }

        static IEnumerable<string> DistinctNuclides(FsaComponent component)
        {
            List<string> names = new List<string>();
            foreach (FsaLine line in component.Lines)
            {
                string name = line.Nuclide ?? "";
                if (name.Length > 0 && !names.Contains(name, StringComparer.OrdinalIgnoreCase))
                {
                    names.Add(name);
                }
            }

            return names;
        }

        static bool Belongs(FsaLine line, string nuclide)
        {
            return string.Equals(line.Nuclide ?? "", nuclide, StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>Линия компонента и линия базы — одна и та же?</summary>
        static bool Match(Dictionary<double, double> table, double energy, out double found)
        {
            found = 0.0;
            double best = SameLineKev;
            bool ok = false;
            foreach (double key in table.Keys)
            {
                double delta = Math.Abs(key - energy);
                if (delta < best)
                {
                    best = delta;
                    found = key;
                    ok = true;
                }
            }

            return ok;
        }

