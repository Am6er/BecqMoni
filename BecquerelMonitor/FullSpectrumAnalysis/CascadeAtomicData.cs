        const double MatchKev = 0.6;

        static readonly object Gate = new object();

        static readonly Dictionary<string, CascadeAtomicData> Cache =
            new Dictionary<string, CascadeAtomicData>(StringComparer.OrdinalIgnoreCase);

        /// <summary>
        /// Атомные участники каскада нуклида; null — сказать нечего (нет
        /// дочернего, нет рентгена и нет β⁺).
        /// </summary>
        public static CascadeAtomicData Of(string nucid)
        {
            if (string.IsNullOrEmpty(nucid))
            {
                return null;
            }

            lock (Gate)
            {
                CascadeAtomicData data;
                if (Cache.TryGetValue(nucid, out data))
                {
                    return data;
                }

                try
                {
                    data = Build(nucid);
                }
                catch (Exception error)
                {
                    // Отказ базы не должен ронять разбор — но и молчать нельзя:
                    // без записанной причины «рентгена не нашлось» неотличимо
                    // от «читатель сломан».
                    data = new CascadeAtomicData
                    {
                        Failed = true,
                        Note = "отказ базы: " + error.Message
                    };
                }

                Cache[nucid] = data;
                return data;
            }
        }

        static CascadeAtomicData Build(string nucid)
        {
            var data = new CascadeAtomicData();
            var notes = new StringBuilder();

            int mass = MassOf(nucid);
            if (mass <= 0)
            {
                return null;
            }

            // Излучения самого распада: гаммы, K-рентген, β⁺. Всё — на распад
            // РОДИТЕЛЯ цепочки, как и в остальной библиотеке.
            var gammaIntensity = new List<GammaLine>();

            // (`S151`) КАНАЛ РАСПАДА У КАЖДОЙ ЛИНИИ, а не только у ветви.
            // Список идёт номер в номер с `gammaIntensity`: без него гамма
            // доставалась той ветви, которая первой нашла её в своей схеме, —
            // то есть порядку строк запроса. Родителей, у которых гаммы
            // приходят более чем одним `dec_type`, в поставке 175.
            // (`S157`) Канал уехал В САМУ СТРОКУ, отдельного списка больше нет:
            // два списка «номер в номер» — та же ловушка, что и ключ по одной
            // энергии, только на шаг раньше.

            // (`S153`) β⁺ — ПО КАНАЛАМ. Общая сумма смешивала ветви, а сверх
            // того у 40 родителей она выходит за долю самой ветви (у `20NA`
            // 196.85 % при ветви 100 %), и такое число доезжало до площадей
            // сумм-пиков без всякой проверки.
            var betaPlusOf = new Dictionary<string, double>(StringComparer.Ordinal);
            string daughter = null;

            // K-серия собирается тремя вёдрами и разбирается ПОСЛЕ цикла:
            // выбор между итогом `KB` и разложением `KpB*` нельзя сделать «на
            // лету», не увидев обеих строк (`KSeriesRule`, `T50`).
            var kAlpha = new List<double[]>();
            var kBetaSplit = new List<double[]>();
            var kBetaTotal = new List<double[]>();
            var kBetaSplitSeries = new HashSet<string>(StringComparer.Ordinal);

            using (SqliteConnection connection = OpenRead(NuclideDatabasePath()))
            using (SqliteCommand command = connection.CreateCommand())
            {
                // (`S89`) Тот же зажим по уровню родителя, что и у библиотеки, и
                // из одного места: без него запрос складывал ВСЕ наборы одного
                // имени, то есть двоил распад у четырёх изомеров.
                //
                // ⛔ `dec_type` И `order by` — ОБА ОБЯЗАТЕЛЬНЫ (`S151`). Графа
                // канала в таблице ЕСТЬ, и без неё принадлежность гаммы ветви
                // решал порядок строк, которого запрос без `order by` вообще не
                // обещает: у SQLite он свойство плана, а не данных.
                command.CommandText =
                    "select type_a, type_c, energy_num, intensity_num, dec_type"
                    + " from decay_radiations"
                    + " where parent_nucid = $n and intensity_num > 0"
                    + DecayParentRule.LevelClause
                    + " order by dr_pk";
                command.Parameters.AddWithValue("$n", nucid);
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        string kind = reader.IsDBNull(0) ? "" : reader.GetString(0);
                        string series = reader.IsDBNull(1) ? "" : reader.GetString(1);
                        double energy = reader.IsDBNull(2) ? 0.0 : reader.GetDouble(2);
                        double intensity = reader.IsDBNull(3) ? 0.0 : reader.GetDouble(3);
                        string channel = reader.IsDBNull(4) ? "" : reader.GetString(4);
                        if (!(intensity > 0.0))
                        {
                            continue;
                        }

                        if (kind == "G" && energy > 0.0)
                        {
                            gammaIntensity.Add(new GammaLine
                            {
                                EnergyKev = energy,
                                IntensityPct = intensity,
                                Channel = channel
                            });
                        }
                        else if (kind == "X" && energy > 0.0 && KSeriesRule.IsSeries(series))
                        {
                            var line = new[] { energy, intensity };
                            if (KSeriesRule.IsBetaTotal(series))
                            {
                                kBetaTotal.Add(line);
                            }
                            else if (KSeriesRule.IsBetaSplit(series))
                            {
                                kBetaSplit.Add(line);
                                kBetaSplitSeries.Add(series);
                            }
                            else
                            {
                                kAlpha.Add(line);
                            }
                        }
                        else if (kind == "B+")
                        {
                            double had;
                            betaPlusOf.TryGetValue(channel, out had);
                            betaPlusOf[channel] = had + intensity;
                        }
                    }
                }

                // Дочерний нуклид — у основного состояния родителя. Ветвей
                // бывает несколько (у Eu-152 захват и β⁻ сразу), берём самую
                // сильную: K-рентген принадлежит атому, в который распад
                // ПРИШЁЛ, и у слабой ветви он тонет в выходе.
                //
                // (`A218`) Зажим по уровню — общий, из `DecayParentRule`. Здесь
                // стоял свой текст `l_seqno = 0`, и он был НЕ той же строгости:
                // у 30 родителей дочернего не находилось вовсе (`234PAm1`
                // лежит на уровне 2, а не на нуле), а ещё у четырёх выбирался
                // не тот — у `183HF` дочерним атомом выходил САМ ГАФНИЙ.
                //
                // ⛔ ПЕТЛИ СНИМАЕМ ЗДЕСЬ, ЯВНО. Правило их не снимает нарочно —
                // обходу ряда они нужны как изомерный переход, — а нам они
                // означали бы «атом сам себе дочерний». В выборку они попадают
                // у 511 родителей из 2535 и у 123 из них побеждают по `perc`.
                command.Parameters.Clear();
                command.CommandText =
                    "select daughter_nucid, perc, dec_type from decay_chain d"
                    + " where nucid = $n"
                    + DecayParentRule.ChainLevelClause;
                command.Parameters.AddWithValue("$n", nucid);
                double best = -1.0;
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        string name = reader.IsDBNull(0) ? null : reader.GetString(0);
                        if (string.Equals(name, nucid, StringComparison.OrdinalIgnoreCase))
                        {
                            continue;
                        }

                        double perc;
                        if (string.IsNullOrEmpty(name)
                            || !double.TryParse(reader.IsDBNull(1) ? "" : reader.GetString(1),
                                                NumberStyles.Float, CultureInfo.InvariantCulture,
                                                out perc))
                        {
                            perc = 0.0;
                        }

                        if (name == null)
                        {
                            continue;
                        }

                        // (`S145`) Берутся ВСЕ ветви, а не одна сильнейшая.
                        // Сильнейшая по-прежнему становится сводным `Daughter`
                        // ради прежних читателей, но физика считается по каждой.
                        int branchZ = ChargeOf(name);
                        int branchA = MassOf(name);
                        if (branchZ > 0 && branchA > 0)
                        {
                            data.Branches.Add(new Branch
                            {
                                Nucid = name,
                                Z = branchZ,
                                A = branchA,
                                Perc = perc,
                                DecType = reader.IsDBNull(2) ? null : reader.GetString(2)
                            });
                        }

                        if (perc > best)
                        {
                            best = perc;
                            daughter = name;
                        }
                    }
                }
            }

            data.Daughter = daughter;

            // K-серия: Kα целиком плюс ОДНО из двух представлений Kβ.
            data.KLines.AddRange(kAlpha);
            data.KLines.AddRange(KSeriesRule.Beta(kBetaSplit, kBetaTotal, kBetaSplitSeries.Count));
            data.KLines.Sort((a, b) => a[0].CompareTo(b[0]));
            data.KIntensityPct = 0.0;
            foreach (double[] kLine in data.KLines)
            {
                data.KIntensityPct += kLine[1];
            }

            // Два кванта на позитрон. Аннигиляция идёт по месту остановки
            // позитрона, то есть практически мгновенно.
            //
            // ⚠ Здесь ещё СЫРАЯ сумма по всем каналам: ветвей на этом месте
            // может не быть вовсе, а ниже стоит ранний выход, которому нужно
            // знать лишь «есть ли аннигиляция в принципе». По ветвям и в их
            // границах она пересчитывается ниже (`S150`, `S153`).
            double betaPlusRaw = 0.0;
            foreach (KeyValuePair<string, double> entry in betaPlusOf)
            {
                betaPlusRaw += entry.Value;
            }

            data.AnnihilationQuanta = 2.0 * betaPlusRaw / 100.0;
            data.GammaIntensity = gammaIntensity;

            if (data.KLines.Count == 0 && !(data.AnnihilationQuanta > 0.0))
            {
                return null;
            }

            int z = daughter != null ? ChargeOf(daughter) : 0;
            if (z <= 0)
            {
                notes.Append("дочерний не определён; ");
                data.Note = notes.ToString();
                return data.KLines.Count > 0 || data.AnnihilationQuanta > 0.0 ? data : null;
            }

            MaterialDatabase.Fluorescence fluorescence = MaterialDatabase.FluorescenceOf(z);
            data.OmegaK = fluorescence != null ? fluorescence.Omega(true) : 0.0;

            // Ветвей может не найтись вовсе (старые/неполные поставки) — тогда
            // работает одна, собранная из сводных полей: поведение прежнее.
            if (data.Branches.Count == 0)
            {
                data.Branches.Add(new Branch
                {
                    Nucid = daughter, Z = z, A = mass, Perc = 100.0
                });
            }

            BetaPlusByBranch(data, betaPlusOf, notes);
            SplitKLines(data, notes);

            // ⛔ ПО ВЕТВЯМ, А НЕ ПО ОДНОЙ (`S145`). У каждой своя схема уровней,
            // свой ω_K, свои K-линии и свой остаток захватных вакансий. Гамма
            // достаётся ТОЙ ветви, в схеме которой нашлась, и помечается её Z.
            // Ключ — НОМЕР ВЕТВИ, а не Z: у двух ветвей Z совпадает (`S148`).
            var halfLifeOf = new Dictionary<int, Dictionary<int, double>>();
            for (int index = 0; index < data.Branches.Count; index++)
            {
                Branch branch = data.Branches[index];
                MaterialDatabase.Fluorescence bf = MaterialDatabase.FluorescenceOf(branch.Z);
                branch.OmegaK = bf != null ? bf.Omega(true) : 0.0;

                List<Transition> scheme;
                Dictionary<int, double> halfLife;
                // Отсутствие базы схем — ОТКАЗ, и он поднимает признак; все
                // прочие записки этой ветки остаются примечаниями.
                if (!LoadScheme(branch.Z, branch.A, out scheme, out halfLife, notes))
                {
                    data.Failed = true;
                }

                halfLifeOf[index] = halfLife;
                branch.Downstream = BuildDownstream(scheme);

                double conversionVacancy = 0.0;
                for (int line = 0; line < gammaIntensity.Count; line++)
                {
                    GammaLine row = gammaIntensity[line];
                    double energyKev = row.EnergyKev;

                    // ⛔ СНАЧАЛА КАНАЛ, ПОТОМ СХЕМА (`S151`). Прежде линия
                    // доставалась той ветви, которая нашла её в схеме первой, а
                    // схема у двух ветвей в ОДИН нуклид одна и та же — значит
                    // решал порядок. Канал в поставке есть у каждой строки
                    // излучения, и он отвечает на этот вопрос прямо.
                    if (!SameChannel(row.Channel, branch.DecType))
                    {
                        continue;
                    }

                    // ⛔ ЗАНЯТОСТЬ ПРОВЕРЯЕТСЯ У СТРОКИ, А НЕ У ЭНЕРГИИ (`S157`).
                    // Прежде здесь стоял `data.Gammas.ContainsKey(energyKev)`, и
                    // вторая строка ТОЙ ЖЕ энергии в ДРУГОМ канале отбрасывалась
                    // как «уже разобранная», хотя разобрана была чужая.
                    if (row.Transition != null)
                    {
                        continue;
                    }

                    Transition match = MatchTransition(scheme, energyKev);
                    if (match == null)
                    {
                        continue;
                    }

                    match.BranchIndex = index;
                    row.Transition = match;
                    if (!data.Gammas.ContainsKey(energyKev))
                    {
                        // Сводка по энергии — первому, кто занял; читатели, которым
                        // нужна принадлежность, ходят по строке.
                        data.Gammas[energyKev] = match;
                    }

                    conversionVacancy += row.IntensityPct / 100.0 * match.AlphaK;
                }

                // (`S150`) Доля β⁺ у каждой гаммы ветви — по населённому
                // уровню. Читается ПОСЛЕ раздачи гамм: годятся только те
                // линии, которые этой ветви и достались.
                LoadBetaPlusOfGamma(nucid, branch, gammaIntensity, notes);

                if (branch.OmegaK > 0.0)
                {
                    double total = branch.KIntensityPct / 100.0 / branch.OmegaK;
                    double prompt = total - conversionVacancy;
                    if (prompt < -0.02)
                    {
                        // Отрицательный остаток физически невозможен: вакансий от
                        // конверсии не может быть больше, чем их всего. Значит
                        // сопоставление взяло не тот переход — ровно та беда, что
                        // описана в TODO D31. Говорим об этом вслух.
                        notes.AppendFormat(CultureInfo.InvariantCulture,
                            "{0}: остаток вакансий отрицателен ({1:F4}), сопоставление под подозрением; ",
                            branch.Nucid, prompt);
                    }

                    branch.PromptVacancy = prompt > 0.0 ? prompt : 0.0;
                }
                else
                {
                    notes.Append("нет ω_K для Z="
                                 + branch.Z.ToString(CultureInfo.InvariantCulture) + "; ");
                }
            }

            // Задержки — ПО СВОЕЙ схеме у каждой ветви: номера уровней у разных
            // ядер свои, и общий ход по ним смешал бы чужие пути (`A290`).
            for (int index = 0; index < data.Branches.Count; index++)
            {
                Dictionary<int, double> halfLife;
                if (!halfLifeOf.TryGetValue(index, out halfLife))
                {
                    continue;
                }

                // ⛔ ПО СТРОКАМ, А НЕ ПО СВОДКЕ ПО ЭНЕРГИИ (`S160`). Здесь
                // ходили по `data.Gammas`, у которого КЛЮЧ ОДИН НА ЭНЕРГИЮ, —
                // значит у межканального дубля второй `Transition` не попадал
                // в расчёт вовсе и оставался с неинициализированными
                // `EmitDelaySec` и `EmitPhases`. После `S157` рабочий путь
                // берёт их ИМЕННО у строки, то есть такая линия молча
                // становилась мгновенной.
                //
                // ⚠ У нынешнего `33NA` ошибка СЛУЧАЙНО не видна: уровень
                // второго канала имеет нулевой период, и «не посчитано»
                // совпадает с «мгновенно». Совпадение — не исправность.
                var own = new List<Transition>();
                foreach (GammaLine row in gammaIntensity)
                {
                    if (row.Transition != null && row.Transition.BranchIndex == index)
                    {
                        own.Add(row.Transition);
                    }
                }

                Delays(own, halfLife);
            }

            // Сводные поля — у сильнейшей ветви, ради прежних читателей.
            foreach (Branch branch in data.Branches)
            {
                if (branch.Z == z)
                {
                    data.PromptVacancy = branch.PromptVacancy;
                    break;
                }
            }

            data.Note = notes.ToString();
            return data;
        }

        /// <summary>
        /// Переход схемы, отвечающий линии распада.
        ///
        /// ⛔ БЛИЖАЙШИЙ ПО ЭНЕРГИИ — НЕВЕРНОЕ ПРАВИЛО, и это стоило часа.
        /// У Hf-176 на линию распада 306.780 кэВ приходится три кандидата:
        /// настоящий 3→2 (306.640, уровень 596.82 кэВ, интенсивность 100 %) и
        /// два самозванца с уровней 3467 и 3847 кэВ, которых β-распад Lu-176
        /// (Q = 1194 кэВ) населить не может в принципе. Ближе по энергии
        /// оказывается САМОЗВАНЕЦ — на 0.02 кэВ, — и с ним число вакансий от
        /// конверсии выходило БОЛЬШЕ полного, то есть отрицательный захват.
        ///
        /// Правило поэтому такое: сперва выбросить переходы, которых в природе
        /// не испускают (нулевая относительная интенсивность), затем брать
        /// переход с САМОГО НИЗКОГО уровня, и лишь при равенстве — ближайший по
        /// энергии.
        /// </summary>
        static Transition MatchTransition(List<Transition> scheme, double energyKev)
        {
            Transition best = null;
            double bestDelta = 0.0;
            foreach (Transition candidate in scheme)
            {
                double delta = Math.Abs(candidate.EnergyKev - energyKev);
                if (delta >= MatchKev)
                {
                    continue;
                }

                if (best == null
                    || candidate.FromSeq < best.FromSeq
                    || (candidate.FromSeq == best.FromSeq && delta < bestDelta))
                {
                    best = candidate;
                    bestDelta = delta;
                }
            }

            return best;
        }

        /// <summary>
        /// Через сколько секунд после распада вылетает каждый квант.
        ///
        /// Ход по схеме сверху вниз: квант перехода с уровня L вылетает через
        /// `приход(L) + T½(L)`, а приход на L — это самый поздний из вылетов
        /// тех переходов, что на L приводят. Уровни идут по убыванию номера,
        /// то есть родители обработаны раньше потомков.
        ///
        /// ⚠ Приближение названо: когда уровень населяется И напрямую распадом,
        /// И через долгоживущий уровень сверху, берётся ПОЗДНЕЕ из двух. Это
        /// сторона осторожная (совпадений получится меньше, а не больше), и на
        /// корпусе она точна — там у всех таких уровней путь один. Разбор по
        /// долям населённости — остаток, TODO S58.
        /// </summary>
        /// <summary>
        /// Развести K-линии между дочерними атомами ветвей (`S145`).
        ///
        /// ⛔ В поставке они лежат ОДНИМ ведром: у Eu-152 основная серия
        /// самария около 39.5–46.6 кэВ, а строка 42.996 кэВ принадлежит
        /// гадолинию, и прежний код применял ко всем один ω_K сильнейшего.
        ///
        /// ⛔ ПРАВИЛО «БЛИЖАЙШИЙ КРАЙ СВЕРХУ» НЕГОДНО, и это поймано своей же
        /// пробой, а не рассуждением. K-линии ТЯЖЁЛОГО атома лежат НИЖЕ края
        /// лёгкого: у Lu-176 (ветви Hf-176 и Yb-176) Kα гафния 55.8 кэВ стоит
        /// ниже края иттербия 61.3, и правило отдавало гафниевый рентген
        /// иттербию — баланс вакансий гафния уходил в минус. То есть первая
        /// редакция чинила Eu-152 ценой поломки Lu-176.
        ///
        /// Годное правило — ДОЛЯ ОТ КРАЯ, и она устойчива по всей таблице:
        /// Kα2 ≈ 0.844, Kα1 ≈ 0.855, Kβ1 ≈ 0.969 от K-края (мерено по Sm, Gd,
        /// Hf, Yb — разброс в третьем знаке). Линия достаётся атому, у которого
        /// она ближе всего к одной из этих трёх опор; линия выше края атому не
        /// принадлежит в принципе и такой атом не рассматривается.
        ///
        /// Линия, которой не нашлось хозяина, остаётся у сильнейшей ветви, и
        /// это НАЗЫВАЕТСЯ в примечании — молча приписывать её было бы тем же
        /// дефектом в мелком масштабе.
        /// </summary>
        /// <summary>
        /// Доли K-линий от K-края: Kα2, Kα1, Kβ1. Мерены по Sm, Gd, Hf, Yb —
        /// разброс в третьем знаке, чего для разведения соседних атомов хватает
        /// с запасом (соседи расходятся на единицы кэВ).
        /// </summary>
        static readonly double[] KLineShares = { 0.844, 0.855, 0.969 };

        /// <summary>
        /// Насколько близкими считать две опоры, чтобы решала доля ветви, кэВ.
        /// </summary>
        const double KLineTieKev = 0.30;

        static void SplitKLines(CascadeAtomicData data, StringBuilder notes)
        {
            int homeless = 0;
            Branch strongest = null;
            foreach (Branch branch in data.Branches)
            {
                if (strongest == null || branch.Perc > strongest.Perc)
                {
                    strongest = branch;
                }
            }

            foreach (double[] line in data.KLines)
            {
                Branch owner = null;
                double bestAway = double.MaxValue;
                foreach (Branch branch in data.Branches)
                {
                    // ⛔ ВЕТВЬ НУЛЕВОЙ ВЕРОЯТНОСТИ ХОЗЯИНОМ НЕ БЫВАЕТ, и это
                    // тоже поймано пробой: у Mn-54 в `decay_chain` числится
                    // ветвь 54FE с долей 0.00 %, и она забирала 3.05 % K-линий
                    // хрома — захват падал 0.8913 → 0.7855 на пустом месте.
                    if (!(branch.Perc > 0.0))
                    {
                        continue;
                    }

                    MaterialDatabase.Fluorescence f = MaterialDatabase.FluorescenceOf(branch.Z);
                    if (f == null || !(f.KEdgeKev > line[0]))
                    {
                        continue;
                    }

                    foreach (double share in KLineShares)
                    {
                        double away = Math.Abs(line[0] - share * f.KEdgeKev);

                        // Соседние Z дают опоры в единицах кэВ друг от друга, и
                        // при почти равной близости решает ДОЛЯ ВЕТВИ: у Cr Kβ
                        // (5.95) опоры хрома и железа расходятся на 0.1 кэВ, а
                        // ветви — на порядки.
                        bool better = away < bestAway - KLineTieKev
                                      || (away < bestAway + KLineTieKev
                                          && owner != null && branch.Perc > owner.Perc)
                                      || owner == null;
                        if (better && away < bestAway + KLineTieKev)
                        {
                            if (away < bestAway)
                            {
                                bestAway = away;
                            }

                            owner = branch;
                        }
                    }
                }

                if (owner == null)
                {
                    owner = strongest;
                    homeless++;
                }

                if (owner == null)
                {
                    continue;
                }

                owner.KLines.Add(line);
                owner.KIntensityPct += line[1];
            }

            if (homeless > 0 && data.Branches.Count > 1)
            {
                notes.AppendFormat(CultureInfo.InvariantCulture,
                    "K-линий без своего края {0}, отданы сильнейшей ветви; ", homeless);
            }
        }

        static readonly Phase[] EmptyLives = new Phase[0];

        static void Delays(List<Transition> gammas, Dictionary<int, double> halfLife)
        {
            var levels = new List<int>();
            foreach (Transition transition in gammas)
            {
                if (!levels.Contains(transition.FromSeq))
                {
                    levels.Add(transition.FromSeq);
                }
            }

            levels.Sort();
            levels.Reverse();

            var arrival = new Dictionary<int, double>();

            // (`A289`) Тот же ход, но копится ещё и СПИСОК периодов пути:
            // выбор «позднее из двух» у обоих один, иначе список отвечал бы за
            // один путь, а сумма — за другой.
            var arrivalLives = new Dictionary<int, Phase[]>();
            foreach (int level in levels)
            {
                double came;
                if (!arrival.TryGetValue(level, out came))
                {
                    came = 0.0;
                }

                Phase[] cameLives;
                if (!arrivalLives.TryGetValue(level, out cameLives))
                {
                    cameLives = EmptyLives;
                }

                double life;
                if (!halfLife.TryGetValue(level, out life) || !(life > 0.0))
                {
                    life = 0.0;
                }

                double emitted = came + life;
                Phase[] lives = cameLives;
                if (life > 0.0)
                {
                    lives = new Phase[cameLives.Length + 1];
                    Array.Copy(cameLives, lives, cameLives.Length);
                    lives[cameLives.Length] = new Phase { Seq = level, HalfLifeSec = life };
                }

                foreach (Transition transition in gammas)
                {
                    if (transition.FromSeq != level)
                    {
                        continue;
                    }

                    transition.EmitDelaySec = emitted;
                    transition.EmitPhases = lives;
                    double have;
                    if (!arrival.TryGetValue(transition.ToSeq, out have) || emitted > have)
                    {
                        arrival[transition.ToSeq] = emitted;
                        arrivalLives[transition.ToSeq] = lives;
                    }
                }
            }
        }

        /// <summary>
        /// Одного ли канала распада строка излучения и ветвь (`S151`).
        ///
        /// ⚠ Незнание одной из сторон — НЕ отказ. Пустая графа `dec_type`
        /// встречается и у ветви (запасная ветвь, собранная из сводных полей), и
        /// у строки излучения в неполной поставке; ответить «разные каналы»
        /// значило бы выбросить линию совсем, а прежнее поведение — раздать по
        /// схеме — здесь безопаснее.
        /// </summary>
        static bool SameChannel(string line, string branch)
        {
            if (string.IsNullOrEmpty(line) || string.IsNullOrEmpty(branch))
            {
                return true;
            }

            return string.Equals(line.Trim(), branch.Trim(), StringComparison.Ordinal);
        }

        /// <summary>
        /// Есть ли у нуклида метка изомера. Метку отделяет РЕГИСТР, а не буква:
        /// `234PAm1` — изомер, `241AM` — нет.
        /// </summary>
        static bool IsomerTail(string nucid)
        {
            if (string.IsNullOrEmpty(nucid))
            {
                return false;
            }

            foreach (char c in nucid)
            {
                if (char.IsLower(c))
                {
                    return true;
                }
            }

            return false;
        }

        /// <summary>
        /// Разложить β⁺ поставки по ветвям и удержать его в физических границах
        /// (`S150`, `S153`).
        ///
        /// ⛔ ЧТО БЫЛО НЕ ТАК. Считалась одна общая сумма `2·ΣB+/100` на распад
        /// родителя, и она же выдавалась за условную вероятность при КАЖДОЙ
        /// гамме — в том числе гамме ветви, в которой позитронов нет вовсе. А
        /// сверх того сумма поставки у 40 родителей выходит за долю самой ветви
        /// (`20NA` — 196.85 % при ветви 100 %, `77RB` — 110.47 %), и такое
        /// число доезжало до `Pairs` и площадей сумм-пиков без всякой проверки:
        /// зажим стоял ОДИН, в конце, у одного потребителя.
        ///
        /// Здесь β⁺ каждого канала кладётся своим ветвям, зажимается их
        /// суммарной долей и превращается в УСЛОВНУЮ долю
        /// <see cref="Branch.BetaPlusShare"/> — при событии ветви, а не на
        /// распад. Общий выход линии 511 (`AnnihilationQuanta`) пересчитывается
        /// по зажатым числам: он остаётся маргинальным, потому что это и есть
        /// выход линии в спектре.
        /// </summary>
        static void BetaPlusByBranch(CascadeAtomicData data,
                                     Dictionary<string, double> betaPlusOf,
                                     StringBuilder notes)
        {
            double total = 0.0;
            foreach (KeyValuePair<string, double> entry in betaPlusOf)
            {
                if (!(entry.Value > 0.0))
                {
                    continue;
                }

                var own = new List<Branch>();
                double bound = 0.0;
                foreach (Branch branch in data.Branches)
                {
                    if (!SameChannel(entry.Key, branch.DecType))
                    {
                        continue;
                    }

                    own.Add(branch);
                    bound += branch.Perc > 0.0 ? branch.Perc : 0.0;
                }

                if (own.Count == 0 || !(bound > 0.0))
                {
                    // Канал есть, ветви под него нет: в выход линии позитроны
                    // всё равно идут, а условной доли им дать не из чего.
                    notes.AppendFormat(CultureInfo.InvariantCulture,
                        "β⁺ канала {0} ({1:F3} %) не привязан ни к одной ветви; ",
                        entry.Key, entry.Value);
                    total += entry.Value;
                    continue;
                }

                double kept = entry.Value;
                if (kept > bound)
                {
                    notes.AppendFormat(CultureInfo.InvariantCulture,
                        "β⁺ канала {0}: поставка даёт {1:F3} % при доле ветвей {2:F3} %, зажато; ",
                        entry.Key, kept, bound);
                    kept = bound;
                }

                double share = kept / bound;
                foreach (Branch branch in own)
                {
                    branch.BetaPlusShare += share;
                    if (branch.BetaPlusShare > 1.0)
                    {
                        branch.BetaPlusShare = 1.0;
                    }
                }

                total += kept;
            }

            if (total > 100.0)
            {
                total = 100.0;
            }

            data.AnnihilationQuanta = 2.0 * total / 100.0;
        }

        /// <summary>
        /// Доля β⁺ у каждой гаммы ветви — ПО НАСЕЛЁННОМУ УРОВНЮ (`S150`).
        ///
        /// Поставка эту связь несёт: `ensdf_feedings` даёт питание каждого
        /// уровня отдельно позитронным (`intensity`) и захватным
        /// (`intensity_ec`) числом, а `ensdf_gammas` — из какого уровня в какой
        /// идёт линия. Поток протягивается СВЕРХУ ВНИЗ, и без этой протяжки
        /// ответ выходит неверным на порядок: у Y-88 прямое питание уровня 1836
        /// кэВ даёт долю 0.208/5.508 = 3.8 %, тогда как через него проходит
        /// почти весь распад сверху, и верная доля — 0.21 %.
        ///
        /// ⛔ ОДИН НАБОР ИЛИ НИЧЕГО. `ensdf_datasets.parent_nucid` изомер НЕ
        /// помечает, и у 432 пар «родитель — дочь» наборов больше одного:
        /// различает их период родителя в `dsid`, которого здесь нет. Взять
        /// наугад — значит подставить чужую схему питаний, поэтому при
        /// неоднозначности доля остаётся ветвевой, а причина попадает в отчёт.
        /// </summary>
        /// <summary>
        /// Насколько близко период набора обязан сойтись с периодом родителя,
        /// чтобы набор считался ЕГО (`S155`). Один процент: паспортные периоды
        /// в двух поставках округлены по-разному (`152EU` — 0.15 % расхождения,
        /// `133BA` — 0.29 %), а состояния родителя различаются порядками.
        /// </summary>
        const double NearHalfLife = 0.01;

        /// <summary>
        /// Насколько ДАЛЕКО обязан лежать второй кандидат. Без этого условия
        /// правило судило бы по одному числу: два близких периода означают, что
        /// поставка их не разводит, и выбирать наугад нельзя.
        /// </summary>
        const double FarHalfLife = 0.10;

        /// <summary>
        /// Период родителя, с. Уровень берётся ТЕМ ЖЕ правилом, что у всей
        /// библиотеки (<see cref="DecayParentRule.LevelClause"/>), и именно
        /// подзапросом, а не переписанным текстом: вторая копия одного правила
        /// разошлась бы с первой молча.
        /// </summary>
        static double ParentHalfLifeSec(string nucid)
        {
            string path = NuclideDatabasePath();
            if (!File.Exists(path))
            {
                return 0.0;
            }

            using (SqliteConnection connection = OpenRead(path))
            using (SqliteCommand command = connection.CreateCommand())
            {
                command.CommandText =
                    "select w.half_life_sec from nuclides w"
                    + " where w.nucid = $n and w.l_seqno = ("
                    + "   select min(parent_l_seqno) from decay_radiations"
                    + "    where parent_nucid = $n" + DecayParentRule.LevelClause + ")";
                command.Parameters.AddWithValue("$n", nucid);
                object raw = command.ExecuteScalar();
                if (raw == null || raw == DBNull.Value)
                {
                    return 0.0;
                }

                double seconds = Convert.ToDouble(raw, CultureInfo.InvariantCulture);
                return seconds > 0.0 ? seconds : 0.0;
            }
        }

        /// <summary>
        /// Какой из нескольких наборов питаний принадлежит ЭТОМУ состоянию
        /// родителя (`S155`). −1 — развести не удалось, и тогда пара 511 не
        /// строится вовсе.
        /// </summary>
        static long ByParentHalfLife(SqliteCommand command, string parentNucid,
                                     List<long> sets, StringBuilder notes)
        {
            double target = ParentHalfLifeSec(parentNucid);
            if (!(target > 0.0))
            {
                notes.AppendFormat(CultureInfo.InvariantCulture,
                    "период {0} неизвестен, набор питаний не разведён; ", parentNucid);
                return -1L;
            }

            var away = new List<double[]>();
            foreach (long id in sets)
            {
                command.Parameters.Clear();
                command.CommandText = "select parent_hl_sec from ensdf_datasets where id = $i";
                command.Parameters.AddWithValue("$i", id);
                object raw = command.ExecuteScalar();
                if (raw == null || raw == DBNull.Value)
                {
                    continue;
                }

                double hl = Convert.ToDouble(raw, CultureInfo.InvariantCulture);
                if (!(hl > 0.0))
                {
                    continue;
                }

                away.Add(new[] { Math.Abs(hl - target) / target, id });
            }

            away.Sort(delegate(double[] a, double[] b) { return a[0].CompareTo(b[0]); });
            if (away.Count == 0 || away[0][0] >= NearHalfLife
                || (away.Count > 1 && away[1][0] <= FarHalfLife))
            {
                notes.AppendFormat(CultureInfo.InvariantCulture,
                    "наборы питаний {0} периодом не разведены ({1} кандидатов); ",
                    parentNucid, away.Count);
                return -1L;
            }

            return (long)away[0][1];
        }

        static void LoadBetaPlusOfGamma(string parentNucid, Branch branch,
                                        List<GammaLine> gammaIntensity,
                                        StringBuilder notes)
        {
            if (branch == null || string.IsNullOrEmpty(branch.Nucid)
                || !(branch.BetaPlusShare > 0.0))
            {
                // Позитронов у ветви нет — считать по уровням нечего.
                return;
            }

            if (IsomerTail(parentNucid))
            {
                notes.Append("изомер: набор питаний ENSDF уровня родителя не различает; ");
                return;
            }

            string path = SchemeDatabasePath();
            if (!File.Exists(path))
            {
                return;
            }

            var levelEnergy = new Dictionary<int, double>();
            var inBeta = new Dictionary<int, double>();
            var inTotal = new Dictionary<int, double>();
            var transitions = new List<double[]>();

            using (SqliteConnection connection = OpenRead(path))
            using (SqliteCommand command = connection.CreateCommand())
            {
                command.CommandText =
                    "select id from ensdf_datasets"
                    + " where upper(parent_nucid) = $p and upper(nucid) = $d"
                    + " order by id";
                command.Parameters.AddWithValue("$p", parentNucid.ToUpperInvariant());
                command.Parameters.AddWithValue("$d", branch.Nucid.ToUpperInvariant());
                var sets = new List<long>();
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        sets.Add(reader.GetInt64(0));
                    }
                }

                long chosen = -1L;
                if (sets.Count == 0)
                {
                    // ⛔ ОТКАЗ БЕЗ ПРИЧИНЫ — ЭТО ТИХИЙ НОЛЬ (`S156`). Правило
                    // `S155` обещает «нет совместного уровневого знания — пары
                    // нет С ДИАГНОСТИКОЙ», и для изомера и неразведённых наборов
                    // причина писалась, а вот при ПОЛНОМ отсутствии набора метод
                    // молча возвращался. Дальше `AnnihilationQuantaOfLine`
                    // законно отдавал ноль — неотличимый от физического вывода
                    // «эта гамма с β⁺ не совпадает». В поставке таких β⁺-ветвей
                    // без единого набора **60**, и ни одной в корпусе.
                    notes.AppendFormat(CultureInfo.InvariantCulture,
                        "набора питаний {0}→{1} нет вовсе, пара 511 не строится; ",
                        parentNucid, branch.Nucid);
                }
                else if (sets.Count == 1)
                {
                    chosen = sets[0];
                }
                else if (sets.Count > 1)
                {
                    // ⛔ НЕОДНОЗНАЧНОСТЬ РАЗВОДИТСЯ ПЕРИОДОМ РОДИТЕЛЯ (`S155`).
                    // Наборы одной пары «родитель — дочь» различаются именно
                    // состоянием родителя, и период у них записан:
                    // `ensdf_datasets.parent_hl_sec` против
                    // `nuclides.half_life_sec` того же уровня, каким живёт вся
                    // остальная библиотека. Измерено: из 432 неоднозначных пар
                    // поставки так разводятся **309**, и среди них ВСЕ
                    // корпусные с β⁺ — `152EU→152SM` (отклонение 0.15 %),
                    // `152EU→152GD`, `44SC→44CA` (отклонение 0).
                    chosen = ByParentHalfLife(command, parentNucid, sets, notes);
                }

                if (chosen < 0L)
                {
                    return;
                }

                command.Parameters.Clear();
                command.Parameters.AddWithValue("$s", chosen);

                command.CommandText =
                    "select seq, energy_kev from ensdf_levels where dataset_id = $s";
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        levelEnergy[reader.GetInt32(0)] =
                            reader.IsDBNull(1) ? 0.0 : reader.GetDouble(1);
                    }
                }

                command.CommandText =
                    "select level_seq, kind, intensity, intensity_ec"
                    + " from ensdf_feedings where dataset_id = $s";
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        if (reader.IsDBNull(0))
                        {
                            continue;
                        }

                        int seq = reader.GetInt32(0);
                        string kind = reader.IsDBNull(1) ? "" : reader.GetString(1);
                        double beta = reader.IsDBNull(2) ? 0.0 : reader.GetDouble(2);
                        double capture = reader.IsDBNull(3) ? 0.0 : reader.GetDouble(3);

                        double had;
                        inTotal.TryGetValue(seq, out had);
                        inTotal[seq] = had + beta + capture;

                        // ⚠ Позитрон — только в канале `E`. У `B` (β⁻) и `A`
                        // графа `intensity` тоже заполнена, и сложить их значило
                        // бы объявить позитронами весь бета-минус.
                        if (kind == "E")
                        {
                            inBeta.TryGetValue(seq, out had);
                            inBeta[seq] = had + beta;
                        }
                    }
                }

                command.CommandText =
                    "select from_level_seq, to_level_seq, energy_kev, intensity,"
                    + " total_intensity, conv_coef"
                    + " from ensdf_gammas where dataset_id = $s";
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        if (reader.IsDBNull(0) || reader.IsDBNull(1) || reader.IsDBNull(2))
                        {
                            continue;
                        }

                        // Вес — ПОЛНАЯ населённость перехода: гамма плюс
                        // конверсия. Поток уровня уходит и той и другой.
                        double weight;
                        if (!reader.IsDBNull(4))
                        {
                            weight = reader.GetDouble(4);
                        }
                        else
                        {
                            double gamma = reader.IsDBNull(3) ? 0.0 : reader.GetDouble(3);
                            double alpha = reader.IsDBNull(5) ? 0.0 : reader.GetDouble(5);
                            weight = gamma * (1.0 + (alpha > 0.0 ? alpha : 0.0));
                        }

                        transitions.Add(new[]
                        {
                            reader.GetInt32(0), reader.GetInt32(1),
                            reader.GetDouble(2), weight > 0.0 ? weight : 0.0
                        });
                    }
                }
            }

            // ⛔ ПРИЧИНА НУЖНА И ЗДЕСЬ (`S163`). `S156` закрыла только «набора
            // нет вовсе», а набор БЕЗ ПЕРЕХОДОВ (`100SN→100IN`) уходил тем же
            // молчаливым `return`: доля β⁺ оставалась пустой, и ноль снова
            // становился неотличим от доказанного отсутствия совпадения.
            if (transitions.Count == 0)
            {
                notes.AppendFormat(CultureInfo.InvariantCulture,
                    "набор питаний {0}→{1} без переходов, пара 511 не строится; ",
                    parentNucid, branch.Nucid);
                return;
            }

            // ⛔ И ЗДЕСЬ ТОЖЕ (`S163`): переходы есть, а ЧИСЛОВЫХ питаний нет
            // (`104IN→104CD`). Тогда весь поток нулевой, доли выходят нулями —
            // но это «не знаем», а не «позитронов при этой гамме не бывает».
            bool anyFeeding = false;
            foreach (KeyValuePair<int, double> entry in inTotal)
            {
                if (entry.Value > 0.0)
                {
                    anyFeeding = true;
                    break;
                }
            }

            if (!anyFeeding)
            {
                notes.AppendFormat(CultureInfo.InvariantCulture,
                    "у набора питаний {0}→{1} нет числовых интенсивностей, пара 511 не строится; ",
                    parentNucid, branch.Nucid);
                return;
            }

            // Уровни — сверху вниз: пока идём вниз, весь поток сверху уже влит.
            var levels = new List<int>();
            foreach (double[] transition in transitions)
            {
                int from = (int)transition[0];
                if (!levels.Contains(from))
                {
                    levels.Add(from);
                }
            }

            levels.Sort(delegate(int a, int b)
            {
                double ea, eb;
                levelEnergy.TryGetValue(a, out ea);
                levelEnergy.TryGetValue(b, out eb);
                int by = eb.CompareTo(ea);
                return by != 0 ? by : b.CompareTo(a);
            });

            // Энергия линии → доля β⁺ и поток, которым она подтверждена.
            var shareOf = new List<double[]>();
            foreach (int level in levels)
            {
                double outTotal = 0.0;
                foreach (double[] transition in transitions)
                {
                    if ((int)transition[0] == level)
                    {
                        outTotal += transition[3];
                    }
                }

                double beta, all;
                inBeta.TryGetValue(level, out beta);
                inTotal.TryGetValue(level, out all);
                double share = all > 0.0 ? beta / all : 0.0;
                if (share > 1.0)
                {
                    share = 1.0;
                }

                foreach (double[] transition in transitions)
                {
                    if ((int)transition[0] != level)
                    {
                        continue;
                    }

                    shareOf.Add(new[] { transition[2], share, transition[3] });
                    if (!(outTotal > 0.0) || !(all > 0.0))
                    {
                        continue;
                    }

                    int to = (int)transition[1];
                    double part = transition[3] / outTotal;
                    double had;
                    inBeta.TryGetValue(to, out had);
                    inBeta[to] = had + beta * part;
                    inTotal.TryGetValue(to, out had);
                    inTotal[to] = had + all * part;
                }
            }

            foreach (GammaLine row in gammaIntensity)
            {
                if (!SameChannel(row.Channel, branch.DecType))
                {
                    continue;
                }

                double energyKev = row.EnergyKev;
                double bestDelta = MatchKev;
                double bestFlux = -1.0;
                bool found = false;
                double share = 0.0;
                foreach (double[] candidate in shareOf)
                {
                    double delta = Math.Abs(candidate[0] - energyKev);
                    if (delta >= MatchKev)
                    {
                        continue;
                    }

                    // Ближайшая по энергии, а при равной близости — та, через
                    // которую идёт больший поток: слабый однофамилец рядом не
                    // должен перебивать основную линию.
                    if (found && delta > bestDelta)
                    {
                        continue;
                    }

                    if (found && delta == bestDelta && candidate[2] <= bestFlux)
                    {
                        continue;
                    }

                    found = true;
                    bestDelta = delta;
                    bestFlux = candidate[2];
                    share = candidate[1];
                }

                if (found)
                {
                    branch.BetaPlusOfGamma[energyKev] = share;
                }
            }
        }

        /// <summary>
        /// Транзитивное замыкание схемы вниз (`S158`): из какого уровня куда
        /// можно спуститься. Считается один раз на ветвь, обходом в глубину с
        /// запоминанием.
        ///
        /// ⚠ Схема — направленный граф БЕЗ циклов по построению (переход всегда
        /// сбрасывает энергию), но защита от повторного входа стоит: битая
        /// поставка с петлёй иначе увела бы обход в бесконечность.
        /// </summary>
        static Dictionary<int, HashSet<int>> BuildDownstream(List<Transition> scheme)
        {
            var closure = new Dictionary<int, HashSet<int>>();
            if (scheme == null || scheme.Count == 0)
            {
                return closure;
            }

            var next = new Dictionary<int, List<int>>();
            foreach (Transition transition in scheme)
            {
                List<int> bag;
                if (!next.TryGetValue(transition.FromSeq, out bag))
                {
                    next[transition.FromSeq] = bag = new List<int>();
                }

                if (!bag.Contains(transition.ToSeq))
                {
                    bag.Add(transition.ToSeq);
                }
            }

            foreach (KeyValuePair<int, List<int>> entry in next)
            {
                if (!closure.ContainsKey(entry.Key))
                {
                    Descend(entry.Key, next, closure, new HashSet<int>());
                }
            }

            return closure;
        }

        static HashSet<int> Descend(int level, Dictionary<int, List<int>> next,
                                    Dictionary<int, HashSet<int>> closure, HashSet<int> path)
        {
            HashSet<int> known;
            if (closure.TryGetValue(level, out known))
            {
                return known;
            }

            var below = new HashSet<int>();
            if (!path.Add(level))
            {
                // Петля в поставке: дальше не идём, но и молчать не будем —
                // пустое множество здесь честнее бесконечного обхода.
                return below;
            }

            List<int> children;
            if (next.TryGetValue(level, out children))
            {
                foreach (int child in children)
                {
                    below.Add(child);
                    below.UnionWith(Descend(child, next, closure, path));
                }
            }

            path.Remove(level);
            closure[level] = below;
            return below;
        }

        /// <summary>
        /// Схема уровней ветви. Возвращает ЛОЖЬ, когда базы схем нет рядом с
        /// программой: это настоящий ОТКАЗ БАЗЫ, а не оговорка разбора
        /// (10.09.2026) — без файла нет ни одного перехода, и всё, что на них
        /// стоит, посчитано по пустому месту. Остальные записки этого метода —
        /// примечания, работа при них идёт.
        /// </summary>
        static bool LoadScheme(int z, int a, out List<Transition> scheme,
                               out Dictionary<int, double> halfLife, StringBuilder notes)
        {
            scheme = new List<Transition>();
            halfLife = new Dictionary<int, double>();

            string path = SchemeDatabasePath();
            if (!File.Exists(path))
            {
                notes.Append("нет schemedb.sqlite рядом с программой; ");
                return false;
            }

            using (SqliteConnection connection = OpenRead(path))
            using (SqliteCommand command = connection.CreateCommand())
            {
                command.CommandText =
                    "select energy_ev, icc_total, icc_k_ppm, from_seq, to_seq, intensity_ppm,"
                    + " multipolarity, mixing_ratio"
                    + " from g4_gamma where z = $z and a = $a";
                command.Parameters.AddWithValue("$z", z);
                command.Parameters.AddWithValue("$a", a);
                int clamped = 0;
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        // Переход, которого не испускают, кандидатом быть не
                        // может: см. MatchTransition.
                        if (reader.IsDBNull(5) || reader.GetDouble(5) <= 0.0)
                        {
                            continue;
                        }

                        double alphaTotal = reader.IsDBNull(1) ? 0.0 : reader.GetDouble(1);
                        if (alphaTotal > AlphaCeiling)
                        {
                            alphaTotal = AlphaCeiling;
                        }

                        double kShare = reader.IsDBNull(2) ? 0.0 : reader.GetDouble(2) / 1.0E6;
                        double alphaK = alphaTotal * kShare;
                        if (alphaK > alphaTotal)
                        {
                            alphaK = alphaTotal;
                        }

                        double energyKev = reader.GetDouble(0) / 1000.0;

                        // (`D37`) ЗАЖИМ ПО СОБСТВЕННОЙ МУЛЬТИПОЛЬНОСТИ СТРОКИ.
                        // Сверяется α_K поставки с ЛСРМ по ТОМУ КОДУ, который
                        // записан в этой же строке; разошлись больше чем в
                        // AlphaMismatchFactor раз — верим ЛСРМ, а не Geant4.
                        // ⚠ Зажим по alphaTotal тут НЕ повторяется нарочно:
                        // при сработавшем признаке под подозрением вся строка,
                        // и её же полный α мерилом быть не может.
                        // ⛔ НОЛЬ У Geant4 — ЭТО ПРОБЕЛ ПОСТАВКИ, А НЕ
                        // ПРОТИВОРЕЧИЕ, и зажим его не берёт. Отношение к нулю
                        // бесконечно, поэтому без `alphaK > 0` зажим ПОДСТАВЛЯЛ
                        // бы ЛСРМ везде, где у Geant4 конверсии нет вовсе, — то
                        // есть чинил бы не тот дефект. Поймано 10.09.2026 на
                        // первом же прогоне пробы: у Th-229 из десяти сработок
                        // ШЕСТЬ были ровно такими (163.9, 261.3, 425.9, 223.5,
                        // 291.4, 491.0 кэВ, у всех α_K Geant4 = 0). Восполнять
                        // пробелы поставки — отдельное решение, и оно не здесь.
                        int code = reader.IsDBNull(6) ? 0 : reader.GetInt32(6);
                        double delta = reader.IsDBNull(7) ? 0.0 : reader.GetDouble(7);
                        double lsrm;
                        if (alphaK > 0.0
                            && IccGrid.AlphaK(z, energyKev, code, delta, out lsrm)
                            && Math.Max(lsrm, alphaK) >= AlphaMismatchFloor
                            && (lsrm > alphaK * AlphaMismatchFactor
                                || alphaK > lsrm * AlphaMismatchFactor))
                        {
                            alphaK = Math.Min(lsrm, AlphaCeiling);
                            clamped++;
                        }

                        scheme.Add(new Transition
                        {
                            EnergyKev = energyKev,
                            AlphaK = alphaK > 0.0 ? alphaK : 0.0,
                            FromSeq = reader.GetInt32(3),
                            ToSeq = reader.GetInt32(4)
                        });
                    }
                }

                AlphaMismatchClamped += clamped;

                command.CommandText =
                    "select seq, half_life_sec from g4_level where z = $z and a = $a";
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        if (!reader.IsDBNull(1))
                        {
                            halfLife[reader.GetInt32(0)] = reader.GetDouble(1);
                        }
                    }
                }
            }

            return true;
        }

        static SqliteConnection OpenRead(string path)
        {
            SqliteConnection connection = new SqliteConnection(
                "Data Source=" + path + ";Mode=ReadOnly;Cache=Shared;");
            connection.Open();
            return connection;
        }

        /// <summary>
        /// СЕТКА ЛСРМ по K-оболочке: α_K(Z, энергия, мультипольность) из
        /// `matdb.icc_coefficients`, `variant = 1` (`D37`).
        ///
        /// НУЖНА ЗАТЕМ, что это ВТОРАЯ, независимая копия коэффициентов
        /// конверсии, и только ею можно спросить у строки `g4_gamma`, сходится
        /// ли её α с её же мультипольностью. Одной поставкой такой вопрос не
        /// задаётся вовсе.
        ///
        /// ⛔ БЕРЁТСЯ ОДНА ОБОЛОЧКА K, А НЕ СУММА K+L+M, которой считает
        /// сверка `tools/nucdb/compare_copies.py --pair 3`, и это НЕ упрощение:
        /// читателю нужен ровно α_K, а сетка по одной оболочке ШИРЕ (у
        /// M-оболочек верх по энергии ниже, чем у K). Замерено 10.09.2026: по
        /// сумме сверяется 55 591 переход, по одной K — **125 470**, и все 34
        /// выброса аудита K-зажим берёт, плюс ещё 10 того же рода (Fe-54
        /// 1492.8 кэВ, код 304: ЛСРМ 7.3e-05 против 4.51 у Geant4).
        ///
        /// ⚠ Экстраполяции нет намеренно: за краями сетки возвращается
        /// «не знаю», а не продлённая степень. Сечение конверсии падает
        /// степенью энергии, и продлённая сетка мерила бы саму себя — та же
        /// оговорка, что у сверки в `compare_copies.py`.
        /// </summary>
        static class IccGrid
        {
            /// <summary>Колонки таблицы в порядке e1…e4, m1…m4.</summary>
            const int ColumnCount = 8;

            static readonly object GridGate = new object();

            /// <summary>Z → (энергии по возрастанию, восемь колонок на узел).</summary>
            static readonly Dictionary<int, double[][]> Loaded =
                new Dictionary<int, double[][]>();

            static readonly Dictionary<int, double[]> Energies =
                new Dictionary<int, double[]>();

            /// <summary>
            /// α_K по ЛСРМ для перехода, заявившего код <paramref name="code"/>
            /// и отношение смешивания <paramref name="delta"/>. false — сказать
            /// нечего: код нерасшифровываем, смесь без δ, энергия вне сетки,
            /// у элемента нет K-оболочки в поставке.
            /// </summary>
            public static bool AlphaK(int z, double energyKev, int code, double delta,
                                      out double alpha)
            {
                alpha = 0.0;
                int first, second;
                if (!Components(code, delta, out first, out second))
                {
                    return false;
                }

                double a1;
                if (!Interpolate(z, energyKev, first, out a1))
                {
                    return false;
                }

                if (second < 0)
                {
                    alpha = a1;
                    return true;
                }

                double a2;
                if (!Interpolate(z, energyKev, second, out a2))
                {
                    return false;
                }

                // Смесь: (α_младшей + δ²·α_старшей) / (1 + δ²).
                double d2 = delta * delta;
                alpha = (a1 + d2 * a2) / (1.0 + d2);
                return true;
            }

            /// <summary>
            /// Код Geant4 → номера колонок ЛСРМ. E0 = 1; при k ≥ 1 E_k = 2k,
            /// M_k = 2k+1; смесь = 100·Nx + Ny (304 = M1+E2). Колонки идут
            /// e1…e4, m1…m4, поэтому номер = k−1 у электрической и 3+k у
            /// магнитной.
            ///
            /// ⛔ СМЕСЬ БЕЗ δ ОТВЕРГАЕТСЯ ЦЕЛИКОМ. Ноль в `mixing_ratio`
            /// означает и «чистый переход», и «данных нет»; свернуть смесь в
            /// первый компонент значило бы считать не ту величину и зажимать
            /// по ней исправные строки.
            ///
            /// <paramref name="second"/> = −1 — компонент один.
            /// </summary>
            static bool Components(int code, double delta, out int first, out int second)
            {
                first = -1;
                second = -1;
                if (code <= 0)
                {
                    return false;
                }

                int hi = code >= 100 ? code / 100 : code;
                int lo = code >= 100 ? code % 100 : -1;

                if (!Column(hi, out first))
                {
                    return false;
                }

                if (lo < 0)
                {
                    return true;
                }

                if (delta == 0.0)
                {
                    return false;
                }

                if (!Column(lo, out second))
                {
                    return false;
                }

                // Младшая мультипольность идёт первой: δ² приходится на старшую.
                if (Order(lo) < Order(hi))
                {
                    int swap = first;
                    first = second;
                    second = swap;
                }

                return true;
            }

            static bool Column(int part, out int column)
            {
                column = -1;
                if (part < 2)
                {
                    // 0 — кода нет, 1 — E0: такой колонки у ЛСРМ нет вовсе.
                    return false;
                }

                int k = part / 2;
                if (k > 4)
                {
                    // E5 и выше: колонок нет.
                    return false;
                }

                column = (part % 2) != 0 ? 3 + k : k - 1;
                return true;
            }

            /// <summary>Порядок мультипольности k, по которому смесь упорядочивается.</summary>
            static int Order(int part)
            {
                return part / 2;
            }

            static bool Interpolate(int z, double energyKev, int column, out double value)
            {
                value = 0.0;
                double[] xs;
                double[][] ys;
                if (!Load(z, out xs, out ys) || xs.Length == 0)
                {
                    return false;
                }

                if (energyKev < xs[0] || energyKev > xs[xs.Length - 1])
                {
                    return false;
                }

                int i = LowerBound(xs, energyKev);
                if (i < xs.Length && xs[i] == energyKev)
                {
                    value = ys[i][column];
                    return value > 0.0;
                }

                double y0 = ys[i - 1][column];
                double y1 = ys[i][column];
                if (y0 <= 0.0 || y1 <= 0.0)
                {
                    return false;
                }

                double t = (Math.Log(energyKev) - Math.Log(xs[i - 1]))
                           / (Math.Log(xs[i]) - Math.Log(xs[i - 1]));
                value = Math.Exp(Math.Log(y0) + t * (Math.Log(y1) - Math.Log(y0)));
                return value > 0.0;
            }

            /// <summary>Первый номер, у которого xs[номер] ≥ x.</summary>
            static int LowerBound(double[] xs, double x)
            {
                int lo = 0;
                int hi = xs.Length;
                while (lo < hi)
                {
                    int mid = lo + (hi - lo) / 2;
                    if (xs[mid] < x)
                    {
                        lo = mid + 1;
                    }
                    else
                    {
                        hi = mid;
                    }
                }

                return lo;
            }

            static bool Load(int z, out double[] xs, out double[][] ys)
            {
                lock (GridGate)
                {
                    if (Energies.TryGetValue(z, out xs))
                    {
                        ys = Loaded[z];
                        return xs.Length > 0;
                    }

                    var energies = new List<double>();
                    var rows = new List<double[]>();
                    try
                    {
                        string path = MatterDatabasePath();
                        if (File.Exists(path))
                        {
                            using (SqliteConnection connection = OpenRead(path))
                            using (SqliteCommand command = connection.CreateCommand())
                            {
                                command.CommandText =
                                    "select energy_kev, e1, e2, e3, e4, m1, m2, m3, m4"
                                    + " from icc_coefficients"
                                    + " where variant = 1 and shell = 'K' and z = $z"
                                    + " order by energy_kev";
                                command.Parameters.AddWithValue("$z", z);
                                using (SqliteDataReader reader = command.ExecuteReader())
                                {
                                    while (reader.Read())
                                    {
                                        var row = new double[ColumnCount];
                                        for (int c = 0; c < ColumnCount; c++)
                                        {
                                            row[c] = reader.IsDBNull(c + 1)
                                                         ? 0.0 : reader.GetDouble(c + 1);
                                        }

                                        energies.Add(reader.GetDouble(0));
                                        rows.Add(row);
                                    }
                                }
                            }
                        }
                    }
                    catch (Exception)
                    {
                        // Нет второй копии — нет и зажима; это не отказ разбора.
                        energies.Clear();
                        rows.Clear();
                    }

                    xs = energies.ToArray();
                    ys = rows.ToArray();
                    Energies[z] = xs;
                    Loaded[z] = ys;
                    return xs.Length > 0;
                }
            }
        }

        static string MatterDatabasePath()
        {
            return Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "matdb.sqlite");
        }

        /// <summary>
        /// Разбор `nucid` на массу, символ элемента и метку состояния:
        /// «176HF» → (176, «HF», «»), «234PAm1» → (234, «PA», «m1»),
        /// «108AGm» → (108, «AG», «m»), «105PDe» → (105, «PD», «e»).
        ///
        /// ⛔ **Метку состояния от символа отделяет РЕГИСТР, а не буква**, и
        /// это единственное место в проекте, где правило записано. Символ в
        /// `nucid` стоит ЗАГЛАВНЫМИ целиком, метка — строчными. Правило «хвост
        /// M или m — изомер» неверно и ломает 176 нуклидов базы разом: всё, чей
        /// символ кончается на M, то есть Am, Cm, Fm, Tm, Sm, Pm. Поймано
        /// измерением 18.08.2026 (`S56`, `D32`): америций разбирался как
        /// «A-241m», не сходился с истиной и шёл в фантомы.
        ///
        /// Возвращает false, если разобрать не удалось: цифр в начале нет либо
        /// заглавных букв после них не осталось.
        /// </summary>
        public static bool SplitNucid(string nucid, out int mass, out string symbol, out string state)
        {
            mass = 0;
            symbol = "";
            state = "";
            if (string.IsNullOrEmpty(nucid))
            {
                return false;
            }

            string text = nucid.Trim();
            int digits = 0;
            while (digits < text.Length && char.IsDigit(text[digits]))
            {
                digits++;
            }

            if (digits == 0 || digits >= text.Length
                || !int.TryParse(text.Substring(0, digits), NumberStyles.None,
                                 CultureInfo.InvariantCulture, out mass))
            {
                mass = 0;
                return false;
            }

            string tail = text.Substring(digits);

            // Хвост состояния: сначала цифры номера состояния, затем строчные
            // буквы самой метки. Оба куска необязательны.
            int end = tail.Length;
            while (end > 0 && char.IsDigit(tail[end - 1]))
            {
                end--;
            }

            int letters = end;
            while (letters > 0 && char.IsLower(tail[letters - 1]))
            {
                letters--;
            }

            // Хотя бы одна заглавная обязана остаться: иначе это не символ
            // элемента, и разбирать нечего.
            if (letters == 0)
            {
                mass = 0;
                return false;
            }

            symbol = tail.Substring(0, letters);
            state = tail.Substring(letters);
            return true;
        }

        /// <summary>Массовое число из `nucid`: «176HF» → 176, «234PAm1» → 234.</summary>
        public static int MassOf(string nucid)
        {
            int mass;
            string symbol, state;
            return SplitNucid(nucid, out mass, out symbol, out state) ? mass : 0;
        }

        /// <summary>
        /// Заряд по `nucid`: «176HF» → 72, «234PAm1» → 91. Через символ элемента
        /// в <see cref="MaterialDatabase"/> — второй таблицы соответствий в
        /// проекте заводить не надо.
        ///
        /// ⚠ Изомер разбирается наравне с основным состоянием, и это не
        /// украшение: **Th-234 распадается именно в Pa-234m1**, то есть без
        /// такого разбора урановый ряд терял ω_K, схему уровней и весь
        /// K-рентген партнёром каскада у одного из двух своих сильных
        /// излучателей (`D32`).
        /// </summary>
        public static int ChargeOf(string nucid)
        {
            int mass;
            string symbol, state;
            if (!SplitNucid(nucid, out mass, out symbol, out state))
            {
                return 0;
            }

            for (int z = 1; z <= 103; z++)
            {
                if (string.Equals(MaterialDatabase.SymbolOf(z), symbol,
                                  StringComparison.OrdinalIgnoreCase))
                {
                    return z;
                }
            }

            return 0;
        }

