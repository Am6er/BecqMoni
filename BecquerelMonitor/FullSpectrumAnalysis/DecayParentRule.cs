namespace BecquerelMonitor.FullSpectrumAnalysis
{
    /// <summary>
    /// ОДНО правило на весь проект: какие строки `decay_radiations` принадлежат
    /// запрошенному родителю. Заведено по `S89` (решение Amber 24.08.2026:
    /// «зажимать по ЗАПРОШЕННОМУ уровню» — состояние родителя есть часть его
    /// личности, и у ОБОИХ читателей одинаково).
    ///
    /// ⛔ **Складывать все уровни нельзя — это ДВОИТ распад.** У четырёх
    /// родителей из 1777, несущих K-рентген, строки лежат более чем на одном
    /// `parent_l_seqno`, и каждый уровень несёт СВОЮ полную ветвь: у `116AGm2`
    /// на уровне 1 сумма β⁻ 99.56 %, на уровне 4 — 100.09 %. Двух распадов по
    /// сто процентов у одного ядра не бывает; это два НАБОРА поставки под одним
    /// именем, а не две части одного распада. `CascadeAtomicData` складывал их
    /// (запрос шёл по одному `parent_nucid`), `FsaSampleLibrary` зажимала по
    /// минимуму — отсюда и расхождение, которое померила `S89`.
    ///
    /// ⛔ **Но и минимум — НЕ «правильный уровень», а лишь ОБЩИЙ** (`S94`,
    /// решено 25.08.2026 по ядерным данным, а не подгонкой правила). Уровень
    /// родителя в базе есть, и лежит он в `nuclides.l_seqno`: у `118INm2` это
    /// 3, у `190Wm2` — 7, у `116AGm2` — 4, у `70CUm2` — 3, и ровно там стоит
    /// СВОЙ набор излучений каждого. Нижний же набор у всех четырёх — это
    /// набор СОСЕДНЕГО изомера `m1`, попавший в поставку под именем `m2`: он
    /// побитово совпадает со строками самого `m1` у `190Wm2` и `70CUm2` и
    /// является их подмножеством у `118INm2` (нет шести строк рентгена) и
    /// `116AGm2` (нет одной слабой гаммы 1863.9 кэВ).
    ///
    /// Нумерацию подтверждает независимо схема уровней Geant4 (`schemedb`,
    /// `g4_level`) — по периоду и спину: `In-118` seq 1 = 60 кэВ / 4.45 мин /
    /// 5+ (это `m1`), seq 3 = 200 кэВ / 8.5 с / 8− (это `m2`); `W-190` seq 6 =
    /// 1743.6 кэВ / 111 нс / 8+, seq 7 = 1840.6 кэВ / 166 мкс / 10−; `Cu-70`
    /// seq 1 = 101.1 кэВ / 33 с / 3−, seq 3 = 242.6 кэВ / 6.6 с / 1+. И в
    /// СВОЁМ наборе у каждого стоит его собственный переход вниз, которого в
    /// чужом нет: 138.2 кэВ (E3) у `118INm2`, 97.0 = 1840.6 − 1743.6 кэВ у
    /// `190Wm2`, 141.3 ≈ 242.6 − 101.1 кэВ у `70CUm2`. Сходятся и ветви с
    /// `l_decays`: у `118INm2` на уровне 3 β⁻ 1.4 % (Σ строк 1.40) и ИТ 98.6 %,
    /// на уровне 1 — β⁻ 100 % (Σ 96.21), то есть ветвь `m1`.
    ///
    /// ⚠ Но схема Geant4 подтверждает ТРЁХ из четырёх, а не всех: у `Ag-116`
    /// её нумерация СДВИНУТА относительно `nuclides.l_seqno` — g4 seq 2 =
    /// 47.9 кэВ / 20 с / 3+ (это `m1`), seq 5 = 129.8 кэВ / 9.3 с / 6− (это
    /// `m2`), тогда как `l_seqno` у них 1 и 4: под seq 1 у g4 стоит лишний
    /// уровень 0 кэВ / 2−. Значит на совпадение `seq` и `l_seqno` опираться
    /// НЕЛЬЗЯ, а уровень `116AGm2` держат только `l_decays` и побитовое
    /// совпадение нижнего блока со строками `116AGm1`.
    ///
    /// ⛔ Довод «наборы различает АТОМ, в котором рождается рентген» стоял
    /// здесь до 25.08.2026 и БЫЛ НЕВЕРЕН — снят встречной проверкой, запросом
    /// к базе. На чужом уровне у `118INm2` строк типа `X` НЕТ ВООБЩЕ (уровень
    /// 1 — это 7 строк `B-` и 15 `G`), а на своём стоят ОБА атома сразу: индий
    /// 24.001 / 24.209 / 27.237–27.924 и олово 25.271 (I = 0.24, от β⁻-ветви
    /// 1.4 %). Ни одного из четырёх спорных изомеров этот признак не
    /// различает: у `190Wm2` вольфрам на обоих уровнях, у `116AGm2` кадмий на
    /// обоих, у `70CUm2` медь на обоих. Вывод держат доводы выше — совпадение
    /// нижнего блока со строками самого `m1`, ветви `l_decays` и собственный
    /// переход вниз, — а не этот.
    ///
    /// Поэтому зажим идёт по СВОЕМУ уровню родителя, а `min(...)` остаётся
    /// запасным — для единственного `123CSm2`, у которого `nuclides.l_seqno`
    /// (8) в `decay_radiations` не встречается (там только 5). Смена правила
    /// затрагивает РОВНО этих четырёх: у остальных 2651 родителя из 2655
    /// уровень в `decay_radiations` один-единственный, и оба выражения дают на
    /// них одно и то же.
    ///
    /// ⚠ Зажим НЕ косметический и на обычных нуклидах: у `Pa-234m1` линия
    /// 1001.03 кэВ лежит на уровне 2, а не на нуле, поэтому «= 0» потеряло бы
    /// её целиком.
    ///
    /// Сверяет обоих читателей ЛИНИЯ К ЛИНИИ проба
    /// `tools/effmaker/probes/DecayReadersProbe.cs`; она же по `S94` требует,
    /// чтобы у родителя с K-рентгеном в базе читатель дал хоть одну K-линию —
    /// согласие в НУЛЕ согласием не считается.
    /// </summary>
    /// ⚠ Открыто наружу РАДИ ЧИТАТЕЛЯ, как и `FsaSampleLibrary.DecayLines` по
    /// `S89`: проба показывает, какой уровень выбрало правило, и обязана делать
    /// это ТЕМ ЖЕ выражением. Своя копия зажима в пробе означала бы два
    /// соглашения о том, что такое «родитель», — ровно ту беду, ради которой
    /// класс и заведён.
    public static class DecayParentRule
    {
        /// <summary>
        /// Довесок к `where` для запроса к `decay_radiations`: оставить строки
        /// того уровня родителя, которым родитель и ЯВЛЯЕТСЯ
        /// (<c>nuclides.l_seqno</c>), а если строк этого уровня в поставке нет
        /// — строки самого нижнего уровня. Параметр имени родителя должен
        /// называться <c>$n</c>.
        /// </summary>
        public const string LevelClause =
            " and parent_l_seqno = coalesce("
            + "   (select w.l_seqno from nuclides w where w.nucid = $n"
            + "     and exists (select 1 from decay_radiations z"
            + "                 where z.parent_nucid = $n and z.parent_l_seqno = w.l_seqno)),"
            + "   (select min(y.parent_l_seqno) from decay_radiations y"
            + "     where y.parent_nucid = $n))";

        /// <summary>
        /// Довесок к `where` для запроса к `decay_chain`: какая из строк
        /// описывает ФИЗИЧЕСКИЙ распад, а какая — тот же переход у
        /// ВОЗБУЖДЁННОГО уровня. Вопрос свой, отдельный от
        /// <see cref="LevelClause"/>: тот решает, чьи строки в
        /// `decay_radiations`, а этот — что считать ребром ряда.
        ///
        /// ⛔ Внешняя таблица обязана называться `d` — выражение зовёт её
        /// поимённо. Параметра выражение не несёт вовсе; если когда-нибудь
        /// понадобится, имя ему только `$n` (договор с
        /// `tools/CORPUS/scripts/chains.py`, который читает этот текст прямо
        /// отсюда и связывает словарём один-единственный параметр).
        ///
        /// ПОЧЕМУ МИНИМУМ ПО ТРОЙКЕ, а не «= 0». Строки с `l_seqno` больше
        /// минимального дублируют тот же переход с другим ветвлением: у
        /// `212BI` на `208TL` стоит 35.94 % при нуле и 67 % при пяти. Но и
        /// нуля мало: у `234PAm1` единственная строка лежит на уровне 2, и
        /// «= 0» терял её целиком, а с нею — весь ряд U-238 ниже
        /// (3 члена вместо 19). Изомер, живущий сам по себе, имеет
        /// собственный `nucid`, поэтому наименьший ПРИСУТСТВУЮЩИЙ уровень
        /// тройки и есть физический распад.
        ///
        /// ⚠ ПЕТЛИ `daughter_nucid = nucid` выражение НЕ СНИМАЕТ и не должно:
        /// в ряду это изомерный переход, и обходу они нужны как строки. Снимает
        /// их ПОТРЕБИТЕЛЬ, явно и у себя, — и это не мелочь: петля попадает в
        /// выборку у 511 родителей из 2535, а у 123 из них она ещё и побеждает
        /// по `perc`. У `183HF` на этом ровно и стоял дефект — дочерним атомом
        /// выходил сам гафний (замер `A218`, `ChainRuleProbeF58`).
        ///
        /// ⚠ У `NucBaseFramework.GetChainBranches` тут стоял свой текст, где
        /// минимум искался среди строк `x.perc not null`. Замер на всей
        /// поставке: троек, где этот довесок хоть что-то меняет, — НОЛЬ, и
        /// потому он снят вместе с копией. Проба следит за этим числом; станет
        /// оно ненулевым — довесок придётся вернуть СЮДА, всем сразу.
        ///
        /// Сводимость (второй копии в дереве нет) и цену правила поверяет
        /// `tools/effmaker/probes/ChainRuleProbeF58.cs`.
        ///
        /// ⛔ (`S189`, П152 24.09.2026) НО МИНИМУМ ПО ТРОЙКЕ — ЛИШЬ ЗАПАСНОЙ
        /// ХОД, А ПЕРВЫМ СТОИТ СВОЙ УРОВЕНЬ РОДИТЕЛЯ ДЛЯ ЭТОЙ ДОЧКИ. Изомер,
        /// «живущий сам по себе», своего `nucid` в `decay_chain` чаще НЕ имеет:
        /// его распад лежит под именем основного состояния на своём
        /// `l_seqno`. И если тройка «родитель — дочь — канал» есть только на
        /// уровне изомера, минимум по ней этот уровень и берёт — распад изомера
        /// садится в ветви основного состояния. `164TM`: на уровне 0 — 164ER
        /// каналом 15 (β⁺ 39 %), на уровне 1 — 164ER каналом 1 (20 %) и ИТ
        /// 80 %; по IAEA LiveChart (ENSDF, выборка 24.09.2026) уровень 1 — это
        /// изомер 5.1 мин с IT 80 % и ε+β⁺ 20 %, а основное состояние — ε+β⁺
        /// 100 %. Прежнее правило давало 164TM ДВЕ ветви в 164ER, вторую —
        /// чужую.
        ///
        /// Поэтому так: если у родителя есть строка СВОЕГО уровня
        /// (<c>nuclides.l_seqno</c>) в ЭТУ ЖЕ дочь — берутся только строки
        /// своего уровня; строки иных уровней в ту же дочь — распад другого
        /// состояния той же пары. Замер по `nucdb` 24.09.2026: таких троек 8
        /// (`131CE`, `164TM`, `166LU`, `174LU`, `184RE`, `202PB`, `90TC`,
        /// `93MO`), и у ВСЕХ восьми LiveChart подтверждает, что строка — изомера
        /// (у `90TC` ветвь в 90MO шла дважды по 100 %).
        ///
        /// ⛔ (`S191`, П158 24.09.2026) СТРОКИ ИНЫХ УРОВНЕЙ В ДРУГУЮ ДОЧЬ СУДИТ
        /// `l_decays`. Одной `decay_chain` их не различить: из 28 таких троек у
        /// родителей со своими строками часть — распад основного состояния,
        /// записанный не на тот уровень (`184AU` α 0.016 % на уровне 3, `191PB`
        /// ε 100 % на уровне 2), часть — изомера (`150EU` β⁻ 89 %, `176LU` ε
        /// 0.095 %). Судья — `l_decays` (моды распада по строкам `nuclides`, с
        /// их `l_seqno`): у СВОЕГО уровня родителя там стоят ВСЕ его моды.
        /// Строка иного уровня в дочь, в которую свой уровень по `l_decays` не
        /// распадается вовсе, — распад другого состояния, и в ветви родителя
        /// она не идёт. Замер 24.09.2026: таких строк 14 (`148HO`, `150EU`,
        /// `171AU`, `176LU`, `185PT`, `199BI`, `201BI`, `242AM`, `258MD` ×2,
        /// `53CO`, `93RU`, `94AG` ×2), и у ВСЕХ четырнадцати IAEA LiveChart
        /// (ENSDF, выборка 24.09.2026) отдаёт эту моду изомеру, а не основному
        /// состоянию.
        ///
        /// Судья молчит — строка остаётся, как была, и это нарочно:
        ///   * у родителя нет строк своего уровня в ДРУГИЕ дочери (`157LU`,
        ///     `95PD`: в `decay_chain` под именем основного лежит ТОЛЬКО набор
        ///     изомера, и снять его — оставить родителя без ветвей вовсе);
        ///   * у своего уровня в `l_decays` нет ни одной моды (14 троек) или
        ///     родителя нет в `nuclides` (6) — судить нечем;
        ///   * дочь у своего уровня есть (судья сравнивает ДОЧЬ, а не код
        ///     канала: у `94AG` ε в 94PD записан кодом 7 здесь и 1 там). Среди
        ///     них — строки изомера с ЧУЖОЙ долей в ту же дочь, что и у
        ///     основного (`197BI` α 55 % при α основного 10⁻⁴ %, `183PT` ε 96.9
        ///     при 100): долю основного знает только `l_decays`, а брать доли
        ///     из второй поставки — решение Amber (журнал П158, варианты).
        /// Петли `daughter = nucid` судья не трогает.
        /// </summary>
        public const string ChainLevelClause =
            " and l_seqno = coalesce("
            + "   (select w.l_seqno from nuclides w where w.nucid = d.nucid"
            + "     and exists (select 1 from decay_chain z where z.nucid = d.nucid"
            + "                 and z.daughter_nucid = d.daughter_nucid and z.l_seqno = w.l_seqno)),"
            + "   (select min(l_seqno) from decay_chain x"
            + "     where x.nucid = d.nucid"
            + "       and x.daughter_nucid = d.daughter_nucid"
            + "       and x.dec_type = d.dec_type))"
            + " and not (d.daughter_nucid <> d.nucid"
            + "   and not exists (select 1 from nuclides w where w.nucid = d.nucid and w.l_seqno = d.l_seqno)"
            + "   and exists (select 1 from nuclides w, decay_chain o where w.nucid = d.nucid"
            + "               and o.nucid = d.nucid and o.l_seqno = w.l_seqno and o.daughter_nucid <> o.nucid)"
            + "   and exists (select 1 from nuclides w, l_decays j where w.nucid = d.nucid"
            + "               and j.nucid = d.nucid and j.l_seqno = w.l_seqno)"
            + "   and not exists (select 1 from nuclides w, l_decays j where w.nucid = d.nucid"
            + "               and j.nucid = d.nucid and j.l_seqno = w.l_seqno"
            + "               and j.daughter_nucid = d.daughter_nucid))";

        /// <summary>
        /// (`S190`, П158 24.09.2026) Код канала «β⁺» в `decay_chain.dec_type`
        /// (подпись в `l_decays.decay_label` — «β+»). ⚠ Тот же код стоит
        /// ЛИТЕРАЛОМ в тексте <see cref="ChainPercColumn"/> — выражение читает
        /// питон, а склейку констант он не разбирает; согласие двух мест
        /// держит `tools/check_parent_rule.py` (раздел 3).
        /// </summary>
        public const string BetaPlusChannel = "15";

        /// <summary>
        /// Столбец выборки вместо голого `perc` для обхода `decay_chain`: ДОЛЯ
        /// ВЕТВИ, %, — одно правило для всех читателей рядов (`S190`, П158
        /// 24.09.2026). Ставится в список `select` запроса с
        /// <see cref="ChainLevelClause"/> (внешняя таблица — алиас `d`, строки
        /// одного родителя), читается числом (<see cref="TryPercent"/>): у
        /// расширенной строки это REAL, у прочих — прежний текст `perc`
        /// побитово.
        ///
        /// ⛔ ЧТО ЧИНИТ. `perc` строки канала «β⁺» (<see cref="BetaPlusChannel"/>)
        /// — доля ПОЗИТРОНОВ, а не ветви ε+β⁺: ENSDF пишет у распада два числа,
        /// «%EC+%B+» и «%B+», и `decay_chain` местами сохранила только второе
        /// (`l_decays` держит оба: код 1 «ec β+ 100%» и код 15 «β+ 39%»).
        /// Читатели рядов брали его долей ветви, и ряд через такого родителя
        /// терял дочь: `164TM` → 164ER 0.39, `131CE` → 131LA 0.11, `119TE` →
        /// 119SB 0.0206, `117I` → 117TE 0.77, `143PM` → 143ND 5.7·10⁻⁸ при
        /// истине 1.0 (ε+β⁺ 100 % по `l_decays` и IAEA LiveChart).
        ///
        /// ПРАВИЛО — то же, что у сумматора совпадений с `S189`: ветвь канала
        /// «β⁺» — всё, что оставляют ей ПРОЧИЕ ветви родителя (петли
        /// `daughter = nucid` — изомерный переход другого уровня — в «прочие» не
        /// идут), если это больше записанного; несколько строк канала делят
        /// остаток пропорционально своим `perc`. Канал, которому остатка не
        /// хватает (`20MG`: β⁺ 100 и βp 30.3), остаётся как записан — это уже
        /// не «доля позитронов вместо ветви», а избыток поставки.
        ///
        /// Окно `over ()` — строки ОДНОГО родителя, прошедшие `where` запроса,
        /// поэтому столбец годится только там, где выборка идёт по одному
        /// `nucid` (`where nucid = $n`), — так устроены все читатели.
        /// </summary>
        public const string ChainPercColumn =
            " case when d.dec_type = '15'"
            + "   and total(case when d.dec_type = '15' then cast(d.perc as real) end) over () > 0"
            + "   and total(case when d.dec_type = '15' then cast(d.perc as real) end) over ()"
            + "     < 100 - total(case when d.dec_type <> '15'"
            + "                         and upper(d.daughter_nucid) <> upper(d.nucid)"
            + "                        then cast(d.perc as real) end) over ()"
            + " then (100 - total(case when d.dec_type <> '15'"
            + "                         and upper(d.daughter_nucid) <> upper(d.nucid)"
            + "                        then cast(d.perc as real) end) over ())"
            + "   * (cast(d.perc as real)"
            + "      / total(case when d.dec_type = '15' then cast(d.perc as real) end) over ())"
            + " else d.perc end";

        /// <summary>
        /// Прочитать значение <see cref="ChainPercColumn"/> (или `perc`): REAL
        /// у расширенной строки, текст у прочих. Текст — инвариантной
        /// культурой (правило точки).
        /// </summary>
        public static bool TryPercent(object value, out double percent)
        {
            percent = 0.0;
            if (value is double)
            {
                percent = (double)value;
                return true;
            }

            if (value is long)
            {
                percent = (long)value;
                return true;
            }

            string text = value as string;
            return text != null
                   && double.TryParse(text, System.Globalization.NumberStyles.Float,
                                      System.Globalization.CultureInfo.InvariantCulture, out percent);
        }
    }
