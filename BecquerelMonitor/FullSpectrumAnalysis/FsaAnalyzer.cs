using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using BecquerelMonitor.Utils;

namespace BecquerelMonitor.FullSpectrumAnalysis
{
    /// <summary>
    /// Как сводятся ПОЛОСА ФИТА и ПОЛОСА БИБЛИОТЕКИ (`S98`).
    ///
    /// До 25.08.2026 они были РАЗНЫМИ, и разница ничем не была названа: фит шёл
    /// от нулевого канала до предпоследнего, а библиотека выбрасывала всякую
    /// линию ниже `Min_Range` прибора. Полоса ниже `Min_Range` входила и в χ², и
    /// в невязку, а описывать её было нечем — образы там запрещены, и всё
    /// брал на себя континуум-сплайн.
    /// </summary>
    public enum FsaBandMode
    {
        /// <summary>
        /// Как было до 25.08.2026: фит целиком, библиотека от `Min_Range`.
        /// Оставлено ТОЛЬКО ради A/B — это и есть измеренный дефект.
        /// </summary>
        Whole,

        /// <summary>
        /// Свести, сузив ФИТ: считать в полосе `MinEnergy…MaxEnergy`
        /// (у корпусных вызовов — `Min_Range…Max_Range` прибора).
        /// </summary>
        FitToLibrary,

        /// <summary>
        /// Свести, опустив пол БИБЛИОТЕКИ до <see cref="FsaBand.DefaultFloorKev"/>:
        /// фит остаётся на всём спектре, образам разрешены линии ниже
        /// `Min_Range`.
        /// </summary>
        LibraryToFit,

        /// <summary>
        /// ⛔ Свести, опустив пол БИБЛИОТЕКИ ДО САМОЙ КРИВОЙ спектра: линии
        /// впускаются не ниже той энергии, где кривая эффективности набирает
        /// <see cref="FsaBand.DefaultFloorFraction"/> от своего максимума
        /// (<see cref="FsaEfficiency.FloorAtFraction"/>).
        ///
        /// Решение Amber 27.08.2026 (`S98`) и довод, за него уплаченный: пол,
        /// заданный ЧИСЛОМ, всегда чей-то чужой. Пол 10 кэВ стоил понятной
        /// части +49 % Σχ², потому что у 79 кривых из 83 эффективность в первой
        /// точке ниже 1e-5; измеренный развёрткой пол 20 кэВ снимает почти всю
        /// цену, но у 19 спектров кривая набирает свой процент лишь к 30 кэВ, и
        /// им 20 всё ещё мало. Кривая знает это про себя сама.
        ///
        /// ⚠ Кривой нет у 38 спектров корпуса из 121; им пол по кривой
        /// назначить нечем, и они падают на `Min_Range`, как при
        /// <see cref="Whole"/>. Это ЗАПАСНАЯ ВЕТВЬ, а не отказ.
        /// </summary>
        LibraryToFitByCurve,

        /// <summary>
        /// ⛔ ОПОРА ПОЛОСЫ ПО СТОЛБЦУ, а не по энергии (`S103`, решение Amber
        /// 27.08.2026). Линии впускаются, как при
        /// <see cref="LibraryToFitByCurve"/>, а затем ПОСЛЕ фита выбрасываются
        /// поимённо те подпороговые, чей столбец сплайн континуума и так
        /// представляет: <c>ContinuumShare</c> выше
        /// <see cref="FsaBand.DefaultShareThreshold"/>. После выброса —
        /// ПЕРЕФИТ.
        ///
        /// Довод — измерение `S103`: одна и та же линия `Xray-I` 28.612 кэВ на
        /// одной группе приборов даёт долю континуума 0.0132 на
        /// `G1S16_Cd109_P5` и 0.7161 на `G1S16_Mix_Mar`, а норма столбца
        /// различается в 4.7 раза. Значит РАЗДЕЛИМОСТЬ ЕСТЬ СВОЙСТВО ФИТА, А НЕ
        /// ЭНЕРГИИ, и никакой пол, выраженный в кэВ или в доле от максимума
        /// кривой, этой границы поймать не может в принципе.
        ///
        /// ⛔⛔ ПОЧЕМУ ПРОХОДОВ ДВА, И ДЕШЕВЛЕ НЕ ВЫХОДИТ. `ContinuumShare`
        /// считается по дополнению Шура в метрике ФИТА: ему нужны активный
        /// набор колонок (какие шапки континуума вообще выжили), матрица Gram
        /// на подобранном узле сетки дрейфа и веса решателя. Ни одного из этих
        /// трёх нет ДО фита, а полосу библиотеки надо задать ДО. Поэтому:
        /// (1) фит по полной полосе (пол по кривой) → (2) поверка столбцов →
        /// (3) выброс линий выше порога → (4) ПЕРЕФИТ с сужённой библиотекой.
        /// Цена — ровно один лишний разбор спектра.
        /// </summary>
        LibraryToFitByShare
    }

    /// <summary>
    /// Умолчание полосы — ОДНО на весь разбор, и печатается вслух.
    ///
    /// ⛔ Выбор сделан числами, а не вкусом; всё измерено 25.08.2026 по ПОНЯТНОЙ
    /// части корпуса (81 спектр), чтением файлов, без прогона.
    ///
    /// **Против <see cref="FsaBandMode.FitToLibrary"/> (сузить фит):**
    ///
    /// * ниже `Min_Range` лежит 4.07 % всех отсчётов части (медиана по спектру
    ///   1.80 %, среднее 5.40 %; выше 10 % у десяти спектров) — но **72 % из
    ///   них (2.93 из 4.07 пп) стоят В ПРЕДЕЛАХ ОДНОЙ ПШПВ от границы**, то есть
    ///   это нижняя половина пиков, чьи центры лежат В ПОЛОСЕ. У G1S ПШПВ(30
    ///   кэВ) = 9.08 кэВ, и рез на 30 кэВ проходит прямо сквозь K-серию цезия
    ///   Ba-133 (30.6…35.8) и сквозь иодную флуоресценцию кристалла;
    /// * верхняя граница не стоит ничего вовсе: выше `Max_Range` медиана
    ///   0.026 %, худший спектр 0.30 %;
    /// * и обрыв стека на границе — та самая причина, по которой фит когда-то
    ///   и распустили на весь спектр.
    ///
    /// **За <see cref="FsaBandMode.LibraryToFit"/> (опустить пол библиотеки):**
    ///
    /// * физика внизу ЕСТЬ: матрица отклика считана на 5…3000 кэВ (140 узлов,
    ///   прочитано в заголовках `*.rmx` корпусных геометрий), кривая
    ///   эффективности спектра доходит до `Min_Range` и ниже у 79 из 81
    ///   (исключения — `AS80_Lu176` и `ASN16_Lu176`, у них кривая с 40 кэВ);
    /// * **приборный образ калечится границей во ВСЕХ 81 спектрах**: иод
    ///   кристалла светит Kα 28.32/28.61 кэВ (81.3 % веса K-серии) и Kβ 32.68
    ///   (18.7 %); при `Min_Range` = 30 кэВ у образа `Xray-I` остаётся ОДНА
    ///   линия Kβ. Образ, у которого выброшена главная линия, — не «неполный»,
    ///   а стоящий не там, и амплитуду он забирает чужую;
    /// * у распадов пол 10 кэВ трогает мало и точно: линии возвращаются лишь
    ///   у 15 спектров части, зато там, где они и есть, — Cd-109 (K-рентген
    ///   серебра 21.99/22.163/25.03/25.454, ΣI = 102.3 % на распад против
    ///   3.64 % у единственной гаммы 88.03), Am-241 (38.9 % против 35.9 %),
    ///   Y-88 (60.6 %), Bi-207 (33.2 %). Ниже 10 кэВ не пускается ничего: там
    ///   лежат Cs 4.97, Ba 4.75, Ce 5.18, Lu 9.11 кэВ — их прибор не видит, а
    ///   столбец у нулевого канала вырожден.
    ///
    /// ⚠ **ЦЕНА НАЗВАНА, и она в шкале, а не в физике.** У трёх спектров кадмия
    /// наблюдаемая нижняя структура стоит НЕ там, куда её поставит библиотека:
    /// по собственной калибровке спектра её центр 15.3 / 14.2 / 18.9 кэВ, а
    /// центр K-серии серебра 22.63 кэВ — это −0.93 / −1.07 / −0.48 ПШПВ. Это
    /// именно те спектры, чья калибровка `ref-cal` с одной опорной линией
    /// (`manifest.csv`), то есть внизу шкалы она экстраполирована. Для Am-241 и
    /// Co-57 та же сверка даёт −0.20 / −0.22 / +0.08 / +0.15 ПШПВ, то есть
    /// расхождение — свойство ТЕХ калибровок, а не затеи. ⛔ Опасность прямая:
    /// у `G1S16_Cd109_P5` нижняя структура несёт 182 539 отсчётов против 50 447
    /// в пике 88 кэВ (в 3.6 раза больше), и сетка дрейфа (её ширина и число
    /// узлов стоят В КОНСТРУКТОРЕ <see cref="FsaAnalyzer"/>, там же довод и
    /// цена — `T82`) в состоянии купить совпадение с ней, утащив линию 88.03
    /// с её нынешних −0.06 ПШПВ. Это ровно та ловушка, которую назвала `S95`
    /// и ловит признак `ПОДАВЛЕН` в `score.py`. Прогон ОБЯЗАН смотреть на
    /// состав, а не только на χ².
    /// </summary>
    public static class FsaBand
    {
        /// <summary>
        /// Пол полосы библиотеки, кэВ. ⛔ Числа здесь нет нарочно (`T82`) — оно
        /// стоит СТРОКОЙ НИЖЕ, у объявления константы. Взято оно не «на глаз»:
        /// это собственное умолчание <c>FsaSampleSpec.MinEnergyKev</c>, которое
        /// и означало «ниже этого прибор не говорит», пока его не начал
        /// затирать `Min_Range` поиска пиков.
        /// </summary>
        public const double DefaultFloorKev = 10.0;

        /// <summary>
        /// ⛔ УМОЛЧАНИЕ РАЗБОРА. Меняется здесь и только здесь; всё, что его
        /// читает, обязано его же и печатать (<see cref="Describe"/>).
        /// Решение Amber 25.08.2026 по строке `S98`.
        /// </summary>
        /// <summary>
        /// ⛔ ЧТО ИМЕННО ПОСТАВЛЯЕТСЯ — отдельно от того, что стоит СЕЙЧАС.
        /// Без этого разделения строка «(умолчание)» врёт на всяком абляционном
        /// прогоне: ключ двигает <see cref="DefaultMode"/>, и сравнение с ним
        /// самим всегда истинно. Поймано на себе 27.08.2026, второй раз за
        /// сутки (первый — эталон `PrintTuning` в пробе).
        /// </summary>
        /// ⛔ Значение — решение Amber 27.08.2026 по `S98`, и оно ИЗМЕРЕНО, а не
        /// выбрано: пол по кривой даёт понятной части recall 100 %, подавленных
        /// 0, медиану 2.86 и матрицу у 81 из 81, а непонятную оставляет ровно
        /// там, где она была до всей затеи (Σχ² 466.6 против 466.7, медиана
        /// 6.05). Прежнее умолчание `LibraryToFit` с полом 10 кэВ стоило
        /// понятной части +49 % Σχ², а на трёх поверочных маринелли теряло ряд
        /// ЦЕЛИКОМ (`B27`) — при поле по кривой состав у них восстановлен
        /// полностью, 7 и 16 нуклидных образов.
        public const FsaBandMode ShippedMode = FsaBandMode.LibraryToFitByCurve;

        public static FsaBandMode DefaultMode = ShippedMode;

        /// <summary>Пол по умолчанию — отдельным полем, чтобы A/B двигал и его.</summary>
        public static double DefaultFloor = DefaultFloorKev;

        /// <summary>
        /// ⛔ ЧТО ИМЕННО ПОСТАВЛЯЕТСЯ ДОЛЕЙ — отдельно от того, что стоит
        /// СЕЙЧАС, по той же причине, что и <see cref="ShippedMode"/>: без
        /// разделения строка «(умолчание)» врёт на всяком прогоне, где долю
        /// сдвинул ключ.
        /// </summary>
        public const double ShippedFloorFraction = 0.01;

        /// <summary>
        /// Доля от максимума кривой, ниже которой линии не впускаются при
        /// <see cref="FsaBandMode.LibraryToFitByCurve"/>. ⛔ Это ТОЖЕ подлежит
        /// A/B: доля взята из наблюдения (у 58 кривых корпуса из 83 она даёт
        /// ровно 20 кэВ, у 19 — 30, у трёх — 40), а не выведена. Развёртку по
        /// ней ставить с положительным контролем: доля, дающая пол, равный
        /// `Min_Range`, обязана воспроизвести <see cref="FsaBandMode.Whole"/>.
        /// </summary>
        public static double DefaultFloorFraction = ShippedFloorFraction;

        /// <summary>
        /// ⛔ ЧТО ПОСТАВЛЯЕТСЯ ПОРОГОМ ДОЛИ КОНТИНУУМА — по той же причине, что
        /// <see cref="ShippedMode"/>: без отдельной константы строка
        /// «(умолчание)» врала бы на всяком прогоне, где порог сдвинул ключ.
        ///
        /// 1.0 — НЕЙТРАЛЬНОЕ значение: доля зажата в [0…1], условие выброса
        /// строгое (<c>share &gt; порога</c>), значит при 1.0 не выбрасывается
        /// НИ ОДНА линия и режим <see cref="FsaBandMode.LibraryToFitByShare"/>
        /// обязан воспроизвести <see cref="FsaBandMode.LibraryToFitByCurve"/>
        /// ПОБИТОВО. Это положительный контроль самой развёртки, и он даровой.
        /// </summary>
        public const double ShippedShareThreshold = 1.0;

        /// <summary>
        /// Порог доли континуума при <see cref="FsaBandMode.LibraryToFitByShare"/>:
        /// подпороговая линия выбрасывается, если её <c>ContinuumShare</c>
        /// СТРОГО больше этого числа. Двигается ключом пробы `--share-thr=`;
        /// как <see cref="DefaultMode"/> и <see cref="DefaultFloorFraction"/>,
        /// живёт ОДНОЙ статикой — читателя у неё два (сам разбор и заверение),
        /// и вторая копия повторила бы `S101`.
        ///
        /// ⚠ Крайние значения — оба контроля развёртки: 1.0 не выбрасывает
        /// ничего (поставка), 0.0 выбрасывает всякую подпороговую линию, у
        /// которой континуум забирает хоть что-нибудь, — и это плечо
        /// <see cref="FsaBandMode.Whole"/>.
        /// </summary>
        public static double DefaultShareThreshold = ShippedShareThreshold;

        /// <summary>
        /// ⛔ СТОРОЖ ОБОИХ КОНЦОВ ПОЛОСЫ (`S101`, измерено 26.08.2026).
        ///
        /// Полосу читают ДВА места — <see cref="FsaAnalyzer"/> (полоса фита и
        /// строка заверения) и <c>FsaSampleSpec</c> (что режет линии). Пока у
        /// каждого была СВОЯ копия, снятая в момент создания, присваивание
        /// полосы одному из них двигало один конец, и A/B по полосе молча мерил
        /// одно и то же: плечо `--band=whole` дало состав и пределы ПОБИТОВО те
        /// же, что поставочный прогон, — 32 файла из 32, разошлись только `ms`
        /// и `cpu_ms`.
        ///
        /// Сегодня копий нет: оба конца читают <see cref="DefaultMode"/> и
        /// <see cref="DefaultFloor"/> В МОМЕНТ ОБРАЩЕНИЯ, а их собственные
        /// свойства сделаны БЕЗ присваивания (`get`-только), так что развести
        /// концы нечем — попытка не компилируется. Этот сторож остаётся
        /// ВСТРЕЧНОЙ проверкой на случай, когда копию заведут снова: он
        /// сличает то, что концы отдают НА САМОМ ДЕЛЕ.
        ///
        /// Пустая строка — сошлось. Положительный контроль самого сторожа —
        /// `CorpusFsaProbe --band-selftest`.
        /// </summary>
        public static string EndsNote(FsaBandMode analyzerBand, double analyzerFloor,
                                      FsaBandMode libraryBand, double libraryFloor)
        {
            if (analyzerBand == libraryBand && Math.Abs(analyzerFloor - libraryFloor) <= 1e-9)
            {
                return "";
            }

            return string.Format(CultureInfo.InvariantCulture,
                "⛔ РАССИНХРОН ПОЛОСЫ (`S101`): анализатор считает {0}, пол {1:F2} кэВ;"
                + " библиотека собирается по {2}, пол {3:F2} кэВ."
                + " A/B по полосе в таком виде мерит РАЗНОЕ у двух концов, и разница"
                + " принадлежит не ключу, а рассинхрону.",
                analyzerBand, analyzerFloor, libraryBand, libraryFloor);
        }

        /// <summary>
        /// Тот же сторож на живых объектах: спрашивает у каждого конца то, что
        /// он отдаёт читателю. ⚠ Спрашивать надо ИМЕННО свойства, а не поля
        /// умолчаний, — сторож затем и заведён, чтобы поймать конец, у которого
        /// снова завелась своя копия.
        /// </summary>
        public static string EndsNote(FsaAnalyzer analyzer, FsaSampleSpec spec)
        {
            if (analyzer == null || spec == null)
            {
                return "";
            }

            return EndsNote(analyzer.Band, analyzer.LibraryFloorKev,
                            spec.Band, spec.LibraryFloorKev);
        }

        /// <summary>
        /// Полоса ОБОИХ концов готовой строкой для шапки прогона: что стоит
        /// сейчас, что поставляется и сошлись ли концы. Умолчание, которого не
        /// видно в выводе, ничем не отличается от случайного, а два конца, чьё
        /// согласие никто не печатает, — от одного.
        /// </summary>
        public static string EndsLine(FsaAnalyzer analyzer, FsaSampleSpec spec)
        {
            string note = EndsNote(analyzer, spec);
            return string.Format(CultureInfo.InvariantCulture,
                "полоса ОБОИХ концов: анализатор {0}/{1:F2} кэВ, библиотека {2}/{3:F2} кэВ — {4}",
                analyzer.Band, analyzer.LibraryFloorKev,
                spec.Band, spec.LibraryFloorKev,
                note.Length == 0 ? "СОШЛИСЬ" : note);
        }

        /// <summary>Разобрать имя режима: `whole` / `fit` / `library`.</summary>
        public static bool TryParse(string name, out FsaBandMode mode)
        {
            mode = DefaultMode;
            if (string.IsNullOrEmpty(name))
            {
                return false;
            }

            switch (name.Trim().ToLowerInvariant())
            {
                case "whole":
                case "as-was":
                    mode = FsaBandMode.Whole;
                    return true;
                case "fit":
                case "fit-to-library":
                    mode = FsaBandMode.FitToLibrary;
                    return true;
                case "library":
                case "library-to-fit":
                case "floor":
                    mode = FsaBandMode.LibraryToFit;
                    return true;
                case "curve":
                case "library-to-curve":
                    mode = FsaBandMode.LibraryToFitByCurve;
                    return true;
                case "share":
                case "column":
                case "library-to-share":
                    mode = FsaBandMode.LibraryToFitByShare;
                    return true;
                default:
                    return false;
            }
        }

        /// <summary>
        /// Строка для печати: что за режим, каков пол и совпадает ли он с
        /// умолчанием. Умолчание, которое нигде не печатается, — это не
        /// умолчание, а тайна.
        /// </summary>
        public static string Describe(FsaBandMode mode, double floorKev, double minKev, double maxKev)
        {
            string tail = mode == ShippedMode ? " (умолчание)" : " (НЕ умолчание, A/B)";
            switch (mode)
            {
                case FsaBandMode.FitToLibrary:
                    return string.Format(CultureInfo.InvariantCulture,
                        "полоса сведена СУЖЕНИЕМ ФИТА до {0:F1}…{1:F1} кэВ{2}",
                        minKev, maxKev, tail);
                case FsaBandMode.LibraryToFit:
                    return string.Format(CultureInfo.InvariantCulture,
                        "полоса сведена ПОЛОМ БИБЛИОТЕКИ {0:F1} кэВ (Min_Range {1:F1}), фит на всём спектре{2}",
                        floorKev > 0.0 ? floorKev : minKev, minKev, tail);
                case FsaBandMode.LibraryToFitByCurve:
                    // ⛔ Печатается ФАКТИЧЕСКИЙ пол, а не заказанный: у спектра
                    // без кривой его назначить нечем, и он падает на Min_Range.
                    // Заверение обязано называть то, что случилось.
                    return floorKev > 0.0
                        ? string.Format(CultureInfo.InvariantCulture,
                            "полоса сведена ПОЛОМ ПО КРИВОЙ {0:F1} кэВ ({1:P1} от максимума, Min_Range {2:F1}), фит на всём спектре{3}",
                            floorKev, DefaultFloorFraction, minKev, tail)
                        : string.Format(CultureInfo.InvariantCulture,
                            "пол по кривой НАЗНАЧИТЬ НЕЧЕМ (кривой нет), библиотека от {0:F1} кэВ — запасная ветвь{1}",
                            minKev, tail);
                case FsaBandMode.LibraryToFitByShare:
                    // ⛔ Называется И пол первого прохода, И порог: без первого
                    // не видно, что вообще было впущено, без второго — что из
                    // впущенного выброшено. Порог печатается всегда, даже
                    // нейтральный: контрольное плечо обязано быть узнаваемым в
                    // журнале.
                    return string.Format(CultureInfo.InvariantCulture,
                        "полоса сведена ОПОРОЙ ПО СТОЛБЦУ: первый проход полом по кривой {0:F1} кэВ"
                        + " ({1:P1} от максимума, Min_Range {2:F1}), затем выброс подпороговых линий"
                        + " с долей континуума > {3:F3} и ПЕРЕФИТ{4}",
                        floorKev > 0.0 ? floorKev : minKev, DefaultFloorFraction, minKev,
                        DefaultShareThreshold, tail);
                default:
                    return string.Format(CultureInfo.InvariantCulture,
                        "полосы РАЗНЫЕ, как до 25.08.2026: фит на всём спектре, библиотека от {0:F1} кэВ{1}",
                        minKev, tail);
            }
        }
    }

    /// <summary>
    /// Полноспектральная декомпозиция (full-spectrum analysis).
    ///
    /// В отличие от поиска пиков вопрос ставится не «есть ли пик на 583 кэВ», а
    /// «какая смесь откликов Th-232, Ra-226, K-40... и фона лучше всего
    /// объясняет весь спектр сразу». Модель:
    ///
    ///     S(i) ~ sum_j A_j * F_j(i; a, b) + B(i) + C(i)
    ///
    /// F_j — образ компонента (сумма профилей единичной площади по таблице
    /// линий: положение из энергетической калибровки, ширина и форма из
    /// ПШПВ-калибровки, вес из выхода на распад родителя и кривой
    /// эффективности);
    /// a, b — дрейф шкалы (усиление и ноль), общие нелинейные параметры,
    /// перебираются сеткой; B — измеренный фон, вычитается с коэффициентом 1;
    /// C — континуум: неотрицательный кусочно-линейный базис («шапки») с шагом
    /// узлов не меньше нескольких ПШПВ, чтобы шапка не могла съесть одиночный
    /// пик; во сколько именно — <see cref="ContinuumKnotFwhm"/>, число стоит
    /// у объявления поля.
    ///
    /// Линейная часть — взвешенный NNLS (активное множество на нормальных
    /// уравнениях) с двумя итерациями хуберовского перевзвешивания, чтобы
    /// систематические расхождения формы не утаскивали оценки. После первого
    /// решения компоненты со значимостью ниже порога выбрасываются и модель
    /// пересчитывается заново.
    /// </summary>
    public sealed class FsaAnalyzer
    {
        /// <summary>Модель континуума.</summary>
        public enum ContinuumMode
        {
            /// <summary>Континуум оценивается SNIP-ом заранее и вычитается.</summary>
            Snip,
            /// <summary>Континуум входит в общую систему уравнений («шапки»).</summary>
            Spline
        }

        /// <summary>
        /// Как сводятся полоса фита и полоса библиотеки (`S98`).
        ///
        /// ⛔ ЧИТАЕТСЯ, А НЕ ХРАНИТСЯ (`S101`): значение берётся у
        /// <see cref="FsaBand.DefaultMode"/> при КАЖДОМ обращении, и своей
        /// копии у анализатора нет. Присваивания нет НАРОЧНО — оно двигало бы
        /// один конец из двух (второй, <c>FsaSampleSpec</c>, читает ту же
        /// статику), а A/B по полосе тогда молча мерит одно и то же: измерено
        /// 26.08.2026, плечо `--band=whole` дало состав и пределы побитово те
        /// же, что поставочный прогон. Рычаг ОДИН — та самая статика; её же
        /// печатает <see cref="FsaBand.Describe"/>, а согласие концов —
        /// <see cref="FsaBand.EndsLine"/>.
        /// Разбор выбора и цена каждой ветки — в шапке <see cref="FsaBand"/>.
        /// </summary>
        public FsaBandMode Band
        {
            get { return FsaBand.DefaultMode; }
        }

        /// <summary>
        /// Пол полосы БИБЛИОТЕКИ, кэВ, при <see cref="FsaBandMode.LibraryToFit"/>.
        ///
        /// ⚠ Анализатор библиотеку НЕ собирает и этим числом ничего не режет —
        /// оно здесь только для того, чтобы <see cref="BandNote"/> называл
        /// полосу целиком. Режет <c>FsaSampleSpec.LineFloorKev</c> при сборке.
        /// ⛔ Как и <see cref="Band"/>, читается у <see cref="FsaBand.DefaultFloor"/>
        /// при обращении и своей копии не имеет (`S101`).
        /// </summary>
        public double LibraryFloorKev
        {
            get { return FsaBand.DefaultFloor; }
        }

        /// <summary>
        /// Полоса фита ПОСЛЕДНЕГО разбора, готовой строкой: что за режим, какие
        /// каналы и какие кэВ вышли. Заполняется в <c>Analyze</c>; читателю
        /// (пробе, форме) остаётся напечатать. Пусто — разбора ещё не было.
        ///
        /// ⚠ Заведено ради правила `failure-signals-need-readers`: умолчание,
        /// которое нельзя увидеть в выводе прогона, ничем не отличается от
        /// случайного.
        /// </summary>
        public string BandNote { get; private set; }

        /// <summary>
        /// Считать по всему спектру, не обрезая по MinEnergy/MaxEnergy: от
        /// первого канала до предпоследнего (последний — канал переполнения).
        /// Разложение должно быть нарисовано на всём спектре: обрыв стека на
        /// границе диапазона поиска пиков читается как дефект отрисовки.
        /// Цена известна и измерена: на 8192-канальном NaI с порогом у самого
        /// начала шкалы χ²/ndf 20.7 (от 40 кэВ) против 28.0 (от нулевого
        /// канала) — шум порога модели описывать нечем, и его берёт на себя
        /// континуум.
        ///
        /// ⚠ С 25.08.2026 это НЕ отдельный выключатель, а вид на
        /// <see cref="Band"/>: «фит целиком» — это и `Whole`, и `LibraryToFit`,
        /// а `false` означает ровно `FitToLibrary`. Двух рычагов на одно
        /// решение здесь быть не должно — с них и началась `S98`.
        ///
        /// ⛔ Присваивания нет (`S101`): оно двигало бы полосу ОДНОМУ концу.
        /// Сузить фит — значит поставить <see cref="FsaBand.DefaultMode"/> в
        /// <see cref="FsaBandMode.FitToLibrary"/>, и тогда это увидят оба.
        /// </summary>
        public bool FitWholeSpectrum
        {
            get { return this.Band != FsaBandMode.FitToLibrary; }
        }

        public ContinuumMode Mode { get; set; }

        /// <summary>
        /// Во сколько частей делится диапазон, задавая САМЫЙ РЕДКИЙ шаг узлов
        /// континуум-сплайна (`BuildHatBasis`). Больше делитель — гуще узлы.
        ///
        /// ⚠ Сгущает только НИЗ шкалы, и в этом весь смысл (`B17`). Шаг узла —
        /// `max(K·ПШПВ, minStep)`, где K — <see cref="ContinuumKnotFwhm"/>:
        /// наверху ПШПВ велика и правит она, внизу мала, и связывает
        /// равномерный пол `minStep`. Уменьшая пол, трогаем ровно то место, где
        /// невязка и стояла гребёнкой с шагом ≈43 кэВ.
        ///
        /// ⛔ ЧИСЛА УМОЛЧАНИЯ ЗДЕСЬ НЕТ НАРОЧНО. Оно стоит В КОНСТРУКТОРЕ, у
        /// присваивания этого свойства, и там же — довод и названная цена
        /// (решение Amber 16.08.2026 по `B17`). Здесь его нет потому, что
        /// вторая копия числа ровно так и стареет: это описание называло 64,
        /// когда конструктор уже ставил другое (`T70`). Такую же копию убрали
        /// из пробы (`T65`, поле `Knots`), и там же рядом она успела
        /// СРАБОТАТЬ — шапка прогона печатала ОДНУ сетку дрейфа, а разбор
        /// считал ДРУГУЮ. Числа того случая в строке `T65`; здесь их нет по
        /// той же причине, по которой нет и умолчания.
        ///
        /// Прочесть поставочное значение можно прогоном, а не чтением:
        /// `CorpusFsaProbe` сличает настроенный анализатор с нетронутым
        /// `new FsaAnalyzer()` отражением и печатает строку «ключами изменено
        /// против поставочного разбора»; на `--knots=64` в ней стоит
        /// `ContinuumKnotDivisor` с поставочным значением и стрелкой на 64.
        /// </summary>
        public int ContinuumKnotDivisor { get; set; }

        /// <summary>
        /// Сколько ПШПВ отмеряет ГУСТОЙ край шага узлов (`S88`). ⛔ ЧИСЛА
        /// УМОЛЧАНИЯ ЗДЕСЬ НЕТ НАРОЧНО (`T82`) — оно стоит У ОБЪЯВЛЕНИЯ ПОЛЯ,
        /// строкой ниже этого описания; при нём посчитана вся история
        /// измерений.
        ///
        /// Порог существует затем, чтобы континуум не мог поглотить одиночный
        /// пик, и трогать его в поставке нельзя. Но ровно он и делает сплайн
        /// неспособным повторить волну с масштабом 50…130 кэВ, а значит —
        /// неспособным её ни объяснить, ни спрятать. Чтобы это стало
        /// утверждением, а не рассуждением, нужен A/B: поле — программная ручка
        /// для проб, как <see cref="LimitQuantileK"/> и
        /// <see cref="ResponseContinuumTrustFloorKev"/>; в UI и конфигурацию не
        /// выводится.
        ///
        /// ⚠ Значение НИЖЕ поставочного ЛОМАЕТ состав: сплайн начинает забирать
        /// пики. Годится только как абляция, читать после него можно форму
        /// невязки, а не разложение.
        /// </summary>
        public double ContinuumKnotFwhm = 4.0;

        /// <summary>
        /// ШТРАФ НА ИЗЛОМ КОНТИНУУМА (`S85`, решение Amber 24.08.2026): вес
        /// слагаемого λ·Σ(c[k−1] − 2c[k] + c[k+1])² на коэффициентах шапок
        /// сплайна. 0 — штрафа нет.
        ///
        /// Зачем. Амплитуда обратного рассеяния данными НЕ ОПРЕДЕЛЯЕТСЯ: от
        /// одной только густоты узлов образ пропадает у двадцати спектров
        /// корпуса, а где выживает — ходит десятками процентов. Спорит он со
        /// СПЛАЙНОМ: тот свободен настолько, что повторяет бугор шириной с пик,
        /// и модель раскладывает одну и ту же форму двумя способами с одинаковой
        /// невязкой. Запрет по ШАГУ УЗЛОВ эту свободу режет грубо — вместе со
        /// способностью описывать настоящий континуум (`S92`: порог 4·ПШПВ
        /// стоит 39 % корпусного χ²). Штраф на вторую разность режет иначе:
        /// медленно меняющуюся подложку он пропускает даром, а излом — тем
        /// дороже, чем он резче.
        ///
        /// ⚠ Величина БЕЗРАЗМЕРНА: внутри домножается на среднее диагональное
        /// значение Грама по блоку шапок, иначе один и тот же λ значил бы разное
        /// на жирном и тощем спектре.
        /// </summary>
        public double ContinuumRoughness = 0.0;

        /// <summary>
        /// Сколько ПЕРВЫХ колонок в `fixedColumns` — шапки континуума. Нужно
        /// затем, что штраф <see cref="ContinuumRoughness"/> ложится на их
        /// коэффициенты и только на них, а в `fixedColumns` за ними идут другие
        /// (наложения, хвосты матричных образов).
        /// </summary>
        int continuumColumns;

        /// <summary>
        /// Каналы узлов континуума последней сборки базиса — для штрафа на
        /// излом (`S85`). Шаг узлов неравномерен, и вторая производная берётся
        /// по шкале, а не по номеру.
        /// </summary>
        List<int> continuumKnots;

        public double MinEnergy { get; set; }

        public double MaxEnergy { get; set; }

        /// <summary>Доля погрешности континуума в весах.</summary>
        public double Xi { get; set; }

        /// <summary>Порог хуберовского перевзвешивания, в сигмах. 0 — выключено.</summary>
        public double HuberM { get; set; }

        /// <summary>
        /// (S43) Коэффициент γ составного шума: дисперсия канала берётся
        /// D = F + γ²·F², где F — отсчёты канала. На больших статистиках чистый
        /// пуассон объявляет знание тысячных долей процента, и χ² жирных
        /// спектров мерит систематику тракта, а не согласие; линейный член
        /// признаёт потолок точности канала (первый кандидат смысла —
        /// дифференциальная нелинейность). 0 — выключено (сегодняшний вес).
        /// Отчётный χ² при этом СЧИТАЕТСЯ ПРЕЖНИМИ весами
        /// (<see cref="FsaResult.Chi2NdfPoisson"/>) — иначе правка мерила бы
        /// себя своей же метрикой.
        /// </summary>
        public double NoiseGamma { get; set; }

        /// <summary>
        /// (S45) Перекладывать фон на шкалу спектра перед вычитанием.
        /// Полярность умолчания, дата её смены и прежнее состояние стоят В
        /// КОНСТРУКТОРЕ, у присваивания этого свойства (`T82`: второй копии в
        /// описании быть не должно — она стареет молча). Зачем оно нужно: фон
        /// снят своим измерением и живёт в своей калибровке — у спектров
        /// корпуса с отдельным фоном шкалы расходятся на 12–58 кэВ на канале
        /// 1000. Выключатель нужен для A/B: «до» и «после» на ОДНОМ составе
        /// корпуса (`CorpusFsaProbe --no-bg-rebin`), иначе эффект правки
        /// смешается с любой другой сменой корпуса.
        /// </summary>
        public bool RebinBackgroundToSpectrum { get; set; }

        /// <summary>
        /// (S43) Коэффициент β коррелированности вычитаемого фона: к дисперсии
        /// канала добавляется β²·B², где B — вычитаемый фон канала (уже в
        /// шкале пробы). Смысл — «фон вырос — вырос везде»: доля фона, общая
        /// всем каналам, не давится статистикой канала. 0 — выключено; работает
        /// только там, где фон действительно вычитается.
        /// </summary>
        public double NoiseBeta { get; set; }

        /// <summary>
        /// (P6) Считать парциальные невязки компонентов: χ²/ndf в пиковых
        /// окнах каждого вошедшего компонента и ΔD — насколько присутствие
        /// компонента улучшает невязку его же зоны (рефит без него при том же
        /// узле дрейфа). Пост-расчёт, состав не трогает; цена — один рефит на
        /// компонент, поэтому умолчание ВЫКЛЮЧЕНО (ручка для проб, как
        /// <see cref="ResponseContinuumTrustFloorKev"/>). Читатель —
        /// CorpusFsaProbe (`--partial`), поля —
        /// <see cref="FsaComponentResult.ZoneChi2Ndf"/> /
        /// <see cref="FsaComponentResult.ZoneDeltaD"/> /
        /// <see cref="FsaComponentResult.ZoneChannels"/>.
        /// </summary>
        public bool PartialResiduals { get; set; }

        /// <summary>
        /// (P6 «б») Гейт по парциальной невязке: исключать нуклидные
        /// компоненты с ΔD &lt; 0 (присутствие ухудшает невязку их же зоны) и
        /// перефитивать один раз. ВКЛЮЧЁН УМОЛЧАНИЕМ решением Amber
        /// 14.08.2026 (вечер) по A/B корпуса-70: фантомы 5/37 → 4/32 (снят и
        /// фантом понятной части, и Np-239 86.8 % на OBS), цена — один
        /// настоящий компонент непонятной части (Bi-214 оникса) и +1.8 % Σχ².
        /// Выключатель для A/B — `--no-pr-gate` у CorpusFsaProbe.
        /// </summary>
        public bool PartialResidualGate { get; set; }

        /// <summary>Порог значимости для отсева перед вторым проходом. 0 — без отсева.</summary>
        public double RefitZ { get; set; }

        /// <summary>
        /// (S47) Убирать свободные образы вылета `SE-2614`/`DE-2614`, когда
        /// разбор идёт ЧЕРЕЗ МАТРИЦУ ОТКЛИКА.
        ///
        /// Почему это верно, и почему только с матрицей. Измерено
        /// `EscapeGateProbe` по всем 13 матрицам корпуса: отклик линии 2614.5
        /// кэВ содержит пики вылета на 2103.5 и 1592.5 — то есть образ Tl-208,
        /// построенный через матрицу, УЖЕ несёт свои вылеты в физически верной
        /// доле (крупные сцинтилляторы SE/пик 0.18…0.24, DE/пик 0.04…0.11).
        /// Свободный столбец рядом с таким образом — ВТОРОЙ СЧЁТ того же, и
        /// взять он может только чужое: на `!AS80x80\Lu-176.xml` `DE-2614`
        /// держал 10.9…17.2 % при Tl-208 в 2.41 %, а на 1592.5 стоит чужая
        /// линия Ac-228 1588.19 — в 4.3 кэВ при ПШПВ около 78.
        ///
        /// БЕЗ матрицы образ строится из одних пиков, вылетов в нём нет вовсе,
        /// и свободный столбец остаётся единственным способом их выразить —
        /// поэтому там он не трогается ни при каком значении этого ключа.
        ///
        /// `Ann-511` под правило НЕ попадает: аннигиляционный квант рождается
        /// в защите и обвязке и ВЛЕТАЕТ в кристалл, а матрица описывает судьбу
        /// кванта, который в кристалл уже попал. Её источника в матрице нет.
        /// </summary>
        public bool EscapeGate { get; set; }

        public double GainRange { get; set; }

        public int GainSteps { get; set; }

        /// <summary>Диапазон сдвига нуля шкалы, кэВ.</summary>
        public double OffsetRangeKev { get; set; }

        public int OffsetSteps { get; set; }

        /// <summary>
        /// Добавлять образы обратного рассеяния, выведенные из найденного
        /// состава. Мерено дважды, и числа принадлежат РАЗНОМУ коду:
        ///
        ///   * харнесс `tools/pie`, 46 спектров, состав цепочками:
        ///     recall 86 % → 89 %, Σχ²/ndf 559 → 547;
        ///   * этот код, весь корпус, состав дочерними (13.08.2026,
        ///     `CorpusFsaProbe --no-backscatter`): понятная часть Σχ²/ndf
        ///     99.7 → 95.9, непонятная 716.6 → 685.4 (−4.4 %), recall
        ///     70 % → 71 %, фантомов 26 → 25. Крупнее всего на
        ///     `ASN16_Cs137` (−13 %) и `OBS_Background` (−15 %).
        ///
        /// Сравнивать две строки между собой нельзя — разный код, разный
        /// корпус и разное правило счёта; каждая верна для своего.
        /// </summary>
        public bool Backscatter { get; set; }

        /// <summary>
        /// Матрица отклика геометрии, если она посчитана и годна. С ней образ
        /// компонента — это сумма ОТКЛИКОВ его линий, то есть пик вместе с
        /// комптоновским плато, краем и пиками вылета; без неё — только пики, а
        /// всё плато достаётся свободной подложке.
        ///
        /// Матрица уже несёт эффективность (она посчитана как доля на квант,
        /// испущенный источником), поэтому кривая эффективности к её весам
        /// ВТОРОЙ раз не применяется.
        /// </summary>
        public EfficiencyMaker.ResponseMatrix ResponseMatrix { get; set; }

        /// <summary>
        /// Вносить каскадное суммирование (<see cref="FsaCascadeSummer"/>):
        /// множитель CF на площадь пика и отдельные сумм-пики. Работает только
        /// вместе с матрицей отклика — эффективности берутся из неё.
        ///
        /// Выключатель нужен не для пользователя, а для измерения: без него
        /// «с поправкой» и «без поправки» на одном спектре не снять, а
        /// утверждение о пользе, не подкреплённое таким A/B, уже однажды
        /// оказалось непроверяемым (S13, порог континуума).
        /// </summary>
        public bool CascadeSumming { get; set; }

        /// <summary>
        /// Ставить ли СУММ-ПИКИ (E_i + E_j) — вторая половина суммирования,
        /// отдельно от множителя на пик. Две половины делают разное: множитель
        /// срезает пик, сумм-пик добавляет структуру там, где её в образе не
        /// было, — и мерить их надо порознь, иначе выигрыш одной спишется на
        /// проигрыш другой.
        /// </summary>
        public bool CascadeSumPeaks { get; set; }

        /// <summary>
        /// Идёт ли сумм-КОНТИНУУМ (S19) в подслой отрисовки. В МОДЕЛЬ он идёт
        /// всегда — это вопрос только про штриховку внутри ленты нуклида.
        ///
        /// Техническая преграда снята: подслой строится тем же кодом, что и
        /// лента, и выше неё не поднимается по построению (S37). Осталась
        /// смысловая, и она не про счёт: подслой читается как «вот эти пики —
        /// суммы», а широкая полка, нарисованная так же, читалась бы как пик,
        /// которого нет. Поэтому умолчание — только пики; поле оставлено
        /// ручкой для проб, в UI не выводится (как
        /// <see cref="ResponseContinuumTrustFloorKev"/>).
        /// </summary>
        public bool SumLayerIncludesContinuum;

        /// <summary>
        /// (`S103`) ПОВЕРКА СТОЛБЦОВ ОТДЕЛЬНЫХ ЛИНИЙ ниже этой энергии, кэВ;
        /// 0 (умолчание) — поверка не считается вовсе и разбор не трогается ни
        /// одним действием. Итог ложится в <see cref="FsaResult.LineColumns"/>,
        /// читатель — ключ `--band-audit=` пробы `CorpusFsaProbe`.
        ///
        /// Заведено ради ОДНОГО вопроса, который иначе решается рассуждением:
        /// линии, впущенные ниже `Min_Range` полом полосы, — они бесполезны
        /// потому, что модель там ничего не предсказывает, или потому, что их
        /// вклад забирает сплайн континуума? Первое — довод за пол, второе —
        /// дефект модели. Числа, которые их разводят, живут только внутри
        /// фита: норма столбца во взвешенной метрике, амплитуда владельца и
        /// доля столбца, представимая шапками континуума.
        ///
        /// ⚠ Поверка стоит по одному построению образа на линию и потому НЕ
        /// поставляется включённой: на спектре с сотней подпороговых линий это
        /// сотня лишних свёрток. В UI не выводится — как
        /// <see cref="ResponseContinuumTrustFloorKev"/>.
        /// </summary>
        public double LineColumnAuditBelowKev;

        /// <summary>
        /// Добавлять образ случайных наложений (pile-up) — автосвёртку самого
        /// спектра со свободной амплитудой. См.
        /// <see cref="BuildPileUpComponent"/>: это НЕ каскад, а свойство
        /// загрузки, и без него пик 662+662 у Cs-137 модели описать нечем.
        ///
        /// Цена измерена по корпусу 13.08.2026 (`CorpusFsaProbe --no-pileup`) и
        /// она МАЛА: χ²/ndf меняется больше чем на 0.1 % только у 4 спектров из
        /// 61, крупнейший сдвиг −0.88 % — как раз на `ASN16_Cs137`, то есть
        /// направление верное. Но объяснить этот спектр наложения не могут: он
        /// остаётся худшим в корпусе (χ²/ndf 45.2) и с ними, и без них. Причина
        /// в другом — горб 662+662 модель ставит по сумме ЭНЕРГИЙ, а измерен он
        /// по сумме СВЕТА и стоит на ~23 кэВ выше (TODO S20).
        /// </summary>
        public bool PileUp { get; set; }

        /// <summary>
        /// Вещество кристалла в именах таблицы кривых света («CsI:Tl», «NaI:Tl»).
        /// Нужно каскадному суммированию: сумм-пик встаёт по сумме СВЕТА, а не
        /// энергий (S20). Пусто — суммы ставятся по энергии, как до 13.08.2026.
        ///
        /// Задаётся снаружи вместе с матрицей: у матрицы вещества нет, от
        /// геометрии в ней остаётся только необратимый отпечаток. Берётся тем
        /// же путём, что у симулятора —
        /// <see cref="EfficiencyMaker.EfficiencySimulator.ScintillatorNameOf(EfficiencyMaker.GeometryModel)"/>.
        /// </summary>
        public string ScintillatorMaterial { get; set; }

        /// <summary>
        /// ОКНО СОВПАДЕНИЯ, секунды: мёртвое время прибора, оно же длительность
        /// импульса (S27). Два кванта складываются в один отсчёт, только если
        /// разошлись во времени меньше, чем на неё, — а разводит их время жизни
        /// промежуточного уровня. Без этого модель ставит Cd-109 сумму
        /// 22 + 88 = 110 кэВ, которой не бывает: уровень Ag-109 88 кэВ живёт
        /// 39.79 с.
        ///
        /// Ноль означает «прибор своего мёртвого времени не назвал» и заменяется
        /// на <see cref="FsaCascadeSummer.DefaultCoincidenceWindowSec"/>.
        /// Источник — `InputDeviceConfig.DeadTime()`; у AtomSpectra это прямо
        /// `(rise + fall + 1)/f`, измерено 1.357 мкс на AS80x80.
        /// </summary>
        public double CoincidenceWindowSec { get; set; }

        /// <summary>
        /// Считать ли K-рентген дочернего атома партнёром совпадения (S27).
        /// Выключатель — для РАЗДЕЛЯЮЩЕГО замера, как
        /// <see cref="CascadeSumPeaks"/>: цену правки надо снимать при одной
        /// версии физики, иначе «стало лучше» ничего не значит.
        /// </summary>
        public bool CascadeXrayPartners { get; set; }

        /// <summary>
        /// Считать ли аннигиляционные кванты партнёром совпадения (S27).
        /// ⛔ Пара 511 + 511 не заводится ни при каком значении — кванты летят
        /// спина к спине, см. <see cref="CascadeAtomicData.AnnihilationQuanta"/>.
        /// </summary>
        public bool CascadeAnnihilationPartners { get; set; }

        /// <summary>
        /// Искать ли ИЗОМЕРЫ по символу Sandia (S27). Полярность умолчания
        /// стоит В КОНСТРУКТОРЕ, у присваивания этого свойства (`T82`: здесь
        /// её не было, а стояла ОБРАТНАЯ — описание пережило смену умолчания).
        /// При снятом ключе имя вида «Ag-108m» не разбирается и компонент
        /// остаётся без поправки — это поведение до `S27`. Ключ — для
        /// разделяющего замера.
        /// </summary>
        public bool CascadeIsomerPartners { get; set; }

        /// <summary>Живёт один разбор: матрицу могли подменить между вызовами.</summary>
        FsaCascadeSummer cascade;

        /// <summary>
        /// Поправка хоть где-то СРАБОТАЛА — не «включена», а изменила образ.
        /// Это разные вещи: суммирователь молча возвращает единицы, когда у
        /// нуклидов состава нет каскадов вовсе (Cs-137, K-40), и пометка
        /// «с суммированием» на таком спектре была бы враньём.
        /// </summary>
        bool cascadeApplied;

        /// <summary>
        /// (`S103`) ИДЁТ ВТОРОЙ ПРОХОД опоры полосы по столбцу. Сторож глубины:
        /// перефит зовёт `Analyze` рекурсивно (чтобы плечо отличалось от
        /// поставки РОВНО библиотекой и ничем иным), и без этого признака второй
        /// проход завёл бы третий, третий четвёртый — выброс на каждом шаге
        /// новый, потому что континуум пересаживается. Здесь проходов ровно два
        /// нарочно: вопрос строки — «годится ли доля континуума опорой», а не
        /// «сойдётся ли она к неподвижной точке».
        /// </summary>
        bool shareRefit;

        /// <summary>
        /// Гистограммы поглощения компонентов, посчитанные ОДИН раз на разбор.
        ///
        /// От узла сетки дрейфа гистограмма не зависит вовсе: усиление и ноль
        /// шкалы накладываются позже, при уширении, а сложение откликов линий,
        /// сумм-пиков и сумм-континуума знает только энергии. До 13.08.2026 её
        /// тем не менее строили заново на каждом узле сетки дрейфа — тогда их
        /// было 81 (9×9; сегодня сетку задают <see cref="GainSteps"/> и
        /// <see cref="OffsetSteps"/>, и число другое) — и с приходом
        /// тройных сумм и сумм-континуума (S19) это стало главной статьёй
        /// расхода: корпусный прогон подорожал с 50 с до 236 с.
        ///
        /// Живёт ровно один разбор, как и остальные кэши: между вызовами могли
        /// смениться и матрица, и калибровка.
        /// </summary>
        readonly Dictionary<FsaComponent, Deposit> deposits = new Dictionary<FsaComponent, Deposit>();

        /// <summary>
        /// Гистограмма поглощения компонента и всё, что от неё отрезано:
        /// подпороговый хвост отдельной колонкой и доля сумм для подслоя.
        /// Ножи применены ДО кэширования, поэтому все три части согласованы
        /// поканально при любом числе обращений.
        /// </summary>
        sealed class Deposit
        {
            public double[] Values;
            public double[] Tail;
            public double[] SumPart;
            public bool CascadeApplied;
        }

        public FsaAnalyzer()
        {
            this.Mode = ContinuumMode.Spline;
            // S98/S101: полоса СЮДА НЕ КОПИРУЕТСЯ вовсе. `Band` и
            // `LibraryFloorKev` — читалки `FsaBand.DefaultMode` /
            // `FsaBand.DefaultFloor`, и рычаг у полосы поэтому ровно один: та
            // статика. Прежние две строки копировали её в момент создания, и
            // второй конец (`FsaSampleSpec`) делал то же самое своей копией —
            // отсюда и рассинхрон, которым `S101` заведена.
            this.MinEnergy = 40.0;
            this.MaxEnergy = 2800.0;
            this.Xi = 0.03;
            this.HuberM = 3.0;
            this.RefitZ = 3.0;
            // S47: умолчание выставлено по A/B корпуса, см. описание свойства
            // и §13с журнала матрицы. Выключатель для A/B — `--no-escape-gate`.
            this.EscapeGate = true;
            // B17: 128 вместо прежних 64 — решение Amber 16.08.2026 по A/B на
            // КОПИИ корпуса. Понятная часть 788.4 -> 736.5 Σχ²/ndf (−6.6 %),
            // невязка модели 23.8 -> 21.0 %, recall 93 % без изменений. Цена
            // названа и принята: у НЕПОНЯТНОЙ части recall 73 -> 69 %, фантомов
            // 27 -> 31 — там образ строится из одних пиков и конкурирует с
            // густым континуумом напрямую. Ключ A/B — `--knots=<делитель>`.
            this.ContinuumKnotDivisor = 128;
            // ⛔ СЕТКА ДРЕЙФА РАСШИРЕНА 24.08.2026 решением Amber (`S93`).
            // Прежняя (±0.8 %, ±3 кэВ, 9×9) была УЗКА для половины корпуса: 46
            // спектров из 81 упирались в край нуля, 17 — в край усиления, 12 —
            // в оба, и значения стояли ровно на ограничении, то есть дрейф у
            // них не подбирался, а обрезался.
            //
            // Замер на понятной части (81 спектр), прежняя сетка -> эта:
            // Σχ² 575.1 -> 535.0, медиана χ²/ndf 3.34 -> 3.05, медиана невязки
            // модели 12.6 -> 11.4 %, верхняя четверть 24.8 -> 19.8 %, на краю
            // 17/46 -> 11/15. Лучше у 41 спектра, хуже у 11.
            //
            // ⚠ Цена названа и принята: фантомов по-прежнему 0, но recall
            // 99 -> 98 % (теряется один спектр в G1S16), а сетка 17×17 стоит
            // вчетверо больше счёта, чем 9×9.
            //
            // ⚠ Шаг при этом ЗАГРУБЛЁН, и это не упущение: 1.00 кэВ против
            // 0.75 и 0.25 % против 0.2. Мерено именно так; узлы добавлены ради
            // ОХВАТА, а не разрешения — упирались в границу, а не в шаг.
            // ⛔ (`S95`, измерено 24.08.2026) РАСШИРЯТЬ СЕТКУ ДАЛЬШЕ — ЛОВУШКА, и
            // выглядит она как улучшение. Развёртка по понятной части корпуса
            // (81 спектр, база `out_v5`, контроль воспроизводит её в точности):
            //
            //   ноль ±8 → ±16 кэВ : Σχ² 477.8 → 452.9 (−5.2 %), медиана 2.90 →
            //       2.89, верхняя четверть невязки 18.9 → 17.2 %, на краю 13 →
            //       7, recall 99 %, фантомов 0 — то есть ВСЕ заглавные числа
            //       лучше;
            //   усиление ±2 → ±4 %: Σχ² не двигается (477.6), медиана ХУЖЕ
            //       (2.90 → 3.04). Здесь запас уже есть, шире не надо.
            //
            // А цена широкого нуля — СОСТАВ: у `G1S16_Cd109_P5` кадмий падает
            // 96 % → 5 %, и спектр забирает приборный образ `Xray-I` (4 → 94 %),
            // потому что ноль уходит на новый край, −16 кэВ. Это ложь: приёмка
            // корпуса ставит его линию 88.03 в −0.06 ПШПВ, а −16 кэВ на 88 кэВ
            // это −1.3 ПШПВ, то есть модельная линия съезжает с настоящего пика
            // целиком. Невязка при этом «улучшается» 87.0 → 53.7 %, χ²/ndf 4.33
            // → 3.90, а recall не замечает вовсе — он спрашивает «нуклид
            // назван?», а не «нуклид ли объясняет спектр».
            //
            // Читатель у этого теперь есть: `score.py` печатает `ПОДАВЛЕН`,
            // когда приборный образ пересилил ВЕСЬ объявленный состав. Он же
            // ловит задним числом `B24` (`G1S16_Ba133_P5`, `Esc-NaI` 61 % при
            // нуле нуклидного). Настоящее лечение — держать дрейф ЛИНИЯМИ, а не
            // общим χ²; это `S95` и это смена базы, то есть решение Amber.
            this.GainRange = 0.02;
            this.GainSteps = 17;
            this.OffsetRangeKev = 8.0;
            this.OffsetSteps = 17;
            this.Backscatter = true;
            this.CascadeSumming = true;
            this.CascadeSumPeaks = true;
            // S27: атомные партнёры каскада включены умолчанием. Окно
            // совпадения ноль — «прибор не назвал»; кто знает мёртвое время,
            // ставит его сам (FsaOverlay берёт у InputDeviceConfig.DeadTime()).
            this.CascadeXrayPartners = true;
            this.CascadeAnnihilationPartners = true;
            this.CascadeIsomerPartners = true;
            this.CoincidenceWindowSec = 0.0;
            this.PileUp = true;
            this.PartialResidualGate = true;

            // ВКЛЮЧЕНО 16.08.2026 — условие включения, записанное 15.08, теперь
            // выполнено. Перекладку выключали не за неё саму: фон в корпусе
            // калибровался ОТДЕЛЬНО, по спектру, бедному линиями, и перекладка
            // честно переносила выдуманное расхождение шкал (A/B корпуса-58:
            // понятная 94.1 → 97.8, +3.9 %, +1 фантом). Измерено, что виноват
            // был именно конвейер: наша перекалибровка РАЗВОДИЛА шкалы, стоявшие
            // в исходных файлах вплотную (медиана по корпусу 5.69 → 9.65 кэВ,
            // разведено 53 спектра из 95). После того как фон, снятый в ТОЙ ЖЕ
            // настройке, стал жить в шкале переднего плана (`build_corpus.py`,
            // `same_setting`, порог 0.30 ПШПВ), перекладка перестала вредить:
            // понятная 100.4 → 100.5 (+0.1 %), фантомов 5 → 5; непонятная
            // 1218.7 → 1219.4 (+0.06 %), фантомов 65 → 63, recall 100/82 % без
            // изменений. Различие осталось у 15 спектров из 118 — тех, чей фон
            // и правда снят в другой настройке; из них крупно портится ровно
            // один, `AS80_Lu176` (+31 %, строка `S52`).
            this.RebinBackgroundToSpectrum = true;
        }

        /// <summary>
        /// Разложить спектр. Возвращает null, если разложение невозможно:
        /// нет калибровок, вырожденный диапазон или пустая библиотека.
        /// </summary>
        public FsaResult Analyze(
            EnergySpectrum spectrum,
            EnergySpectrum backgroundSpectrum,
            FwhmCalibration fwhmCalibration,
            List<FsaComponent> originalLibrary,
            FsaEfficiency efficiency)
        {
            if (spectrum == null || spectrum.Spectrum == null || fwhmCalibration == null
                || spectrum.EnergyCalibration == null || originalLibrary == null || originalLibrary.Count == 0)
            {
                return null;
            }

            int channels = spectrum.NumberOfChannels;
            if (channels < 32)
            {
                return null;
            }

            // Кэши уширения живут ровно один разбор: калибровку могли изменить
            // на месте, и тогда ссылка та же, а числа другие.
            this.depositChannels = null;
            this.depositChannelsCalibration = null;
            this.kernelBank = null;
            this.deposits.Clear();

            // Каскадные поправки — на ту же матрицу, что и образы: она даёт им
            // обе эффективности. Кэш поправок внутри живёт один разбор, потому
            // что матрица между вызовами могла смениться.
            this.cascade = this.CascadeSumming
                ? FsaCascadeSummer.Create(this.ResponseMatrix, this.ScintillatorMaterial,
                                          this.CoincidenceWindowSec, this.CascadeXrayPartners,
                                          this.CascadeAnnihilationPartners,
                                          this.CascadeIsomerPartners)
                : null;
            this.cascadeApplied = false;

            EnergyCalibration calibration = spectrum.EnergyCalibration;

            // S98: сужает фит РОВНО один режим. `Whole` и `LibraryToFit`
            // считают весь спектр — разница между ними в полосе БИБЛИОТЕКИ, а
            // не здесь.
            bool narrowFit = this.Band == FsaBandMode.FitToLibrary;
            int chLo = narrowFit
                ? ClampChannel(EnergyToChannelSafe(calibration, this.MinEnergy, channels), channels)
                : 0;
            int chHi = narrowFit
                ? ClampChannel(EnergyToChannelSafe(calibration, this.MaxEnergy, channels), channels)
                : channels - 1;
            if (chHi < chLo)
            {
                int swap = chLo;
                chLo = chHi;
                chHi = swap;
            }

            // Последний канал АЦП — канал переполнения: в него падает всё, что
            // выше шкалы. Образа у такой структуры нет, объяснить её фит не
            // может — верхний канал исключается, когда диапазон дошёл до края.
            if (chHi >= channels - 1)
            {
                chHi = channels - 2;
            }

            if (chHi <= chLo + 10)
            {
                return null;
            }

            // S98: полоса фита названа вслух и уносится читателю. Печатать её
            // обязан тот, кто разбор заказал: строка «фит 0…1022 (−10.2…2913.6
            // кэВ)» вместе с режимом — единственный способ отличить прогон с
            // новым умолчанием от прогона со старым, когда числа уже сведены в
            // таблицу.
            //
            // ⛔ Пол называется ФАКТИЧЕСКИЙ, а не числовой (`S101`): при поле по
            // кривой линии режет `FsaEfficiency.FloorAtFraction` той же кривой,
            // что подана сюда, а `LibraryFloorKev` — число для ветки
            // `LibraryToFit` и к кривой отношения не имеет. До 27.08.2026 здесь
            // печаталось именно оно, и заверение анализатора называло 10.0 кэВ
            // там, где библиотека резала по 20 или 30, — два конца, называющие
            // разные числа об одном и том же.
            double noteFloor = this.Band == FsaBandMode.LibraryToFitByCurve
                               || this.Band == FsaBandMode.LibraryToFitByShare
                ? (efficiency != null
                       ? efficiency.FloorAtFraction(FsaBand.DefaultFloorFraction)
                       : 0.0)
                : this.LibraryFloorKev;
            this.BandNote = string.Format(CultureInfo.InvariantCulture,
                "{0}; фит {1}…{2} ({3:F1}…{4:F1} кэВ)",
                FsaBand.Describe(this.Band, noteFloor, this.MinEnergy, this.MaxEnergy),
                chLo, chHi, calibration.ChannelToEnergy(chLo), calibration.ChannelToEnergy(chHi));

            double liveTime = spectrum.LiveTime > 0.0 ? spectrum.LiveTime : spectrum.MeasurementTime;
            if (liveTime <= 0.0)
            {
                liveTime = 1.0;
            }

            int[] raw = spectrum.Spectrum;
            double[] y = new double[channels];
            double[] variance = new double[channels];
            double[] backgroundCurve = new double[channels];
            int[] snipContinuum = null;

            // Фон, поданный и НЕ ВЗЯТЫЙ, — это отказ, и он обязан быть назван
            // (S44). До 15.08.2026 обе ветки ниже молча обнуляли ссылку: у
            // одиннадцати спектров G1S корпуса фон лежал в файле обрезанным на
            // 12–20 верхних каналов, манифест писал «встроен», проба печатала
            // background=1 — а вычитания не было ни в одном прогоне.
            string backgroundRejected = null;
            EnergySpectrum background = backgroundSpectrum;
            if (background != null && background.Spectrum == null)
            {
                backgroundRejected = "у фонового спектра нет отсчётов";
                background = null;
            }
            else if (background != null && background.NumberOfChannels != channels)
            {
                backgroundRejected = string.Format(CultureInfo.InvariantCulture,
                    "каналов у фона {0}, у спектра {1}",
                    background.NumberOfChannels, channels);
                background = null;
            }

            double backgroundScale = 0.0;
            if (background != null)
            {
                double backgroundLive = background.LiveTime > 0.0 ? background.LiveTime : background.MeasurementTime;
                if (backgroundLive > 0.0)
                {
                    backgroundScale = liveTime / backgroundLive;
                }
                else
                {
                    backgroundRejected = "у фона не задано время измерения";
                    background = null;
                }
            }

            if (this.Mode == ContinuumMode.Snip)
            {
                snipContinuum = Snip(fwhmCalibration, spectrum);
                for (int i = 0; i < channels; i++)
                {
                    double continuum = snipContinuum != null ? snipContinuum[i] : 0.0;
                    y[i] = raw[i] - continuum;
                    double c = this.Xi * continuum;
                    variance[i] = Math.Max(raw[i], 1.0) + c * c;
                }
            }
            else
            {
                for (int i = 0; i < channels; i++)
                {
                    y[i] = raw[i];
                    variance[i] = Math.Max(raw[i], 1.0);
                }
            }

            // Фон измерен и нормирован по живому времени, поэтому он не
            // подбирается, а вычитается: свободный коэффициент фона вырожден с
            // компонентами пробы (комнатный K-40 против K-40 в образце), и NNLS
            // раздувает фон вместо образца.
            double[] backgroundFull = null;
            if (background != null)
            {
                backgroundFull = new double[channels];
                int[] backgroundSnip = this.Mode == ContinuumMode.Snip ? Snip(fwhmCalibration, background) : null;

                // Фон снят СВОИМ измерением и живёт в СВОЕЙ шкале: у спектров
                // корпуса с отдельным фоном калибровки расходятся на 12–58 кэВ
                // на канале 1000 (S45). Поканальное вычитание при этом вынимает
                // из-под пика соседний континуум, а пик фона оставляет рядом.
                // Поэтому фон перекладывается на шкалу спектра по ЭНЕРГИИ —
                // тем же способом, каким это давно делает обычное вычитание
                // фона в приложении (`SpectrumAriphmetics`).
                double[] own = new double[channels];
                double[] ownPeak = new double[channels];
                for (int i = 0; i < channels; i++)
                {
                    own[i] = background.Spectrum[i];
                    // в режиме SNIP континуум фона уже сидит внутри оценки
                    // континуума переднего спектра — вычитается только пиковая
                    // часть; разность берётся в СВОЕЙ шкале фона, до перекладки
                    ownPeak[i] = backgroundSnip != null
                        ? Math.Max(0.0, background.Spectrum[i] - backgroundSnip[i])
                        : own[i];
                }

                double[] rebinned = this.RebinBackgroundToSpectrum
                    ? Rebin(own, background.EnergyCalibration, calibration, channels)
                    : own;
                double[] rebinnedPeak = backgroundSnip == null
                    ? rebinned
                    : (this.RebinBackgroundToSpectrum
                        ? Rebin(ownPeak, background.EnergyCalibration, calibration, channels)
                        : ownPeak);
                for (int i = 0; i < channels; i++)
                {
                    double full = rebinned[i] * backgroundScale;
                    backgroundFull[i] = full;
                    double value = rebinnedPeak[i] * backgroundScale;

                    backgroundCurve[i] = value;
                    y[i] -= value;
                    // Дисперсия — от ПОЛНОГО фона, как в харнессе: шум отсчёта
                    // фона не уменьшается оттого, что его континуум учтён в
                    // другом слагаемом модели.
                    variance[i] += Math.Max(Math.Abs(full) * backgroundScale, backgroundScale * backgroundScale);
                }
            }

            List<double[]> fixedColumns = new List<double[]>();
            if (this.Mode == ContinuumMode.Spline)
            {
                List<int> knots;
                fixedColumns.AddRange(BuildHatBasis(fwhmCalibration, chLo, chHi, channels,
                                                   this.ContinuumKnotDivisor,
                                                   this.ContinuumKnotFwhm, out knots));
                this.continuumKnots = knots;
            }
            else
            {
                this.continuumKnots = null;
            }

            // Шапки идут ПЕРВЫМИ и подряд — на этом держится штраф на излом
            // (`S85`): вторая разность берётся по соседям, а соседство здесь
            // задаёт порядок узлов по шкале.
            this.continuumColumns = fixedColumns.Count;

            // Наложения участвуют с САМОГО начала, вместе с сеткой дрейфа:
            // на загруженном спектре они держат целый пик (662+662 у цезия), и
            // подбирать по нему дрейф без образа значит подбирать по мусору.
            // Список вызывающего не трогаем — он его собирал и переиспользует.
            List<FsaComponent> library = originalLibrary;

            // (S47) Образы вылета убираются ЗДЕСЬ, а не в `FsaLibrary`: знать,
            // через матрицу пойдёт разбор или из одних пиков, может только
            // анализатор, а собирателей библиотеки в дереве восемь. Убрать
            // столбец, который матрица уже содержит, — не «улучшение фита», а
            // прекращение второго счёта.
            if (this.EscapeGate && this.ResponseMatrix != null)
            {
                List<FsaComponent> kept = new List<FsaComponent>(library.Count);
                foreach (FsaComponent component in library)
                {
                    if (!FsaLibrary.IsEscapeImage(component.Name))
                    {
                        kept.Add(component);
                    }
                }

                if (kept.Count < library.Count)
                {
                    library = kept;
                }
            }

            // Список КАНДИДАТОВ — то, что предъявлено фиту, без служебной
            // добавки наложений: по нему считаются характеристические пределы
            // (S9). Наложения — образ прибора, а не кандидат библиотеки, и
            // строки «< МДА» у них не бывает.
            List<FsaComponent> candidates = library;

            if (this.PileUp)
            {
                FsaComponent pileUp = this.BuildPileUpComponent(raw, calibration, chLo, chHi, channels);
                if (pileUp != null)
                {
                    // Копия делается с `library`, а НЕ с `originalLibrary`: выше
                    // из неё мог уйти образ вылета (S47), и копия исходника
                    // вернула бы его молча.
                    library = new List<FsaComponent>(library);
                    library.Add(pileUp);
                }
            }

            // Отчётные веса — ПРЕЖНЯЯ метрика (пуассон плюс шум вычтенного
            // фона), какой бы ни была метрика решателя: χ², посчитанный ими
            // (Chi2NdfPoisson), сравним между прогонами с разными весами и с
            // Хубером — величиной, которую правка весов сама оптимизирует,
            // мерить её пользу нельзя (ловушка из fsa-hypotheses §1/§4).
            double[] reportWeights = new double[channels];
            for (int i = 0; i < channels; i++)
            {
                reportWeights[i] = 1.0 / variance[i];
            }

            // (S43) Составной шум: D = F + γ²F² + β²B². Меняются только веса
            // РЕШАТЕЛЯ (и пределы S9 — они описывают тот же оценщик);
            // отчётная метрика остаётся прежней.
            if (this.NoiseGamma > 0.0 || (this.NoiseBeta > 0.0 && backgroundFull != null))
            {
                double g2 = this.NoiseGamma * this.NoiseGamma;
                double b2 = this.NoiseBeta * this.NoiseBeta;
                for (int i = 0; i < channels; i++)
                {
                    double extra = g2 * (double)raw[i] * raw[i];
                    if (b2 > 0.0 && backgroundFull != null)
                    {
                        extra += b2 * backgroundFull[i] * backgroundFull[i];
                    }

                    variance[i] += extra;
                }
            }

            double[] baseWeights = new double[channels];
            for (int i = 0; i < channels; i++)
            {
                baseWeights[i] = 1.0 / variance[i];
            }

            // --offset задан в кэВ; в каналы переводится по фактическому наклону
            // шкалы на границах фита, иначе одна и та же величина означала бы
            // разное для 1024- и 8192-канальных приборов.
            double energyLo = calibration.ChannelToEnergy(chLo);
            double energyHi = calibration.ChannelToEnergy(chHi);
            double channelsPerKev = energyHi > energyLo
                ? (chHi - chLo) / (energyHi - energyLo)
                : (chHi - chLo) / Math.Max(1.0, this.MaxEnergy - this.MinEnergy);
            double offsetRangeChannels = this.OffsetRangeKev * channelsPerKev;

            int gainSteps = Math.Max(1, this.GainSteps);
            int offsetSteps = Math.Max(1, this.OffsetSteps);
            double bestGain = 1.0;
            double bestOffset = 0.0;
            double bestChi2 = Double.MaxValue;
            int bestGainIndex = 0;
            int bestOffsetIndex = 0;
            for (int gi = 0; gi < gainSteps; gi++)
            {
                double gain = gainSteps == 1
                    ? 1.0
                    : 1.0 - this.GainRange + 2.0 * this.GainRange * gi / (gainSteps - 1);
                for (int oi = 0; oi < offsetSteps; oi++)
                {
                    double offset = offsetSteps == 1
                        ? 0.0
                        : -offsetRangeChannels + 2.0 * offsetRangeChannels * oi / (offsetSteps - 1);
                    FitResult probe = FitOnce(library, fixedColumns, calibration, fwhmCalibration, efficiency,
                                              gain, offset, chLo, chHi, channels, y, baseWeights, null);
                    if (probe != null && probe.Chi2 < bestChi2)
                    {
                        bestChi2 = probe.Chi2;
                        bestGain = gain;
                        bestOffset = offset;
                        bestGainIndex = gi;
                        bestOffsetIndex = oi;
                    }
                }
            }

            if (bestChi2 == Double.MaxValue)
            {
                return null;
            }

            FitResult best = FitHuber(library, fixedColumns, calibration, fwhmCalibration, efficiency,
                                      bestGain, bestOffset, chLo, chHi, channels, y, variance, baseWeights, reportWeights, null);
            if (best == null)
            {
                return null;
            }

            // (S78) Всё, что было ПРЕДЪЯВЛЕНО фиту, и с какой значимостью его
            // видели в последний раз. Отсев по значимости и гейт по парциальной
            // невязке убирают колонку из `Columns` ЦЕЛИКОМ, и без этого следа
            // «образ не строился» и «образ построен и признан незначимым»
            // становятся на экране одним и тем же — молчаливым отсутствием
            // строки. Словарь, а не список: один и тот же образ переживает
            // несколько проходов, и нужна ПОСЛЕДНЯЯ значимость, с которой его
            // видели живым.
            var offeredZ = new Dictionary<string, double>(StringComparer.Ordinal);
            var offeredKind = new Dictionary<string, FsaComponentKind>(StringComparer.Ordinal);
            Action<FitResult> remember = fit =>
            {
                for (int k = 0; k < fit.Columns.Count; k++)
                {
                    FsaComponent component = fit.Columns[k].Component;
                    if (component == null)
                    {
                        continue;
                    }

                    offeredZ[component.Name] = fit.Z[k];
                    offeredKind[component.Name] = component.Kind;
                }
            };

            remember(best);

            // Образ обратного рассеяния по найденному составу — до отсева по z:
            // отсев решает, какие компоненты дожили, и решать это надо уже при
            // закрытой области рассеяния.
            List<FsaComponent> working = library;
            if (this.Backscatter)
            {
                List<FsaComponent> derived = BuildBackscatterComponents(best, efficiency);
                if (derived.Count > 0)
                {
                    List<FsaComponent> extended = new List<FsaComponent>(library);
                    extended.AddRange(derived);
                    FitResult refit = FitHuber(extended, fixedColumns, calibration, fwhmCalibration, efficiency,
                                               bestGain, bestOffset, chLo, chHi, channels, y, variance, baseWeights, reportWeights, null);
                    if (refit != null)
                    {
                        best = refit;
                        working = extended;
                    }

                    remember(best);
                }
            }

            // «Предварительный анализ состава»: второй проход без компонентов,
            // не прошедших порог значимости в первом.
            if (this.RefitZ > 0.0)
            {
                List<FsaComponent> keep = new List<FsaComponent>();
                int total = 0;
                for (int k = 0; k < best.Columns.Count; k++)
                {
                    FsaComponent component = best.Columns[k].Component;
                    if (component == null)
                    {
                        continue;
                    }

                    total++;
                    if (best.Z[k] >= this.RefitZ)
                    {
                        keep.Add(component);
                    }
                }

                if (keep.Count > 0 && keep.Count < total)
                {
                    FitResult refit = FitHuber(working, fixedColumns, calibration, fwhmCalibration, efficiency,
                                               bestGain, bestOffset, chLo, chHi, channels, y, variance, baseWeights, reportWeights, keep);
                    if (refit != null)
                    {
                        best = refit;
                        remember(best);
                    }
                }
            }

            // Второй круг: форма образа задаётся составом, а состав только что
            // изменился отсевом.
            if (this.Backscatter)
            {
                List<FsaComponent> survivors = new List<FsaComponent>();
                for (int k = 0; k < best.Columns.Count; k++)
                {
                    FsaComponent component = best.Columns[k].Component;
                    if (component != null && !component.Derived)
                    {
                        survivors.Add(component);
                    }
                }

                List<FsaComponent> derived = BuildBackscatterComponents(best, efficiency);
                if (derived.Count > 0)
                {
                    survivors.AddRange(derived);
                    FitResult refit = FitHuber(survivors, fixedColumns, calibration, fwhmCalibration, efficiency,
                                               bestGain, bestOffset, chLo, chHi, channels, y, variance, baseWeights, reportWeights, null);
                    if (refit != null)
                    {
                        best = refit;
                        remember(best);
                    }
                }
            }

            // (P6 «б») Гейт по парциальной невязке: нуклидный компонент, чьё
            // ПРИСУТСТВИЕ ухудшает невязку его же пиковых окон (ΔD < 0 — без
            // него зоне лучше), исключается, и состав перефитивается один раз.
            // Амплитудный тест такое не видит по построению: z фантома
            // неотличим от z настоящего (память libraryfit-z-gate-blind), а
            // здесь судится форма зоны, не амплитуда. Мешающие образы,
            // производные и готовые (наложения) не судятся — гейт для
            // нуклидных кандидатов.
            if (this.PartialResidualGate)
            {
                List<FsaComponent> gateAll = new List<FsaComponent>();
                for (int k = 0; k < best.Columns.Count; k++)
                {
                    if (best.Columns[k].Component != null)
                    {
                        gateAll.Add(best.Columns[k].Component);
                    }
                }

                List<FsaComponent> gateKeep = new List<FsaComponent>(gateAll);
                for (int k = 0; k < best.Columns.Count; k++)
                {
                    FitColumn column = best.Columns[k];
                    FsaComponent component = column.Component;
                    if (component == null || best.Amplitude[k] <= 0.0
                        || component.Kind == FsaComponentKind.Nuisance
                        || component.Derived || component.FixedTemplate != null)
                    {
                        continue;
                    }

                    bool[] zone = this.PeakWindowMask(component, calibration, fwhmCalibration,
                                                      bestGain, bestOffset, chLo, chHi, channels);
                    if (zone == null)
                    {
                        continue;
                    }

                    double dWith = 0.0;
                    for (int i = chLo; i <= chHi; i++)
                    {
                        if (zone[i])
                        {
                            dWith += best.Residual[i] * best.Residual[i] * reportWeights[i];
                        }
                    }

                    List<FsaComponent> without = new List<FsaComponent>(gateAll);
                    without.Remove(component);
                    FitResult probe = this.FitHuber(gateAll, fixedColumns, calibration, fwhmCalibration,
                                                    efficiency, bestGain, bestOffset, chLo, chHi, channels,
                                                    y, variance, baseWeights, null, without);
                    if (probe == null || probe.Residual == null)
                    {
                        continue;
                    }

                    double dWithout = 0.0;
                    for (int i = chLo; i <= chHi; i++)
                    {
                        if (zone[i])
                        {
                            dWithout += probe.Residual[i] * probe.Residual[i] * reportWeights[i];
                        }
                    }

                    if (dWithout - dWith < 0.0)
                    {
                        gateKeep.Remove(component);
                    }
                }

                if (gateKeep.Count < gateAll.Count)
                {
                    FitResult refit = FitHuber(gateAll, fixedColumns, calibration, fwhmCalibration, efficiency,
                                               bestGain, bestOffset, chLo, chHi, channels,
                                               y, variance, baseWeights, reportWeights, gateKeep);
                    if (refit != null)
                    {
                        best = refit;
                        remember(best);
                    }
                }
            }

            FsaResult result = BuildResult(best, spectrum, fwhmCalibration, backgroundCurve, snipContinuum,
                               chLo, chHi, channels,
                               bestGain, bestOffset, liveTime, efficiency,
                               gainSteps > 1 && (bestGainIndex == 0 || bestGainIndex == gainSteps - 1),
                               offsetSteps > 1 && (bestOffsetIndex == 0 || bestOffsetIndex == offsetSteps - 1));

            // (`S103`) Поверка столбцов подпороговых линий — ПОСЛЕ отчётного
            // фита и только по заказу: при нулевом пороге сюда не заходят.
            // Библиотека берётся та же, по которой фит и строился (`library`),
            // а не исходная: выше из неё могли уйти образы вылета (S47).
            //
            // (`S103`) Заказчиков у поверки два. Второй — опора полосы по
            // столбцу: ей та же поверка нужна ниже `Min_Range` независимо от
            // ключа `--band-audit=`. Порог берётся НАИБОЛЬШИЙ из двух, а не по
            // одному разу на заказчика: поверка стоит построения образа на
            // каждую линию, и считать её дважды значило бы платить дважды за
            // одно и то же.
            bool shareBand = this.Band == FsaBandMode.LibraryToFitByShare && !this.shareRefit;
            double shareBelow = shareBand ? this.MinEnergy : 0.0;
            HashSet<FsaLine> shareDrops = shareBand ? new HashSet<FsaLine>() : null;
            this.AuditLineColumns(result, best, library, calibration, fwhmCalibration,
                                  efficiency, bestGain, bestOffset, chLo, chHi, channels,
                                  Math.Max(this.LineColumnAuditBelowKev, shareBelow),
                                  this.LineColumnAuditBelowKev > 0.0,
                                  shareDrops, shareBelow, FsaBand.DefaultShareThreshold);

            // ⛔⛔ (`S103`) ВТОРОЙ ПРОХОД, И ОН ЗДЕСЬ НЕ ОТ ЛЕНИ. Доля континуума
            // измеряется В МЕТРИКЕ ФИТА (дополнение Шура по активным шапкам,
            // Gram на подобранном узле сетки дрейфа, веса решателя) — ни одной
            // из этих трёх вещей не существует до фита, а полосу библиотеки
            // задают ДО него. Дешевле не выходит: чтобы узнать, отличима ли
            // линия от континуума, надо сперва посадить континуум.
            //
            // Перефит — РЕКУРСИВНЫЙ вызов того же `Analyze`, а не отдельная
            // ветка: так второй проход гарантированно идёт тем же кодом, что и
            // первый (сетка дрейфа, гейты, пределы, каскад), и «плечо
            // отличается только библиотекой» остаётся правдой, а не обещанием.
            // Сторож `shareRefit` держит глубину ровно два.
            if (shareBand && shareDrops.Count > 0)
            {
                List<FsaComponent> narrowed = NarrowLibraryByShare(originalLibrary, shareDrops);
                if (narrowed != null && narrowed.Count > 0)
                {
                    this.shareRefit = true;
                    FsaResult second;
                    try
                    {
                        second = this.Analyze(spectrum, backgroundSpectrum, fwhmCalibration,
                                              narrowed, efficiency);
                    }
                    finally
                    {
                        this.shareRefit = false;
                    }

                    if (second != null)
                    {
                        second.ShareDroppedLines = shareDrops.Count;
                        second.ShareOfferedLines = CountLinesBelow(library, shareBelow);
                        second.ShareDroppedComponents = CountEmptied(originalLibrary, narrowed);
                        this.BandNote += string.Format(CultureInfo.InvariantCulture,
                            "; опора по столбцу: выброшено {0} линий из {1} подпороговых,"
                            + " образов опустело {2}",
                            second.ShareDroppedLines, second.ShareOfferedLines,
                            second.ShareDroppedComponents);
                        return second;
                    }
                }
            }

            if (shareBand)
            {
                // Плечо, где не выброшено ничего, обязано БЫТЬ НАЗВАНО, иначе
                // «рычаг не сработал» и «рычаг не важен» неразличимы.
                result.ShareOfferedLines = CountLinesBelow(library, shareBelow);
                this.BandNote += string.Format(CultureInfo.InvariantCulture,
                    "; опора по столбцу: выброшено 0 линий из {0} подпороговых, перефита не было",
                    result.ShareOfferedLines);
            }

            // (S78) Кто был предъявлен, но до отчёта не дожил. Считается
            // ПОСЛЕ всех проходов и по фактическому составу результата, а не по
            // одному из гейтов: убрать колонку могут двое (отсев по значимости
            // `RefitZ` и гейт по парциальной невязке), и правило, знающее только
            // про одного, однажды промолчит про второго.
            var reported = new HashSet<string>(StringComparer.Ordinal);
            foreach (FsaComponentResult component in result.Components)
            {
                reported.Add(component.Name);
            }

            foreach (KeyValuePair<string, double> pair in offeredZ)
            {
                if (reported.Contains(pair.Key))
                {
                    continue;
                }

                FsaComponentKind kind;
                result.SuppressedImages.Add(new FsaSuppressedImage
                {
                    Name = pair.Key,
                    Kind = offeredKind.TryGetValue(pair.Key, out kind) ? kind : FsaComponentKind.Single,
                    Z = pair.Value
                });
            }

            result.SuppressedImages.Sort(
                (left, right) => string.CompareOrdinal(left.Name, right.Name));
            result.BackgroundRejected = backgroundRejected;
            result.BackgroundUsed = background != null && backgroundScale > 0.0;
            // Пределы считаются по ТОЙ библиотеке, что пошла в фит (S47): образ,
            // снятый гейтом вылета, кандидатом не был, и печатать ему МДА
            // значило бы отвечать «не обнаружен» про то, чего не искали.
            this.ComputeCharacteristicLimits(result, best, candidates, calibration, fwhmCalibration,
                                             efficiency, bestGain, bestOffset, chLo, chHi, channels,
                                             variance, liveTime);
            if (this.PartialResiduals)
            {
                this.ComputePartialResiduals(result, best, fixedColumns, calibration, fwhmCalibration,
                                             efficiency, bestGain, bestOffset, chLo, chHi, channels,
                                             y, variance, baseWeights, reportWeights);
            }

            return result;
        }

        /// <summary>
        /// Квантиль нормального распределения для ошибок первого и второго рода
        /// характеристических пределов (S9). Поставочное значение стоит У
        /// ОБЪЯВЛЕНИЯ ПОЛЯ, строкой ниже (`T82`), и отвечает α = β = 5 % —
        /// умолчание ISO 11929. Поле, а не константа, — программная ручка для
        /// проб, в UI и конфигурацию не выводится (как
        /// <see cref="ResponseContinuumTrustFloorKev"/>).
        /// </summary>
        public double LimitQuantileK = 1.6449;

        /// <summary>
        /// Характеристические пределы разложения (S9): порог решения a* и предел
        /// обнаружения a# для КАЖДОГО нуклидного кандидата библиотеки — и
        /// вошедшего в состав, и отброшенного отсевом. Формализм — Xu et al.,
        /// ART 182 (2022) 110109, лучший из их тестов (w2) поверх ISO 11929.
        ///
        /// Оценщик амплитуды компонента j линеен: â_j = Σ_i w_i·y_i, где w —
        /// строка j взвешенной псевдообратной Π = (ΦᵀWΦ)⁻¹ΦᵀW по активному
        /// множеству финального фита. Для активного j строка берётся готовой из
        /// обратной активной части Грама (H); для неактивного — дополнением
        /// Шура по той же H: β = H·g_Aj, знаменатель g_jj − g_Ajᵀβ. Ни одного
        /// нового обращения матрицы здесь нет нарочно: на приборах с тысячей
        /// шапок континуума обращение на каждый нуклид стоило бы минуты.
        ///
        /// Под нулевой гипотезой (нуклида нет) дисперсия статистики
        /// σ₀² = Σ w_i²·v0_i, где v0 — дисперсия канала БЕЗ отсчётов самого
        /// компонента (у Xu — эквивалентный фон m). Порог решения a* = k·σ₀.
        /// Предел обнаружения — наименьшее истинное a, при котором тест ещё
        /// срабатывает с ошибкой β: a# = a* + k·σ(a#); поскольку пуассонова
        /// дисперсия растёт линейно, σ²(a) = σ₀² + a·Σ w_i²·φ_ij, и при α = β
        /// уравнение решается замкнуто: a# = 2·k·σ₀ + k²·γ (ISO 11929).
        ///
        /// Три сознательных отступления от статьи, все — консервативные:
        ///   * веса берутся финального хуберовского прохода, а σ₀ и σ(a#)
        ///     надуваются на √(χ²/ndf), как и сигмы амплитуд: у Xu модель верна
        ///     по построению, у нас невязка формы реальна, и пределы без надувки
        ///     обещали бы точность, которой у разбора нет;
        ///   * пределы описывают ЛИНЕЙНУЮ статистику w·y — обрезание NNLS нулём
        ///     делает фактическое решение «а ≥ a*» только консервативнее
        ///     (у Xu тот же выбор: их тест тоже линейный);
        ///   * у компонента, не вошедшего в финальный фит, подпороговый хвост
        ///     образа (отвязка континуума) не моделируется — весь образ идёт
        ///     одной колонкой, и a# у таких чуть завышен.
        ///
        /// Величины возвращаются в шкале скорости счёта (имп/с), как
        /// <see cref="FsaComponentResult.CountRate"/>: перевод в Бк требует
        /// абсолютного уровня кривой эффективности, которого у большинства
        /// спектров нет (E1/V1), и врать беккерелями здесь нельзя.
        /// </summary>
        void ComputeCharacteristicLimits(FsaResult result, FitResult fit, List<FsaComponent> library,
                                         EnergyCalibration calibration, FwhmCalibration fwhmCalibration,
                                         FsaEfficiency efficiency, double gain, double offset,
                                         int chLo, int chHi, int channels,
                                         double[] variance, double liveTime)
        {
            if (result == null || fit == null || fit.Weights == null || fit.Gram == null
                || fit.ActiveIndices == null || library == null)
            {
                return;
            }

            List<int> A = fit.ActiveIndices;
            double[,] H = fit.ActiveInverse;
            double[] W = fit.Weights;
            double inflate = Math.Sqrt(Math.Max(1.0, fit.Chi2Ndf));
            double k1 = this.LimitQuantileK;
            double[] projection = new double[channels];

            foreach (FsaComponent component in library)
            {
                if (component == null || component.Kind == FsaComponentKind.Nuisance
                    || component.Derived)
                {
                    continue;
                }

                // Колонка компонента в финальном фите; отброшенные отсевом или
                // вторым кругом рассеяния строят образ заново на том же дрейфе.
                int col = -1;
                for (int k = 0; k < fit.Columns.Count; k++)
                {
                    if (ReferenceEquals(fit.Columns[k].Component, component))
                    {
                        col = k;
                        break;
                    }
                }

                double amplitude = col >= 0 ? fit.Amplitude[col] : 0.0;
                double[] phi;
                if (col >= 0)
                {
                    phi = fit.Columns[col].Values;
                }
                else if (this.ResponseMatrix != null && !component.WeightsAreFinal)
                {
                    double[] lowTail;
                    phi = this.BuildTemplateFromResponse(component, calibration, fwhmCalibration,
                                                         gain, offset, chLo, chHi, channels, out lowTail);
                }
                else
                {
                    phi = BuildTemplate(component, calibration, fwhmCalibration, efficiency,
                                        gain, offset, chLo, chHi, channels);
                }

                if (phi == null)
                {
                    continue;
                }

                FsaCharacteristicLimit limit = new FsaCharacteristicLimit
                {
                    Name = component.Name,
                    Kind = component.Kind,
                    Detected = col >= 0 && amplitude > 0.0,
                    CountRate = amplitude / liveTime,
                    DecisionThresholdRate = Double.NaN,
                    DetectionLimitRate = Double.NaN,
                    TotalYieldPercent = component.TotalYieldPercent
                };
                result.CharacteristicLimits.Add(limit);

                if (H == null || A.Count == 0)
                {
                    limit.Degenerate = true;
                    limit.Collinearity = 1.0;
                    continue;
                }

                // Проекция строки оценщика на каналы: p_i такое, что
                // â_j = Σ_i W_i·p_i·y_i.
                Array.Clear(projection, 0, channels);
                bool jActive = col >= 0 && fit.Active[col];
                if (jActive)
                {
                    int ja = A.IndexOf(col);

                    // Коллинеарность из тех же матриц: эффективная информация
                    // активного компонента — 1/H_jj, её доля от полной — по
                    // дополнению Шура.
                    double hjj = H[ja, ja];
                    double gjjActive = fit.Gram[col, col];
                    if (hjj > 0.0 && gjjActive > 0.0)
                    {
                        double share = 1.0 - 1.0 / (hjj * gjjActive);
                        limit.Collinearity = share < 0.0 ? 0.0 : (share > 1.0 ? 1.0 : share);
                    }

                    for (int a = 0; a < A.Count; a++)
                    {
                        double h = H[ja, a];
                        if (h == 0.0)
                        {
                            continue;
                        }

                        double[] t = fit.Columns[A[a]].Values;
                        for (int i = chLo; i <= chHi; i++)
                        {
                            projection[i] += h * t[i];
                        }
                    }
                }
                else
                {
                    double gjj;
                    double[] gAj = new double[A.Count];
                    if (col >= 0)
                    {
                        for (int a = 0; a < A.Count; a++)
                        {
                            gAj[a] = fit.Gram[A[a], col];
                        }

                        gjj = fit.Gram[col, col];
                    }
                    else
                    {
                        for (int a = 0; a < A.Count; a++)
                        {
                            gAj[a] = DotWeighted(fit.Columns[A[a]].Values, phi, W, chLo, chHi);
                        }

                        gjj = DotWeighted(phi, phi, W, chLo, chHi);
                    }

                    double[] beta = new double[A.Count];
                    double crossTerm = 0.0;
                    for (int a = 0; a < A.Count; a++)
                    {
                        double sum = 0.0;
                        for (int b = 0; b < A.Count; b++)
                        {
                            sum += H[a, b] * gAj[b];
                        }

                        beta[a] = sum;
                        crossTerm += gAj[a] * sum;
                    }

                    double denominator = gjj - crossTerm;
                    if (!(gjj > 0.0) || denominator <= 1.0E-10 * gjj)
                    {
                        limit.Degenerate = true;
                        limit.Collinearity = 1.0;
                        continue;
                    }

                    double shareTaken = 1.0 - denominator / gjj;
                    limit.Collinearity = shareTaken < 0.0 ? 0.0
                        : (shareTaken > 1.0 ? 1.0 : shareTaken);

                    for (int i = chLo; i <= chHi; i++)
                    {
                        projection[i] = phi[i];
                    }

                    for (int a = 0; a < A.Count; a++)
                    {
                        double b = beta[a];
                        if (b == 0.0)
                        {
                            continue;
                        }

                        double[] t = fit.Columns[A[a]].Values;
                        for (int i = chLo; i <= chHi; i++)
                        {
                            projection[i] -= b * t[i];
                        }
                    }

                    for (int i = chLo; i <= chHi; i++)
                    {
                        projection[i] /= denominator;
                    }
                }

                double nullVariance = 0.0;
                double varianceSlope = 0.0;
                for (int i = chLo; i <= chHi; i++)
                {
                    double p = projection[i];
                    if (p == 0.0)
                    {
                        continue;
                    }

                    double w = W[i] * p;
                    double v0 = variance[i] - amplitude * phi[i];
                    if (v0 < 1.0)
                    {
                        v0 = 1.0;
                    }

                    nullVariance += w * w * v0;
                    varianceSlope += w * w * phi[i];
                }

                if (!(nullVariance > 0.0))
                {
                    limit.Degenerate = true;
                    continue;
                }

                double s0 = inflate * Math.Sqrt(nullVariance);
                double threshold = k1 * s0;
                double detection = 2.0 * k1 * s0 + k1 * k1 * inflate * inflate * varianceSlope;
                limit.DecisionThresholdRate = threshold / liveTime;
                limit.DetectionLimitRate = detection / liveTime;

                // (S68) Тот же предел, но НЕ в имп/с, а пиковыми отсчётами:
                // сколько кандидат набрал бы в своих окнах, стой его амплитуда
                // на a#. Счёт по окнам линеен по амплитуде (профили единичной
                // площади, окно от неё не зависит), поэтому берётся при
                // единичной амплитуде и умножается — второго прохода по каналам
                // не нужно.
                //
                // ⚠ `detection`, а не `DetectionLimitRate`: первое — амплитуда,
                // второе уже поделено на живое время, и делить второй раз
                // значило бы применить его дважды.
                limit.DetectionLimitPeakCounts = detection
                    * this.PeakWindowCounts(component, phi, calibration, fwhmCalibration,
                                            gain, offset, chLo, chHi, channels);
            }

            // Те же числа — на строках состава, чтобы читателю не соединять два
            // списка по имени. Мешающим образам пределы не считаются: NaN, а не
            // ноль, — ноль читался бы как «порог нулевой».
            Dictionary<string, FsaCharacteristicLimit> byName =
                new Dictionary<string, FsaCharacteristicLimit>(StringComparer.Ordinal);
            foreach (FsaCharacteristicLimit limit in result.CharacteristicLimits)
            {
                byName[limit.Name] = limit;
            }

            foreach (FsaComponentResult component in result.Components)
            {
                FsaCharacteristicLimit limit;
                if (byName.TryGetValue(component.Name, out limit))
                {
                    component.DecisionThresholdRate = limit.DecisionThresholdRate;
                    component.DetectionLimitRate = limit.DetectionLimitRate;
                }
                else
                {
                    component.DecisionThresholdRate = Double.NaN;
                    component.DetectionLimitRate = Double.NaN;
                }
            }
        }

        /// <summary>Скалярное произведение двух колонок с весами фита.</summary>
        static double DotWeighted(double[] a, double[] b, double[] weights, int chLo, int chHi)
        {
            double sum = 0.0;
            for (int i = chLo; i <= chHi; i++)
            {
                sum += a[i] * weights[i] * b[i];
            }

            return sum;
        }

        /// <summary>
        /// (`S103`) ЧЕГО СТОИТ СТОЛБЕЦ ОТДЕЛЬНОЙ ЛИНИИ и куда он смотрит —
        /// поверка ПОСЛЕ фита, разбор не трогающая ни одним действием.
        ///
        /// Столбец линии строится ТЕМИ ЖЕ построителями, что и образ её
        /// компонента, на ТОМ ЖЕ узле сетки дрейфа: матричный путь кладёт в
        /// гистограмму поглощения ОДНУ линию (с её каскадным множителем) и
        /// уширяет, безматричный — зовёт <see cref="BuildTemplate"/> на клоне с
        /// единственной линией. Тот же нож подпорогового хвоста применяется и
        /// здесь, иначе поверяемый столбец отличался бы от того, что реально
        /// стоит в фите.
        ///
        /// ⛔ Складывать столбцы линий и ждать столбца компонента нельзя:
        /// уширение линейно, а вот нож хвоста режет по окнам ВСЕХ линий
        /// компонента сразу — на одиночной гистограмме он вынимает ровно то же,
        /// что вынул бы на общей, но соседние линии в общей могут закрыть
        /// окном бин, который в одиночной остался бы открытым. Для линий
        /// НИЖЕ рабочего окна прибора разница исчезающая (их отклик — почти
        /// один пик), но правило знать надо.
        /// </summary>
        /// <param name="below">
        /// Порог поверки, кэВ: поверяются линии строго ниже него. Параметром, а
        /// не полем, потому что заказчиков у поверки СТАЛО ДВА и пороги у них
        /// разные: ключ `--band-audit=` (поле <see cref="LineColumnAuditBelowKev"/>)
        /// и опора полосы по столбцу (`S103`, порог = `Min_Range`). Считать её
        /// дважды нельзя — это второй проход по всем подпороговым линиям.
        /// </param>
        /// <param name="keepRows">
        /// Класть строки в <see cref="FsaResult.LineColumns"/>. `false` —
        /// поверка считалась ТОЛЬКО ради выброса линий, и её никто не заказывал:
        /// список обязан остаться null, иначе «поверку не заказывали» и «поверка
        /// пуста» станут неразличимы.
        /// </param>
        /// <param name="dropSink">
        /// Куда складывать линии на выброс (`S103`); null — не выбрасывать.
        /// Складываются САМИ ОБЪЕКТЫ линий, а не пары «имя+энергия»: библиотека
        /// второго прохода строится из тех же <see cref="FsaLine"/>, и сличение
        /// по ссылке не может ошибиться на двух линиях с равной энергией.
        /// </param>
        /// <param name="dropBelow">
        /// Граница, ниже которой линия вообще может быть выброшена. Отдельно от
        /// <paramref name="below"/>: поверка могла быть заказана шире выброса, и
        /// тогда выброшенным оказалось бы то, чего опора полосы не касается.
        /// </param>
        /// <param name="dropAboveShare">
        /// Выбрасывать линию, если её доля континуума СТРОГО больше этого числа.
        /// </param>
        void AuditLineColumns(FsaResult result, FitResult fit, List<FsaComponent> library,
                              EnergyCalibration calibration, FwhmCalibration fwhmCalibration,
                              FsaEfficiency efficiency, double gain, double offset,
                              int chLo, int chHi, int channels,
                              double below, bool keepRows,
                              HashSet<FsaLine> dropSink, double dropBelow, double dropAboveShare)
        {
            if (!(below > 0.0) || fit == null || fit.Columns == null || fit.Weights == null
                || library == null)
            {
                return;
            }

            double[] w = fit.Weights;
            List<FsaLineColumn> rows = new List<FsaLineColumn>();

            // Активные шапки континуума — по границе блока, которую отдал сам
            // фит, а не по второй копии смещения.
            List<int> continuumSet = new List<int>();
            for (int k = fit.FixedFirst; k < fit.FixedFirst + this.continuumColumns
                                          && k < fit.Columns.Count; k++)
            {
                if (k >= 0 && fit.Active != null && fit.Active[k])
                {
                    continuumSet.Add(k);
                }
            }

            double[,] continuumInverse = InvertGramSubset(fit.Gram, continuumSet);

            foreach (FsaComponent component in library)
            {
                if (component == null || component.FixedTemplate != null
                    || component.Lines == null || component.Lines.Count == 0)
                {
                    continue;
                }

                bool anyBelow = false;
                foreach (FsaLine probe in component.Lines)
                {
                    if (probe.Energy > 0.0 && probe.Intensity > 0.0 && probe.Energy < below)
                    {
                        anyBelow = true;
                        break;
                    }
                }

                if (!anyBelow)
                {
                    continue;
                }

                int own = -1;
                for (int k = 0; k < fit.Columns.Count; k++)
                {
                    if (ReferenceEquals(fit.Columns[k].Component, component))
                    {
                        own = k;
                        break;
                    }
                }

                double amplitude = own >= 0 ? fit.Amplitude[own] : 0.0;

                // Вся активная модель, КРОМЕ столбца самого владельца: иначе
                // доля вышла бы единицей тождественно — линия входит в свой же
                // столбец, и «модель её представляет» было бы тавтологией.
                List<int> othersSet = new List<int>();
                if (fit.ActiveIndices != null)
                {
                    foreach (int k in fit.ActiveIndices)
                    {
                        if (k != own)
                        {
                            othersSet.Add(k);
                        }
                    }
                }

                double[,] othersInverse = InvertGramSubset(fit.Gram, othersSet);

                for (int i = 0; i < component.Lines.Count; i++)
                {
                    FsaLine line = component.Lines[i];
                    if (!(line.Energy > 0.0) || !(line.Intensity > 0.0) || line.Energy >= below)
                    {
                        continue;
                    }

                    double[] phi = this.BuildLineColumn(component, i, calibration, fwhmCalibration,
                                                        efficiency, gain, offset, chLo, chHi, channels);
                    if (phi == null)
                    {
                        continue;
                    }

                    double sum = 0.0;
                    double sumBelow = 0.0;
                    for (int ch = chLo; ch <= chHi; ch++)
                    {
                        sum += phi[ch];
                        if (calibration.ChannelToEnergy(ch) < below)
                        {
                            sumBelow += phi[ch];
                        }
                    }

                    bool degenerate;
                    double gjj = DotWeighted(phi, phi, w, chLo, chHi);
                    double contShare = SchurShare(phi, gjj, w, fit, continuumSet, continuumInverse,
                                                  chLo, chHi, out degenerate);
                    bool ignore;
                    double modelShare = SchurShare(phi, gjj, w, fit, othersSet, othersInverse,
                                                   chLo, chHi, out ignore);

                    // (`S103`) ВЫБРОС. Порог строгий, и это существенно: при
                    // пороге 1.0 доля, зажатая в [0…1], его не превосходит
                    // никогда — значит контрольное плечо не выбрасывает ничего
                    // и обязано совпасть с поставкой побитово.
                    if (dropSink != null && line.Energy < dropBelow && contShare > dropAboveShare)
                    {
                        dropSink.Add(line);
                    }

                    rows.Add(new FsaLineColumn
                    {
                        Component = component.Name,
                        Kind = component.Kind,
                        EnergyKev = line.Energy,
                        IntensityPct = line.Intensity,
                        ColumnNorm = gjj > 0.0 ? Math.Sqrt(gjj) : 0.0,
                        ColumnSum = sum,
                        ColumnSumBelow = sumBelow,
                        Amplitude = amplitude,
                        Area = amplitude * sum,
                        AreaBelow = amplitude * sumBelow,
                        ContinuumShare = contShare,
                        ModelShare = modelShare,
                        Degenerate = degenerate
                    });
                }
            }

            if (keepRows)
            {
                result.LineColumns = rows;
            }
        }

        /// <summary>
        /// (`S103`) Библиотека ВТОРОГО ПРОХОДА: та же, минус поимённо
        /// выброшенные линии. Компонент, у которого не осталось ни одной линии,
        /// не «пустеет», а исчезает — пустой образ в НМНК есть вырожденный
        /// столбец, и собиратель библиотеки поступает с ним ровно так же
        /// (<c>FsaSampleLibrary</c>: «образы без единой линии выбрасываются»).
        ///
        /// ⛔ Компоненты, у которых выбрасывать нечего, кладутся ССЫЛКОЙ, а
        /// затронутые — КОПИЕЙ. Править список вызывающего нельзя: он его
        /// собирал и переиспользует (в пробе — на соседний спектр), а
        /// «сужение», уехавшее в чужой объект, было бы утечкой плеча A/B в
        /// прогон целиком.
        /// </summary>
        static List<FsaComponent> NarrowLibraryByShare(List<FsaComponent> library,
                                                       HashSet<FsaLine> drops)
        {
            if (library == null || drops == null || drops.Count == 0)
            {
                return null;
            }

            List<FsaComponent> narrowed = new List<FsaComponent>(library.Count);
            foreach (FsaComponent component in library)
            {
                if (component == null)
                {
                    continue;
                }

                if (component.FixedTemplate != null || component.Lines == null
                    || component.Lines.Count == 0)
                {
                    narrowed.Add(component);
                    continue;
                }

                int hit = 0;
                foreach (FsaLine line in component.Lines)
                {
                    if (drops.Contains(line))
                    {
                        hit++;
                    }
                }

                if (hit == 0)
                {
                    narrowed.Add(component);
                    continue;
                }

                if (hit >= component.Lines.Count)
                {
                    continue;
                }

                FsaComponent copy = new FsaComponent(component.Name, component.Kind)
                {
                    WeightsAreFinal = component.WeightsAreFinal,
                    Derived = component.Derived,
                    FixedTemplate = component.FixedTemplate,
                    TotalYieldPercent = component.TotalYieldPercent
                };

                foreach (FsaLine line in component.Lines)
                {
                    if (!drops.Contains(line))
                    {
                        copy.Lines.Add(line);
                    }
                }

                narrowed.Add(copy);
            }

            return narrowed;
        }

        /// <summary>
        /// (`S103`) Сколько линий вообще лежит ниже порога — знаменатель для
        /// числа выброшенных. Без него «выброшено 0» ничем не отличается от
        /// «выбрасывать было нечего», а это разные новости.
        /// </summary>
        static int CountLinesBelow(List<FsaComponent> library, double below)
        {
            if (library == null || !(below > 0.0))
            {
                return 0;
            }

            int n = 0;
            foreach (FsaComponent component in library)
            {
                if (component == null || component.FixedTemplate != null
                    || component.Lines == null)
                {
                    continue;
                }

                foreach (FsaLine line in component.Lines)
                {
                    if (line.Energy > 0.0 && line.Intensity > 0.0 && line.Energy < below)
                    {
                        n++;
                    }
                }
            }

            return n;
        }

        /// <summary>(`S103`) Сколько образов исчезло целиком при сужении.</summary>
        static int CountEmptied(List<FsaComponent> library, List<FsaComponent> narrowed)
        {
            if (library == null || narrowed == null)
            {
                return 0;
            }

            var kept = new HashSet<string>(StringComparer.Ordinal);
            foreach (FsaComponent component in narrowed)
            {
                if (component != null)
                {
                    kept.Add(component.Name);
                }
            }

            int gone = 0;
            foreach (FsaComponent component in library)
            {
                if (component != null && !kept.Contains(component.Name))
                {
                    gone++;
                }
            }

            return gone;
        }

        /// <summary>
        /// Обратная подматрица Gram по набору колонок; null — набор пуст или
        /// вырожден. Тот же <see cref="InvertSymmetric"/>, что у пределов S9.
        /// </summary>
        static double[,] InvertGramSubset(double[,] gram, List<int> set)
        {
            if (gram == null || set == null || set.Count == 0)
            {
                return null;
            }

            double[,] sub = new double[set.Count, set.Count];
            for (int a = 0; a < set.Count; a++)
            {
                for (int b = 0; b < set.Count; b++)
                {
                    sub[a, b] = gram[set[a], set[b]];
                }
            }

            return InvertSymmetric(sub, set.Count);
        }

        /// <summary>
        /// Доля столбца <paramref name="phi"/>, представимая набором колонок
        /// <paramref name="set"/>, по дополнению Шура во взвешенной метрике
        /// фита: 1 − (g_jj − g_Aj·H·g_Aj) / g_jj. Ноль — набор столбец не
        /// объясняет вовсе, единица — объясняет целиком.
        /// </summary>
        static double SchurShare(double[] phi, double gjj, double[] weights, FitResult fit,
                                 List<int> set, double[,] inverse, int chLo, int chHi,
                                 out bool degenerate)
        {
            degenerate = false;
            if (!(gjj > 0.0))
            {
                degenerate = true;
                return 1.0;
            }

            if (inverse == null || set == null || set.Count == 0)
            {
                return 0.0;
            }

            double[] g = new double[set.Count];
            for (int a = 0; a < set.Count; a++)
            {
                g[a] = DotWeighted(fit.Columns[set[a]].Values, phi, weights, chLo, chHi);
            }

            double cross = 0.0;
            for (int a = 0; a < set.Count; a++)
            {
                double s = 0.0;
                for (int b = 0; b < set.Count; b++)
                {
                    s += inverse[a, b] * g[b];
                }

                cross += g[a] * s;
            }

            double denominator = gjj - cross;
            if (denominator <= 1.0E-10 * gjj)
            {
                degenerate = true;
                return 1.0;
            }

            double share = 1.0 - denominator / gjj;
            return share < 0.0 ? 0.0 : (share > 1.0 ? 1.0 : share);
        }

        /// <summary>
        /// Столбец ОДНОЙ линии компонента — теми же построителями, что и весь
        /// образ. См. <see cref="AuditLineColumns"/>.
        /// </summary>
        double[] BuildLineColumn(FsaComponent component, int lineIndex,
                                 EnergyCalibration calibration, FwhmCalibration fwhmCalibration,
                                 FsaEfficiency efficiency, double gain, double offset,
                                 int chLo, int chHi, int channels)
        {
            FsaLine line = component.Lines[lineIndex];
            if (this.ResponseMatrix != null && !component.WeightsAreFinal)
            {
                EfficiencyMaker.ResponseMatrix matrix = this.ResponseMatrix;
                double bin = matrix.BinKev;
                if (!(bin > 0.0))
                {
                    return null;
                }

                double[] deposit = new double[(int)(line.Energy / bin + 0.5) + 1];
                FsaCascadeSummer.Correction correction =
                    this.cascade != null ? this.cascade.For(component) : null;
                if (correction != null && !correction.Any)
                {
                    correction = null;
                }

                double weight = line.Intensity / 100.0;
                double cf = correction != null && correction.LineFactors != null
                            && lineIndex < correction.LineFactors.Length
                    ? correction.LineFactors[lineIndex]
                    : 1.0;
                if (Math.Abs(cf - 1.0) < 1.0E-6)
                {
                    matrix.Accumulate(deposit, line.Energy, weight);
                }
                else
                {
                    for (int c = 0; c < EfficiencyMaker.EfficiencySimulator.ResponseChannelCount; c++)
                    {
                        bool peakChannel = c == (int)EfficiencyMaker.EfficiencySimulator.ResponseChannel.Peak;
                        matrix.AccumulateChannel(deposit, line.Energy,
                                                 peakChannel ? weight * cf : weight, c);
                    }
                }

                // Тот же нож, что в `DepositOf`: подпороговый континуум уезжает
                // в соседнюю свободную колонку и в столбце образа не стоит.
                this.SplitContinuumBelowTrustFloor(deposit, null, bin, component,
                                                   calibration, fwhmCalibration, channels);
                return this.BroadenResponseDeposit(deposit, calibration, fwhmCalibration, bin,
                                                   gain, offset, chLo, chHi, channels);
            }

            FsaComponent one = new FsaComponent(component.Name, component.Kind);
            one.Lines.Add(line);
            one.WeightsAreFinal = component.WeightsAreFinal;
            return BuildTemplate(one, calibration, fwhmCalibration, efficiency,
                                 gain, offset, chLo, chHi, channels);
        }

        FsaResult BuildResult(FitResult fit, EnergySpectrum spectrum, FwhmCalibration fwhmCalibration,
                              double[] backgroundCurve, int[] snipContinuum,
                              int chLo, int chHi, int channels, double gain, double offset, double liveTime,
                              FsaEfficiency efficiency, bool gainOnEdge, bool offsetOnEdge)
        {
            // Калибровка — та же, по которой строились образы; берётся у
            // спектра, как в Analyze. ПШПВ приходит параметром: у спектра её
            // может не быть вовсе, она достраивается выше.
            EnergyCalibration calibration = spectrum.EnergyCalibration;

            FsaResult result = new FsaResult
            {
                FirstChannel = chLo,
                LastChannel = chHi,
                Chi2Ndf = fit.Chi2Ndf,
                Chi2NdfPoisson = fit.Chi2NdfBase,
                ModelResidual = fit.ModelResidual,
                Gain = gain,
                OffsetChannels = offset,
                LiveTime = liveTime,
                EfficiencyUsed = efficiency != null,
                ResponseMatrixUsed = fit.FromResponseMatrix,
                CascadeSummingUsed = this.cascadeApplied,
                GainOnGridEdge = gainOnEdge,
                OffsetOnGridEdge = offsetOnEdge,
                Background = backgroundCurve,
                Continuum = new double[channels],
                Model = new double[channels]
            };

            if (snipContinuum != null)
            {
                for (int i = chLo; i <= chHi; i++)
                {
                    result.Continuum[i] = snipContinuum[i];
                }
            }

            double totalPeakCounts = 0.0;
            double allPeakCounts = 0.0;
            for (int k = 0; k < fit.Columns.Count; k++)
            {
                FitColumn column = fit.Columns[k];
                double amplitude = fit.Amplitude[k];
                if (column.Component == null)
                {
                    // шапки континуума схлопываются в одну кривую
                    if (amplitude > 0.0)
                    {
                        for (int i = chLo; i <= chHi; i++)
                        {
                            result.Continuum[i] += amplitude * column.Values[i];
                        }
                    }

                    continue;
                }

                if (amplitude <= 0.0)
                {
                    continue;
                }

                double[] curve = new double[channels];
                for (int i = chLo; i <= chHi; i++)
                {
                    curve[i] = amplitude * column.Values[i];
                }

                // ⛔ РЯД, СВЯЗАННЫЙ РАВНОВЕСИЕМ, ОСТАЁТСЯ В ОТЧЁТЕ ПОЧЛЕННО
                // (указание Amber 18.08.2026, поправка к `S70`). Связка меняет
                // ЧИСЛО СВОБОДНЫХ АМПЛИТУД, а не список компонентов: у ряда одна
                // колонка и одна амплитуда на весь ряд, но в таблице обязаны
                // остаться те же строки, что и без связки, — и с долями. Иначе
                // галка не «убирает неустойчивых кандидатов», а сокращает
                // состав, чего от неё не просили.
                //
                // Разделяется по НУКЛИДУ ЛИНИИ: в колонке ряда линии помечены
                // своим членом (`FsaLine.Nuclide`), и большего не нужно.
                if (this.SplitChainMembers(column.Component, curve, amplitude, calibration,
                                           fwhmCalibration, efficiency, gain, offset,
                                           chLo, chHi, channels, liveTime, fit.Z[k],
                                           result, ref totalPeakCounts, ref allPeakCounts))
                {
                    continue;
                }

                // Та часть кривой, что пришла от сумм-пиков: та же амплитуда,
                // тот же дрейф — отличается только состав образа.
                double[] sumOnly = this.BuildSumPeakCurve(column.Component, calibration, fwhmCalibration,
                                                          gain, offset, chLo, chHi, channels);
                if (sumOnly != null)
                {
                    for (int i = 0; i < channels; i++)
                    {
                        sumOnly[i] *= amplitude;
                    }
                }

                FsaComponentResult component = new FsaComponentResult
                {
                    Name = column.Component.Name,
                    Kind = column.Component.Kind,

                    // (`S72`) Колонка ряда, которую разложить почленно не вышло
                    // (в рабочее окно прибора попали линии одного члена),
                    // остаётся строкой ПРО РЯД: имя у неё корневое, а амплитуда
                    // закреплена связкой так же, как у разложенных.
                    ChainRoot = column.Component.Kind == FsaComponentKind.Chain
                        ? column.Component.Name : null,
                    Curve = curve,
                    SumPeakCurve = sumOnly,
                    PeakCounts = this.PeakWindowCounts(column.Component, curve, calibration,
                                                       fwhmCalibration, gain, offset,
                                                       chLo, chHi, channels),
                    CountRate = amplitude / liveTime,
                    Z = fit.Z[k]
                };

                result.Components.Add(component);
                if (component.Kind != FsaComponentKind.Nuisance)
                {
                    totalPeakCounts += component.PeakCounts;
                }

                // Второй итог — по ВСЕМ образам, служебные вместе с нуклидными
                // (S49). Одной суммой тут не обойтись: «пирог» отвечает на
                // вопрос «из чего проба» и вылет с аннигиляцией в него не
                // берёт, а «сколько занимает компонент» — вопрос другой, и на
                // него нулём отвечать нельзя.
                allPeakCounts += component.PeakCounts;
            }

            foreach (FsaComponentResult component in result.Components)
            {
                component.PeakSharePercent = allPeakCounts > 0.0
                    ? 100.0 * component.PeakCounts / allPeakCounts
                    : 0.0;
            }

            for (int i = chLo; i <= chHi; i++)
            {
                double sum = result.Continuum[i];
                foreach (FsaComponentResult component in result.Components)
                {
                    sum += component.Curve[i];
                }

                result.Model[i] = sum;
            }

            // (`S111`, решение Amber 01.09.2026) НЕВЯЗКА В ОТСЧЁТАХ — обе
            // половины, ровно те, что рисует лента на экране: измерение выше
            // модели («не описано») и модель выше измерения («приписано
            // лишнее»). Пара считается ЗДЕСЬ, а не в отрисовке, потому что то
            // же число нужно пробам и корпусу, а второй копии правила в
            // проекте быть не должно.
            //
            // ⚠ Мера НЕ ТА ЖЕ, что <see cref="FsaResult.ModelResidual"/>: там ε,
            // оценённая по χ² доля формы, и она остаётся — ею меряется корпус
            // (медиана понятной части 10.7 %). Здесь отсчёты, и на одном и том
            // же спектре числа расходятся: `G1S24_Th228_P5` — ε 34.2 %, а по
            // отсчётам +20.25 / −6.80 %. На ЭКРАН по решению Amber идут
            // отсчёты: человек читает строку как площадь нарисованной ленты.
            double aboveCounts = 0.0, belowCounts = 0.0, measuredCounts = 0.0;
            int[] raw = spectrum.Spectrum;
            for (int i = chLo; i <= chHi && i < raw.Length; i++)
            {
                double background = backgroundCurve != null && i < backgroundCurve.Length
                    ? backgroundCurve[i] : 0.0;
                double net = raw[i] - background;
                double difference = net - result.Model[i];
                measuredCounts += net;
                if (difference > 0.0)
                {
                    aboveCounts += difference;
                }
                else
                {
                    belowCounts -= difference;
                }
            }

            result.ResidualAboveShare = measuredCounts > 0.0 ? aboveCounts / measuredCounts : 0.0;
            result.ResidualBelowShare = measuredCounts > 0.0 ? belowCounts / measuredCounts : 0.0;

            // ДОЛЯ — ОДНА МЕРА НА ВЕСЬ ПРОЕКТ, доля СЛОЯ (`S76`, решение Amber
            // 23.08.2026), и считается она там же, где строятся слои.
            //
            // ⛔ Прежде здесь стоял «пирог» по ПИКОВЫМ отсчётам среди нуклидных
            // образов: знаменатель — `totalPeakCounts`, у мешающих ноль. Экран
            // печатал ДРУГОЕ число под тем же словом, и сверить их было нечем.
            // Считать долю раньше модели теперь нельзя: разнос подложки идёт по
            // готовым кривым, поэтому вызов стоит ПОСЛЕ сборки `result.Model`.
            //
            // ⚠ `totalPeakCounts` остался при `SplitChainMembers` — там он
            // делит колонку ряда между членами, и это другая арифметика.
            result.ComputeComponentShares();

            return result;
        }

        /// <summary>
        /// Разложить колонку СВЯЗАННОГО РАВНОВЕСИЕМ ряда на строки его членов
        /// (`S70`, поправка Amber 18.08.2026). Возвращает false, если колонка
        /// рядом не является и её надо отчитать как обычно.
        ///
        /// Связка равновесия трогает ЧИСЛО СВОБОДНЫХ АМПЛИТУД, а не состав: у
        /// ряда одна колонка в фите, но читателю полагаются те же строки, что и
        /// без неё. Доли между членами при этом не подгоняются данными — они
        /// закреплены накопленной долей ветвления, и в этом весь смысл галки.
        ///
        /// ⚠ Члены раскладываются так, чтобы их сумма ТОЧНО равнялась кривой
        /// колонки: доля канала раздаётся по весу образов членов в этом канале.
        /// Строить членам образы независимо и класть их как есть нельзя — у
        /// матричного образа подпороговый хвост отвязывается от ПОЛНОЙ колонки
        /// (<see cref="ResponseContinuumTrustFloorKev"/>), и сумма независимо
        /// построенных членов разошлась бы с ней на этот хвост. Верх стека
        /// обязан сходиться с моделью.
        /// </summary>
        bool SplitChainMembers(FsaComponent component, double[] curve, double amplitude,
                               EnergyCalibration calibration, FwhmCalibration fwhmCalibration,
                               FsaEfficiency efficiency, double gain, double offset,
                               int chLo, int chHi, int channels, double liveTime, double z,
                               FsaResult result, ref double totalPeakCounts, ref double allPeakCounts)
        {
            if (component.Kind != FsaComponentKind.Chain || component.Lines.Count == 0)
            {
                return false;
            }

            // Члены — в порядке первого появления линии: так строки идут в том
            // же порядке, в каком ряд обходится от корня.
            List<string> order = new List<string>();
            Dictionary<string, FsaComponent> parts =
                new Dictionary<string, FsaComponent>(StringComparer.OrdinalIgnoreCase);
            foreach (FsaLine line in component.Lines)
            {
                string name = string.IsNullOrEmpty(line.Nuclide) ? component.Name : line.Nuclide;
                FsaComponent part;
                if (!parts.TryGetValue(name, out part))
                {
                    part = new FsaComponent(name, FsaComponentKind.Single)
                    {
                        WeightsAreFinal = component.WeightsAreFinal
                    };
                    parts[name] = part;
                    order.Add(name);
                }

                part.Lines.Add(line);
            }

            if (order.Count < 2)
            {
                return false;
            }

            // Образ каждого члена и их сумма по каналам.
            List<double[]> images = new List<double[]>(order.Count);
            double[] sum = new double[channels];
            foreach (string name in order)
            {
                double[] image = this.MemberTemplate(parts[name], calibration, fwhmCalibration,
                                                     efficiency, gain, offset, chLo, chHi, channels);
                images.Add(image);
                if (image == null)
                {
                    continue;
                }

                for (int i = chLo; i <= chHi; i++)
                {
                    sum[i] += image[i];
                }
            }

            for (int m = 0; m < order.Count; m++)
            {
                double[] image = images[m];
                if (image == null)
                {
                    continue;
                }

                double[] part = new double[channels];
                for (int i = chLo; i <= chHi; i++)
                {
                    if (sum[i] > 0.0)
                    {
                        part[i] = curve[i] * image[i] / sum[i];
                    }
                }

                FsaComponent source = parts[order[m]];
                double[] sumOnly = this.BuildSumPeakCurve(source, calibration, fwhmCalibration,
                                                          gain, offset, chLo, chHi, channels);
                if (sumOnly != null)
                {
                    for (int i = 0; i < channels; i++)
                    {
                        sumOnly[i] *= amplitude;
                    }
                }

                FsaComponentResult member = new FsaComponentResult
                {
                    Name = source.Name,
                    Kind = FsaComponentKind.Single,

                    // (`S72`) Вид у члена — `Single` нарочно: строки ряда идут
                    // общим списком и сортируются вместе со всеми (`S71`).
                    // Связанность амплитуды несёт ОТДЕЛЬНОЕ поле — иначе она
                    // либо потерялась бы вовсе, либо утащила бы строку в другую
                    // группу порядка.
                    ChainRoot = component.Name,
                    Curve = part,
                    SumPeakCurve = sumOnly,
                    PeakCounts = this.PeakWindowCounts(source, part, calibration, fwhmCalibration,
                                                       gain, offset, chLo, chHi, channels),
                    CountRate = amplitude / liveTime,

                    // ⚠ Значимость у всех членов ОДНА — колонки-то одна. Это не
                    // упущение, а прямое следствие связки: данные различают ряд
                    // целиком, а не его члена, и делать вид, что у Ra-224 своя
                    // значимость, значило бы вернуть ровно ту неправду, ради
                    // снятия которой связка и заведена.
                    Z = z
                };

                result.Components.Add(member);
                totalPeakCounts += member.PeakCounts;
                allPeakCounts += member.PeakCounts;
            }

            return true;
        }

        /// <summary>
        /// Образ ОДНОГО члена связанного ряда — тем же построителем, что и
        /// целая колонка, чтобы форма линий и уширение совпадали.
        /// </summary>
        double[] MemberTemplate(FsaComponent part, EnergyCalibration calibration,
                                FwhmCalibration fwhmCalibration, FsaEfficiency efficiency,
                                double gain, double offset, int chLo, int chHi, int channels)
        {
            if (this.ResponseMatrix != null && !part.WeightsAreFinal)
            {
                double[] lowTail;
                return this.BuildTemplateFromResponse(part, calibration, fwhmCalibration,
                                                      gain, offset, chLo, chHi, channels, out lowTail);
            }

            return BuildTemplate(part, calibration, fwhmCalibration, efficiency,
                                 gain, offset, chLo, chHi, channels);
        }

        /// <summary>
        /// Отсчёты компонента в его ПИКОВЫХ ОКНАХ (±2 ПШПВ вокруг каждой линии
        /// и каждого сумм-пика), а не по всему образу.
        ///
        /// Так решено (S24в, Amber 08.08.2026), потому что по всему образу доля
        /// в «пироге» несравнима между нуклидами: подпороговый континуум образа
        /// отвязывается в свою колонку со своей свободной амплитудой
        /// (<see cref="ResponseContinuumTrustFloorKev"/>), и урезано у разных
        /// нуклидов по-разному — у высокоэнергичных под порогом континуума
        /// больше. Приписать хвост обратно нельзя: его амплитуда своя. Пиковые
        /// окна разрезом НЕ трогаются никогда (они нарочно остаются в основном
        /// образе), поэтому счёт по ним от порога не зависит вовсе и правило
        /// выходит одинаковым для всех строк.
        ///
        /// Число перестало быть «долей спектра» и стало «долей пиковых
        /// отсчётов» — это разные величины, и подпись у него своя.
        ///
        /// Окна берутся тем же ±2 ПШПВ, что и в
        /// <see cref="SplitContinuumBelowTrustFloor"/>: два места, считающие
        /// «пиковое окно» по-своему, однажды разойдутся. Перекрытия
        /// складываются один раз — маска по каналам, а не сумма по линиям.
        /// </summary>
        double PeakWindowCounts(FsaComponent component, double[] curve, EnergyCalibration calibration,
                                FwhmCalibration fwhmCalibration, double gain, double offset,
                                int chLo, int chHi, int channels)
        {
            if (component == null || curve == null)
            {
                return 0.0;
            }

            bool[] inWindow = this.PeakWindowMask(component, calibration, fwhmCalibration,
                                                  gain, offset, chLo, chHi, channels);
            if (inWindow == null)
            {
                return 0.0;
            }

            double counts = 0.0;
            for (int i = chLo; i <= chHi; i++)
            {
                if (inWindow[i])
                {
                    counts += curve[i];
                }
            }

            return counts;
        }

        /// <summary>
        /// Маска пиковых окон компонента (±2 ПШПВ вокруг каждой линии и
        /// каждого сумм-пика, правило <see cref="PeakWindowCounts"/>).
        /// null — ни одна линия не легла в окно фита: счёт по такой маске был
        /// бы не «пиковым», а случайным остатком. Одна на два потребителя
        /// (пиковый счёт и парциальные невязки P6) нарочно: два места,
        /// считающие «пиковое окно» по-своему, однажды разойдутся.
        /// </summary>
        bool[] PeakWindowMask(FsaComponent component, EnergyCalibration calibration,
                              FwhmCalibration fwhmCalibration, double gain, double offset,
                              int chLo, int chHi, int channels)
        {
            if (component == null)
            {
                return null;
            }

            bool[] inWindow = new bool[channels];
            bool any = false;

            foreach (FsaLine line in component.Lines)
            {
                if (line.Intensity > 0.0
                    && MarkPeakWindow(inWindow, line.Energy, calibration, fwhmCalibration,
                                      gain, offset, chLo, chHi, channels))
                {
                    any = true;
                }
            }

            // Сумм-пик принадлежит своему нуклиду и стоит там, где линии нет
            // вовсе; без него у плотных каскадов (Lu-176) пиковый счёт терял бы
            // то, что каскадная поправка вынесла из линий.
            FsaCascadeSummer.Correction correction =
                this.cascade != null && this.CascadeSumPeaks ? this.cascade.For(component) : null;
            if (correction != null && correction.SumPeaks != null)
            {
                foreach (FsaCascadeSummer.SumPeak peak in correction.SumPeaks)
                {
                    if (MarkPeakWindow(inWindow, peak.Energy, calibration, fwhmCalibration,
                                       gain, offset, chLo, chHi, channels))
                    {
                        any = true;
                    }
                }
            }

            return any ? inWindow : null;
        }

        /// <summary>
        /// (P6) Парциальные невязки вошедших компонентов, гипотеза
        /// fsa-hypotheses-2026-08.md §2. Для каждой строки состава:
        /// ZoneChi2Ndf — χ²/ndf остатка в пиковых окнах компонента ПРЕЖНИМИ
        /// весами (у фантома с настоящими линиями z неотличим от настоящего —
        /// амплитудный тест слеп, а форма его зоны нет); ZoneDeltaD — рефит
        /// того же состава БЕЗ компонента при том же узле дрейфа, разница
        /// Σw·r² по зоне: ≈0 значит «своей зоне компонент не нужен» — сигнал
        /// соседям отдаёт NNLS, как у Pu-238 в поверке S9. Состав и амплитуды
        /// НЕ трогаются — чистый пост-расчёт; сигма-множитель (а) выводится
        /// читателем как √(max(1, ZoneChi2Ndf)/max(1, χ²/ndf общего)).
        /// </summary>
        void ComputePartialResiduals(FsaResult result, FitResult best, List<double[]> fixedColumns,
                                     EnergyCalibration calibration, FwhmCalibration fwhmCalibration,
                                     FsaEfficiency efficiency, double gain, double offset,
                                     int chLo, int chHi, int channels,
                                     double[] y, double[] variance, double[] baseWeights,
                                     double[] reportWeights)
        {
            if (result == null || best == null || best.Residual == null || best.Columns == null)
            {
                return;
            }

            List<FsaComponent> components = new List<FsaComponent>();
            for (int k = 0; k < best.Columns.Count; k++)
            {
                if (best.Columns[k].Component != null)
                {
                    components.Add(best.Columns[k].Component);
                }
            }

            int row = 0;
            for (int k = 0; k < best.Columns.Count; k++)
            {
                FitColumn column = best.Columns[k];
                if (column.Component == null || best.Amplitude[k] <= 0.0)
                {
                    continue;
                }

                if (row >= result.Components.Count)
                {
                    break;
                }

                FsaComponentResult target = result.Components[row++];
                if (!string.Equals(target.Name, column.Component.Name, StringComparison.Ordinal))
                {
                    // Строки результата создаются BuildResult в этом же порядке
                    // и по этим же условиям; разъехались — считать нечего.
                    break;
                }

                bool[] zone = this.PeakWindowMask(column.Component, calibration, fwhmCalibration,
                                                  gain, offset, chLo, chHi, channels);
                if (zone == null)
                {
                    continue;
                }

                double dWith = 0.0;
                int zoneChannels = 0;
                for (int i = chLo; i <= chHi; i++)
                {
                    if (zone[i])
                    {
                        dWith += best.Residual[i] * best.Residual[i] * reportWeights[i];
                        zoneChannels++;
                    }
                }

                if (zoneChannels == 0)
                {
                    continue;
                }

                target.ZoneChannels = zoneChannels;
                target.ZoneChi2Ndf = dWith / zoneChannels;

                List<FsaComponent> without = new List<FsaComponent>(components);
                without.Remove(column.Component);
                FitResult refit = this.FitHuber(components, fixedColumns, calibration, fwhmCalibration,
                                                efficiency, gain, offset, chLo, chHi, channels,
                                                y, variance, baseWeights, null, without);
                if (refit == null || refit.Residual == null)
                {
                    continue;
                }

                double dWithout = 0.0;
                for (int i = chLo; i <= chHi; i++)
                {
                    if (zone[i])
                    {
                        dWithout += refit.Residual[i] * refit.Residual[i] * reportWeights[i];
                    }
                }

                target.ZoneDeltaD = dWithout - dWith;
            }
        }

        /// <summary>
        /// Пометить в маске каналы окна ±2 ПШПВ вокруг линии с учётом дрейфа
        /// шкалы. Возвращает false, если линия за краем окна фита или ПШПВ там
        /// не определена.
        /// </summary>
        bool MarkPeakWindow(bool[] inWindow, double energy, EnergyCalibration calibration,
                            FwhmCalibration fwhmCalibration, double gain, double offset,
                            int chLo, int chHi, int channels)
        {
            if (!(energy > 0.0))
            {
                return false;
            }

            double position = EnergyToChannelSafe(calibration, energy, channels);
            if (Double.IsNaN(position))
            {
                return false;
            }

            double p = gain * position + offset;
            double fwhm = fwhmCalibration.ChannelToFwhm(p);
            if (!(fwhm > 0.0) || Double.IsNaN(fwhm))
            {
                return false;
            }

            int from = (int)Math.Floor(p - 2.0 * fwhm);
            int to = (int)Math.Ceiling(p + 2.0 * fwhm);
            if (from < chLo)
            {
                from = chLo;
            }

            if (to > chHi)
            {
                to = chHi;
            }

            if (from > to)
            {
                return false;
            }

            for (int i = from; i <= to; i++)
            {
                inWindow[i] = true;
            }

            return true;
        }

