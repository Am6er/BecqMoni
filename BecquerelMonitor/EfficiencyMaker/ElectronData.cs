        /// <summary>
        /// Подобрать материал по составу кристалла. Совпадением считается точное
        /// совпадение набора элементов с ненулевой долей; если состава нет в
        /// таблице, возвращается null и поправка на вылет электрона не считается.
        /// </summary>
        public static Material Match(GeometryMaterial material)
        {
            if (material == null)
            {
                return null;
            }

            List<int> present = new List<int>();
            foreach (KeyValuePair<int, double> pair in material.Fractions)
            {
                if (pair.Value > 0.0)
                {
                    present.Add(pair.Key);
                }
            }

            present.Sort();
            for (int i = 0; i < Signatures.Length; i++)
            {
                int[] sig = Signatures[i];
                if (sig.Length != present.Count)
                {
                    continue;
                }

                bool same = true;
                for (int k = 0; k < sig.Length; k++)
                {
                    if (sig[k] != present[k])
                    {
                        same = false;
                        break;
                    }
                }

                if (same)
                {
                    return All[i];
                }
            }

            return null;
        }

        public static Material ByName(string name)
        {
            foreach (Material m in All)
            {
                if (string.Equals(m.Name, name, StringComparison.OrdinalIgnoreCase))
                {
                    return m;
                }
            }

            return null;
        }

        /// <summary>Пробег CSDA, г/см², по кинетической энергии в кэВ.</summary>
        public static double RangeOf(Material m, double energyKev)
        {
            return LogLog(m.Energy, m.Range, energyKev * 1e-3);
        }

        /// <summary>Доля энергии, уходящая в тормозное излучение.</summary>
        public static double YieldOf(Material m, double energyKev)
        {
            return LogLog(m.Energy, m.Yield, energyKev * 1e-3);
        }

        /// <summary>
        /// Обратная задача: какой энергии (кэВ) отвечает остаточный пробег
        /// <paramref name="range"/> г/см². Нужна, чтобы узнать, сколько энергии
        /// электрон унёс, вылетев через границу.
        /// </summary>
        public static double EnergyOfRange(Material m, double range)
        {
            return LogLog(m.Range, m.Energy, range) * 1e3;
        }

        /// <summary>
        /// Интерполяция по двойному логарифму с продолжением по крайнему
        /// наклону. Обе величины степенные по энергии, на логарифмах это почти
        /// прямая, ошибка внутри сетки — доли процента.
        /// </summary>
        static double LogLog(double[] x, double[] y, double v)
        {
            int n = x.Length;
            if (!(v > 0.0))
            {
                return y[0];
            }

            int i;
            if (v <= x[0])
            {
                i = 0;
            }
            else if (v >= x[n - 1])
            {
                i = n - 2;
            }
            else
            {
                int lo = 0, hi = n - 1;
                while (hi - lo > 1)
                {
                    int mid = (lo + hi) >> 1;
                    if (x[mid] <= v)
                    {
                        lo = mid;
                    }
                    else
                    {
                        hi = mid;
                    }
                }

                i = lo;
            }

            double lx0 = Math.Log(x[i]), lx1 = Math.Log(x[i + 1]);
            double ly0 = Math.Log(y[i]), ly1 = Math.Log(y[i + 1]);
            double t = (Math.Log(v) - lx0) / (lx1 - lx0);
            return Math.Exp(ly0 + t * (ly1 - ly0));
        }
