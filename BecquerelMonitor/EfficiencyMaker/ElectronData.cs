        // Набор Z, по которому вещество опознаётся: йод + цезий -> CsI и так далее.
        static readonly int[][] Signatures =
        {
            new int[] { 53, 55 },        // CsI
            new int[] { 11, 53 },        // NaI
            new int[] { 8, 32, 83 },     // BGO
            new int[] { 35, 57 },        // LaBr3
            new int[] { 35, 58 },        // CeBr3
            new int[] { 38, 53 },        // SrI2
            new int[] { 48, 52 },        // CdTe
            new int[] { 30, 48, 52 },    // CZT
            new int[] { 8, 14, 64 },     // GSO
            new int[] { 32 },            // Ge (в том числе HPGe)
            new int[] { 13 },            // Al
            new int[] { 6, 9 },          // PTFE (C2F4)
            new int[] { 1, 8 }           // вода
        };

        /// <summary>
        /// Подобрать материал по составу кристалла. Совпадением считается точное
        /// совпадение набора элементов с ненулевой долей; если состава нет в
        /// таблице, возвращается null и поправка на вылет электрона не считается.
        /// </summary>
        public static Material Match(GeometryMaterial material)
        {
            if (material == null)
            {
                return null;
            }

            List<int> present = new List<int>();
            foreach (KeyValuePair<int, double> pair in material.Fractions)
            {
                if (pair.Value > 0.0)
                {
                    present.Add(pair.Key);
                }
            }

            present.Sort();
            for (int i = 0; i < Signatures.Length; i++)
            {
                int[] sig = Signatures[i];
                if (sig.Length != present.Count)
                {
                    continue;
                }

                bool same = true;
                for (int k = 0; k < sig.Length; k++)
                {
                    if (sig[k] != present[k])
                    {
                        same = false;
                        break;
                    }
                }

                if (same)
                {
                    return Computed()[i];
                }
            }

            return null;
        }

