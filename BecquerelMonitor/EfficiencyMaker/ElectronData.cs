    /// по пути торможения (<see cref="ThickTargetBrem"/>) не добирал того, что
    /// излучается на последних десяти килоэлектронвольтах. Недостача равна
    /// `Y(10 кэВ) / Y(T)` и предсказывает 11.4 % при T = 100 кэВ и 0.97 % при
    /// 2614 кэВ; измеренная подтяжка к ESTAR была 1.089 и 1.010 — на верху
    /// шкалы совпадает в сотых долях процента.
