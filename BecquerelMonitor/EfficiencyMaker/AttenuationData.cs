        public static bool HasElement(int z)
        {
            return OnStandardGrid.ContainsKey(z) || WithEdges.ContainsKey(z);
        }

        /// <summary>
        /// Массовый коэффициент ослабления элемента, см2/г, лог-лог
        /// интерполяцией. За краями таблицы держится крайнее значение:
        /// экстраполировать степенной закон фотопоглощения вниз нельзя.
        /// </summary>
        public static double MassAttenuation(int z, double energyKev)
        {
            if (!(energyKev > 0.0))
            {
                return 0.0;
            }

            double e = energyKev / 1000.0;
            double[] plain;
            if (OnStandardGrid.TryGetValue(z, out plain))
            {
                return Interpolate(StandardGrid, plain, e);
            }

            double[,] rows;
            if (!WithEdges.TryGetValue(z, out rows))
            {
                return 0.0;
            }

            int n = rows.GetLength(0);
            if (e <= rows[0, 0])
            {
                return rows[0, 1];
            }

            if (e >= rows[n - 1, 0])
            {
                return rows[n - 1, 1];
            }

            int hi = 1;
            while (hi < n - 1 && rows[hi, 0] < e)
            {
                hi++;
            }

            return Between(rows[hi - 1, 0], rows[hi - 1, 1], rows[hi, 0], rows[hi, 1], e);
        }

        static double Interpolate(double[] grid, double[] values, double e)
        {
            int n = grid.Length;
            if (e <= grid[0])
            {
                return values[0];
            }

            if (e >= grid[n - 1])
            {
                return values[n - 1];
            }

            int hi = 1;
            while (hi < n - 1 && grid[hi] < e)
            {
                hi++;
            }

            return Between(grid[hi - 1], values[hi - 1], grid[hi], values[hi], e);
        }

        static double Between(double x0, double y0, double x1, double y1, double x)
        {
            if (!(x1 > x0))
            {
                // край поглощения: две точки с одной энергией
                return y1;
            }

            double f = (Math.Log(x) - Math.Log(x0)) / (Math.Log(x1) - Math.Log(x0));
            return Math.Exp(Math.Log(y0) + f * (Math.Log(y1) - Math.Log(y0)));
        }
