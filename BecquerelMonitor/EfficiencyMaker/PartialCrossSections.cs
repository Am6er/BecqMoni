        /// <summary>
        /// Сечение канала для элемента, см2/г. Интерполяция логарифмическая по
        /// энергии и линейная по значению: у каналов есть нули (рождение пар ниже
        /// порога), и логарифм по значению там неприменим.
        /// </summary>
        public static double MassCrossSection(int z, double energyKev, PhotonProcess process)
        {
            double[,] rows;
            if (!Table.TryGetValue(z, out rows) || !(energyKev > 0.0))
            {
                return 0.0;
            }

            double e = energyKev / 1000.0;
            int n = rows.GetLength(0);
            int lo, hi;
            if (e <= rows[0, 0])
            {
                lo = hi = 0;
            }
            else if (e >= rows[n - 1, 0])
            {
                lo = hi = n - 1;
            }
            else
            {
                hi = 1;
                while (hi < n - 1 && rows[hi, 0] < e)
                {
                    hi++;
                }

                lo = hi - 1;
            }

            double a = Column(rows, lo, process);
            if (lo == hi)
            {
                return a;
            }

            double x0 = rows[lo, 0], x1 = rows[hi, 0];
            if (!(x1 > x0))
            {
                // край поглощения: две строки с одной энергией, берём верхнюю
                return Column(rows, hi, process);
            }

            double b = Column(rows, hi, process);
            double f = (Math.Log(e) - Math.Log(x0)) / (Math.Log(x1) - Math.Log(x0));
            return a + f * (b - a);
        }

        static double Column(double[,] rows, int i, PhotonProcess process)
        {
            switch (process)
            {
                case PhotonProcess.Coherent: return rows[i, 1];
                case PhotonProcess.Incoherent: return rows[i, 2];
                case PhotonProcess.Photoelectric: return rows[i, 3];
                default: return rows[i, 4] + rows[i, 5];
            }
        }
