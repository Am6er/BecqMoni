        /// <summary>
        /// Шестой хвост, `JNTK` (`S112`): таблица совместной эффективности пар.
        /// Нулевой размер — «не считалась», и <see cref="JointFactor"/> отдаёт
        /// 1.0. Вынесено отдельным методом, потому что вложенность чтения
        /// хвостов и без него дошла до восьми уровней.
        /// </summary>
        static void ReadJoint(ResponseMatrix matrix, Stream stream, BinaryReader reader)
        {
            if (stream.Length - stream.Position < 12
                || Encoding.ASCII.GetString(reader.ReadBytes(4)) != "JNTK")
            {
                return;
            }

            if (matrix.Options != null)
            {
                matrix.Options.JointNodes = reader.ReadInt32();
            }
            else
            {
                reader.ReadInt32();
            }

            // ⚠ Раннего выхода при пустой таблице здесь БОЛЬШЕ НЕТ: за ней
            // идёт седьмой хвост, он пишется ВСЕГДА, и выйти отсюда значило
            // бы потерять `JointHistories` у матрицы с выключенной парой.
            int nodes = reader.ReadInt32();
            if (nodes > 0)
            {
                matrix.JointPoints = reader.ReadInt64();
                double[] grid = new double[nodes];
                for (int i = 0; i < nodes; i++)
                {
                    grid[i] = reader.ReadDouble();
                }

                double[][] table = new double[nodes][];
                double[][] noise = new double[nodes][];
                for (int i = 0; i < nodes; i++)
                {
                    table[i] = new double[nodes];
                    noise[i] = new double[nodes];
                    for (int j = 0; j < nodes; j++)
                    {
                        table[i][j] = reader.ReadDouble();
                        noise[i][j] = reader.ReadDouble();
                    }
                }

                matrix.JointEnergies = grid;
                matrix.JointKappa = table;
                matrix.JointKappaError = noise;
            }

            // ⚡ СЕДЬМОЙ ХВОСТ, `JNTH` (`T255`): ЧИСЛО ТОЧЕК замера κ.
            //
            // ⛔ Зачем поле в файле, если сама таблица уже там. С `T255`
            // `JointHistories` входит в КЛЕЙМО (условно — см.
            // <see cref="ComputeStamp"/>), а всякая настройка клейма обязана
            // приезжать обратно с диска: иначе матрица, посчитанная
            // `--jn=400000`, после чтения получит умолчание, пересчитает
            // клеймо БЕЗ строки и не сойдётся САМА С СОБОЙ — восьмой случай
            // того же, что `T114`, `A66`, `E34`, `T242` и `S112`.
            //
            // ⚠ ХВОСТОМ, А НЕ ПОДЪЁМОМ ФОРМАТА. У файлов до 10.09.2026
            // хвоста нет — поле остаётся умолчанием, то есть ровно тем, чем
            // оно было при их счёте (замер того же дня: все 44 матрицы
            // склада посчитаны умолчанием), — и клеймо сходится побайтно.
            // Подъём формата объявил бы склад чужим на ровном месте.
            //
            // ⚠ Читается ЗДЕСЬ ЖЕ, а не отдельным методом: сторож
            // `tools/check_matrix_keys.py` (правило «что в клейме, то в
            // файле») смотрит тело `Load` и тела ЕГО вызовов на один
            // уровень, и поле, прочитанное на два уровня вглубь, для него
            // не существует.
            if (matrix.Options != null && stream.Length - stream.Position >= 8
                && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "JNTH")
            {
                matrix.Options.JointHistories = reader.ReadInt32();

                // ⛔ ВОСЬМОЙ ХВОСТ, `PKBN` (`AMBER16`): ДОПУСК ПИКА ПО
                // ПОЛУБИНУ. Читается здесь же и по тем же двум причинам, что
                // `JNTH` выше: сторож `tools/check_matrix_keys.py` смотрит тело
                // `Load` и тела его вызовов на один уровень, а у файлов до
                // 11.09.2026 хвоста нет — флаг остаётся `false`, то есть ровно
                // тем, чем он был при их счёте, и клеймо сходится само с собой.
                if (stream.Length - stream.Position >= 5
                    && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "PKBN")
                {
                    matrix.Options.PeakToleranceHalfBin = reader.ReadBoolean();

                    // ⛔ ДЕВЯТЫЙ ХВОСТ, `XRKL` (`AMBER16` п. 1): РАЗВЕДЕНИЕ K- И
                    // L-ВЫЛЕТА. Читается здесь же и по тем же двум причинам,
                    // что `JNTH` и `PKBN` выше: сторож
                    // `tools/check_matrix_keys.py` смотрит тело `Load` и тела
                    // его вызовов на один уровень, а у файлов до 11.09.2026
                    // хвоста нет — флаг остаётся `false`, то есть ровно тем,
                    // чем он был при их счёте, и клеймо сходится само с собой.
                    if (stream.Length - stream.Position >= 5
                        && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "XRKL")
                    {
                        matrix.Options.SplitXrayShells = reader.ReadBoolean();

                        // ⛔ ДЕСЯТЫЙ И ОДИННАДЦАТЫЙ ХВОСТЫ, `KDIP` и `LETA`
                        // (`F11` (а)): читаются здесь же и по тем же двум
                        // причинам, что хвосты выше; у файлов до 11.09.2026 их
                        // нет — поля остаются 0, то есть ровно тем, чем были
                        // при их счёте, и клеймо сходится само с собой.
                        if (stream.Length - stream.Position >= 8
                            && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "KDIP")
                        {
                            matrix.Options.KDipLight = reader.ReadInt32();
                            if (stream.Length - stream.Position >= 12
                                && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "LETA")
                            {
                                matrix.Options.LightEtaEh = reader.ReadDouble();

                                // ⛔ ДВЕНАДЦАТЫЙ ХВОСТ, `NORM` (`AMBER13` (б)):
                                // нормировка строк. Читается здесь же по тем же
                                // двум причинам, что хвосты выше; у файлов до
                                // 12.09.2026 его нет — поле остаётся
                                // `PerEmittedQuantum`, то есть ровно тем, чем
                                // они и были при счёте.
                                if (stream.Length - stream.Position >= 5
                                    && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "NORM")
                                {
                                    matrix.Normalization =
                                        (ResponseMatrixNormalization)reader.ReadByte();

                                    // ⛔ ХВОСТЫ `LBIN`, `PKCH`, `LYSP` (П23
                                    // 12.09.2026: `A267`, `A306`, `M9`):
                                    // читаются здесь же и по тем же двум
                                    // причинам, что хвосты выше; у файлов до
                                    // 12.09.2026 их нет — поля остаются
                                    // `false`/`false`/0, то есть ровно тем,
                                    // чем были при их счёте, и клеймо
                                    // сходится само с собой.
                                    if (stream.Length - stream.Position >= 5
                                        && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "LBIN")
                                    {
                                        matrix.Options.LightBinUnified = reader.ReadBoolean();
                                        if (stream.Length - stream.Position >= 5
                                            && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "PKCH")
                                        {
                                            matrix.Options.PeakChannelByTolerance = reader.ReadBoolean();
                                            if (stream.Length - stream.Position >= 8
                                                && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "LYSP")
                                            {
                                                matrix.Options.LYieldSupply = reader.ReadInt32();

                                                // ⛔ ХВОСТ `ETRN` (`A72`, П27
                                                // 12.09.2026): у файлов до
                                                // 12.09.2026 его нет — поле
                                                // остаётся `false`, чем и
                                                // было при их счёте.
                                                if (stream.Length - stream.Position >= 5
                                                    && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "ETRN")
                                                {
                                                    matrix.Options.ElectronTransport = reader.ReadBoolean();
                                                }
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }

