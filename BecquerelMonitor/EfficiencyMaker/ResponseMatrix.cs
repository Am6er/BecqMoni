        /// <summary>
        /// Отпечаток геометрии и условий счёта. Считается от ТЕКСТА геометрии в
        /// том же формате, в каком она пишется на диск: так в него попадают все
        /// поля модели разом, и добавленное завтра поле не окажется молча вне
        /// проверки. Плюс ключи физики, сетка и версия переноса.
        ///
        /// Версия физики стоит ПЕРЕД хешем открытым текстом (`phys=N;хеш`):
        /// хеш необратим, и спрятанную в него версию <see cref="PhysicsFromStamp"/>
        /// уже никак не достанет — форма показывала «физика 0» про только что
        /// посчитанную матрицу. В сравнение отпечатков префикс входит наравне
        /// с хешем.
        /// </summary>
        /// <summary>Совпадают ли сетки побитово — сравнение для клейма (`T42`).</summary>
        static bool SameGrid(double[] a, double[] b)
        {
            if (a == null || b == null || a.Length != b.Length)
            {
                return false;
            }

            for (int i = 0; i < a.Length; i++)
            {
                if (a[i] != b[i])
                {
                    return false;
                }
            }

            return true;
        }

        /// <summary>
        /// ⛔ (`E34`, решение Amber 06.09.2026, ветка «а») ВЫХОД ПОПРАВКИ НА
        /// ОДНОКРАТНОЕ РАССЕЯНИЕ У МАТРИЦЫ ЗАВЕДОМО СТИРАЕТСЯ — считать её
        /// незачем.
        ///
        /// У ветки <see cref="EfficiencySimulator.SingleScatter"/> два выхода, и
        /// на пути сборки матрицы оба бывают пустыми ОДНОВРЕМЕННО:
        ///
        /// 1. **Пиковый счёт.** `ScatteredRun` возвращает вклад только при
        ///    <see cref="EfficiencySimulator.InPeak"/>, а тот требует
        ///    `E − deposited ≤ PeakHalfWidthKev`. У рассеявшегося по дороге
        ///    кванта недобор положителен всегда, поэтому при НУЛЕВОМ допуске
        ///    вклад ноль при любой истории. (Матрица этот счёт и так
        ///    выбрасывает — см. шапку `Run`, — но условие честнее писать по
        ///    самой ветке, а не по её читателю.)
        /// 2. **Гистограмма.** Всё, что ветка кладёт, ложится в бины НИЖЕ пика
        ///    (`Deposit` сдвигает не попавшее в пик в `peak−1`), а
        ///    `AnalogContinuumRun` перезаписывает бины `0…peak−1` целиком —
        ///    вместе с каналами и светом.
        ///
        /// Значит при «допуск нулевой И аналоговый континуум включён» ветка
        /// считает то, что будет стёрто, а стоит она 1.45…1.96× всего счёта
        /// узла (замер полосы `F76` 06.09.2026, физика 16, 3 млн историй;
        /// полоса П1 того же дня намерила на полной сцене 1.54× и 1.65×).
        ///
        /// ⛔ **Условие обязано НЕ ЗАДЕТЬ путь кривой эффективности**
        /// (`EfficiencyCalculation.cs`): там допуск берётся из геометрии и
        /// ветка работает по-настоящему. Поэтому решение стоит В СБОРЩИКЕ
        /// МАТРИЦЫ (<see cref="ResponseMatrixBuilder"/>, `MakeSimulator`), куда
        /// кривая не заходит вовсе, а не внутри симулятора: правило, спрятанное
        /// в общий код, однажды сработало бы и там.
        ///
        /// ⛔ **Ответ идёт и в клеймо** (`scat=`), иначе повторяется беда
        /// `A77`/`T114`: числа другие, клеймо прежнее. Матрица, посчитанная с
        /// погашенной веткой, побитово равна посчитанной ключом `--scat=0` — и
        /// клеймо у них теперь тоже одно.
        ///
        /// Допуск нулевой у ВСЕХ узлов сразу: он либо не берётся из геометрии
        /// вовсе, либо геометрия не знает своего разрешения (`DS_Fwhm662`
        /// отсутствует — файлы LSRM его не содержат), и тогда
        /// <see cref="GeometryModel.PeakHalfWidthKev"/> отдаёт ноль на любой
        /// энергии. Поэтому вопрос решается один раз на матрицу.
        ///
        /// ⚠ Оговорка об одном крае: у узла из ОДНОГО бина
        /// `AnalogContinuumRun` не зовётся (`histogram.Length > 1`), и там
        /// стирания не было бы. Такой узел означает `E &lt; BinKev/2`; при
        /// нижнем узле сетки 5 кэВ и шаге 2 кэВ он недостижим, замера на нём
        /// нет.
        /// </summary>
        public static bool SingleScatterErased(GeometryModel geometry, ResponseMatrixOptions options)
        {
            if (geometry == null || options == null || !options.AnalogContinuum)
            {
                return false;
            }

            // ⚠ С 11.09.2026 допуск даёт не только геометрия: решением Amber
            // умолчанием стоит ПОЛУБИН (`PeakToleranceHalfBin`), и он от
            // геометрии не зависит вовсе — значит `FwhmAt662Percent` для него
            // не спрашивается. Забыть этот ключ здесь значило бы утверждать
            // «ветвь стёрта» там, где она работает.
            if (options.PeakToleranceHalfBin && options.BinKev > 0.0)
            {
                return false;
            }

            return !options.PeakToleranceFromGeometry || !(geometry.FwhmAt662Percent > 0.0);
        }

        /// <summary>
        /// Умолчания настроек — ОДИН экземпляр на процесс (`T255`).
        ///
        /// Нужен клейму: поля, входящие в него по правилу `T42` («нет отличия —
        /// нет строки»), обязаны сравниваться с умолчанием САМОГО КЛАССА, а не
        /// с литералом рядом. Литерал — вторая копия числа, и она разойдётся с
        /// полем при первой же правке умолчания, молча объявив склад чужим.
        ///
        /// ⚠ Экземпляр, а не пересоздание на каждый вызов: годность матрицы
        /// проверяется с UI-потока на каждый тик живого набора геометрии.
        /// Читается он только на чтение и никем не правится.
        /// </summary>
        static readonly ResponseMatrixOptions DefaultOptions = new ResponseMatrixOptions();

        public static string ComputeStamp(GeometryModel geometry, ResponseMatrixOptions options)
        {
            if (geometry == null)
            {
                return "";
            }

            // ⛔ (`A244`) КАЖДОЕ число клейма печатается ИНВАРИАНТОМ, целые в том
            // числе. Дробные так стояли и раньше, а целые уходили через
            // `StringBuilder.Append(int)`, то есть по культуре ПОТОКА: клеймо
            // снимается и с UI-потока, и из фоновой задачи без переноса
            // контекста, и разойтись им нельзя — на равенстве клейм держится
            // решение «считать заново или взять готовую матрицу». Для целых на
            // ru-RU/de-DE/en-US строка выходит та же (замер `CultureProbeO14`,
            // раздел `A244`), поэтому ни одна посчитанная матрица не устарела.
            var sb = new StringBuilder();
            sb.Append("phys=").Append(PhysicsVersion.ToString(CultureInfo.InvariantCulture)).Append(';');
            if (options != null)
            {
                sb.Append("emin=").Append(options.MinEnergyKev.ToString("R", CultureInfo.InvariantCulture)).Append(';');
                sb.Append("emax=").Append(options.MaxEnergyKev.ToString("R", CultureInfo.InvariantCulture)).Append(';');
                sb.Append("nodes=").Append(options.NodeCount.ToString(CultureInfo.InvariantCulture)).Append(';');
                // ⛔ В отпечаток идёт САМА СЕТКА, а не ключ `ResolveEdges`, и
                // это не мелочь, а цена рабочего дня (`T42`, 17.08.2026).
                //
                // Ключом было нельзя двумя способами. Без него включение
                // `ResolveEdges` не пересчитывало НИЧЕГО: гвард видел прежнее
                // клеймо и брал прежний файл, то есть правка тихо не работала.
                // А с ним — пересчитывались ВСЕ 45 сцен корпуса, хотя края
                // разрешаются только у сцен, где у вещества пробы есть K-край в
                // рабочем диапазоне; у остальных сетка та же и матрица вышла бы
                // ПОБИТОВО ТОЙ ЖЕ. Часы уходили на счёт заведомо неизменного.
                //
                // Сетка — то, что на матрицу влияет, и отпечаток обязан спрашивать
                // именно её. Тогда «пересчитать» означает «пересчитать
                // изменившееся», а не «всё».
                // ⚠ И пишется она ТОЛЬКО когда отличается от штатной — иначе
                // смена формата клейма обесценивает все посчитанные матрицы
                // разом. Наступлено 17.08.2026: первый вариант писал сетку
                // всегда, старые клейма перестали совпадать в принципе, и гвард
                // погнал в пересчёт 45 сцен из 45 — включая те, где сетка та же.
                // Двадцать минут машины на счёт заведомо неизменного.
                //
                // Правило: нет отличия — нет строки, и клеймо совпадает с прежним
                // побайтно. Тогда включение краёв пересчитывает ровно сцены с
                // K-краем в рабочем диапазоне, а остальные остаются годными.
                double[] plainGrid = options.BuildGrid(null);
                double[] gridStamp = options.BuildGrid(geometry);
                if (!SameGrid(plainGrid, gridStamp))
                {
                    sb.Append("grid=").Append(gridStamp.Length.ToString(CultureInfo.InvariantCulture)).Append(':');
                    foreach (double node in gridStamp)
                    {
                        sb.Append(node.ToString("R", CultureInfo.InvariantCulture)).Append(',');
                    }

                    sb.Append(';');
                }
                // ⚠ Цели останова по шуму (`ContinuumErrorTarget`, `PilotDivisor`,
                // `MaxHistoriesFactor`) в отпечаток НЕ входят НАМЕРЕННО: они
                // описывают УСИЛИЕ, а не содержание. Матрица, посчитанная плоским
                // числом историй, для цели 3 % не «устарела» — она ЛУЧШЕ, чем дал
                // бы останов, и пересчитывать её значит ухудшать. Годность усилия
                // судит отдельная ветка гварда («посчитана гуще штатной — не
                // понижать», `T36`), и там ей место: у неё есть числа, а у
                // отпечатка только равно/не равно.
                sb.Append("bin=").Append(options.BinKev.ToString("R", CultureInfo.InvariantCulture)).Append(';');
                sb.Append("hist=").Append(options.Histories.ToString(CultureInfo.InvariantCulture)).Append(';');
                sb.Append("xray=").Append(options.XrayEscape ? "1" : "0").Append(';');
                sb.Append("coh=").Append(options.CoherentPassesThrough ? "1" : "0").Append(';');
                sb.Append("brem=").Append(options.Bremsstrahlung ? "1" : "0").Append(';');
                // ⛔ (`E34`) Клеймо называет ветку ТАК, КАК ОНА СЧИТАЛАСЬ, а не
                // так, как стоит ключ: при погашенном выходе (см.
                // <see cref="SingleScatterErased"/>) сборщик ветку не считает
                // вовсе, и матрица выходит побитово равной посчитанной с
                // `--scat=0`. Написать здесь «1» значило бы отдать двум разным
                // числам одно клеймо — ровно `A77`/`T114`.
                sb.Append("scat=")
                  .Append(options.SingleScatter && !SingleScatterErased(geometry, options) ? "1" : "0")
                  .Append(';');
                sb.Append("npl=").Append(options.LightNonproportionality ? "1" : "0").Append(';');
                sb.Append("acont=").Append(options.AnalogContinuum ? "1" : "0").Append(';');
                sb.Append("bound=").Append(options.BoundScattering ? "1" : "0").Append(';');
                sb.Append("bremsb=").Append(options.BremFromData ? "1" : "0").Append(';');
                // Зерно — по тому же правилу, что и сетка выше: пишется, только
                // если оно НЕ штатное. Матрица со штатным зерном сохраняет
                // прежнее клеймо побайтно, и появление ключа не гонит в
                // пересчёт ни одной посчитанной сцены.
                if (options.Seed != 0)
                {
                    sb.Append("seed=").Append(options.Seed.ToString(CultureInfo.InvariantCulture)).Append(';');
                }

                // Рулетка — по тому же правилу: пишется, только если включена.
                if (!options.SampleFluorescence)
                {
                    sb.Append("nofluo=1;");
                }

                if (options.ScatterRoulette > 0.0)
                {
                    sb.Append("roul=")
                      .Append(options.ScatterRoulette.ToString("R", CultureInfo.InvariantCulture))
                      .Append(';');
                }

                // ⛔ (`S130`) Три ключа физики 02.09.2026 — по тому же правилу
                // `T42`: пишутся, ТОЛЬКО когда включены. Выключенные они
                // считают прежнюю физику (измерено побайтно), и добавление
                // полей не должно гнать в пересчёт ни одной готовой матрицы.
                //
                // ⚠ Без этих строк ключи были бы неотличимы в клейме: матрица
                // с новой физикой легла бы поверх старой под тем же именем, и
                // гвард отдал бы разбору что попало.
                // `A60`: в клеймо пишется ВЫКЛЮЧЕННЫЙ ключ — включённый
                // есть умолчание физики 15, а выключенный делает матрицу
                // другой и обязан быть отличим.
                if (!options.LXrayEscape)
                {
                    sb.Append("nolx=1;");
                }

                if (options.XcomPairThreshold)
                {
                    sb.Append("pairth=1;");
                }

                // `A101`: с 04.09.2026 каскад K→L — УМОЛЧАНИЕ (физика 16), и в
                // клеймо пишется ВЫКЛЮЧЕННЫЙ, как это сделано для `A60`.
                // Правило `T42` соблюдено ровно так же: строка появляется только
                // у матрицы, отличной от умолчания. ⚠ Прежние матрицы стали
                // чужими не из-за неё, а из-за подъёма версии физики — правка
                // меняет отклик ВСЕГДА, и старая матрица честно объявлена
                // негодной (`A67`).
                if (!options.KLCascade)
                {
                    sb.Append("noklcasc=1;");
                }

                // `S112`: совместная эффективность пар. В клеймо пишется
                // ВЫКЛЮЧЕННАЯ — по тому же правилу `T42`, что у `nolx` и
                // `noklcasc`: строка появляется только у матрицы, отличной от
                // умолчания.
                //
                // ⛔ (`T255`, решение Amber 10.09.2026 «внести УСЛОВНО, как
                // `SingleScatter`») ЧИСЛО узлов и точек κ ВХОДИТ в клеймо —
                // но условно, двумя условиями сразу, и оба обязательны.
                //
                // 1. ТОЛЬКО ТАМ, ГДЕ ПАРА СЧИТАЕТСЯ. Условие — зеркало раннего
                //    выхода <c>ResponseMatrixBuilder.BuildJoint</c>: при
                //    `JointNodes <= 1` или сетке короче двух узлов таблицы κ
                //    не будет вовсе, и число точек тогда не описывает ничего.
                //    Это тот же ход, что у `scat=` (`E34`): клеймо называет
                //    ветку ТАК, КАК ОНА СЧИТАЛАСЬ, а не так, как стоит ключ.
                //    ⚠ Один узел приравнен к нулю ИМЕННО ЗДЕСЬ, а прежде
                //    `nojoint=1` писалось только при `<= 0`: матрица с
                //    `--jnodes=1` таблицы κ не несла, а клеймо носила от
                //    матрицы, которая несёт. Складу это не стоит ничего —
                //    все 44 его матрицы посчитаны умолчательными 24
                //    (замер 10.09.2026).
                //
                // 2. ТОЛЬКО ПРИ ОТЛИЧИИ ОТ УМОЛЧАНИЯ — правило `T42`, как у
                //    `seed=` и сетки. Писать числа всегда значило бы поменять
                //    клеймо у ВСЕХ готовых матриц и объявить чужим весь склад
                //    (44 сцены, трое суток счёта) ради поля, которое у них у
                //    всех одинаковое. Умолчания берутся у самого класса
                //    (<see cref="DefaultOptions"/>), а не литералами: копия
                //    числа здесь разошлась бы с полем при первой же правке.
                //
                // ⚠ Прежняя оговорка «число κ в клеймо не входит, оно меняет
                // шум таблицы, а не модель» СНЯТА решением Amber: шум κ входит
                // в поправку каскада, то есть в числа разбора, и матрица,
                // посчитанная на 24 узлах, при 48 признавалась годной молча.
                bool jointComputed = options.JointNodes > 1
                                     && gridStamp != null && gridStamp.Length >= 2;
                if (!jointComputed)
                {
                    sb.Append("nojoint=1;");
                }
                else
                {
                    if (options.JointNodes != DefaultOptions.JointNodes)
                    {
                        sb.Append("jnodes=")
                          .Append(options.JointNodes.ToString(CultureInfo.InvariantCulture))
                          .Append(';');
                    }

                    if (options.JointHistories != DefaultOptions.JointHistories)
                    {
                        sb.Append("jhist=")
                          .Append(options.JointHistories.ToString(CultureInfo.InvariantCulture))
                          .Append(';');
                    }
                }

                if (options.PositronTransport)
                {
                    // Половины `S126` обязаны различаться: со смещением
                    // вершины и без него это две разные матрицы.
                    sb.Append("e+tr=1;");
                    sb.Append("e+off=").Append(options.PositronOffset ? "1" : "0").Append(';');
                }

                if (options.RayleighToCrystal)
                {
                    sb.Append("rayl2=1;");
                }

                if (options.AnalogConeSampling)
                {
                    sb.Append("cone=1;");
                }

                // ⛔ (`E34`) Допуск пика из геометрии — по тому же правилу
                // `T42`: пишется, ТОЛЬКО когда включён. Он двигает ПИК
                // матрицы, и матрица, посчитанная с ним, обязана быть отличима
                // от прежней — иначе повторяется беда `T114`: содержимое
                // другое, а клеймо то же, и гвард отдаёт разбору что попало.
                if (options.PeakToleranceFromGeometry)
                {
                    sb.Append("peakw=1;");
                }

                // ⛔ (`AMBER16`, решение Amber 11.09.2026 «Допуск по БИНУ, а не
                // по ПШПВ») — тем же правилом `T42`: пишется, ТОЛЬКО когда
                // включён. Умолчанием он ВКЛЮЧЕН, и это нарочно не исключение:
                // ключ двигает пик, значит матрица с ним обязана быть отличима
                // от всех посчитанных до 11.09.2026, у которых допуск был ноль.
                if (options.PeakToleranceHalfBin)
                {
                    sb.Append("peakb=1;");
                }

                // ⛔ (`AMBER16` п. 1, решение Amber 11.09.2026 «Развести K и L
                // отдельными каналами») — тем же правилом `T42`: пишется,
                // ТОЛЬКО когда включён.
                //
                // ⚠ Ключ обязан быть в клейме, хотя СУММУ отклика он не меняет
                // ни на бит: он перекладывает L-вылет из канала № 3 в № 5, то
                // есть меняет ЧИСЛА существующего канала. Матрица с ним и без
                // него дают разный ответ на «сколько в канале вылета
                // K-рентгена», и одно клеймо на два разных ответа — ровно беда
                // `A77`/`T114`.
                if (options.SplitXrayShells)
                {
                    sb.Append("xrkl=1;");
                }

                // ⛔ (`F11` (а), решение Amber 11.09.2026 «K-провал — следующей
                // полосой» и «η — в единый счёт склада, ключом») — тем же
                // правилом `T42`: пишется, ТОЛЬКО когда включён. Оба ключа
                // двигают положение всего, что ниже ~120 кэВ, относительно
                // пика, — матрица с ними обязана быть отличима от склада.
                // Значение уровня (1/2/3) — в клеймо числом: половины
                // измеряются порознь и дают разные матрицы.
                if (options.KDipLight != 0)
                {
                    sb.Append("kdip=")
                      .Append(options.KDipLight.ToString(CultureInfo.InvariantCulture))
                      .Append(';');
                }

                if (options.LightEtaEh > 0.0)
                {
                    sb.Append("leta=")
                      .Append(options.LightEtaEh.ToString("R", CultureInfo.InvariantCulture))
                      .Append(';');
                }

                // ⛔ (П23 12.09.2026: `A267`, `A306`, `M9` — три решения Amber
                // «в СЛЕДУЮЩИЙ единый счёт склада») — тем же правилом `T42`:
                // пишутся, ТОЛЬКО когда включены. Все три двигают матрицу
                // (шкалу бинов, раскладку по каналам, L-линии отклика), и
                // матрица с любым из них обязана быть отличима от склада
                // физики 16. Три ключа, а не один «физика 17», нарочно:
                // единый счёт включил все (13.09.2026, П37, умолчания класса
                // `lbin=1;pkch=1;lys=2;`), а абляция может выключать по
                // одному — и такая матрица честно другая по клейму.
                if (options.LightBinUnified)
                {
                    sb.Append("lbin=1;");
                }

                if (options.PeakChannelByTolerance)
                {
                    sb.Append("pkch=1;");
                }

                if (options.LYieldSupply != 0)
                {
                    sb.Append("lys=")
                      .Append(options.LYieldSupply.ToString(CultureInfo.InvariantCulture))
                      .Append(';');
                }

                // ⛔ (`A72`, П27 12.09.2026, решение Amber «Вести электрон
                // переносом») — тем же правилом `T42`: пишется, ТОЛЬКО когда
                // включён. Двигает пик и континуум всех строк и поток
                // случайных чисел; выключенный — ни строки, клеймо склада
                // сходится побайтно.
                if (options.ElectronTransport)
                {
                    sb.Append("etr=1;");
                }
            }

            // (`AMBER13` (б)) Нормировка — тем же правилом `T42`: строка
            // пишется ТОЛЬКО у сцены поля. Текст геометрии её и так несёт
            // (`DS_Scene = ISO`), но нормировка — свойство МАТРИЦЫ, а не
            // размера, и клеймо обязано называть её само, а не через ключ
            // файла, который однажды переименуют.
            if (NormalizationOf(geometry) == ResponseMatrixNormalization.PerUnitFluence)
            {
                sb.Append("norm=fluence;");
            }

            sb.Append("geom=").Append(GeometryText(geometry));

            using (SHA256 sha = SHA256.Create())
            {
                byte[] hash = sha.ComputeHash(Encoding.UTF8.GetBytes(sb.ToString()));
                var hex = new StringBuilder(hash.Length * 2);
                foreach (byte b in hash)
                {
                    hex.Append(b.ToString("x2", CultureInfo.InvariantCulture));
                }

                return "phys=" + PhysicsVersion.ToString(CultureInfo.InvariantCulture)
                       + ";" + hex;
            }
        }

        /// <summary>
        /// Текст геометрии для отпечатка. Собирается тем же `GeometryWriter`,
        /// что сохраняет модель на диск, — но в памяти (`Render`), без
        /// временного файла: проверка годности зовётся с UI-потока на каждый
        /// тик живого набора, и файловая пара запись/чтение/удаление там —
        /// лишний ввод-вывод на ровном месте. Если сборка почему-либо не
        /// удалась, откатываемся на <see cref="GeometryModel.Describe"/>:
        /// хуже, но лучше, чем отпечаток, не зависящий от геометрии вовсе.
        /// </summary>
        static string GeometryText(GeometryModel geometry)
        {
            try
            {
                return GeometryWriter.Render(StampView(geometry));
            }
            catch (Exception)
            {
                return geometry.Describe();
            }
        }

        /// <summary>
        /// Та же геометрия, но приведённая к виду, от которого клеймо ЗАВИСЕТЬ
        /// ДОЛЖНО. Сейчас приведение одно: у зазора НУЛЕВОЙ ТОЛЩИНЫ снимается
        /// вещество.
        ///
        /// ⛔ Зачем (`AMBER1`, поймано 08.09.2026 замером). `GeometryWriter`
        /// печатает блок зазора ВСЕГДА — это решение Amber про ФОРМАТ ФАЙЛА, и
        /// оно верное: поле должно уезжать в `.in` и приезжать обратно. Но
        /// клеймо считается с того же текста, и из-за этого файл БЕЗ блока
        /// зазора и файл С блоком «0 см, воздух» давали РАЗНЫЕ клейма, хотя
        /// сцена у них побитово одна: слой нулевой толщины в неё не кладётся
        /// вовсе (<see cref="EfficiencySimulator"/>, `Add` отсекает вырожденную
        /// область). Цена расхождения — 42 матрицы склада, которые обесценивал
        /// рядовой перезапуск `CorpusGeomProbe`, ничего в физике не меняя.
        ///
        /// Замер, которым это поймано: `G1S_point5` из корпуса давал
        /// `5cb53b9c…` и сходился со своей матрицей, а он же, переписанный
        /// писателем, — `fcdfff16…` и «НЕ СОШЛОСЬ». Положительный контроль —
        /// `AS80_point0` с зазором 21.7 мм: у него клеймо не менялось.
        ///
        /// Правило то же, что у сетки (`T42`) и у ключей физики (`S130`): НЕТ
        /// ОТЛИЧИЯ — НЕТ СТРОКИ, и клеймо совпадает с прежним побайтно. Поэтому
        /// вещество снимается ровно так, как его оставляет чтение файла без
        /// блока зазора (пустой <see cref="GeometryMaterial"/>), а не как-нибудь
        /// иначе: иначе прежние матрицы стали бы чужими все разом.
        ///
        /// ⚠ Толщины из клейма НЕ убираются: печатать «0 см» файл без блока
        /// зазора и так заставляет разбор (поля числовые, умолчание — ноль), и
        /// эти две строки у обоих видов текста одинаковы.
        /// </summary>
        static GeometryModel StampView(GeometryModel geometry)
        {
            if (geometry == null)
            {
                return geometry;
            }

            // Зазор нулевой толщины в сцену не кладётся вовсе — блок с ним
            // и файл без блока обязаны давать ОДНО клеймо (`AMBER1`).
            bool dropGap = !(geometry.FrontGapThickness > 0.0
                             || geometry.SideGapThickness > 0.0);
            if (!dropGap && !geometry.InShield)
            {
                return geometry;
            }

            GeometryModel view = geometry.Clone();
            if (dropGap)
            {
                view.Gap = new GeometryMaterial();
            }

            // (`AMBER12`) Защита снимается ВСЕГДА и по той же причине, что
            // зазор: она не входит в сцену переноса. Матрица, посчитанная
            // до 09.09.2026, и она же с поднятым признаком — одни и те же
            // числа, и разъехавшееся клеймо объявило бы их чужими: 44
            // корпусные сцены в пересчёт из-за галки, которую читает
            // ТОЛЬКО разбор.
            view.InShield = false;
            return view;
        }

        public bool IsValidFor(GeometryModel geometry, ResponseMatrixOptions options)
        {
            return !string.IsNullOrEmpty(this.Stamp)
                && string.Equals(this.Stamp, ComputeStamp(geometry, options), StringComparison.Ordinal);
        }

        /// <summary>Годна ли для этой геометрии — по СВОИМ параметрам.</summary>
        public bool IsValidFor(GeometryModel geometry)
        {
            return this.Options != null && this.IsValidFor(geometry, this.Options);
        }

