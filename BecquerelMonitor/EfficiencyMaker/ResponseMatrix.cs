        /// <summary>
        /// Версии генерации из файла БЕЗ чтения матрицы целиком: версия формата
        /// и версия физики из отпечатка (`phys=N;` — первый ключ). Заголовок
        /// «магия, формат, отпечаток» одинаков у всех форматов, поэтому
        /// работает и для файла, который <see cref="Load"/> читать отказался, —
        /// ради формы, которая обязана сказать «устарела: формат N», а не
        /// «матрицы нет». false — файла нет или он не наш; неразобранная
        /// физика возвращается нулём (файл старше отпечатков с `phys=`).
        /// </summary>
        public static bool PeekVersions(string path, out int format, out int physics)
        {
            format = 0;
            physics = 0;
            if (!File.Exists(path))
            {
                return false;
            }

            try
            {
                using (var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read))
                using (var reader = new BinaryReader(stream, Encoding.UTF8))
                {
                    if (Encoding.ASCII.GetString(reader.ReadBytes(4)) != "BQRM")
                    {
                        return false;
                    }

                    format = reader.ReadInt32();
                    physics = PhysicsFromStamp(reader.ReadString());
                    return true;
                }
            }
            catch (Exception)
            {
                return format > 0;      // формат прочли — уже есть что сказать
            }
        }

        /// <summary>Версия физики из отпечатка; 0 — в отпечатке её нет.</summary>
        public static int PhysicsFromStamp(string stamp)
        {
            if (string.IsNullOrEmpty(stamp) || !stamp.StartsWith("phys=", StringComparison.Ordinal))
            {
                return 0;
            }

            int end = stamp.IndexOf(';');
            int value;
            return end > 5 && int.TryParse(stamp.Substring(5, end - 5), NumberStyles.None,
                                           CultureInfo.InvariantCulture, out value)
                ? value : 0;
        }

        /// <summary>Читает матрицу; null, если файла нет или он не наш.</summary>
        public static ResponseMatrix Load(string path)
        {
            MatrixRefusal refusal;
            int fileFormat;
            return Load(path, out refusal, out fileFormat);
        }

        /// <summary>
        /// То же чтение, но отказ НАЗЫВАЕТ СЕБЯ (`A50`).
        ///
        /// Прежде отказов было четыре — файла нет, файл не наш, формат прежний,
        /// файл обрублен, — а ответ один: <c>null</c>. Потребитель мог сказать
        /// только «матрицы нет», и человек с матрицей прежнего формата видел в
        /// легенде «· без матрицы» ровно то же, что человек, у которого файла
        /// нет вовсе: зацепиться не за что, а лечится это по-разному
        /// (пересчитать против посчитать).
        ///
        /// ⚠ <paramref name="fileFormat"/> имеет смысл только при
        /// <see cref="MatrixRefusal.OldFormat"/> — это версия ФАЙЛА, ради
        /// сообщения «посчитана форматом N, читаем M». У остальных отказов он 0.
        /// </summary>
        public static ResponseMatrix Load(string path, out MatrixRefusal refusal, out int fileFormat)
        {
            refusal = MatrixRefusal.NoFile;
            fileFormat = 0;
            if (!File.Exists(path))
            {
                return null;
            }

            refusal = MatrixRefusal.Unreadable;
            try
            {
                using (var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read))
                using (var reader = new BinaryReader(stream, Encoding.UTF8))
                {
                    if (Encoding.ASCII.GetString(reader.ReadBytes(4)) != "BQRM")
                    {
                        refusal = MatrixRefusal.NotOurs;
                        return null;
                    }

                    int format = reader.ReadInt32();
                    if (format != FormatVersion)
                    {
                        refusal = MatrixRefusal.OldFormat;
                        fileFormat = format;
                        return null;
                    }

                    var matrix = new ResponseMatrix
                    {
                        Stamp = reader.ReadString(),
                        BinKev = reader.ReadDouble(),
                        Histories = reader.ReadInt32(),
                        CreatedUtc = new DateTime(reader.ReadInt64(), DateTimeKind.Utc),
                        BuildSeconds = reader.ReadDouble()
                    };

                    matrix.Options = ReadOptions(reader);

                    // Границы ТЕЛА — для отпечатка (`A121`): от конца блока
                    // параметров до конца строк по каналам, ровно то, что
                    // `RenderBody` кладёт в файл.
                    long bodyStart = stream.Position;
                    int nodes = reader.ReadInt32();
                    matrix.Energies = new double[nodes];
                    for (int i = 0; i < nodes; i++)
                    {
                        matrix.Energies[i] = reader.ReadDouble();
                    }

                    int channels = reader.ReadInt32();
                    matrix.ChannelRows = new float[channels][][];
                    for (int c = 0; c < channels; c++)
                    {
                        float[][] rows = new float[nodes][];
                        for (int i = 0; i < nodes; i++)
                        {
                            int length = reader.ReadInt32();
                            float[] row = new float[length];
                            for (int b = 0; b < length; b++)
                            {
                                row[b] = reader.ReadSingle();
                            }

                            rows[i] = row;
                        }

                        matrix.ChannelRows[c] = rows;
                    }

                    long bodyEnd = stream.Position;

                    // Хвост с достигнутым шумом (`T46`). У файлов, записанных
                    // раньше, его нет — поля остаются нулями и null, ровно тем
                    // значением, которое их описание уже называет «не считалось».
                    // Хвост читается ПОСЛЕ данных и на них не влияет: битый или
                    // обрезанный хвост оставляет матрицу годной, а не роняет её.
                    try
                    {
                        if (stream.Length - stream.Position >= 4
                            && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "NOIS")
                        {
                            matrix.ContinuumRelativeError = reader.ReadDouble();
                            matrix.ContinuumWeightedError = reader.ReadDouble();
                            matrix.HistoriesSpent = reader.ReadInt64();
                            matrix.HistoriesWorstNode = reader.ReadInt64();
                            matrix.NodeHistories = ReadLongs(reader);
                            matrix.NodeErrors = ReadDoubles(reader);
                            matrix.NodeSeconds = ReadDoubles(reader);

                            // Ключи клейма вторым хвостом (`A66`). Без них
                            // матрица, посчитанная с ключом, не сходится сама
                            // с собой и числится негодной навсегда.
                            if (matrix.Options != null
                                && stream.Length - stream.Position >= 4
                                && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "OPTF")
                            {
                                matrix.Options.XcomPairThreshold = reader.ReadBoolean();
                                matrix.Options.PositronTransport = reader.ReadBoolean();
                                matrix.Options.PositronOffset = reader.ReadBoolean();
                                matrix.Options.RayleighToCrystal = reader.ReadBoolean();
                                matrix.Options.AnalogConeSampling = reader.ReadBoolean();
                                if (stream.Length - stream.Position >= 1)
                                {
                                    matrix.Options.LXrayEscape = reader.ReadBoolean();
                                }

                                // `A101` тем же хвостом. ⛔ Умолчание поля —
                                // `true` (каскад K→L считает физика 16), и у
                                // старого файла байта нет: после чтения флаг
                                // остаётся ВКЛЮЧЁННЫМ, а не выключенным. Прежде
                                // здесь стояло «умолчание `false`» — это было
                                // неверно про поле и неверно про старый файл
                                // (`A120`, найдено 04.09.2026, исправлено
                                // 06.09.2026): настоящее поведение задаёт
                                // объявление `KLCascade = true` ниже.
                                //
                                // Клеймо от этого не расходится: `noklcasc`
                                // пишется ТОЛЬКО у выключенного каскада, значит
                                // и старый файл, и его пересчёт молчат об этом
                                // ключе одинаково. Годность старого файла решает
                                // не он, а версия физики — 15 против 16.
                                if (stream.Length - stream.Position >= 1)
                                {
                                    matrix.Options.KLCascade = reader.ReadBoolean();
                                }

                                // Третий хвост, `BODY` (`A121`): записанный
                                // отпечаток тела. У файлов до 05.09.2026 его
                                // нет — поле остаётся null, «отпечатка нет».
                                if (stream.Length - stream.Position >= 36
                                    && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "BODY")
                                {
                                    matrix.StoredBodyFingerprint = Hex(reader.ReadBytes(32));

                                    // Четвёртый хвост, `PKWT` (`E34`): допуск
                                    // пика сборщика. У файлов до 06.09.2026 его
                                    // нет — флаг остаётся `false`, то есть ровно
                                    // тем, чем он был при их счёте, и клеймо
                                    // сходится само с собой.
                                    if (stream.Length - stream.Position >= 5
                                        && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "PKWT")
                                    {
                                        matrix.Options.PeakToleranceFromGeometry = reader.ReadBoolean();

                                        // Пятый хвост, `RLFL` (`T242`): рулетка
                                        // и флуоресценция пробы. У файлов до
                                        // 06.09.2026 его нет — поля остаются
                                        // умолчаниями (0 и `true`), то есть тем,
                                        // чем они были при их счёте, и клеймо
                                        // сходится само с собой.
                                        if (stream.Length - stream.Position >= 13
                                            && Encoding.ASCII.GetString(reader.ReadBytes(4)) == "RLFL")
                                        {
                                            matrix.Options.ScatterRoulette = reader.ReadDouble();
                                            matrix.Options.SampleFluorescence = reader.ReadBoolean();
                                            ReadJoint(matrix, stream, reader);
                                        }
                                    }
                                }
                            }
                        }
                    }
                    catch (Exception)
                    {
                        // Хвост — уточнение, а не условие годности матрицы.
                    }

                    // Отпечаток ПЕРЕСЧИТЫВАЕТСЯ по байтам файла, а не берётся
                    // из хвоста (`A121`): правленое тело обязано перестать
                    // сходиться с записанным, иначе хвост ничего не проверяет.
                    // Цена — один проход SHA-256 по телу, миллисекунды на
                    // мегабайт; и он не условие годности — не вышел, значит
                    // отпечатка нет, матрица остаётся годной.
                    try
                    {
                        matrix.BodyFingerprint = HashRange(stream, bodyStart, bodyEnd);
                    }
                    catch (Exception)
                    {
                        matrix.BodyFingerprint = null;
                    }

                    matrix.RebuildTotals();
                    refusal = MatrixRefusal.None;
                    return matrix;
                }
            }
            catch (Exception)
            {
                // Обрубок или чужой файл — это «матрицы нет», а не отказ работы.
                return null;
            }
        }
    }

    /// <summary>
    /// Почему матрица не прочиталась (`A50`). <see cref="None"/> — прочиталась.
    ///
    /// Заведено затем, что молчащий <c>null</c> сваливал в одну кучу четыре
    /// разных беды с четырьмя разными лечениями, и приложение не могло сказать
    /// человеку ни одной из них.
    /// </summary>
    public enum MatrixRefusal
    {
        /// <summary>Прочиталась.</summary>
        None,

        /// <summary>Файла нет — матрицу для этой геометрии не считали.</summary>
        NoFile,

        /// <summary>Файл есть, но не наш: нет метки `BQRM`.</summary>
        NotOurs,

        /// <summary>Файл наш, но посчитан ПРЕЖНИМ форматом — надо пересчитать.</summary>
        OldFormat,

        /// <summary>Файл наш и формат нынешний, а чтение оборвалось (обрубок).</summary>
        Unreadable
    }

