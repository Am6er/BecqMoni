        public void Save(string path)
        {
            string directory = Path.GetDirectoryName(Path.GetFullPath(path));
            if (!string.IsNullOrEmpty(directory))
            {
                Directory.CreateDirectory(directory);
            }

            // Пишем через временный файл: прерванная запись не должна оставить
            // обрубок, который при следующем открытии сойдёт за годную матрицу.
            string temp = path + ".tmp";
            using (var stream = new FileStream(temp, FileMode.Create, FileAccess.Write, FileShare.None))
            using (var writer = new BinaryWriter(stream, Encoding.UTF8))
            {
                writer.Write(Encoding.ASCII.GetBytes("BQRM"));
                writer.Write(FormatVersion);
                writer.Write(this.Stamp ?? "");
                writer.Write(this.BinKev);
                writer.Write(this.Histories);
                writer.Write(this.CreatedUtc.Ticks);
                writer.Write(this.BuildSeconds);
                WriteOptions(writer, this.Options);

                // ТЕЛО — сетка и строки по каналам — сначала собирается в
                // ПАМЯТИ, и в файл уходят ровно те байты, с которых снят
                // отпечаток (`A121`): второй путь записи «в файл отдельно, в
                // хеш отдельно» однажды разошёлся бы молча. Цена — копия тела
                // в памяти на время записи, сотни килобайт.
                byte[] body = this.RenderBody();
                writer.Write(body);
                byte[] digest;
                using (var sha = SHA256.Create())
                {
                    digest = sha.ComputeHash(body);
                }

                this.BodyFingerprint = Hex(digest);
                this.StoredBodyFingerprint = this.BodyFingerprint;

                // ⛔ У 799 МАТРИЦ СКЛАДА ЭТОГО ХВОСТА НЕТ, И ДОПИСЫВАТЬ ЕГО НЕ
                // НАДО — решение Amber 23.08.2026 (`T53`): ждём естественного
                // обновления. Матрица пересчитывается сама при смене физики или
                // геометрии, и хвост появляется у каждой в свой черёд; пересчёт
                // склада ради одних только полей шума стоит часов, а дописывать
                // числа в готовые файлы задним числом — риск испортить то, что
                // считалось верно. ⚠ Пока хвоста нет, поля читаются нулями, и
                // «шум был нулевой» от «не записано» отличается только по дате
                // файла; знать это надо тому, кто их читает.
                //
                // ДОСТИГНУТЫЙ ШУМ И ЦЕНА ПРОГОНА — ХВОСТОМ, ЗА ДАННЫМИ (`T46`).
                // Прежде их не было в файле вовсе: посчитанной матрице нельзя
                // было задать вопрос «а какого шума ты добилась и чем за него
                // заплатила», ответ жил только в консоли пробы и терялся.
                //
                // ⛔ `FormatVersion` НЕ ПОДНЯТ, и это не забывчивость. `Load`
                // сверяет версию НА РАВЕНСТВО (строка ниже) — плюс один объявил
                // бы нечитаемыми все уже посчитанные матрицы, а это 45 сцен
                // корпуса в пересчёт ради трёх чисел, при том что сами числа
                // матрицы не меняются ни на бит. Хвост устроен так, что старую
                // и новую поставку можно смешивать: у старого файла его просто
                // нет, а старый exe до него не доходит — он останавливается
                // там, где кончились данные. Метка `NOIS` отличает хвост от
                // случайного мусора в обрубке.
                writer.Write(Encoding.ASCII.GetBytes("NOIS"));
                writer.Write(this.ContinuumRelativeError);
                writer.Write(this.ContinuumWeightedError);
                writer.Write(this.HistoriesSpent);
                writer.Write(this.HistoriesWorstNode);
                WriteLongs(writer, this.NodeHistories);
                WriteDoubles(writer, this.NodeErrors);
                WriteDoubles(writer, this.NodeSeconds);

                // ⛔ ВТОРОЙ ХВОСТ, `OPTF` — КЛЮЧИ, КОТОРЫЕ ВХОДЯТ В КЛЕЙМО.
                //
                // `WriteOptions` их не пишет, а `ComputeStamp` учитывает — и это
                // ровно та дыра, которую `T114` уже закрывала для ЗЕРНА: матрица,
                // посчитанная с ключом, после чтения получала `false`,
                // пересчитывала клеймо БЕЗ него и не сходилась САМА С СОБОЙ —
                // `IsValidFor` отвечал «нет» навсегда, разбор печатал «БЕЗ
                // МАТРИЦЫ». Тогда лечили подъёмом формата; здесь хвостом, потому
                // что плюс один к `FormatVersion` объявил бы нечитаемыми все уже
                // посчитанные матрицы.
                //
                // Совместимость полная в обе стороны: у старого файла хвоста нет,
                // и флаги остаются СВОИМИ УМОЛЧАНИЯМИ — а он и правда считался
                // умолчаниями своего времени, так что его клеймо сходится; старый
                // exe до хвоста не доходит. Найдено ревизией 02.09.2026 (`A66`).
                //
                // ⚠ УМОЛЧАНИЕ НЕ У ВСЕХ СЕМИ `false` — с 13.09.2026 (физика
                // 17, П37) их ПЯТЬ: `LXrayEscape`, `KLCascade`,
                // `PositronOffset`, `PositronTransport` и `RayleighToCrystal` —
                // true; `XcomPairThreshold` и `AnalogConeSampling` — false
                // (до того — три, `A120`, счёт 06.09.2026).
                //
                // Клеймо это выдерживает, но каждый по-своему, и разница важна:
                // `LXrayEscape` и `KLCascade` попадают в клеймо ТОЛЬКО
                // ВЫКЛЮЧЕННЫМИ (`nolx=1`, `noklcasc=1`), а `PositronTransport`
                // и `RayleighToCrystal` — ТОЛЬКО ВКЛЮЧЁННЫМИ (`e+tr=1;e+off=N`,
                // `rayl2=1`), как `peakb`/`xrkl`/`kdip` у физики 16 со склада
                // 12.09.2026: правило `T42` здесь — «отличие от склада до
                // ключа», и матрицы физики 17 несут их сами. Файл без хвоста
                // `OPTF` старше 02.09.2026 (физика ≤ 12) и негоден по версии,
                // так что то, каким умолчанием он читается, ничего не решает.
                ResponseMatrixOptions flags = this.Options ?? new ResponseMatrixOptions();
                writer.Write(Encoding.ASCII.GetBytes("OPTF"));
                writer.Write(flags.XcomPairThreshold);
                writer.Write(flags.PositronTransport);
                writer.Write(flags.PositronOffset);
                writer.Write(flags.RayleighToCrystal);
                writer.Write(flags.AnalogConeSampling);
                writer.Write(flags.LXrayEscape);          // `A60`
                writer.Write(flags.KLCascade);            // `A101`

                // ⛔ ТРЕТИЙ ХВОСТ, `BODY` — ОТПЕЧАТОК ТЕЛА (`A121`, решение Amber
                // 05.09.2026 «клеймо + отпечаток тела хвостом файла»). Метка и
                // 32 байта SHA-256 от тела — байтов между блоком параметров и
                // меткой `NOIS`: сетка узлов и строки по каналам. Шапка, клеймо
                // и хвосты шума в него НЕ входят: они описывают настройки и
                // прогон, а отпечаток отвечает за ЧИСЛА.
                //
                // `FormatVersion` НЕ ПОДНЯТ по тому же доводу, что у двух хвостов
                // выше: плюс один объявил бы негодными все 44 корпусные и 4
                // рабочие матрицы разом ради поля, которое их чисел не меняет.
                // Старый файл без хвоста читается как прежде и печатает
                // «отпечатка нет»; старый exe до хвоста не доходит.
                writer.Write(Encoding.ASCII.GetBytes("BODY"));
                writer.Write(digest);

                // ⛔ ЧЕТВЁРТЫЙ ХВОСТ, `PKWT` — ДОПУСК ПИКА (`E34`).
                //
                // Заведён по той же причине, что `OPTF` (`A66`) и зерно до него
                // (`T114`): ключ входит в КЛЕЙМО, а `WriteOptions` его не
                // пишет. Не сохранив его, матрица после чтения получила бы
                // `false`, пересчитала клеймо БЕЗ `peakw=1` и перестала бы
                // сходиться САМА С СОБОЙ — `IsValidFor` отвечал бы «нет»
                // навсегда, а разбор печатал «БЕЗ МАТРИЦЫ».
                //
                // Отдельным хвостом, а не байтом в конец `OPTF`, нарочно: в
                // `OPTF` следом сразу идёт метка `BODY`, и лишний байт перед
                // ней читался бы старым файлом как сдвиг метки. Здесь же
                // совместимость полная в обе стороны — у прежнего файла хвоста
                // нет и флаг остаётся умолчанием (`false`, ровно так он и
                // считался), а прежний exe до хвоста не доходит.
                writer.Write(Encoding.ASCII.GetBytes("PKWT"));
                writer.Write(flags.PeakToleranceFromGeometry);

                // ⛔ ПЯТЫЙ ХВОСТ, `RLFL` — РУЛЕТКА И ФЛУОРЕСЦЕНЦИЯ ПРОБЫ
                // (`T242`, сводка ключей обоих путей 06.09.2026).
                //
                // Четвёртый случай ОДНОЙ И ТОЙ ЖЕ беды, после зерна (`T114`),
                // пятёрки `OPTF` (`A66`) и допуска пика (`PKWT`, `E34`):
                // `ScatterRoulette` и `SampleFluorescence` входят в КЛЕЙМО
                // (`roul=`, `nofluo=1`), а `WriteOptions` их не пишет. Матрица,
                // посчитанная `--roulette=0.125` или `--fluo=0`, после чтения с
                // диска получала умолчания (0 и `true`), пересчитывала клеймо
                // БЕЗ этих строк и не сходилась САМА С СОБОЙ: `IsValidFor`
                // отвечал «нет» навсегда, а разбор печатал «БЕЗ МАТРИЦЫ».
                //
                // ⚠ Найдено СВОДКОЙ, а не прогоном, и иначе не находилось:
                // оба ключа абляционные, штатный склад считается умолчаниями, а
                // при умолчаниях клеймо молчит об обоих и сходится. То есть
                // дыра ждала первого же замера рулетки или флуоресценции.
                //
                // Совместимость та же, что у хвостов выше: у прежнего файла
                // хвоста нет, поля остаются умолчаниями — ровно тем, чем они и
                // были при его счёте, — и клеймо сходится побайтно. Ни одна из
                // 44 корпусных матриц не устарела.
                writer.Write(Encoding.ASCII.GetBytes("RLFL"));
                writer.Write(flags.ScatterRoulette);
                writer.Write(flags.SampleFluorescence);

                // ⚡ ШЕСТОЙ ХВОСТ, `JNTK` — СОВМЕСТНАЯ ЭФФЕКТИВНОСТЬ ПАР
                // (`S112`, задача Amber 09.09.2026).
                //
                // ⛔ Здесь версия формата ПОДНЯТА (7 → 8), в отличие от хвостов
                // выше, и это не забывчивость наоборот: κ меняет ЧИСЛА разбора,
                // а не только его происхождение. Матрица без таблицы считает
                // сумм-пики по-старому, и читать её как годную значило бы
                // держать в складе две модели под одним именем. Цена подъёма
                // названа при решении, у `FormatVersion`.
                //
                // Хвостом, а не полем блока параметров, — чтобы порядок чтения
                // всего остального не сдвинулся ни на байт.
                double[] jointGrid = this.JointEnergies;
                double[][] jointTable = this.JointKappa;
                double[][] jointError = this.JointKappaError;
                bool haveJoint = jointGrid != null && jointGrid.Length > 0
                                 && jointTable != null && jointTable.Length == jointGrid.Length;
                writer.Write(Encoding.ASCII.GetBytes("JNTK"));

                // ⛔ САМА НАСТРОЙКА, А НЕ ТОЛЬКО ЕЁ ПЛОД. `JointNodes` входит в
                // КЛЕЙМО (`nojoint=1` у выключенной), и без этого поля матрица,
                // посчитанная `--jnodes=0`, после чтения получала бы умолчание,
                // пересчитывала клеймо БЕЗ строки и не сходилась САМА С СОБОЙ —
                // седьмой случай того же, что `T114`, `A66`, `E34` и `T242`.
                // Поймано сторожем `tools/check_matrix_keys.py` в тот же день.
                writer.Write(flags.JointNodes);
                writer.Write(haveJoint ? jointGrid.Length : 0);
                if (haveJoint)
                {
                    writer.Write(this.JointPoints);
                    foreach (double e in jointGrid)
                    {
                        writer.Write(e);
                    }

                    for (int i = 0; i < jointGrid.Length; i++)
                    {
                        for (int j = 0; j < jointGrid.Length; j++)
                        {
                            writer.Write(jointTable[i][j]);
                            writer.Write(jointError != null && jointError.Length == jointGrid.Length
                                         ? jointError[i][j] : 0.0);
                        }
                    }
                }

                // ⚡ СЕДЬМОЙ ХВОСТ, `JNTH` — ЧИСЛО ТОЧЕК замера κ (`T255`,
                // решение Amber 10.09.2026). Формат НЕ поднят: подробности и
                // довод — у <see cref="ReadJointHistories"/>. Пишется ВСЕГДА,
                // и при выключенной паре тоже: читатель ищет его в обоих
                // случаях, а «поле есть, только когда его значение неважно» —
                // это ровно та неявность, которой стоят разряды `T114`.
                writer.Write(Encoding.ASCII.GetBytes("JNTH"));
                writer.Write(flags.JointHistories);

                // ⛔ ВОСЬМОЙ ХВОСТ, `PKBN` — ДОПУСК ПИКА ПО ПОЛУБИНУ
                // (`AMBER16`, решение Amber 11.09.2026 «Допуск по БИНУ, а не по
                // ПШПВ»).
                //
                // Восьмой случай ОДНОЙ И ТОЙ ЖЕ беды, после зерна (`T114`),
                // `OPTF` (`A66`), допуска из геометрии (`E34`), рулетки с
                // флуоресценцией (`T242`) и `JointNodes` (`S112`): ключ входит в
                // КЛЕЙМО (`peakb=1`), а `WriteOptions` его не пишет. Не сохранив
                // его, матрица после чтения получила бы `false`, пересчитала
                // клеймо БЕЗ `peakb=1` и перестала бы сходиться САМА С СОБОЙ —
                // `IsValidFor` отвечал бы «нет» навсегда, а разбор печатал «БЕЗ
                // МАТРИЦЫ». ⚠ Дыру нашёл не человек, а сторож
                // `tools/check_matrix_keys.py` — в тот же час, когда ключ
                // появился, и до первого счёта склада.
                //
                // Формат НЕ поднят и совместимость полная в обе стороны: у
                // прежнего файла хвоста нет, флаг остаётся умолчанием (`false`)
                // — ровно тем, чем он был при его счёте, — и клеймо сходится
                // побайтно. Ни одна из 44 корпусных матриц не устарела.
                writer.Write(Encoding.ASCII.GetBytes("PKBN"));
                writer.Write(flags.PeakToleranceHalfBin);

                // ⛔ ДЕВЯТЫЙ ХВОСТ, `XRKL` — РАЗВЕДЕНИЕ K- И L-ВЫЛЕТА
                // (`AMBER16` п. 1, решение Amber 11.09.2026 «Развести K и L
                // отдельными каналами»).
                //
                // ДЕВЯТЫЙ случай одной и той же беды, после зерна (`T114`),
                // `OPTF` (`A66`), допуска из геометрии (`E34`), рулетки с
                // флуоресценцией (`T242`), `JointNodes` (`S112`) и допуска по
                // полубину (`PKBN`, `AMBER16` п. 2): ключ входит в КЛЕЙМО
                // (`xrkl=1`), а `WriteOptions` его не пишет. Не сохранив его,
                // матрица после чтения получила бы `false`, пересчитала клеймо
                // БЕЗ `xrkl=1` и перестала бы сходиться САМА С СОБОЙ —
                // `IsValidFor` отвечал бы «нет» навсегда, а разбор печатал «БЕЗ
                // МАТРИЦЫ». ⚠ Восьмой раз дыру нашёл сторож
                // `tools/check_matrix_keys.py` в тот же час, что и ключ; девятый
                // хвост заведён СРАЗУ, не дожидаясь его.
                //
                // Формат НЕ поднят и совместимость полная в обе стороны: у
                // прежнего файла хвоста нет, флаг остаётся умолчанием (`false`)
                // — ровно тем, чем он был при его счёте, — и клеймо сходится
                // побайтно. Ни одна из 44 корпусных матриц не устарела.
                //
                // ⚠ Число КАНАЛОВ этот хвост не описывает и описывать не
                // должен: оно лежит в теле файла числом, и пустой шестой канал
                // пишется наравне с полным (см.
                // <see cref="ResponseMatrixOptions.SplitXrayShells"/>).
                writer.Write(Encoding.ASCII.GetBytes("XRKL"));
                writer.Write(flags.SplitXrayShells);

                // ⛔ ДЕСЯТЫЙ И ОДИННАДЦАТЫЙ ХВОСТЫ, `KDIP` и `LETA` — K-ПРОВАЛ
                // КРИВОЙ СВЕТА И η МОДЕЛИ ПЕЙНА (`F11` (а), решения Amber
                // 11.09.2026). Те же два довода, что у `PKBN` и `XRKL`: ключи
                // входят в КЛЕЙМО (`kdip=`, `leta=`), и без хвоста матрица не
                // сходилась бы САМА С СОБОЙ. Формат НЕ поднят: у прежнего файла
                // хвостов нет, поля остаются умолчаниями (0 и 0) — ровно тем,
                // чем они были при его счёте, — и клеймо сходится побайтно.
                writer.Write(Encoding.ASCII.GetBytes("KDIP"));
                writer.Write(flags.KDipLight);
                writer.Write(Encoding.ASCII.GetBytes("LETA"));
                writer.Write(flags.LightEtaEh);

                // ⛔ ДВЕНАДЦАТЫЙ ХВОСТ, `NORM` — НОРМИРОВКА СТРОК (`AMBER13` (б),
                // решение Amber 10.09.2026 «Внести в (б) требованием»). Один
                // байт: 0 — на квант источника (доли), 1 — на единичный
                // флюенс (эффективная площадь, см²). Не настройка, а свойство
                // матрицы, положенное сценой (<see cref="NormalizationOf"/>);
                // в клеймо входит строкой `norm=fluence` у сцены поля, и без
                // хвоста матрица поля после чтения стала бы «долями» —
                // потребитель сложил бы см² с долями молча. Формат НЕ поднят:
                // у прежнего файла хвоста нет, поле остаётся 0 — ровно тем,
                // чем были все матрицы до появления сцены поля, — и клеймо
                // сходится побайтно. Ни одна из 44 корпусных матриц не
                // устарела.
                writer.Write(Encoding.ASCII.GetBytes("NORM"));
                writer.Write((byte)this.Normalization);

                // ⛔ ТРИНАДЦАТЫЙ, ЧЕТЫРНАДЦАТЫЙ И ПЯТНАДЦАТЫЙ ХВОСТЫ — `LBIN`,
                // `PKCH`, `LYSP` (П23 12.09.2026: `A267`, `A306`, `M9`, три
                // решения Amber «в СЛЕДУЮЩИЙ единый счёт склада»). Те же два
                // довода, что у `PKBN`/`XRKL`/`KDIP`: ключи входят в КЛЕЙМО
                // (`lbin=1`, `pkch=1`, `lys=N`), и без хвоста матрица не
                // сходилась бы САМА С СОБОЙ. Формат НЕ поднят: у прежнего
                // файла хвостов нет, поля остаются умолчаниями (`false`,
                // `false`, 0) — ровно тем, чем они были при его счёте, — и
                // клеймо сходится побайтно. Ни одна из 44 матриц склада не
                // устарела.
                writer.Write(Encoding.ASCII.GetBytes("LBIN"));
                writer.Write(flags.LightBinUnified);
                writer.Write(Encoding.ASCII.GetBytes("PKCH"));
                writer.Write(flags.PeakChannelByTolerance);
                writer.Write(Encoding.ASCII.GetBytes("LYSP"));
                writer.Write(flags.LYieldSupply);

                // ⛔ ШЕСТНАДЦАТЫЙ ХВОСТ — `ETRN` (`A72`, П27 12.09.2026,
                // решение Amber «Вести электрон переносом»). Те же два довода:
                // ключ входит в клеймо (`etr=1`), и без хвоста матрица не
                // сходилась бы сама с собой. Формат НЕ поднят: у прежнего
                // файла хвоста нет, поле остаётся `false` — ровно тем, чем
                // было при его счёте.
                writer.Write(Encoding.ASCII.GetBytes("ETRN"));
                writer.Write(flags.ElectronTransport);
            }

            if (File.Exists(path))
            {
                File.Delete(path);
            }

            File.Move(temp, path);
        }

        /// <summary>
        /// Тело файла — сетка и строки по каналам — как оно пишется на диск.
        /// Каналы, а не сумма: сумма восстанавливается из них точно, а обратно
        /// — нет. Пустой канал занимает по четыре байта на узел.
        /// </summary>
        byte[] RenderBody()
        {
            using (var memory = new MemoryStream())
            using (var writer = new BinaryWriter(memory, Encoding.UTF8))
            {
                writer.Write(this.Energies.Length);
                foreach (double e in this.Energies)
                {
                    writer.Write(e);
                }

                writer.Write(this.ChannelRows.Length);
                foreach (float[][] channel in this.ChannelRows)
                {
                    foreach (float[] row in channel)
                    {
                        writer.Write(row.Length);
                        foreach (float v in row)
                        {
                            writer.Write(v);
                        }
                    }
                }

                writer.Flush();
                return memory.ToArray();
            }
        }

        /// <summary>SHA-256 байтов потока со смещения <paramref name="start"/> до <paramref name="end"/>, hex.</summary>
        static string HashRange(Stream stream, long start, long end)
        {
            stream.Position = start;
            using (var sha = SHA256.Create())
            {
                byte[] buffer = new byte[1 << 16];
                long left = end - start;
                while (left > 0)
                {
                    int n = stream.Read(buffer, 0, (int)Math.Min(buffer.Length, left));
                    if (n <= 0)
                    {
                        break;
                    }

                    sha.TransformBlock(buffer, 0, n, null, 0);
                    left -= n;
                }

                sha.TransformFinalBlock(buffer, 0, 0);
                return Hex(sha.Hash);
            }
        }

        static string Hex(byte[] bytes)
        {
            var hex = new StringBuilder(bytes.Length * 2);
            foreach (byte b in bytes)
            {
                hex.Append(b.ToString("x2", CultureInfo.InvariantCulture));
            }

            return hex.ToString();
        }

        // Помощники хвоста `T46`: длина, затем значения; null пишется нулевой
        // длиной и читается обратно как null — «не считалось», а не пустой
        // массив, который выглядел бы как «посчитано и вышло ноль».
        static void WriteLongs(BinaryWriter writer, long[] a)
        {
            writer.Write(a == null ? 0 : a.Length);
            if (a == null)
            {
                return;
            }

            foreach (long v in a)
            {
                writer.Write(v);
            }
        }

